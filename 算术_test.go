// ==================================================================
// 验算 · 对拍之法
//
// 小者穷举，大者对拍。
//
// 四位八位之器，穷举可尽；二十四位之器，2^48 种输入穷举不得，
// 故取边界之例与随机之例，与 Go 原生运算逐一比对。
// 凡有不合，必是电路有差，而非 Go 有差。
// ==================================================================

// 志数 算爻器四志之值，用供比对。
type 志数 struct {
	进位 爻
	零  爻
	负  爻
	溢出 爻
}

// 读列 自网表读出一列线所成之数，众[0] 为最低位。
func 读列(n *网表, 众 []*线) int {
	v := 0
	for i, w := range 众 {
		v |= n.读(w).数() << i
	}
	return v
}

// 置列 将一数置入一列线，众[0] 为最低位。
func 置列(n *网表, 众 []*线, v int) {
	for i, w := range 众 {
		n.驱动(w, 由数(v>>i&1))
	}
}

// 欲算 依 Go 原生算出 n 位算爻器应有之果与四志。
func 欲算(位 int, a, b int, 操 算爻之操) (int, 志数) {
	掩 := 1<<位 - 1
	符位 := 1 << (位 - 1)
	有符 := func(v int) int {
		v &= 掩
		if v&符位 != 0 {
			v -= 1 << 位
		}
		return v
	}
	a &= 掩
	b &= 掩
	sa, sb := 有符(a), 有符(b)

	s, 进, 溢 := 0, 0, 0
	switch 操 {
	case 加:
		全 := a + b
		s = 全 & 掩
		进 = 全 >> 位 & 1
		if 有符(s) != sa+sb {
			溢 = 1
		}
	case 减:
		// 括号不可省：Go 之中 & 比 - 绑得紧，a - b&掩 实为 a - (b&掩)。
		s = (a - b) & 掩
		if a >= b {
			进 = 1 // 无借位
		}
		if 有符(s) != sa-sb {
			溢 = 1
		}
	case 交:
		s = a & b
	case 并:
		s = a | b
	case 殊:
		s = a ^ b
	case 升:
		s = a << 1 & 掩
	case 降:
		s = a >> 1
	case 较:
		if sa < sb {
			s = 1
		}
	default:
		panic(fmt.Sprintf("欲算：未知之操 %d", int(操)))
	}

	return s, 志数{
		进位: 由数(进),
		零:  作爻(s == 0),
		负:  由数(s >> (位 - 1) & 1),
		溢出: 由数(溢),
	}
}

// 算爻器之验 一座算爻器及其接线。造之费时，故只造一次而反复驱之。
type 算爻器之验 struct {
	网 *网表
	位 int
	甲 []*线
	乙 []*线
	果 []*线
	择 [3]*线
	志 *算爻志
}

// 建算爻器之验 造一座 n 位算爻器以供验算。
func 建算爻器之验(位 int) *算爻器之验 {
	n := 建网表("算爻器")
	e := &算爻器之验{
		网: n, 位: 位,
		甲: n.列线("甲", 位),
		乙: n.列线("乙", 位),
		果: n.列线("果", 位),
		择: [3]*线{n.引线("择0"), n.引线("择1"), n.引线("择2")},
	}
	e.志 = n.置算爻器(e.甲, e.乙, e.择, e.果)
	return e
}

// 算 置入 甲、乙 与 操，调定，回以果与四志。
func (e *算爻器之验) 算(a, b int, 操 算爻之操) (int, 志数) {
	置列(e.网, e.甲, a)
	置列(e.网, e.乙, b)
	for i := 0; i < 3; i++ {
		e.网.驱动(e.择[i], 由数(int(操)>>i&1))
	}
	if err := e.网.调定(0); err != nil {
		panic(err)
	}
	return 读列(e.网, e.果), 志数{
		进位: e.网.读(e.志.进位),
		零:  e.网.读(e.志.零),
		负:  e.网.读(e.志.负),
		溢出: e.网.读(e.志.溢出),
	}
}

// 核 以一例对拍，不合则记过。
func (e *算爻器之验) 核(t *testing.T, a, b int, 操 算爻之操) bool {
	t.Helper()
	得, 得志 := e.算(a, b, 操)
	欲, 欲志 := 欲算(e.位, a, b, 操)
	if 得 != 欲 {
		t.Errorf("%s 甲=%d 乙=%d：果得 %d，欲 %d", 操.名(), a, b, 得, 欲)
		return false
	}
	if 得志 != 欲志 {
		t.Errorf("%s 甲=%d 乙=%d：志得 进位%s 零%s 负%s 溢出%s，欲 进位%s 零%s 负%s 溢出%s",
			操.名(), a, b,
			得志.进位.符(), 得志.零.符(), 得志.负.符(), 得志.溢出.符(),
			欲志.进位.符(), 欲志.零.符(), 欲志.负.符(), 欲志.溢出.符())
		return false
	}
	return true
}

