# 廿三、器之数 差一（器区遂不抵藏之极）。
try_mut "廿三：器之数 差一" \
	's/\t器之数 = 0o100/\t器之数 = 0o77/'

# 廿四、器区之界 差一（器基 ＋ 1，出之口 遂落在器区之外）。
try_mut "廿四：器区之界 差一" \
	's/func 是器区\(址 int\) bool \{ return 址 >= 器基 && 址 < 器基\+器之数 \}/func 是器区(址 int) bool { return 址 >= 器基 + 1 \&\& 址 < 器基+器之数 }/'

# 廿五、化选之口 不收其值（择而不得，序 遂恒问化零）。
try_mut "廿五：化选之口 不收其值" \
	's/\tcase 化选之口:\n\t\tk\.择化 = 值/\tcase 化选之口:\n\t\t_ = 值 \/\/ 变异：化选 不收/'

# 廿六、化可之口 越界则阳（**不问则已，问则必有一答，答不出便答「不可」**）。
#
# 越界者若答阳，则 序 遂转去一个不存在的化——
# 而其时 转化 会陷 越化，越化 是**枢之过**，机遂止。
# 序 本是先问而后转，故它走不到；然他日若有他不问而转者，此口便是它的坑。
try_mut "廿六：化可之口 越界则阳" \
	's/\t\tif k\.择化 < 0 \|\| k\.择化 >= len\(k\.化\) \{\n\t\t\treturn 0\n\t\t\}/\t\tif k.择化 < 0 || k.择化 >= len(k.化) {\n\t\t\treturn 1\n\t\t}/'

# 廿七、化可之口 问 现化 而非 所择之化（择之无用，问的仍是自己）。
try_mut "廿七：化可 问现化而非所择" \
	's/if k\.化\[k\.择化\]\.状\.可行否\(\) \{/if k.化[k.当].状.可行否() {/'

# 廿八、告之口 恒阴（读不得其告，异步之断遂半聋）。
try_mut "廿八：告之口 恒阴" \
	's/\tcase 告之口:\n\t\tif k\.钟\.告待 \{\n\t\t\treturn 1\n\t\t\}\n\t\treturn 0/\tcase 告之口:\n\t\treturn 0 \/\/ 变异：告 恒阴/'

# 廿九、举告 而不举（写阳于 告之口 而 告待 不立）。
try_mut "廿九：举告 而不举" \
	's/\t\tk\.钟\.告待 = 值 != 0/\t\tk.钟.告待 = false \/\/ 变异：举告 而不举/'

# 三十、界基之口 差一（报的不是化之界）。
try_mut "三十：界基之口 差一" \
	's/\tcase 界基之口:\n\t\treturn k\.化\[k\.当\]\.界基/\tcase 界基之口:\n\t\treturn k.化[k.当].界基 + 1 \/\/ 变异：界基 差一/'

# ══════════════════════════════════════════════════════════════
# 五、界址（五）· M6
#
# 界址 是 M6 之骨：**屏** 与 **重定位** 皆自它出。
# 此一节之五变异，是「两化之内存互不干扰」那句话的五个反面。
# ══════════════════════════════════════════════════════════════

# 卅一、变换 恒等（界址不施，虚址 径作物址）。
#
# 此是 M6 之**本变异**。若它存活，则「各自的内存互不干扰」一语
# 从未被验过——而诸验犹绿，只是因为它们从未故意同址。
# 故 Test同址而异物 **故意同址**：若两化各用一址，
# 「互不干扰」便是理所当然，也就验不出什么了。
try_mut "卅一：变换 恒等（界址不施）" \
	's/\treturn \(块\.界基 \+ 址\) & 址掩/\treturn 址 \& 址掩 \/\/ 变异：界址不施/'

# 卅二、变换 越界不回界基（径以虚址为物址）。
#
# 越界之所以回 界基，非为真的要去读它——只为给 L2 一个**不泄枢密**的去处，
# 那一笔随即被 撤 掉。若径以虚址为物址，则化态便真能读到枢之码：
# 纵撤其值，其线已通，而**线通之一瞬，便是屏破之一瞬**。
try_mut "卅二：变换 越界不回界基" \
	's/\t\treturn 块\.界基 & 址掩/\t\treturn 址 \& 址掩 \/\/ 变异：越界 径以虚址为物址/'

# 卅三、越界否 恒否（化态之界遂不设）。
try_mut "卅三：越界否 恒否" \
	's/func \(k \*枢机\) 越界否\(权 特权\) bool \{\n\tif 权 == 枢态 \{\n\t\treturn false\n\t\}\n\t块 := k\.化\[k\.当\]\n\treturn k\.虚址 < 0 \|\| k\.虚址 >= 块\.界限/func (k *枢机) 越界否(权 特权) bool {\n\t_ = 权\n\treturn false \/\/ 变异：不检其界/'

# 卅四、取指之检 用 化之极 而非 界限（旧病：由果抄果）。
#
# 有化之时，化态之界由 **化块之界限** 出，不由 化之极 出——
# 化之极 只是「无化之时」那一界。二者虽常同指，其义则异：
# 一是因（此化有多大），一是果（化之域止于何所）。
try_mut "卅四：取指之检 用化之极" \
	's/\tif 旧相 == 0 && 旧特权 == 化态 && !k\.是化之域\(m\.计\) \{/\tif 旧相 == 0 \&\& 旧特权 == 化态 \&\& m.计 >= 化之极 { \/\/ 变异：用 化之极 而非 界限/'

# 卅五、是化之域 界限 差一（化态遂多取一指令）。
try_mut "卅五：是化之域 界限差一" \
	's/func \(k \*枢机\) 是化之域\(址 int\) bool \{\n\t块 := k\.化\[k\.当\]\n\treturn 址 >= 0 && 址 < 块\.界限/func (k *枢机) 是化之域(址 int) bool {\n\t块 := k.化[k.当]\n\treturn 址 >= 0 \&\& 址 < 块.界限 + 1/'

# ══════════════════════════════════════════════════════════════
# 六、化与序（七）· M6
# ══════════════════════════════════════════════════════════════

# 卅六、转化 不复其器（新化一上来便用着旧化之器）。
#
# 化之器只有一处安身（化块）。转化 若不自块复之，
# 则新化之第一令起，它的 计、和、乃至欲出之字，全是上一个化的。
try_mut "卅六：转化 不复其器" \
	's/\tm\.诸器 = 的\.诸器/\t_ = 的.诸器 \/\/ 变异：转化 不复古化之器/'

# 卅七、转化 不复其钟（新化承旧化之余）。
#
# 钟.过 是「此化已得几令」。不复其零，则新化头一片遂短了，
# 短多少全看旧化是何时被夺的——**诸化之片遂不等长**，
# 而「片 之数名副其实」之约成虚言。它不报错，只是时辰不公。
#
# 此变异之所以可杀，端赖 Test转化则复其钟 **径自枢态呼 行转化**——
# 序 之中造不出一个「不等于 片」的 过，故假 序 观之则量不到此处。
try_mut "卅七：转化 不复其钟" \
	's/\tk\.钟\.过 = 0 \/\/ 新化得一整片，不承旧化之余/\t\/\/ 变异：新化承旧化之余/'

# 卅八、化息 而不毕（息了而仍可行，序 遂复择之）。
#
# 毕 是 状，不是「转走」。化息 只改其状，**转走是 序 的事**——
# 谁该接着跑，化息 不当预。此变异若活，则 毕 之一状遂成虚设，
# 而 序 之「遍寻无可行者则止」亦无处可寻。
try_mut "卅八：化息 而不毕" \
	's/\t块\.状 = 化毕/\t_ = 化毕 \/\/ 变异：化息 而不毕/'

# 卅九、告之检 先加后判（片 ＝ 8 者只得 7 令）。
#
# 过 是「此化**已得**几令」，非「将要取第几条」。
# 先加后判，则 过 在尚未执行之令的取指相上就已递增，
# 于是 片 ＝ 8 者只得 7 令——少一条，且不报错。
# 其差止一条令，而**片 之数遂名不符实**；此即「错而无声」之类。
try_mut "卅九：告之检 先加后判" \
	's/\t\tif k\.钟\.片 > 0 \{\n\t\t\tk\.钟\.过\+\+\n\t\t\}\n//' \
	's/\tif 旧相 == 0 && 旧特权 == 化态 \{\n\t\tif k\.告至\(\) \{/\tif 旧相 == 0 \&\& 旧特权 == 化态 {\n\t\tif k.钟.片 > 0 {\n\t\t\tk.钟.过++\n\t\t}\n\t\tif k.告至() {/'

# 四十、告 不销（陷而不销其告，化态遂每一取指皆陷）。
#
# **销其告者，陷也，非处理器也。** 陷 若不销，
# 则告恒在：机 遂空转于「陷 → 序 → 回 → 陷」之环而一令不进。
# 那是死环，不是错——而死环在 跑 之上限之下看起来只是「跑不完」。
try_mut "四十：告 不销" \
	's/\t\t\tk\.钟\.过, k\.钟\.告待 = 0, false \/\/ \*\*销其告者，陷也\*\*——见 告之口 之注/\t\t\tk.钟.过 = 0 \/\/ 变异：告 不销/'

# 四十一、告至 不闻其举告（只听钟鸣）。
#
# 告 之来路有二：钟鸣（时到），与举告（人举）。
# 二者皆归于一口，故 告至 当**皆问之**。若不闻其举告，
# 则异步之断遂只剩同步之一途——而他日外设来时，它一字也递不进来。
try_mut "四十一：告至 不闻其举告" \
	's/func \(k \*枢机\) 告至\(\) bool \{ return k\.钟\.告待 \|\| k\.钟\.鸣否\(\) \}/func (k *枢机) 告至() bool { return k.钟.鸣否() } \/\/ 变异：不闻其举告/'

# 四十二、器口之簿 之口号 越出器区（表与实不符）。
#
# 器口之簿 是唯一真源：演示 之器区表、器口之数，皆由它出。
# 表若说的是另一件事，它便是谎——而谎不报错，只是少了一行。
try_mut "四十二：口簿 之号越出器区" \
	's/\t\{化可之口, "化可",/\t{器之数, "化可",/'

