#!/bin/zsh
# 变异测试之具：故意把 枢.go 改错，看诸验能否杀之。
# 一变异而诸验皆绿，则说明有处**验不到**——那才是真病。
#
# 用法（在仓库根，或在别处亦可——路是自算的）：
#     zsh 具/变异枢.sh
#
# ⚠ 一、须以 zsh 呼之。shebang 只在「直接执行」时生效，交给解释器时它不作数；
#      以 bash 呼之则此具会**静默地谎报「尽杀」**——详见 具/变异译.sh 之注。
# ⚠ 二、**跑之前先提交**。此具自愈之陷阱已设（EXIT/INT/TERM/HUP/PIPE 皆设），
#      然 git 是最后一道退路（`git checkout -- 枢.go`）。
#      无退路而自愈失手，则下一趟以「带变异之版」为原样，诸果皆废。
#
# ─────────────────────────────────────────────────────────────
# 何以枢须另立一具，而不并入 变异译.sh
#
# L2 之可信由 L1 逐拍对拍而来，L3 之上**再无 L4 可对其拍**。
# 故 L3 之可信只剩一条路：证明它什么也没做（Test枢与周期对拍），
# 加上——**量它自己新加的那几件事验到了什么**。
#
# M5 是三件事：特权、爻变、器区。M6 又添三件：界址、化、序。
# 故 M6 收档之时，此具之变异自 25 拓至 45，其新拓者皆在界址与调度之上：
# 变换 之恒等（屏破）、转化 之复器与复钟、化息 之毕、告 之举至陷销。
#
# 「验到了什么」不能靠自陈。一个说「一切正常」的检查，
# 必须先证明它**分得出不正常**。故立此具，立七检：
#   〇、残留之检：上一趟若横死（SIGKILL），其遗毒当先清——详见其处之注。
#   一、起手之检：当下之 枢.go 须是干净的，否则所量者全是错的。
#   二、首之检：干净之 枢.go 全绿。
#   三、验数之检：包内实有之验 与 实跑之验 当同（有验未被跑则报）。
#   四、还原之检：每试之前先还原，收工之后校校验和。
#   五、尾之检：还原之后仍全绿。
#   六、自检：末了注入一个无害变异，此具**当报「存活」**——
#             一个只会说「已杀」的器，它的沉默什么也不说明。
#
# 变量名一律用 ASCII。非为媚 bash，而是**前一具曾因此坏过**。
#
# ─────────────────────────────────────────────────────────────
# 变异之式 是会朽的
#
# 此具之式**径写 枢.go 之原文**。源码一改，式便不合；
# 式不合则 变异未注入，而**未注入不等于已杀**——
# 故此具对之另标「疑」，不与「已杀」同列（见 try_mut）。
#
# M6 之收档，45 式之中 13 式已朽（M5 之旧式）。朽者不改，
# 则此具之「已杀」里头掺了不该算的——**那比存活更险，
# 因为它不报忧，只报喜**。故凡见「疑」，须改式，勿以「已杀」饰之。
# ─────────────────────────────────────────────────────────────
set -u

# 路自算：本具在 具/ 之下，仓库根是其上一级。
ROOT=${0:A:h:h}
cd "$ROOT" || exit 1

SRC=枢.go
# 备份与标记皆用**固定名**（不掺 $$）。其故见下「残留之检」：
# 名随进程而变，则新的一趟认不出上一趟的尸首；名固定，则一望而知。
BAK=${TMPDIR:-/tmp}/mut-shu-枢.go.bak
MARK=${TMPDIR:-/tmp}/mut-shu-枢.go.mark

# 跑**全部**测试，不择其名。其故见 具/变异译.sh 之 run：
# 手抄一张 -run 名单，名单漏掉的东西**不报错，只是不见了**。
run() { ./跑.sh test -count=1 ./... 2>&1; }
restore() { cp "$BAK" "$SRC"; }
sum() { cksum < "$SRC"; }

# 无论如何都要自愈：EXIT / INT / TERM / HUP / PIPE 皆置一陷阱。
# PIPE 之故：作者尝以 `zsh 具/变异译.sh | head -8` 观其首数行，
# head 读够即闭其管，脚本遂死于 SIGPIPE，死时源文件正带着一个变异。
cleanup() {
	if [[ -f "$BAK" ]]; then
		cp "$BAK" "$SRC"
		rm -f "$BAK"
	fi
	rm -f "$MARK"
}
trap cleanup EXIT INT TERM HUP PIPE

# ---- 残留之检：陷阱捕不得的那一类死法 ----
#
# 陷阱**只捕得住可捕之信号**。SIGKILL（kill -9，或超时被强杀）捕不得、
# 拦不住、不作数——进程无声而去，一个字也来不及收。
# 此具尝真死于其手：退出码 137（=128+9），$SRC 带着变异十一留在盘上，
# 而新的一趟全不知情，遂以那带病之版为「原样」，往后诸果皆废。
#
# 故不靠陷阱，靠**遗书**：每注一变异先落标记，收工方删。
# 起手时标记犹在 ⇒ 上一趟是横死的，其言不可信，其迹当清。
if [[ -f "$MARK" ]]; then
	print -r -- "【残留之检】⚠ 上一趟未收工（标记犹在）——是被 SIGKILL 者，或崩者。"
	print -r -- "            陷阱捕不得 SIGKILL，故以此记认之。上趟诸果**皆不可信**。"
	if [[ -f "$BAK" ]]; then
		cp "$BAK" "$SRC"
		print -r -- "            已自上趟之备份还原 $SRC（备份只可能是干净之版）。"
	else
		print -r -- "            ⚠ 备份竟不在！$SRC 今带何变异，无从得知——止，请自查 git。"
		exit 1
	fi
	rm -f "$MARK"
	print -r -- ""
fi

cp "$SRC" "$BAK" || exit 1
SUM0=$(sum)

# ---- 〇、起手之检 ----
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
	if ! git diff --quiet -- "$SRC" 2>/dev/null; then
		print -r -- "【起手之检】⚠ $SRC 有未提交之改动，此具将**以它为原样**。"
		print -r -- "            若它是上一趟跑坏而未还原的，则下列诸果皆不可信。"
		git diff --stat -- "$SRC" | sed 's/^/            /'
		print -r -- ""
	fi
fi

# ---- 一、首之检 ----
out=$(run)
if ! print -r -- "$out" | grep -q '^ok'; then
	print -r -- "【首之检】不过：干净之 $SRC 竟不绿。止。"
	print -r -- "$out" | grep -E 'FAIL|_test\.go:[0-9]+' | head -20
	exit 1
fi
print -r -- "【首之检】干净之 $SRC 全绿 ✓"

# ---- 三、验数之检 ----
验数=$(grep -hoE '^func Test[^ (]+' *_test.go | wc -l | tr -d ' ')
实跑=$(./跑.sh test -count=1 -v ./... 2>&1 | grep -cE '^--- (PASS|FAIL|SKIP)')
if [[ "$验数" -ne "$实跑" ]]; then
	print -r -- "【验数之检】⚠ 包内实有 $验数 验，实跑 $实跑 验——有验未被跑。"
	print -r -- "            未被跑之验杀不着任何变异，而此具**不会报**——它只报「存活」。"
else
	print -r -- "【验数之检】$实跑 验皆跑 ✓"
fi
print -r -- ""

# ---- 试一变异 ----
# 用法：try_mut <名> <perl 式> [更多 perl 式…]
#
# 三数：杀、活、疑。此三者**不声明为 local**，故诸次共享而逐次累加，
# 收工时一并报出——免得逐行点数。手点之数，必漏。
#
# 「疑」者二：一式不合而**未注入**，一死于编译或崩。
# 二者皆非案杀之，而**皆曾被「已杀」盖过去**——故另立一数，不与杀同列。
杀=0
活=0
疑=0

try_mut() {
	local name="$1"; shift
	local expr before after out who
	restore                      # 四、还原之检（置前）：起点必干净
	before=$(sum)
	: > "$MARK"                  # 落遗书：此刻起，$SRC 是**带病**的
	for expr in "$@"; do
		perl -0pi -e "$expr" "$SRC"
	done
	after=$(sum)

	printf '%-34s' "$name"
	if [[ "$before" == "$after" ]]; then
		print -r -- "变异未注入 ✗（式已不合，须改式，勿以「已杀」饰之）"
		疑=$((疑 + 1))
		rm -f "$MARK"
		return
	fi

	out=$(run)
	rm -f "$MARK"                # 病已除，遗书可销
	if print -r -- "$out" | grep -q '^ok'; then
		print -r -- "存活 ✗（有处验不到，须查明）"
		活=$((活 + 1))
	else
		who=$(print -r -- "$out" | grep -oE -- '--- FAIL: [^ ]+' | head -1 | sed 's/--- FAIL: //')
		if [[ -z "$who" ]]; then
			print -r -- "已杀 ✓  （编译不过或崩，非案杀之，须察）"
			疑=$((疑 + 1))
		else
			print -r -- "已杀 ✓  ${who}"
			杀=$((杀 + 1))
		fi
	fi
}

# ══════════════════════════════════════════════════════════════
# 一、特权（六）
# ══════════════════════════════════════════════════════════════

# 一、取指之检 判反特权：化态 取指入界外而不检。
try_mut "一：取指之检 判反特权" \
	's/旧相 == 0 && 旧特权 == 化态 && !k\.是化之域\(m\.计\)/旧相 == 0 \&\& 旧特权 == 枢态 \&\& !k.是化之域(m.计)/'

# 二、特权之令 化态行之而不陷（径行 降化/回/转化/化息）。
try_mut "二：特权之令 化态不陷" \
	's/\tif 特权之令\[码\] \{\n\t\tif 旧特权 == 化态 \{/\tif 特权之令[码] {\n\t\tif 旧特权 == 枢态 {/'

# 三、化之极 差一（枢基 之上一字遂成化之域，化态可触）。
#
# 是枢之域 由 化之极 出而不由 枢基 出，正是为此：
# 由因出果，则此一改立红；由果抄果，则两处皆可独改而无声。
# 又：上电之化 界限 ＝ 化之极，故此改亦使化 0 多触一字——两途皆可杀之。
try_mut "三：化之极 差一" \
	's/\t化之极 = 枢基/\t化之极 = 枢基 + 1/'

# 四、降化 不忘其特权（降而不降权，用户程遂以枢态跑下去）。
try_mut "四：降化 不忘其特权" \
	's/\tcase 降化:\n\t\t\/\/ 降化：指定其往。特权 ← 化态，计 ← 丙型之址（虚址）。\n\t\tk\.特权 = 化态/\tcase 降化:\n\t\t\/\/ 降化：指定其往。特权 ← 化态，计 ← 丙型之址（虚址）。\n\t\t_ = 化态 \/\/ 变异：降而不降权/'

# 五、回 弹栈而不复其权（一律降为化态，M5 之权宜复辟）。
#
# 栈既立（M6），回 之权当**自记中来**，不当一律降之：
# 序 在枢态行 转化 而不就，其 回 当归枢态，非归化态。
# 若一律降之，则 序 之后的枢之正文遂以化态行——一取指便陷，陷而复陷。
try_mut "五：回 弹栈而不复其权" \
	's/\t\tk\.特权 = 记\.权/\t\tk.特权 = 化态 \/\/ 变异：弹栈而不复其权/'

# 六、回 栈空而不降其权（回而不降权）。
#
# 此变异最险：特权一旦漏出去，此后的每一次存取都不再受检，
# 而机器一声不响。**特权之漏，是最静的一种错。**
try_mut "六：回 栈空而不降其权" \
	's/\t\} else \{\n\t\tk\.特权 = 化态\n\t\tm\.计 = 截址\(块\.计\)/\t} else {\n\t\t_ = 化态 \/\/ 变异：栈空而不降其权\n\t\tm.计 = 截址(块.计)/'

# ══════════════════════════════════════════════════════════════
# 二、爻变（八）
# ══════════════════════════════════════════════════════════════

# 七、越权之写 不撤（越权虽陷，其字已入藏）。
#
# M6 之新险：变换 把越界之址**引去了 界基**，故所污者不是 化 自以为在写的
# 那一址，而是它自己域首那一字。守错了址，则纵一字不撤，验也是绿的——
# 那一笔根本没落在那里。此病已发一次，今守整片 藏（Test化态写枢之域则撤）
# 与 域首（Test越界者毕而他化续行），两验夹之。
try_mut "七：越权之写 不撤" \
	's/\t\tif 是存 \{\n\t\t\tm\.诸字 = 旧字 \/\/ 撤其写入/\t\tif 是存 {\n\t\t\t_ = 旧字 \/\/ 变异：不撤/'

# 八、越权之读 不撤（越权虽陷，其值已入器——那值是偷来的）。
try_mut "八：越权之读 不撤" \
	's/\t\t\} else \{\n\t\t\tm\.诸器 = 旧器 \/\/ 撤其读回/\t\t} else {\n\t\t\t_ = 旧器 \/\/ 变异：不撤/'

# 九、未定之码 不陷。
try_mut "九：未定之码 不陷" \
	's/\tif 取型\(码\) == 未定型 \{\n\t\tk\.陷\(越令之变, m\.计,\n\t\t\tfmt\.Sprintf\("未定之码 0o%02o（%s）", 码, 别卦符\(码\)\)\)\n\t\treturn\n\t\}\n//'

# 十、变之表 之槽差一（越权之变 遂跳去 变越令）。
try_mut "十：变之表 之槽差一" \
	's/变之表基\+int\(因\), k\.特权, 因, 由/变之表基+int(因)+1, k.特权, 因, 由/'

# 十一、陷 不记其因（因 恒留初值，诸变遂不可辨）。
try_mut "十一：陷 不记其因" \
	's/\tk\.因, k\.特权 = 因, 枢态/\tk.特权 = 枢态 \/\/ 变异：不记其因/'

# 十二、化态之陷 亦压栈（不入块）——**底在块，深在栈，二者不叠**。
#
# 化态之陷若亦压栈，则 块之计 与 块之诸器 遂**永不更新**；
# 化 跑回来时（序 之 转化 自块复其器），它的器已不是它的器了。
# 此错极静：字照出，数照加，只是**和 少了几分**——
# 而少几分看起来像算错，不像丢人。
try_mut "十二：化态之陷 亦压栈" \
	's/\tif 旧特权 != 化态 \{/\tif true { \/\/ 变异：化态亦压栈，不入块/'

# 十三、存计 忘其自增（块之计 ← 返址−1，回 遂返于陷之自身，成死环）。
try_mut "十三：存计 忘其自增" \
	's/\t块\.诸器, 块\.计 = m\.诸器, 返址/\t块.诸器, 块.计 = m.诸器, 返址-1/'

# 十四、轰 不置其止（轰而不止，机继续跑下去）。
try_mut "十四：轰 不置其止" \
	's/\tk\.机\.止 = true\n\tk\.轰否, k\.轰由 = true, 由/\tk.轰否, k.轰由 = true, 由/'

# ══════════════════════════════════════════════════════════════
# 三、叩（五）
# ══════════════════════════════════════════════════════════════

# 十五、叩 不校其号（越号者遂乱跃于叩之表之中）。
try_mut "十五：叩 不校其号" \
	's/\tif 号 < 0 \|\| 号 >= 叩号数 \{\n\t\tk\.陷\(越号之变, m\.计,\n\t\t\tfmt\.Sprintf\("叩号 %d 越出 0\.\.%d", 号, 叩号数-1\)\)\n\t\treturn\n\t\}\n//'

# 十六、叩之表 之槽差一（叩「出」遂跃入 叩「言」）。
try_mut "十六：叩之表 之槽差一" \
	's/叩之表基\+号, 旧特权/叩之表基+号+1, 旧特权/'

# 十七、还 M3 之债 还迟了（置于「号在界内」之后，越号之叩遂带着 止 一起陷）。
#
# 此是**真病复发**之防：昔年 行叩 之中那个「m.止 = false」正置于
# 「号在界内」之后，故越号之叩带着 L2 那个 止 一起陷进去——
# 陷虽成，机已止，变之处理器一字不得行。
# 它不报错，只是那一支**静静地不去**。故立此变异以守之。
try_mut "十七：债还迟了（越号则不止）" \
	's/\tm\.止 = false\n\n\t\/\/ 二、校号。/\t\/\/ 二、校号。/' \
	's/\tk\.记 = append\(k\.记, 枢记\{拍: k\.拍\(\),\n\t\t辞: fmt\.Sprintf\("%s，返 0o%06o（%s）",/\tm.止 = false\n\tk.记 = append(k.记, 枢记{拍: k.拍(),\n\t\t辞: fmt.Sprintf("%s，返 0o%06o（%s）",/'

# 十八、叩之号 取自 兑器 而非 乾器（叩之约：号 在 乾）。
#
# 叩之约散在两处（译卦器之 叩号 与枢之 乾器），若一处改一处不改，
# 则叩 号 全错，而错法极静：叩「出」遂成 叩「息」，程遂无声而终。
try_mut "十八：叩之号 取自兑器" \
	's/\t号 := m\.诸器\[乾器\]/\t号 := m.诸器[兑器] \/\/ 变异：叩之号 取自兑器/'

# 十九、叩 认错其来处（径以 枢态 入枢，化态之叩遂压栈而块不受其器）。
try_mut "十九：叩 认错其来处" \
	's/k\.入枢\(m\.计, 叩之表基\+号, 旧特权, k\.因, 由\)/k.入枢(m.计, 叩之表基+号, 枢态, k.因, 由)/'

# ══════════════════════════════════════════════════════════════
# 四、器区（十一）
# ══════════════════════════════════════════════════════════════

# 二十、器区之存 亦入藏（器区遂与寻常之藏无异，唯多一重副作用）。
try_mut "二十：器区之存 亦入藏" \
	's/\t\tif 是存 \{\n\t\t\tm\.诸字 = 旧字\n\t\t\tk\.器写\(址, 旧器\[取rd\(令\)\]\)/\t\tif 是存 {\n\t\t\tk.器写(址, 旧器[取rd(令)])/'

# 廿一、志之口 恒阴（枢遂不知可出与否）。
try_mut "廿一：志之口 恒阴" \
	's/\tcase 志之口:\n\t\treturn 1 \/\/ 恒可出/\tcase 志之口:\n\t\treturn 0 \/\/ 变异：恒阴/'

# 廿二、出之口 写而无所受（欲出之字弃于总线，串口一字不得）。
#
# 此变异**初版作「出之口 与 志之口 互易」**，其果是编译不过
# （志之口 遂有二支）——此具报「已杀」，然那不是案杀的，是**编译器**杀的。
#
# 一个靠编译不过而死的变异，什么也没验到：
# 它只证明「源码改坏了便编不过」，不证明「诸验分得出出与不出」。
# 编不过与「验到了」是两回事，而前者会把后者**盖过去**——
# 故此具对这一类另作标注（「非案杀之，须察」），此处则径改为纯语义之变异：
# append 一行易作「_ = 值」，编得过，而字已弃。
#
# 又：替换之文中的 & 须作 \&——在 perl 之替换侧，& 是「整个匹配」之义。
try_mut "廿二：出之口 写而无所受" \
