# 七、字之文与常数（三）
# ══════════════════════════════════════════════════════════════

# 四十三、字之文 只容 BMP（旧说「三字节之 UTF-8」复辟）。
#
# 三字节之 UTF-8 只到 U+FFFF，码位则不择（二十四位 ≥ 二十一位）。
# 此变异正落在分道之处：U+20000（𠀀）与 U+1F600 遂被当作「非字」。
# Test字之文 若只验 BMP 之内者，此变异便活——**瞎处须另立一验**。
try_mut "四十三：字之文 只容 BMP" \
	's/\tcase 字 > unicode\.MaxRune:/\tcase 字 > 0xFFFF:/'

# 四十四、变之数 差一（表有五槽而因有五个，此数若错则表溢出）。
try_mut "四十四：变之数 差一" \
	's/\t变之数  = 5/\t变之数  = 4/'

# 四十五、器口之数 不由簿数出（**凡手抄之单，必漏**）。
#
# 器口之数 若手书，则增一口而数不变——而那不变不报错，
# 只是演示之表少一行。故立 Test器口之簿 以量之：
# 所量者非其数，而是**其数与其簿相合否**。
try_mut "四十五：器口之数 不由簿出" \
	's/func 器口之数\(\) int \{ return len\(器口之簿\) \}/func 器口之数() int { return len(器口之簿) + 1 }/'

