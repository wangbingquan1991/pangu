# ---- 六、自检：此具**会**报「存活」否？ ----
#
# 上列诸检防的是「假绿」（器坏了，却说尽杀）。此检防的是另一种：
# 一个**只会说「已杀」**的器——它的沉默什么也不说明。
# 故末了注入一个无害变异（改一句注释）：诸验当仍全绿，而此具当报「存活」。
print -r -- ""
