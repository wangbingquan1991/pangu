#!/bin/zsh
# 变异测试之具：故意把 枢.go 改错，看诸验能否杀之。
# 一变异而诸验皆绿，则说明有处**验不到**——那才是真病。
#
# 用法（在仓库根，或在别处亦可——路是自算的）：
#     zsh 具/变异枢.sh
#
# ⚠ 一、须以 zsh 呼之。shebang 只在「直接执行」时生效，交给解释器时它不作数；
#      以 bash 呼之则此具会**静默地谎报「尽杀」**——详见 具/变异译.sh 之注。
# ⚠ 二、**跑之前先提交**。此具自愈之陷阱已设（EXIT/INT/TERM/HUP/PIPE 皆设），
#      然 git 是最后一道退路（`git checkout -- 枢.go`）。
#      无退路而自愈失手，则下一趟以「带变异之版」为原样，诸果皆废。
#
# ─────────────────────────────────────────────────────────────
# 何以枢须另立一具，而不并入 变异译.sh
#
# L2 之可信由 L1 逐拍对拍而来，L3 之上**再无 L4 可对其拍**。
# 故 L3 之可信只剩一条路：证明它什么也没做（Test枢与周期对拍），
# 加上——**量它自己新加的那三件事（特权、爻变、器区）验到了什么**。
#
# 「验到了什么」不能靠自陈。一个说「一切正常」的检查，
# 必须先证明它**分得出不正常**。故立此具，立七检：
#   〇、残留之检：上一趟若横死（SIGKILL），其遗毒当先清——详见其处之注。
#   一、起手之检：当下之 枢.go 须是干净的，否则所量者全是错的。
#   二、首之检：干净之 枢.go 全绿。
#   三、验数之检：包内实有之验 与 实跑之验 当同（有验未被跑则报）。
#   四、还原之检：每试之前先还原，收工之后校校验和。
#   五、尾之检：还原之后仍全绿。
#   六、自检：末了注入一个无害变异，此具**当报「存活」**——
#             一个只会说「已杀」的器，它的沉默什么也不说明。
#
# 变量名一律用 ASCII。非为媚 bash，而是**前一具曾因此坏过**。
# ─────────────────────────────────────────────────────────────
set -u

# 路自算：本具在 具/ 之下，仓库根是其上一级。
ROOT=${0:A:h:h}
cd "$ROOT" || exit 1

SRC=枢.go
# 备份与标记皆用**固定名**（不掺 $$）。其故见下「残留之检」：
# 名随进程而变，则新的一趟认不出上一趟的尸首；名固定，则一望而知。
BAK=${TMPDIR:-/tmp}/mut-shu-枢.go.bak
MARK=${TMPDIR:-/tmp}/mut-shu-枢.go.mark

# 跑**全部**测试，不择其名。其故见 具/变异译.sh 之 run：
# 手抄一张 -run 名单，名单漏掉的东西**不报错，只是不见了**。
run() { ./跑.sh test -count=1 ./... 2>&1; }
restore() { cp "$BAK" "$SRC"; }
sum() { cksum < "$SRC"; }

# 无论如何都要自愈：EXIT / INT / TERM / HUP / PIPE 皆置一陷阱。
# PIPE 之故：作者尝以 `zsh 具/变异译.sh | head -8` 观其首数行，
# head 读够即闭其管，脚本遂死于 SIGPIPE，死时源文件正带着一个变异。
cleanup() {
	if [[ -f "$BAK" ]]; then
		cp "$BAK" "$SRC"
		rm -f "$BAK"
	fi
	rm -f "$MARK"
}
trap cleanup EXIT INT TERM HUP PIPE

# ---- 残留之检：陷阱捕不得的那一类死法 ----
#
# 陷阱**只捕得住可捕之信号**。SIGKILL（kill -9，或超时被强杀）捕不得、
# 拦不住、不作数——进程无声而去，一个字也来不及收。
# 此具尝真死于其手：退出码 137（=128+9），$SRC 带着变异十一留在盘上，
# 而新的一趟全不知情，遂以那带病之版为「原样」，往后诸果皆废。
#
# 故不靠陷阱，靠**遗书**：每注一变异先落标记，收工方删。
# 起手时标记犹在 ⇒ 上一趟是横死的，其言不可信，其迹当清。
if [[ -f "$MARK" ]]; then
	print -r -- "【残留之检】⚠ 上一趟未收工（标记犹在）——是被 SIGKILL 者，或崩者。"
	print -r -- "            陷阱捕不得 SIGKILL，故以此记认之。上趟诸果**皆不可信**。"
	if [[ -f "$BAK" ]]; then
		cp "$BAK" "$SRC"
		print -r -- "            已自上趟之备份还原 $SRC（备份只可能是干净之版）。"
	else
		print -r -- "            ⚠ 备份竟不在！$SRC 今带何变异，无从得知——止，请自查 git。"
		exit 1
	fi
	rm -f "$MARK"
	print -r -- ""
fi

cp "$SRC" "$BAK" || exit 1
SUM0=$(sum)

# ---- 〇、起手之检 ----
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
	if ! git diff --quiet -- "$SRC" 2>/dev/null; then
		print -r -- "【起手之检】⚠ $SRC 有未提交之改动，此具将**以它为原样**。"
		print -r -- "            若它是上一趟跑坏而未还原的，则下列诸果皆不可信。"
		git diff --stat -- "$SRC" | sed 's/^/            /'
		print -r -- ""
	fi
fi

# ---- 一、首之检 ----
out=$(run)
if ! print -r -- "$out" | grep -q '^ok'; then
	print -r -- "【首之检】不过：干净之 $SRC 竟不绿。止。"
	print -r -- "$out" | grep -E 'FAIL|_test\.go:[0-9]+' | head -20
	exit 1
fi
print -r -- "【首之检】干净之 $SRC 全绿 ✓"

# ---- 三、验数之检 ----
验数=$(grep -hoE '^func Test[^ (]+' *_test.go | wc -l | tr -d ' ')
实跑=$(./跑.sh test -count=1 -v ./... 2>&1 | grep -cE '^--- (PASS|FAIL|SKIP)')
if [[ "$验数" -ne "$实跑" ]]; then
	print -r -- "【验数之检】⚠ 包内实有 $验数 验，实跑 $实跑 验——有验未被跑。"
	print -r -- "            未被跑之验杀不着任何变异，而此具**不会报**——它只报「存活」。"
else
	print -r -- "【验数之检】$实跑 验皆跑 ✓"
fi
print -r -- ""

# ---- 试一变异 ----
# 用法：try_mut <名> <perl 式> [更多 perl 式…]
try_mut() {
	local name="$1"; shift
	local expr before after out who
	restore                      # 四、还原之检（置前）：起点必干净
	before=$(sum)
	: > "$MARK"                  # 落遗书：此刻起，$SRC 是**带病**的
	for expr in "$@"; do
		perl -0pi -e "$expr" "$SRC"
	done
	after=$(sum)

	printf '%-34s' "$name"
	if [[ "$before" == "$after" ]]; then
		print -r -- "变异未注入 ✗（式已不合，须改式，勿以「已杀」饰之）"
		rm -f "$MARK"
		return
	fi

	out=$(run)
	rm -f "$MARK"                # 病已除，遗书可销
	if print -r -- "$out" | grep -q '^ok'; then
		print -r -- "存活 ✗（有处验不到，须查明）"
	else
		who=$(print -r -- "$out" | grep -oE -- '--- FAIL: [^ ]+' | head -1 | sed 's/--- FAIL: //')
		if [[ -z "$who" ]]; then
			print -r -- "已杀 ✓  （编译不过或崩，非案杀之，须察）"
		else
			print -r -- "已杀 ✓  ${who}"
		fi
	fi
}

# ══════════════════════════════════════════════════════════════
# 一、特权
# ══════════════════════════════════════════════════════════════

# 一、取指之检 判反特权：化态 取指入枢之域而不检。
try_mut "一：取指之检 判反特权" \
	's/if 旧相 == 0 \&\& 旧特权 == 化态 \&\& 是枢之域\(m\.计\)/if 旧相 == 0 \&\& 旧特权 == 枢态 \&\& 是枢之域(m.计)/'

# 二、特权之令 化态行之而不陷（径行 降化/回）。
try_mut "二：特权之令 化态不陷" \
	's/\tif 特权之令\[码\] \{\n\t\tif 旧特权 == 化态 \{/\tif 特权之令[码] {\n\t\tif 旧特权 == 枢态 {/'

# 三、化之极 差一（枢基 之上一字遂成化之域，化态可触）。
#
# 是枢之域 由 化之极 出而不由 枢基 出，正是为此：
# 由因出果，则此一改立红；由果抄果，则两处皆可独改而无声。
try_mut "三：化之极 差一" \
	's/\t化之极 = 枢基/\t化之极 = 枢基 + 1/'

# 四、降化 不忘其特权（降而不降权，用户程遂以枢态跑下去）。
try_mut "四：降化 不忘其特权" \
	's/\tcase 降化:\n\t\t\/\/ 降化：指定其往。特权 ← 化态，计 ← 丙型之址。\n\t\tk\.特权 = 化态/\tcase 降化:\n\t\t\/\/ 降化：指定其往。特权 ← 化态，计 ← 丙型之址。/'

# 五、回 不忘其特权（回而不降权）。
#
# 此变异最险：特权一旦漏出去，此后的每一次存取都不再受检，
# 而机器一声不响。**特权之漏，是最静的一种错。**
try_mut "五：回 不忘其特权" \
	's/\tcase 回:\n\t\t\/\/ 回：返其来处。特权 ← 化态，计 ← 存计。\n\t\tk\.特权 = 化态/\tcase 回:\n\t\t\/\/ 回：返其来处。特权 ← 化态，计 ← 存计。/'

# ══════════════════════════════════════════════════════════════
# 二、爻变
# ══════════════════════════════════════════════════════════════

# 六、越权之写 不撤（越权虽陷，其字已入藏）。
try_mut "六：越权之写 不撤" \
	's/\t\tif 是存 \{\n\t\t\tm\.诸字 = 旧字 \/\/ 撤其写入/\t\tif 是存 {\n\t\t\t_ = 旧字 \/\/ 不撤/'

# 七、越权之读 不撤（越权虽陷，其值已入器——那值是偷来的）。
try_mut "七：越权之读 不撤" \
	's/\t\t\} else \{\n\t\t\tm\.诸器 = 旧器 \/\/ 撤其读回/\t\t} else {\n\t\t\t_ = 旧器 \/\/ 不撤/'

# 八、未定之码 不陷。
try_mut "八：未定之码 不陷" \
	's/\tif 取型\(码\) == 未定型 \{\n\t\tk\.陷\(越令之变, m\.计,\n\t\t\tfmt\.Sprintf\("未定之码 0o%02o（%s）", 码, 别卦符\(码\)\)\)\n\t\treturn\n\t\}\n//'

# 九、变之表 之槽差一（越权之变 遂跳去 变越令）。
try_mut "九：变之表 之槽差一" \
	's/m\.计, m\.相, m\.令 = 变之表基\+int\(因\), 0, 0/m.计, m.相, m.令 = 变之表基+int(因)+1, 0, 0/'

# 十、陷 不记其因（因 恒留初值，诸变遂不可辨）。
try_mut "十：陷 不记其因" \
	's/\tk\.存计, k\.因, k\.特权 = 存计, 因, 枢态/\tk.存计, k.特权 = 存计, 枢态/'

# 十一、陷 之来处记错一字（回 将返于叩之自身，遂成死循环）。
try_mut "十一：存计 忘其自增" \
	's/\tk\.存计, k\.特权 = m\.计, 枢态/\tk.存计, k.特权 = m.计-1, 枢态/'

# 十二、枢态之变 不轰（存计 将覆而不止，回 遂不知返于何所）。
try_mut "十二：枢态之变 不轰" \
	's/\tif k\.特权 == 枢态 \{\n\t\tk\.轰\(fmt\.Sprintf\("%s（枢态之变，无可救）", 由\)\)\n\t\treturn\n\t\}\n//'

# 十三、轰 不置其止（轰而不止，机继续跑下去）。
try_mut "十三：轰 不置其止" \
	's/\tk\.机\.止 = true\n\tk\.轰否, k\.轰由 = true, 由/\tk.轰否, k.轰由 = true, 由/'

# ══════════════════════════════════════════════════════════════
# 三、叩
# ══════════════════════════════════════════════════════════════

# 十四、叩 不升其特权（服务例程遂以化态跑，一取指便陷）。
try_mut "十四：叩 不升其特权" \
	's/\tk\.存计, k\.特权 = m\.计, 枢态/\tk.存计 = m.计/'

# 十五、叩 不校其号（越号者遂乱跃于叩之表之中）。
try_mut "十五：叩 不校其号" \
	's/\tif 号 < 0 \|\| 号 >= 叩号数 \{\n\t\tk\.陷\(越号之变, m\.计,\n\t\t\tfmt\.Sprintf\("叩号 %d 越出 0\.\.%d", 号, 叩号数-1\)\)\n\t\treturn\n\t\}\n//'

# 十六、叩之表 之槽差一（叩「出」遂跃入 叩「言」）。
try_mut "十六：叩之表 之槽差一" \
	's/m\.计, m\.相, m\.令 = 叩之表基\+号, 0, 0/m.计, m.相, m.令 = 叩之表基+号+1, 0, 0/'

# 十七、枢态行叩 不轰（存计 将覆而不止）。
try_mut "十七：枢态行叩 不轰" \
	's/\tif 旧特权 == 枢态 \{\n\t\t\/\/ 枢态 行 叩，其存计将覆——见 轰 之注。\n\t\tk\.轰\(fmt\.Sprintf\("枢态行 叩（号 %d「%s」）：存计 将覆，故不许", 号, 名\)\)\n\t\treturn\n\t\}\n//'

# 十八、还 M3 之债 还迟了（置于「号在界内」之后，越号之叩遂带着 止 一起陷）。
#
# 此是**真病复发**之防：昔年 行叩 之中那个「m.止 = false」正置于
# 「号在界内」之后，故越号之叩带着 L2 那个 止 一起陷进去——
# 陷虽成，机已止，变之处理器一字不得行。
# 它不报错，只是那一支**静静地不去**。故立此变异以守之。
try_mut "十八：债还迟了（越号则不止）" \
	's/\tm\.止 = false\n\n\t\/\/ 二、校权。/\t\/\/ 二、校权。/' \
	's/\tk\.存计, k\.特权 = m\.计, 枢态\n\tm\.计, m\.相, m\.令 = 叩之表基\+号, 0, 0/\tk.存计, k.特权 = m.计, 枢态\n\tm.计, m.相, m.令, m.止 = 叩之表基+号, 0, 0, false/'

# ══════════════════════════════════════════════════════════════
# 四、器区
# ══════════════════════════════════════════════════════════════

# 十九、器区之存 亦入藏（器区遂与寻常之藏无异，唯多一重副作用）。
try_mut "十九：器区之存 亦入藏" \
	's/\t\tif 是存 \{\n\t\t\tm\.诸字 = 旧字\n\t\t\tk\.器写\(址, 旧器\[取rd\(令\)\]\)/\t\tif 是存 {\n\t\t\tk.器写(址, 旧器[取rd(令)])/'

# 二十、志之口 恒阴（枢遂不知可出与否）。
try_mut "二十：志之口 恒阴" \
	's/\tcase 志之口:\n\t\treturn 1 \/\/ 恒可出/\tcase 志之口:\n\t\treturn 0 \/\/ 恒可出/'

# 二十一、出之口 与 志之口 互易（欲出者遂入只读之口，无物受之）。
try_mut "廿一：出之口 误为只读" \
	's/\tcase 出之口:\n\t\tk\.串口\.出 = append/\tcase 出之口:\n\t\t_ = 0\n\tcase 志之口:\n\t\tk.串口.出 = append/'

# 二十二、器之数 差一（器区遂不终于藏之极）。
try_mut "廿二：器之数 差一" \
	's/\t器之数 = 8/\t器之数 = 7/'

# 二十三、器区之判 用 枢基 而不由 化之极（旧病：由果抄果）。
try_mut "廿三：器区之界 不由化之极" \
	's/func 是器区\(址 int\) bool \{ return 址 >= 器基 \&\& 址 < 器基\+器之数 \}/func 是器区(址 int) bool { return 址 >= 器基 - 1 \&\& 址 < 器基+器之数 }/'

# ══════════════════════════════════════════════════════════════
# 五、字之文
# ══════════════════════════════════════════════════════════════

# 二十四、字之文 只容 BMP（旧说「三字节之 UTF-8」复辟）。
#
# 三字节之 UTF-8 只到 U+FFFF，码位则不择（二十四位 ≥ 二十一位）。
# 此变异正落在分道之处：U+20000（𠀀）与 U+1F600 遂被当作「非字」。
# Test字之文 若只验 BMP 之内者，此变异便活——**瞎处须另立一验**。
try_mut "廿四：字之文 只容 BMP" \
	's/\tcase 字 > unicode\.MaxRune:/\tcase 字 > 0xFFFF:/'

# 二十五、变之数 与 变之因之众 不相干（表有三槽而因只有三个，此数若错则表溢出）。
try_mut "廿五：变之数 差一" \
	's/\t变之数  = 3/\t变之数  = 2/'

print -r -- ""

# ---- 四、还原之检（收工） ----
restore
SUM1=$(sum)
if [[ "$SUM0" != "$SUM1" ]]; then
	print -r -- "【还原之检】不过：收工之 $SRC 与原样不符，止。切勿再信上列诸果。"
	exit 1
fi
print -r -- "【还原之检】$SRC 已复原样，校验和相符 ✓"

# ---- 五、尾之检 ----
out=$(run)
if print -r -- "$out" | grep -q '^ok'; then
	print -r -- "【尾之检】还原之后全绿 ✓"
else
	print -r -- "【尾之检】不过：还原之后竟不绿。止。"
	print -r -- "$out" | grep -E 'FAIL|_test\.go:[0-9]+' | head -20
	restore
	rm -f "$BAK"
	exit 1
fi

# ---- 六、自检：此具**会**报「存活」否？ ----
#
# 上列诸检防的是「假绿」（器坏了，却说尽杀）。此检防的是另一种：
# 一个**只会说「已杀」**的器——它的沉默什么也不说明。
# 故末了注入一个无害变异（改一句注释）：诸验当仍全绿，而此具当报「存活」。
print -r -- ""
before=$(sum)
: > "$MARK"
perl -0pi -e 's/^package 盘古/package 盘古 \/\/ 自检/' "$SRC"
after=$(sum)
if [[ "$before" == "$after" ]]; then
	print -r -- "【自检】不过：无害变异未注入，式已不合。止。"
	restore
	rm -f "$BAK" "$MARK"
	exit 1
fi
out=$(run)
rm -f "$MARK"
if print -r -- "$out" | grep -q '^ok'; then
	print -r -- "【自检】无害变异（改一句注释）→ 报「存活」✓"
	print -r -- "        此具分得出不正常——故上列「已杀」诸条，是可信的"
else
	print -r -- "【自检】不过：无害变异竟被杀，此具或验错了对象。止。"
fi
restore
rm -f "$BAK" "$MARK"
