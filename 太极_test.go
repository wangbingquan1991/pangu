// ==================================================================
// 太极之验
//
// 门级模拟器之验，与寻常程序之验有三大不同，故先言之：
//
// 一、**慢。** 一拍须令三万余门重算至定，约四毫秒。故诸验不可穷举，
//     只能取样；穷举之事俟 周期.go（L2，纯整数，快万倍）为之，
//     再以 对拍 验二者不悖。
//
// 二、**不可复读。** 读一器之值即是读一组线之电平，无副作用；
//     然**写**须一拍辰，而拍辰则全机进退一格。故欲改机器之态，
//     唯有写机器码而跑之——没有「直接给寄存器赋值」的捷径。
//
// 三、**错则无声。** 接错一根线，机器照跑，只是算错了数。
//     故每一验皆须与一个**独立算出**的参照值相对，
//     而参照式不可抄被测之身（典/02 有前车）。
// ==================================================================

// 建太极机 造一部太极，藏之地址位数为 址。
func 建太极机(t *testing.T, 址 int) *太极 {
	t.Helper()
	return 建网表(fmt.Sprintf("太极%d", 址)).置太极(址)
}

// 重装 复位而后装载，使一机可反复用于诸验（造一次网表，验许多回）。
func 重装(t *testing.T, m *太极, 诸令 []int) {
	t.Helper()
	if len(诸令) > m.藏.字 {
		t.Fatalf("诸令 %d 字溢于藏之 %d 字", len(诸令), m.藏.字)
	}
	if err := m.重置并装载(诸令); err != nil {
		t.Fatalf("重置并装载：%v", err)
	}
}

// 跑毕 跑至停机，回所拍之数。
func 跑毕(t *testing.T, m *太极, 诸令 []int) int {
	t.Helper()
	拍, err := m.跑(4000)
	if err != nil {
		t.Fatalf("%v\n%s", err, 印令(诸令))
	}
	if !m.止否() {
		t.Fatalf("跑毕之后 止 当为阳\n%s", 印令(诸令))
	}
	return 拍
}

// 载常 造一段把常数 v 置入 器 的机器码。v 可为任意二十四位之值。
//
// 三途，视其形而定：
//
//	0..2047          一 加数 可了（加数 符号扩展，故 2048..4095 不可用之，
//	                 用之则 4095 进门成了 -1——此病作者犯过，故志之）
//	低十二位全阴者     一 载高 可了
//	其余              载高 置其高，并数 补其低（并数 零扩展，故可行）
//
// 器 不可为坤——坤恒为零，写入被吞。
func 载常(器, v int) []int {
	if 器 <= 0 || 器 >= 8 {
		panic(越界("载常之器", 器, 1, 7))
	}
	u := v & 字掩
	if u <= (数掩 >> 1) {
		return []int{编乙(数操(加), 器, 0, u)}
	}
	if (u & 数掩) == 0 {
		return []int{编乙(载高, 器, 0, u>>数位)}
	}
	return []int{
		编乙(载高, 器, 0, u>>数位),
		编乙(数操(并), 器, 器, u&数掩),
	}
}

// 偏码 以一有符号之偏移，编成乙型之立即数域。
//
// 负偏移须自行取其十二位之补，不可径写 数掩 − n ——
// 盖 -1 之域是 0xFFF（= 数掩），而 数掩 − 1 是 0xFFE，所表者乃是 -2。
// 差之毫厘，谬以一字。
func 偏码(n int) int { return n & 数掩 }

// 参照操 以 Go 原生算出 甲 操 乙 之果，供诸验作参照。
//
// 此式必自二之补之第一义写出，不可抄 算术.go 之电路——
// 抄则同错同对，验之何益。
func 参照操(o 算爻之操, 甲, 乙 int) int {
	甲 &= 字掩
	乙 &= 字掩
	switch o {
	case 加:
		return 截字(甲 + 乙)
	case 减:
		return 截字(甲 - 乙)
	case 交:
		return 甲 & 乙
	case 并:
		return 甲 | 乙
	case 殊:
		return 甲 ^ 乙
	case 升:
		return 截字(甲 << 1)
	case 降:
		return 甲 >> 1
	case 较:
		if 补之(甲) < 补之(乙) {
			return 1
		}
		return 0
	}
	panic(越界("参照操", int(o), 0, 7))
}

// 数之元 依扩展之约，算出 数版 指令之第二操作数。
//
// 此即 令.go 之 用符号 在参照式中的化身：加、减、较 符号扩展，
// 交、并、殊 零扩展，存取恒符号。器版之 乙 是二十四位之全值，
// 数版之 乙 只是十二位之域——二者**本就不必相等**，
// 如 交数 0xFFF 是 0x000FFF，而 器版之 -1 是 0xFFFFFF。
func 数之元(码, 数 int) int {
	if 用符号(码) {
		return 截字(符号扩(数&数掩, 数位))
	}
	return 数 & 数掩
}

