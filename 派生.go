package 盘古

import "fmt"

// ==================================================================
// 派生 · 万门出于一
//
// 此文件中只有 与非门 一种是真正的原语。非、与、或、或非、异或、同或、
// 二择一之择门、多入之全与门与全或门、以及译门，皆由与非门叠累而成。
//
// 网表_测试.go 中有一道「纯粹」之验：断言诸般电路落成之后，
// 网表之中除 与非门 外别无他种原语。此验一破，便是有人偷用了别的门。
// ==================================================================

// 与非门 唯一的原语。与门之后取反。
type 与非门 struct {
	甲 *线
	乙 *线
	出 *线
}

// 名 门之名。
func (g *与非门) 名() string { return "与非" }

// 入线 甲与乙。
func (g *与非门) 入线() []*线 { return []*线{g.甲, g.乙} }

// 出线 唯一之出。
func (g *与非门) 出线() []*线 { return []*线{g.出} }

// 算 甲与乙皆阳则出阴，否则出阳。
func (g *与非门) 算() { g.出.新值 = g.甲.值.与非(g.乙.值) }

// 置与非门 装一与非门。
func (n *网表) 置与非门(甲, 乙, 出 *线) *与非门 {
	return n.装门(&与非门{甲: 甲, 乙: 乙, 出: 出}).(*与非门)
}

// 置非门 反相器。一与非门两入并一即得。
func (n *网表) 置非门(入, 出 *线) {
	n.置与非门(入, 入, 出)
}

// 置继门 缓冲。两非相叠，值不变而势加厚，亦用于接续一根线。
func (n *网表) 置继门(入, 出 *线) {
	中 := n.私线()
	n.置非门(入, 中)
	n.置非门(中, 出)
}

// 置与门 与门。与非之后取反，二与非而成。
func (n *网表) 置与门(甲, 乙, 出 *线) {
	中 := n.私线()
	n.置与非门(甲, 乙, 中)
	n.置非门(中, 出)
}

// 置或门 或门。依德摩根之律，甲或乙 即 非（非甲 与 非乙），三与非而成。
func (n *网表) 置或门(甲, 乙, 出 *线) {
	非甲 := n.私线()
	非乙 := n.私线()
	n.置非门(甲, 非甲)
	n.置非门(乙, 非乙)
	n.置与非门(非甲, 非乙, 出)
}

// 置或非门 或非。或门之后取反。
func (n *网表) 置或非门(甲, 乙, 出 *线) {
	中 := n.私线()
	n.置或门(甲, 乙, 中)
	n.置非门(中, 出)
}

// 置异或门 异或。四与非而成：
//
//	中 = 甲 与非 乙
//	出 = （甲 与非 中） 与非 （乙 与非 中）
func (n *网表) 置异或门(甲, 乙, 出 *线) {
	中 := n.私线()
	甲中 := n.私线()
	乙中 := n.私线()
	n.置与非门(甲, 乙, 中)
	n.置与非门(甲, 中, 甲中)
	n.置与非门(乙, 中, 乙中)
	n.置与非门(甲中, 乙中, 出)
}

// 置同或门 同或。异或之后取反。
func (n *网表) 置同或门(甲, 乙, 出 *线) {
	中 := n.私线()
	n.置异或门(甲, 乙, 中)
	n.置非门(中, 出)
}

// 置择门 二择一多路器。择为阴则出从甲，择为阳则出从乙。
func (n *网表) 置择门(择, 甲, 乙, 出 *线) {
	非择 := n.私线()
	取甲 := n.私线()
	取乙 := n.私线()
	n.置非门(择, 非择)
	n.置与门(甲, 非择, 取甲)
	n.置与门(乙, 择, 取乙)
	n.置或门(取甲, 取乙, 出)
}

// 置全与门 多入与门，由二入与门级联而成。至少须有一根入线。
func (n *网表) 置全与门(众 []*线, 出 *线) {
	if len(众) == 0 {
		panic("置全与门：须至少一根入线")
	}
	当前 := 众[0]
	for _, w := range 众[1:] {
		次 := n.私线()
		n.置与门(当前, w, 次)
		当前 = 次
	}
	n.置继门(当前, 出)
}

// 置全或门 多入或门，由二入或门级联而成。至少须有一根入线。
func (n *网表) 置全或门(众 []*线, 出 *线) {
	if len(众) == 0 {
		panic("置全或门：须至少一根入线")
	}
	当前 := 众[0]
	for _, w := range 众[1:] {
		次 := n.私线()
		n.置或门(当前, w, 次)
		当前 = 次
	}
	n.置继门(当前, 出)
}

// 置全异或门 多入异或门，又称奇偶门。入线之中阳爻为奇数则出阳。
func (n *网表) 置全异或门(众 []*线, 出 *线) {
	if len(众) == 0 {
		panic("置全异或门：须至少一根入线")
	}
	当前 := 众[0]
	for _, w := range 众[1:] {
		次 := n.私线()
		n.置异或门(当前, w, 次)
		当前 = 次
	}
	n.置继门(当前, 出)
}

// 置译门 n 位译码器。
//
// 众 为入线，众[0] 权重最低（2^0），依数值位序。
// 出 须有 2^n 根；出[i] 当且仅当 众 所成之数恰为 i 时为阳。
func (n *网表) 置译门(众 []*线, 出 []*线) {
	k := len(众)
	if k == 0 || k > 12 {
		panic(fmt.Sprintf("置译门：入线 %d 根，须在 1..12 之间", k))
	}
	if len(出) != 1<<k {
		panic(fmt.Sprintf("置译门：入线 %d 根，出线须 %d 根，实得 %d 根", k, 1<<k, len(出)))
	}
	// 各入线的反相只备一次，供诸出线共用。
	反 := make([]*线, k)
	for i, w := range 众 {
		反[i] = n.私线()
		n.置非门(w, 反[i])
	}
	for i := range 出 {
		项 := make([]*线, k)
		for b := 0; b < k; b++ {
			if i>>b&1 == 1 {
				项[b] = 众[b]
			} else {
				项[b] = 反[b]
			}
		}
		n.置全与门(项, 出[i])
	}
}
