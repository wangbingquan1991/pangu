// 程.go 手编之机器码。
//
// 此文件所载者，是一段段**人手写出**的二十四位机器码——
// 在译卦器（汇编器）出来之前，这是本机唯一的「程序」。
// 每一条指令都是用 编甲/编乙/编丙 三个函拼出来的，
// 其右侧之注，便是它的汇编文字；反汇编之辞由 令之辞 生出，
// 故注与实码若不相符，印令 一照即现。
//
// 之所以另立一文件而不附于 令_test.go：
// 演示（演示.go）不是测试，而 Go 的 _test.go 只在 go test 之下编译，
// 演示.go 无从引用其中的标识符。程序不是测试的私产，
// 它是本机的公产——机器与演示与测试，三者共用之。
//
// 之所以不附于 令.go：令.go 是**规范**，此文件是**用例**。
// 规范说「令该长成什么样」，用例说「用它能写出什么」。
// 二者混居，则改一例而疑其规，非所宜也。

// 斐波那契之令 手编之斐波那契机器码，十一字。
//
// 艮 为计数，坎、巽 为相邻之二数，震 为暂存，离 为结果。
// 收敛之后 离 = fib(10) = 55。
//
// 偏移皆相对量：等跃 执行之时 计 已为四，故 偏 5 即跳至第九字。
// 全程序不涉绝对地址（除末之 跃 3），遂为位置无关。
//
// 此十一字是 典/04 为 M3 所定验收之的：
// 「跑通一段手写的 24 位机器码（如计算斐波那契），L1 与 L2 结果一致」。
// 太极（L1）、周期（L2）、对拍，三验皆以它为之。
func 斐波那契之令() []int {
	return []int{
		编乙(数操(加), 1, 0, 10),   // 0  加数 艮, 坤, 10   艮 = 10
		编乙(数操(加), 2, 0, 0),    // 1  加数 坎, 坤, 0    坎 = 0
		编乙(数操(加), 3, 0, 1),    // 2  加数 巽, 坤, 1    巽 = 1
		编甲(等跃, 0, 1, 0, 5),    // 3  等跃 坤, 艮, 坤, +5  若 艮==0 则跃至 9
		编甲(器操(加), 4, 2, 3, 0), // 4  加 震, 坎, 巽     震 = 坎 + 巽
		编甲(器操(加), 2, 3, 0, 0), // 5  加 坎, 巽, 坤     坎 = 巽
		编甲(器操(加), 3, 4, 0, 0), // 6  加 巽, 震, 坤     巽 = 震
		编乙(数操(减), 1, 1, 1),    // 7  减数 艮, 艮, 1    艮 = 艮 - 1
		编丙(跃, 3),              // 8  跃 3
		编甲(器操(加), 5, 2, 0, 0), // 9  加 离, 坎, 坤     离 = 坎
		编丙(停机, 0),             // 10 停机
	}
}

// 存取之令 专测存取与载高之机器码，七字。
//
// 收敛之后：藏[12] = 7，震 = 7，巽 = 0x00ABCD。
//
// 数据之址取 12 而不取 20：本程序占 0..6，故址 ≥ 7 即不相犯；
// 取 12 则此程序可容于十六字之藏（址 4），太极之诸验遂得用小藏，
// 门数减半而验之速倍之。
func 存取之令() []int {
	return []int{
		编乙(数操(加), 1, 0, 12),    // 0  加数 艮, 坤, 12     艮 = 12（基址）
		编乙(数操(加), 2, 0, 7),     // 1  加数 坎, 坤, 7      坎 = 7
		编乙(存字, 2, 1, 0),        // 2  存字 坎, [艮 + 0]   藏[12] ← 7
		编乙(载字, 4, 1, 0),        // 3  载字 震, [艮 + 0]   震 ← 藏[12]
		编乙(载高, 3, 0, 0x00A),    // 4  载高 巽, 0x00A      巽 = 0x00A000
		编乙(数操(并), 3, 3, 0xBCD), // 5  并数 巽, 巽, 0xBCD  巽 = 0x00ABCD
		编丙(停机, 0),              // 6  停机
	}
}

// 累加之令 一匝 N 次之循环，累加 1..N。L1 跑不动，唯 L2 可。
//
// N 须能容于 加数 之十二位有符号立即数（0..2047），
// 否则 载常 出二字，址 4 之负偏 −3 便指错了地方。
func 累加之令(N int) []int {
	if N <= 0 || N > (数掩>>1) {
		panic(越界("累加之令之 N", N, 1, 数掩>>1))
	}
	return []int{
		编乙(数操(加), 1, 0, N),      // 0  艮 = N
		编乙(数操(加), 4, 0, 0),      // 1  震 = 0
		编甲(器操(加), 4, 4, 1, 0),   // 2  震 += 艮
		编乙(数操(减), 1, 1, 1),      // 3  艮 -= 1
		编甲(异跃, 0, 1, 0, 偏码(-3)), // 4  艮 != 0 → 5-3 = 2
		编丙(停机, 0),               // 5  停机
	}
}

// 偏码 把一个可能带负号的小整数，写成十二位之补码样。
//
// 此函之要，在破一个极易犯的想当然：−1 的十二位样是 0xFFF，
// 亦即是 数掩 本身，而非 数掩 − 1。数掩 − 1 是 −2。
// 凡手写负数偏移、负数立即数，皆当过此函，不可自减。
func 偏码(n int) int { return n & 数掩 }

// 斐波那契之数 以 Go 原生算出 fib(n)，供诸验作参照。
//
// 此参照不由本机算出，故不 contaminated：本机若算错，必与此不合。
func 斐波那契之数(n int) int {
	a, b := 0, 1
	for i := 0; i < n; i++ {
		a, b = b, a+b
	}
	return a
}

// 印令 一列机器码之反汇编，供诊断。
func 印令(诸令 []int) string {
	var b strings.Builder
	for i, 令 := range 诸令 {
		fmt.Fprintf(&b, "%2d │ %s │ %s\n", i, 字之卦(令), 令之辞(令))
	}
	return b.String()
}

// 印诸器 一记八器之值，六位八进制，供迹。
func 印诸器(诸 [8]int) string {
	var b strings.Builder
	for i := 0; i < 8; i++ {
		if i > 0 {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "%06o", 诸[i]&字掩)
	}
	return b.String()
}
