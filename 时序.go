package 盘古

import "fmt"

// ==================================================================
// 时序 · 八卦之序
//
// 前此一切皆是组合之电路：入变则出随，无所记忆，过而不留。
// 一入一出之间，电路不知自己刚才是什么——故不能计数，不能寻址，
// 不能成机。
//
// 时序之要，在乎**反馈**：以出为入，首尾相衔，使电路得以自持其一态。
// 两枚与非门交相为入，便记住了一爻。此即锁爻器。
//
// 然光有记忆犹未足。何时记、记什么，须有一个统一的号令，
// 否则诸器各记其时，全机遂乱。此号令即**辰**。
//
// ============================ 时序之约 ============================
//
// 本模拟器不建传播延迟之模型——一线的负载何时重算，只看事件之序，
// 不看时间。如此则有一问：无延迟之时序，主从触发器还能正确否？
//
// 能。其理如下。
//
// 主从者，前级（主）以 反辰 为启，后级（从）以 辰 为启。
// 辰 为阴时，主透明而纳 入，从守；辰 转为阳时，主守而存其所得，
// 从透明而纳主之所存。故有效之沿者，辰 由阴转阳之顷也。
//
// 关键的竞争在于：辰 既转阳，从已开，而 反辰 尚未及变，
// 主犹透明。此时若有 入 的变化漏过主而达于从，则所见非沿前之值。
//
// 但只要**入 在辰翻转之顷稳定不变**，主纵透明，其所存者仍是那个
// 沿前之值，从所纳者亦仍是它——竞争虽在，结果无差。
//
// 此即真实电路中的**建立时间与保持时间**。本模拟器把它写成了
// 一条使用之约，而非电路之律：
//
//	凡欲写某器，须先置其入、置其存允，待调定已安，方可拍辰。
//	拍辰之后，方可更其入。
//
// 违此约者，未必立错，然错则无声——故本文件中的 置存爻器、
// 卦器堆、藏 皆按此约使用，测试亦按此约而写。
// ==================================================================

// ------------------------------------------------------------------
// 辰 · 时序之枢
// ------------------------------------------------------------------

// 辰 时钟。
//
// 辰非电路，乃**驱动之约**：一根无驱者之线，由网表之外拨动，
// 每拨一次便调定一次，待全电路安定之后再拨。
//
// 上升之沿为有效之沿：诸边锁爻器皆于辰由阴转阳之顷纳其入。
type 辰 struct {
	网  *网表
	线  *线
	拍数 int // 已拍之数
}

// 置辰线 造一根名为「辰」的线，无驱者，待外力拨之。其初值为阴。
func (n *网表) 置辰线() *线 { return n.引线("辰") }

// 建辰 以某线为辰。
func 建辰(n *网表, 线 *线) *辰 { return &辰{网: n, 线: 线} }

// 现 辰之现值。
func (c *辰) 现() 爻 { return c.线.值 }

// 置 拨辰至某爻，并调定至安定。
func (c *辰) 置(y 爻) error {
	c.网.驱动(c.线, y)
	return c.网.调定(0)
}

// 起 辰由阴转阳。此即有效之沿。
func (c *辰) 起() error { return c.置(阳) }

// 伏 辰由阳转阴。
func (c *辰) 伏() error { return c.置(阴) }

// 拍 辰之一拍：先伏后起。起处即有效之沿。
//
// 一拍之中，诸寄存器先于伏时敞开其主而纳新，后于起时合主开从而
// 锁定新值。故一拍即「全机齐进一格」。
func (c *辰) 拍() error {
	if err := c.伏(); err != nil {
		return err
	}
	c.拍数++
	return c.起()
}

// 复位 以总复之轨清诸寄存器，须拍辰方能见效。
//
// 复为阳而拍一记，则凡经 置存爻器 所造之器尽归于阴。
// 此乃上电定初值之法。
func (c *辰) 复位() error {
	复 := c.网.总复()
	c.网.驱动(复, 阳)
	if err := c.拍(); err != nil {
		return err
	}
	c.网.驱动(复, 阴)
	return c.网.调定(0)
}

// ------------------------------------------------------------------
// 锁爻器 · 记忆之始
// ------------------------------------------------------------------

// 置锁爻器 门控 D 锁存器。启为阳则**透明**（出随入），启为阴则**守**（出不变）。
//
//	置端 = 入 与非 启      低有效之置位
//	清端 = （非 入） 与非 启  低有效之清零
//	出   = 置端 与非 反出
//	反出 = 清端 与非 出
//
// 启为阴时，置端、清端皆阳，两枚与非门互以对方的出为入，
// 遂成自持之环——这便是「记得」。启为阳时，环被打破，出乃随入。
//
// 反出 可为 nil，则内部自取一私线。
//
// 凡五与非门。
func (n *网表) 置锁爻器(入, 启, 出, 反出 *线) {
	非入 := n.私线()
	n.置非门(入, 非入)

	置端 := n.私线()
	清端 := n.私线()
	n.置与非门(入, 启, 置端)
	n.置与非门(非入, 启, 清端)

	if 反出 == nil {
		反出 = n.私线()
	}
	n.置与非门(置端, 反出, 出)
	n.置与非门(清端, 出, 反出)
}

// 置边锁爻器 主从上升沿 D 触发器。
//
// 主以 反辰 为启，从以 辰 为启。辰阴则主纳 入、从守；
// 辰转阳则主守其所纳、从纳主之所存。故出之变，唯在上升之沿。
//
// 十或十一与非门（反辰 由网表共用，多处只造一次）。
func (n *网表) 置边锁爻器(入, 辰 *线, 出 *线) {
	反辰 := n.反相(辰)
	主出 := n.私线()
	n.置锁爻器(入, 反辰, 主出, nil)
	n.置锁爻器(主出, 辰, 出, nil)
}

// 置存爻器 n 位寄存器：存允 为阳，则于辰之上升沿纳 入；否则守其旧。
//
// 写法是「以出为入」的反馈，而非门控时钟：
//
//	所存 = 存允 ? 入 : 出
//	所存 &= 非 总复
//
// 之所以不取「以存允去与辰，各器自生其时钟」的门控之术，
// 是因为那样做则各器之时钟有别，先后参差（时钟偏移），
// 快者已纳而慢者未及，一拍之内诸器遂不齐。
// 今诸器共用一根辰，存允 只择其入，则一拍之下万器齐进——
// 纵在本模拟器无延迟之模型中此弊不显，此约亦当立，
// 盖它要防的是将来真机上的偏移，不是今日模拟里的错。
func (n *网表) 置存爻器(入 []*线, 存允, 辰 *线, 出 []*线) {
	k := len(入)
	if len(出) != k {
		panic("置存爻器：出入之数须相若")
	}
	if k == 0 {
		panic("置存爻器：位数不可为零")
	}
	非复 := n.反相(n.总复())
	for i := 0; i < k; i++ {
		择存 := n.私线()
		n.置择门(存允, 出[i], 入[i], 择存)
		所存 := n.私线()
		n.置与门(择存, 非复, 所存)
		n.置边锁爻器(所存, 辰, 出[i])
	}
}

// ------------------------------------------------------------------
// 卦器堆 · 八器以八卦为名
// ------------------------------------------------------------------

// 卦器堆 八个 n 位寄存器，以八卦为名。
//
// 号 三爻以择其一——三位正合一卦之数，此即「以卦择器」。
// 两个读端口（甲、乙）可同时读两器，为将来算爻器的双入而备。
// 写口只有一个：入 与 号 与 存允，于辰之上升沿写入。
type 卦器堆 struct {
	位  int     // 字长
	入  []*线    // 写入之数，众[0] 为最低位
	号  [3]*线   // 所写之器的卦号，号[0] 为最低位
	存允 *线      // 写允许
	读甲 [3]*线   // 甲口所读之器
	读乙 [3]*线   // 乙口所读之器
	出甲 []*线    // 甲口之出
	出乙 []*线    // 乙口之出
	诸器 [8][]*线 // 八器之出，以卦号为序
}

// 器名 第 i 器之名，以八卦名之。
func (r *卦器堆) 器名(i int) string { return 卦名(i) }

// 置卦器堆 造一座八器之堆。
//
// 号、读甲、读乙 皆三根，众[0] 为最低位。
// 出甲、出乙 各 位 根，由本函数自建，回以 卦器堆 可取。
func (n *网表) 置卦器堆(位 int, 入 []*线, 号 [3]*线, 存允, 辰 *线, 读甲, 读乙 [3]*线) *卦器堆 {
	if len(入) != 位 {
		panic(fmt.Sprintf("置卦器堆：入 须 %d 根，实得 %d 根", 位, len(入)))
	}
	r := &卦器堆{
		位:  位,
		入:  入,
		号:  号,
		存允: 存允,
		读甲: 读甲,
		读乙: 读乙,
		出甲: n.列线("甲读", 位),
		出乙: n.列线("乙读", 位),
	}

	// 一、号 三爻译出八线，一线当一器。
	译出 := n.私列(8)
	n.置译门(号[:], 译出)

	// 二、八器各立。译出[i] 与 存允 相与，方为该器之写允许。
	for i := 0; i < 8; i++ {
		器允 := n.私线()
		n.置与门(译出[i], 存允, 器允)
		r.诸器[i] = n.列线(fmt.Sprintf("器%s", 卦名(i)), 位)
		n.置存爻器(入, 器允, 辰, r.诸器[i])
	}

	// 三、两读口，各以多择门自八器中择其一。
	候选 := make([]*线, 8)
	for b := 0; b < 位; b++ {
		for i := 0; i < 8; i++ {
			候选[i] = r.诸器[i][b]
		}
		n.置多择门(读甲[:], 候选, r.出甲[b])
		n.置多择门(读乙[:], 候选, r.出乙[b])
	}
	return r
}

// ------------------------------------------------------------------
// 藏 · 存储器
// ------------------------------------------------------------------

// 藏 随机存取之存储器。
//
// 写者，以 址线 译出诸字之写允许，于辰之上升沿纳 入；
// 读者，纯系组合——以 址线 为择，自诸字中选出其一而 out。
// 此即「同拍写入、随时读出」，与真实之静态存储器一般。
//
// 之所以读不设寄存器而写设之，是因为读只求快（组合即可），
// 写必须对齐于辰（否则一拍之内所写之数尚未定，读已取走）。
type 藏 struct {
	位  int    // 字长
	址  int    // 地址之位数
	字  int    // 字数，即 1 << 址
	址线 []*线   // 地址，众[0] 为最低位
	入  []*线   // 写入之数
	存允 *线     // 写允许
	出  []*线   // 读出之数
	诸字 [][]*线 // 诸字之出，以地址为序
}

// 置藏 造一座存储器。位 为字长，址 为地址之位数。
//
// 址线 须 址 根，入、出 各 位 根（出 由本函数自建）。
func (n *网表) 置藏(位, 址 int, 址线, 入 []*线, 存允, 辰 *线) *藏 {
	if 址 <= 0 || 址 > 8 {
		panic(fmt.Sprintf("置藏：地址位数 %d 须在 1..8 之间", 址))
	}
	if len(址线) != 址 {
		panic(fmt.Sprintf("置藏：址线须 %d 根，实得 %d 根", 址, len(址线)))
	}
	if len(入) != 位 {
		panic(fmt.Sprintf("置藏：入 须 %d 根，实得 %d 根", 位, len(入)))
	}
	m := &藏{
		位:  位,
		址:  址,
		字:  1 << 址,
		址线: 址线,
		入:  入,
		存允: 存允,
		出:  n.列线("读出", 位),
		诸字: make([][]*线, 1<<址),
	}

	译出 := n.私列(m.字)
	n.置译门(址线, 译出)

	for j := 0; j < m.字; j++ {
		字允 := n.私线()
		n.置与门(译出[j], 存允, 字允)
		m.诸字[j] = n.列线(fmt.Sprintf("字%02d", j), 位)
		n.置存爻器(入, 字允, 辰, m.诸字[j])
	}

	候选 := make([]*线, m.字)
	for b := 0; b < 位; b++ {
		for j := 0; j < m.字; j++ {
			候选[j] = m.诸字[j][b]
		}
		n.置多择门(址线, 候选, m.出[b])
	}
	return m
}

// ------------------------------------------------------------------
// 计爻器 · 程序计数器
// ------------------------------------------------------------------

// 计爻器 程序计数器。每拍可自增一、可载新值、可守而不动。
//
//	载 为阳：纳 入（跳转）
//	载 为阴而 增 为阳：加一（顺序而下）
//	二者皆阴：守（停机或插入气泡）
type 计爻器 struct {
	位 int
	入 []*线 // 跳转之目标
	载 *线   // 载允许
	增 *线   // 增允许
	出 []*线 // 当前所值
}

// 置计爻器 造一具程序计数器。出 由本函数自建。
//
// 内部以 置增爻器 加一，以两重择门择三途：
//
//	所存 = 载 ? 入 : （增 ? 出 + 1 : 出）
func (n *网表) 置计爻器(位 int, 入 []*线, 载, 增, 辰 *线) *计爻器 {
	if len(入) != 位 {
		panic(fmt.Sprintf("置计爻器：入 须 %d 根，实得 %d 根", 位, len(入)))
	}
	p := &计爻器{
		位: 位,
		入: 入,
		载: 载,
		增: 增,
		出: n.列线("计", 位),
	}

	加一 := n.私列(位)
	n.置增爻器(p.出, 加一)

	所存 := n.私列(位)
	for i := 0; i < 位; i++ {
		或增 := n.私线()
		n.置择门(增, p.出[i], 加一[i], 或增)
		n.置择门(载, 或增, 入[i], 所存[i])
	}
	n.置存爻器(所存, n.恒阳(), 辰, p.出)
	return p
}
