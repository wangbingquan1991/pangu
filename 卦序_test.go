// Test卦序为排列 文王之序与先天之序当互为一一对应。
//
// 此验最浅，却是其余诸验的地基：序列若非排列，则必有一卦重复、一卦失落，
// 而下面的结构之验未必看得出来。
func Test卦序为排列(t *testing.T) {
	见 := make([]bool, 别卦数)
	for 序 := 1; 序 <= 别卦数; 序++ {
		值 := 文王先天(序)
		if 值 < 0 || 值 >= 别卦数 {
			t.Fatalf("文王序 %d 之先天值 %d 越出 0..%d", 序, 值, 别卦数-1)
		}
		if 见[值] {
			t.Fatalf("先天值 %d 重复出现：第 %d 卦", 值, 序)
		}
		见[值] = true
	}
	for v, b := range 见 {
		if !b {
			t.Errorf("先天值 %d 失落，无一卦当之", v)
		}
	}

	// 往返：先天 → 文王 → 先天，须回到原处。
	for 序 := 1; 序 <= 别卦数; 序++ {
		if 得 := 先天文王(文王先天(序)); 得 != 序 {
			t.Errorf("往返不合：文王序 %d → 先天 %d → 文王序 %d", 序, 文王先天(序), 得)
		}
	}
	for v := 0; v < 别卦数; v++ {
		if 得 := 文王先天(先天文王(v)); 得 != v {
			t.Errorf("往返不合：先天 %d → 文王序 %d → 先天 %d", v, 先天文王(v), 得)
		}
	}
}

// Test卦序之结构 文王卦序分三十二对，其法有二，皆可验：
//
//	二十八对：后卦为前卦颠倒一百八十度（综卦，即位反转）；
//	四对（文王序位 1、27、29、61 起首者）：其卦颠倒之后仍是自身，
//	        故改以逐爻阴阳互易（错卦）为偶。
//
// 此验之力在于：它是独立于数据来源的结构约束。序列中任一字有误，
// 至多破坏两对，故能定位；若整段偏移一位，则三十二对尽破。
func Test卦序之结构(t *testing.T) {
	// 四对以错卦为偶者，其首卦之文王序位。
	错对 := map[int]bool{1: true, 27: true, 29: true, 61: true}

	for 双 := 0; 双 < 别卦数/2; 双++ {
		首序 := 双*2 + 1
		甲 := 文王先天(首序)
		乙 := 文王先天(首序 + 1)

		if 错对[首序] {
			if 倒置(甲) != 甲 {
				t.Errorf("文王序 %d/%d：既以错卦为偶，其首卦当颠倒自同，然 倒置(%d)=%d",
					首序, 首序+1, 甲, 倒置(甲))
			}
			if 乙 != 错卦(甲) {
				t.Errorf("文王序 %d/%d：当为错卦，然 先天 %d 与 %d 非逐爻互易（错卦当为 %d）",
					首序, 首序+1, 甲, 乙, 错卦(甲))
			}
			continue
		}
		if 倒置(甲) == 甲 {
			t.Errorf("文王序 %d/%d 之首卦颠倒自同，当入错卦之列，然未列入", 首序, 首序+1)
		}
		if 乙 != 倒置(甲) {
			t.Errorf("文王序 %d/%d：当为综卦（位反转），然 先天 %d 与 %d 不合（倒置当为 %d）",
				首序, 首序+1, 甲, 乙, 倒置(甲))
		}
	}
}

// Test自对称之卦 颠倒而不变者，恰八卦；其文王序位恰在 1、2、27、28、29、30、61、62。
//
// 六爻颠倒自同，即六位之回文，其形由前三爻定，故恰 2³ = 8 个。
// 这八个自同之卦落在何处，是文王卦序自身的性质，非本表所造——
// 故可反用来验表。
func Test自对称之卦(t *testing.T) {
	var 得 []int
	for v := 0; v < 别卦数; v++ {
		if 倒置(v) == v {
			得 = append(得, 先天文王(v))
		}
	}
	if len(得) != 8 {
		t.Fatalf("颠倒自同之卦当有 8 个，实得 %d 个：%v", len(得), 得)
	}
	欲 := map[int]bool{1: true, 2: true, 27: true, 28: true, 29: true, 30: true, 61: true, 62: true}
	for _, 序 := range 得 {
		if !欲[序] {
			t.Errorf("颠倒自同之卦当在文王序 {1,2,27,28,29,30,61,62} 中，然得 %d", 序)
		}
	}
	for 序 := range 欲 {
		有 := false
		for _, d := range 得 {
			if d == 序 {
				有 = true
				break
			}
		}
		if !有 {
			t.Errorf("文王序 %d 当为颠倒自同之卦，然未得", 序)
		}
	}
}

// Test八纯卦 上下两经卦相同者（八纯卦），其文王序位恰在 1、2、29、30、51、52、57、58。
//
// 八纯卦即乾、坤、坎、离、震、艮、巽、兑各自重：乾一、坤二、坎二十九、
// 离三十、震五十一、艮五十二、巽五十七、兑五十八。此亦文王卦序自身之性质。
func Test八纯卦(t *testing.T) {
	var 得 []string
	欲 := []int{1, 2, 29, 30, 51, 52, 57, 58}
	for 序 := 1; 序 <= 别卦数; 序++ {
		v := 文王先天(序)
		if 上卦(v) == 下卦(v) {
			得 = append(得, 别卦名(v))
			if 序 != 欲[len(得)-1] {
				t.Errorf("第 %d 个纯卦之文王序位当为 %d，实为 %d（卦名 %s）",
					len(得), 欲[len(得)-1], 序, 别卦名(v))
			}
		}
	}
	if len(得) != 8 {
		t.Fatalf("八纯卦当有 8 个，实得 %d 个：%v", len(得), 得)
	}
	t.Logf("八纯卦之名：%s", strings.Join(得, "、"))
}

// Test名实互证 逐卦核其卦名与上下二经卦之实。
//
// 此验专为「位约定」而设。表里存的是数字，数字本身不错也能全错——
// 若上卦下卦颠倒，或经卦之值以爻为高位而非以初爻为高位，
// 则诸卦之名与实尽皆相左。
//
// 故此处所择，尽是「非回文」之卦，且成对取其对偶：
// 泰与否、需与讼、师与比、屯与蒙、既济与未济、颐与大过、中孚与小过。
// 上下若倒，则此七对双双互换，验必破。八纯卦亦在列，以定经卦之值。
func Test名实互证(t *testing.T) {
	诸例 := []struct {
		序    int
		名    string
		上, 下 int
	}{
		{1, "乾", 乾卦, 乾卦},
		{2, "坤", 坤卦, 坤卦},
		{3, "屯", 坎卦, 震卦},   // 水雷屯
		{4, "蒙", 艮卦, 坎卦},   // 山水蒙
		{5, "需", 坎卦, 乾卦},   // 水天需
		{6, "讼", 乾卦, 坎卦},   // 天水讼
		{7, "师", 坤卦, 坎卦},   // 地水师
		{8, "比", 坎卦, 坤卦},   // 水地比
		{9, "小畜", 巽卦, 乾卦},  // 风天小畜
		{10, "履", 乾卦, 兑卦},  // 天泽履
		{11, "泰", 坤卦, 乾卦},  // 地天泰
		{12, "否", 乾卦, 坤卦},  // 天地否
		{21, "噬嗑", 离卦, 震卦}, // 火雷噬嗑
		{27, "颐", 艮卦, 震卦},  // 山雷颐
		{28, "大过", 兑卦, 巽卦}, // 泽风大过
		{29, "坎", 坎卦, 坎卦},
		{30, "离", 离卦, 离卦},
		{51, "震", 震卦, 震卦},
		{52, "艮", 艮卦, 艮卦},
		{57, "巽", 巽卦, 巽卦},
		{58, "兑", 兑卦, 兑卦},
		{61, "中孚", 巽卦, 兑卦}, // 风泽中孚
		{62, "小过", 震卦, 艮卦}, // 雷山小过
		{63, "既济", 坎卦, 离卦}, // 水火既济
		{64, "未济", 离卦, 坎卦}, // 火水未济
	}

	for _, 例 := range 诸例 {
		v := 文王先天(例.序)
		if 例.名 != "" && 别卦名(v) != 例.名 {
			t.Errorf("文王序 %d 之名当为「%s」，实为「%s」", 例.序, 例.名, 别卦名(v))
		}
		if 上卦(v) != 例.上 || 下卦(v) != 例.下 {
			t.Errorf("文王序 %d「%s」当为 %s上%s下，实为 %s上%s下",
				例.序, 例.名, 八卦符(例.上), 八卦符(例.下), 八卦符(上卦(v)), 八卦符(下卦(v)))
		}
	}
}

// Test爻象与倒置相合 一卦之六爻，颠倒之后当恰为原爻串之首尾逆序。
//
// 此验把 别卦爻 与 倒置 互锁：二者各自皆可读懂，然若位约定不一致，
// 则「位反转」与「爻序逆转」便不是同一件事，验必破。
func Test爻象与倒置相合(t *testing.T) {
	for v := 0; v < 别卦数; v++ {
		原 := []rune(别卦爻(v))
		倒 := []rune(别卦爻(倒置(v)))
		if len(原) != 6 || len(倒) != 6 {
			t.Fatalf("爻串当六爻，实得 %d 与 %d", len(原), len(倒))
		}
		for i := 0; i < 6; i++ {
			if 原[i] != 倒[5-i] {
				t.Errorf("先天值 %d：爻串 %s 与 倒置之爻串 %s 非首尾逆序", v, string(原), string(倒))
				break
			}
		}
		// 错卦：六爻尽反。
		错 := []rune(别卦爻(错卦(v)))
		for i := 0; i < 6; i++ {
			同 := 原[i] == 错[i]
			if 同 {
				t.Errorf("先天值 %d：错卦之第 %d 爻当与原爻相反，实同", v, i+1)
				break
			}
		}
	}
}

// Test卦符之基 U+4DC0 段的起点与偏移。
//
// 乾居首、坤次之、既济六十三、未济六十四——四端一定，则基址与偏移皆定。
// 此验防的是「差一」之错，那是抄表最常见的失手处。
func Test卦符之基(t *testing.T) {
	诸例 := []struct {
		先天值 int
		文王序 int
		符   string
		名   string
	}{
		{63, 1, "䷀", "乾"},
		{0, 2, "䷁", "坤"},
		{21, 63, "䷾", "既济"},
		{42, 64, "䷿", "未济"},
	}
	for _, 例 := range 诸例 {
		if 得 := 先天文王(例.先天值); 得 != 例.文王序 {
			t.Errorf("先天值 %d 之文王序当为 %d，实为 %d", 例.先天值, 例.文王序, 得)
		}
		if 得 := 别卦符(例.先天值); 得 != 例.符 {
			t.Errorf("先天值 %d 之卦符当为 %s，实为 %s", 例.先天值, 例.符, 得)
		}
		if 得 := 别卦名(例.先天值); 得 != 例.名 {
			t.Errorf("先天值 %d 之卦名当为 %s，实为 %s", 例.先天值, 例.名, 得)
		}
		if 得 := 文王卦符(例.文王序); 得 != 例.符 {
			t.Errorf("文王序 %d 之卦符当为 %s，实为 %s", 例.文王序, 例.符, 得)
		}
	}
}

// Test文档之例 典/07-卦序映射表.md 第六节所举之例，须与实现相合。
//
// 文档里的例子会腐坏：代码一改，文档未改，读者按例一试便知是错的。
// 故把例子写成测试，教它自己看住自己。
func Test文档之例(t *testing.T) {
	诸例 := []struct {
		法 string
		得 interface{}
		欲 interface{}
	}{
		{"文王先天(21)", 文王先天(21), 44},
		{"先天文王(44)", 先天文王(44), 21},
		{"别卦符(44)", 别卦符(44), "䷔"},
		{"别卦名(44)", 别卦名(44), "噬嗑"},
		{"别卦象(44)", 别卦象(44), "☲☳"}, // 离上震下
		{"别卦爻(44)", 别卦爻(44), "⚊⚋⚋⚊⚋⚊"},
		{"上卦(44)", 上卦(44), 5},  // 离
		{"下卦(44)", 下卦(44), 4},  // 震
		{"倒置(44)", 倒置(44), 13}, // 贲
		{"错卦(44)", 错卦(44), 19}, // 井
	}
	for _, 例 := range 诸例 {
		if 例.得 != 例.欲 {
			t.Errorf("%s 当为 %v，实为 %v", 例.法, 例.欲, 例.得)
		}
	}
}

// Test卦序越界 越界当报以统一之辞，而非静默返回。
func Test卦序越界(t *testing.T) {
	诸验 := []struct {
		名 string
		验 func()
	}{
		{"文王先天(0)", func() { 文王先天(0) }},
		{"文王先天(65)", func() { 文王先天(65) }},
		{"先天文王(-1)", func() { 先天文王(-1) }},
		{"先天文王(64)", func() { 先天文王(64) }},
		{"上卦(64)", func() { 上卦(64) }},
		{"下卦(-1)", func() { 下卦(-1) }},
		{"倒置(64)", func() { 倒置(64) }},
		{"错卦(-1)", func() { 错卦(-1) }},
		{"文王卦符(65)", func() { 文王卦符(65) }},
	}
	for _, v := range 诸验 {
		func() {
			defer func() {
				if recover() == nil {
					t.Errorf("%s 越界而未报", v.名)
				}
			}()
			v.验()
		}()
	}
}
