package 盘古

import (
	"fmt"
	"strings"
)

// ==================================================================
// 演 · 第一档（L1 爻级）
//
// 此乃全机最底层的模拟器。它不认识指令，也不认识数字，
// 只认识线与门：一根线承载一爻，一个门读若干入线、写若干出线。
//
// 求值用事件驱动：一线之值一变，唯其负载（读取它的门）重新求值，
// 其余门安坐不动。如此可模拟出真实的传播延迟次序，
// 亦使环形的振荡电路能被察觉——那是我们刻意保留的一种错误。
// ==================================================================

// 默认步上限 推演步数超过此数即判为振荡。
const 默认步上限 = 1 << 20

// 线 连络诸门的一根导线，承载一爻之值。
//
// 每根线至多有一个驱者（写它的门），可有多个负载（读它的门）。
// 无驱者之线由网表之外驱动，如同手工拨动的开关。
type 线 struct {
	名  string
	值  爻
	新值 爻
	驱者 门
	负载 []门
}

// 门 一切逻辑元件的共相。
//
// 算() 只读取入线的现值，把结果写入出线的新值；
// 新值何时落为现值，由网表的调定过程决定。
// 如此分离，方使时序电路（锁爻器、辰）得以成立。
type 门 interface {
	// 名 门之名，用于诊断与述网表。
	名() string
	// 入线 门所读取的线。
	入线() []*线
	// 出线 门所写入的线。
	出线() []*线
	// 算 依入线现值，写出线新值。
	算()
}

// 恒源 电源之轨，恒出一爻，无入。
//
// 此非门也——门者受入而出，恒源无入。它是电路得以成立的常识前提，
// 犹天地之有阴阳。故「万门出于一」之验容它与与非门并存：
// 凡受入而算者，皆出于与非；恒源不与焉。
//
// 之所以不取 NAND(a, ¬a) 之类巧法造恒电平，是因为在事件驱动之下，
// a 变而 ¬a 未及变，会先吐出一个假值再复真——那是一次真实的毛刺。
// 电源之轨不当有毛刺。
type 恒源 struct {
	出 *线
	值 爻
}

// 名 源之名。
func (g *恒源) 名() string { return "恒源" }

// 入线 恒源无入。
func (g *恒源) 入线() []*线 { return nil }

// 出线 唯一之出。
func (g *恒源) 出线() []*线 { return []*线{g.出} }

// 算 恒出其定值。
func (g *恒源) 算() { g.出.新值 = g.值 }

// 网表 一座电路。线成网，门成表，值在其中流布。
type 网表 struct {
	名  string
	线表 map[string]*线
	线序 []*线
	门表 []门
	队列 []门
	在队 map[门]bool
	私号 int
	步数 int // 最近一次调定所走之步
	总步 int // 自建网表以来累计所走之步
	地  *线  // 接地之轨，恒阴
	源  *线  // 电源之轨，恒阳
}

// 建网表 造一座空电路。
func 建网表(名 string) *网表 {
	return &网表{
		名:  名,
		线表: make(map[string]*线),
		在队: make(map[门]bool),
	}
}

// 引线 造一根有名之线。名不可重复。
func (n *网表) 引线(名 string) *线 {
	if _, 有 := n.线表[名]; 有 {
		panic(fmt.Sprintf("网表「%s」：线「%s」已存在", n.名, 名))
	}
	w := &线{名: 名}
	n.线表[名] = w
	n.线序 = append(n.线序, w)
	return w
}

// 私线 造一根内部用线，名由网表自拟，不与外部相干。
func (n *网表) 私线() *线 {
	n.私号++
	return n.引线(fmt.Sprintf("私%d", n.私号))
}

// 私列 造一组内部用线。
func (n *网表) 私列(数 int) []*线 {
	众 := make([]*线, 数)
	for i := range 众 {
		众[i] = n.私线()
	}
	return 众
}

// 列线 造一组线，名以 前缀 加序号，如 甲0 甲1 甲2。
func (n *网表) 列线(前缀 string, 数 int) []*线 {
	众 := make([]*线, 数)
	for i := range 众 {
		众[i] = n.引线(fmt.Sprintf("%s%d", 前缀, i))
	}
	return 众
}

// 恒阴 网表共用的接地之轨，恒阴。
//
// 此线无驱者，故其值永为初始之阴。凡需恒阴之处皆引此线，如共用地。
func (n *网表) 恒阴() *线 {
	if n.地 == nil {
		n.地 = n.引线("地")
	}
	return n.地
}

// 恒阳 网表共用的电源之轨，恒阳，由一恒源驱之。
func (n *网表) 恒阳() *线 {
	if n.源 == nil {
		n.源 = n.引线("源")
		n.装门(&恒源{出: n.源, 值: 阳})
	}
	return n.源
}

// 索线 依名取线。
func (n *网表) 索线(名 string) *线 {
	w, 有 := n.线表[名]
	if !有 {
		panic(fmt.Sprintf("网表「%s」：无线「%s」", n.名, 名))
	}
	return w
}

// 有此线乎 查名是否已用。
func (n *网表) 有此线乎(名 string) bool {
	_, 有 := n.线表[名]
	return 有
}

// 装门 登记一门，接线，并唤醒它作初次求值。
//
// 一线的驱者至多一个：若某线已有驱者而又被他门所写，是为短路，立时报错。
func (n *网表) 装门(g 门) 门 {
	for _, w := range g.入线() {
		if w == nil {
			panic(fmt.Sprintf("门「%s」：有空入线", g.名()))
		}
		w.负载 = append(w.负载, g)
	}
	for _, w := range g.出线() {
		if w == nil {
			panic(fmt.Sprintf("门「%s」：有空出线", g.名()))
		}
		if w.驱者 != nil {
			panic(fmt.Sprintf("网表「%s」：线「%s」既受「%s」所驱，不可再受「%s」所驱（短路）",
				n.名, w.名, w.驱者.名(), g.名()))
		}
		w.驱者 = g
	}
	n.门表 = append(n.门表, g)
	n.唤醒(g)
	return g
}

// 唤醒 请一门入待算之列。
func (n *网表) 唤醒(g 门) {
	if n.在队[g] {
		return
	}
	n.在队[g] = true
	n.队列 = append(n.队列, g)
}

// 驱动 由网表之外把一爻置入某线，如同拨动开关。此线必须无驱者。
func (n *网表) 驱动(w *线, y 爻) {
	if w.驱者 != nil {
		panic(fmt.Sprintf("网表「%s」：线「%s」已由「%s」所驱，不可外力置入", n.名, w.名, w.驱者.名()))
	}
	w.新值 = y
	if w.新值 != w.值 {
		w.值 = w.新值
		for _, g := range w.负载 {
			n.唤醒(g)
		}
	}
}

// 调定 事件驱动地推演，直到再无爻变。
//
// 若推演步数逾上限而犹未安定，则电路中必有环形振荡，回以错误。
// 上限为零时用 默认步上限。
//
// 步数 计的是**本次**调定所走之步，每次调定之始归零。
// 若用累计之步，则反复驱同一网表久了，纵是完好之电路也会误报振荡。
func (n *网表) 调定(上限 int) error {
	if 上限 <= 0 {
		上限 = 默认步上限
	}
	n.步数 = 0
	for len(n.队列) > 0 {
		g := n.队列[0]
		n.队列 = n.队列[1:]
		delete(n.在队, g)

		g.算()

		for _, w := range g.出线() {
			if w.新值 != w.值 {
				w.值 = w.新值
				for _, h := range w.负载 {
					n.唤醒(h)
				}
			}
		}

		n.步数++
		n.总步++
		if n.步数 > 上限 {
			return fmt.Errorf("网表「%s」本次调定逾 %d 步而未安，疑为振荡", n.名, 上限)
		}
	}
	return nil
}

// 读 取一线的现值。
func (n *网表) 读(w *线) 爻 { return w.值 }

// 读名 依名取一线的现值。
func (n *网表) 读名(名 string) 爻 { return n.索线(名).值 }

// 门数 网表中门之总数。
func (n *网表) 门数() int { return len(n.门表) }

// 线数 网表中线之总数。
func (n *网表) 线数() int { return len(n.线序) }

// 述 述此网表之形貌，用供检视。
func (n *网表) 述() string {
	var b strings.Builder
	fmt.Fprintf(&b, "网表「%s」：门 %d，线 %d，累计推演 %d 步\n", n.名, n.门数(), n.线数(), n.总步)
	for _, g := range n.门表 {
		fmt.Fprintf(&b, "  %-4s  %s → %s\n",
			g.名(), strings.Join(线名表(g.入线()), " · "), strings.Join(线名表(g.出线()), " · "))
	}
	return b.String()
}

// 线名表 取一组线之名。
func 线名表(众 []*线) []string {
	s := make([]string, len(众))
	for i, w := range 众 {
		if w == nil {
			s[i] = "（空）"
			continue
		}
		s[i] = w.名
	}
	return s
}
