// 算爻之操 算爻器八种运算，各配一经卦。择者三爻，正合一卦之数。
//
// 序依本系统的卦象位序：值之二进制自高至低为初爻、二爻、三爻，
// 而择线依数值位序（择[0] 为最低位）。二者互为镜像，故
// 值 7 = 阳阳阳 = 乾，值 0 = 阴阴阴 = 坤。
type 算爻之操 int

// 算爻器之八操。
const (
	加 算爻之操 = 0 // 坤 ☷ 甲 与 乙 相加
	减 算爻之操 = 1 // 艮 ☶ 甲 减 乙
	交 算爻之操 = 2 // 坎 ☵ 逐位与
	并 算爻之操 = 3 // 巽 ☴ 逐位或
	殊 算爻之操 = 4 // 震 ☳ 逐位异或
	升 算爻之操 = 5 // 离 ☲ 甲 左移一爻，低位补阴
	降 算爻之操 = 6 // 兑 ☱ 甲 右移一爻，高位补阴（逻辑右移）
	较 算爻之操 = 7 // 乾 ☰ 甲 小于 乙（有符号）则出一，否则出零
)

// 名 八操之卦名。
func (o 算爻之操) 名() string { return 卦名(int(o)) }

// 符 八操之卦符。
func (o 算爻之操) 符() string { return 八卦符(int(o)) }

// 算爻志 算爻器的四种志（标志位）。
type 算爻志 struct {
	进位 *线 // 无符号之进位；减法时，为「无借位」
	零  *线 // 果为全阴
	负  *线 // 果之最高位为阳（以有符号视之则为负）
	溢出 *线 // 有符号溢出
}

// 置算爻器 n 位算爻器。八种运算，以三爻（一卦）择之。
//
// 甲、乙、果 各 n 根，众[0] 为最低位。择 三根，择[0] 为最低位。
//
// 内部先八路并算，再以多择门择其一。移位二路纯系接线，不耗一门：
// 左移者诸位皆上移一阶而末位接地，右移者皆下一阶而首位接地。
func (n *网表) 置算爻器(甲, 乙 []*线, 择 [3]*线, 果 []*线) *算爻志 {
	k := len(甲)
	if len(乙) != k || len(果) != k {
		panic("置算爻器：甲、乙、果 三者之数须相若")
	}
	if k == 0 {
		panic("置算爻器：位数不可为零")
	}

	// 一、加：甲 与 乙 相加。
	加果 := n.私列(k)
	加链 := n.置加爻器(甲, 乙, n.恒阴(), 加果)

	// 二、减：甲 加「乙之补」，即甲 加（乙 逐位取反）加一。
	// 乙已含于加法器之内，故此处只须取反乙并置进位为一。
	非乙 := n.私列(k)
	for i, w := range 乙 {
		n.置非门(w, 非乙[i])
	}
	减果 := n.私列(k)
	减链 := n.置加爻器(甲, 非乙, n.恒阳(), 减果)

	// 三、逐位三操。
	交果 := n.私列(k)
	并果 := n.私列(k)
	殊果 := n.私列(k)
	for i := 0; i < k; i++ {
		n.置与门(甲[i], 乙[i], 交果[i])
		n.置或门(甲[i], 乙[i], 并果[i])
		n.置异或门(甲[i], 乙[i], 殊果[i])
	}

	// 四、移位二操：纯接线，不耗一门。
	升果 := make([]*线, k)
	降果 := make([]*线, k)
	升果[0] = n.恒阴()
	for i := 1; i < k; i++ {
		升果[i] = 甲[i-1]
	}
	for i := 0; i < k-1; i++ {
		降果[i] = 甲[i+1]
	}
	降果[k-1] = n.恒阴()

	// 五、比较：甲 小于 乙（有符号）当且仅当「减果之符」异或「减之溢出」。
	// 减之溢出者：甲、乙 异号，而结果与甲异号。
	减溢出 := n.私线()
	异号 := n.私线()
	果异甲 := n.私线()
	n.置异或门(甲[k-1], 乙[k-1], 异号)
	n.置异或门(甲[k-1], 减果[k-1], 果异甲)
	n.置与门(异号, 果异甲, 减溢出)

	小于 := n.私线()
	n.置异或门(减果[k-1], 减溢出, 小于)

	较果 := make([]*线, k)
	较果[0] = 小于
	for i := 1; i < k; i++ {
		较果[i] = n.恒阴()
	}

	// 六、八路既备，择其一而 out。
	诸果 := [8][]*线{加果, 减果, 交果, 并果, 殊果, 升果, 降果, 较果}
	候选 := make([]*线, 8)
	for i := 0; i < k; i++ {
		for o := range 候选 {
			候选[o] = 诸果[o][i]
		}
		n.置多择门(择[:], 候选, 果[i])
	}

	// 七、诸志。
	志 := &算爻志{负: 果[k-1]}

	// 进位与溢出，唯加、减二操有意义，余者皆阴。
	// 择零（坤）者：择 三位皆阴；择一（艮）者：唯初位为阳。
	反择 := n.私列(3)
	for i := range 反择 {
		n.置非门(择[i], 反择[i])
	}
	加选 := n.私线()
	n.置全与门([]*线{反择[0], 反择[1], 反择[2]}, 加选)
	减选 := n.私线()
	n.置全与门([]*线{择[0], 反择[1], 反择[2]}, 减选)

	// 加 之溢出：进入最高位之进位 异或 离最高位之进位。
	加溢出 := n.私线()
	if k >= 2 {
		n.置异或门(加链.诸位[k-2], 加链.诸位[k-1], 加溢出)
	} else {
		n.置继门(n.恒阴(), 加溢出)
	}

	进位加 := n.私线()
	进位减 := n.私线()
	n.置与门(加选, 加链.末(), 进位加)
	n.置与门(减选, 减链.末(), 进位减)
	志.进位 = n.私线()
	n.置或门(进位加, 进位减, 志.进位)

	溢出加 := n.私线()
	溢出减 := n.私线()
	n.置与门(加选, 加溢出, 溢出加)
	n.置与门(减选, 减溢出, 溢出减)
	志.溢出 = n.私线()
	n.置或门(溢出加, 溢出减, 志.溢出)

	// 零：果 诸位皆阴。
	或有 := n.私线()
	n.置全或门(果, 或有)
	志.零 = n.私线()
	n.置非门(或有, 志.零)

	return 志
}
