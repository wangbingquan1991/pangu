// ==================================================================
// 算术 · 四象之数
//
// 门既备，可以计数矣。
//
// 半加器并两爻为一和一位；全加器纳进位而受三入；
// 诸全加器首尾相衔，进位自低向高逐位传递，是为行波进位加法器。
//
// 减法不另立一器：甲减乙，即甲加「乙之补」。求补之法，
// 逐位阳阴互易而后加一。负数不设符号位，正负二数共处一域，
// 加减遂归一途——此即「阳阴互易」之实。
//
// 此间一切仍皆由与非门派生，未尝偷用他门。
// ==================================================================

// 置半加器 半加器：两爻相加，出 和 与 进位。
//
//	和 = 甲 异或 乙
//	进位 = 甲 与 乙
func (n *网表) 置半加器(甲, 乙, 和, 进位 *线) {
	n.置异或门(甲, 乙, 和)
	n.置与门(甲, 乙, 进位)
}

// 置全加器 全加器：甲、乙、入位 三者相加，出 和 与 出位。
//
//	和 = 甲 异或 乙 异或 入位
//	出位 = （甲 与 乙）或（入位 与（甲 异或 乙））
func (n *网表) 置全加器(甲, 乙, 入位, 和, 出位 *线) {
	甲乙 := n.私线()
	n.置异或门(甲, 乙, 甲乙)
	n.置异或门(甲乙, 入位, 和)

	与甲乙 := n.私线()
	n.置与门(甲, 乙, 与甲乙)
	与入次 := n.私线()
	n.置与门(入位, 甲乙, 与入次)
	n.置或门(与甲乙, 与入次, 出位)
}

// 进位链 加法器进位之迹，据之可判有符号溢出。
type 进位链 struct {
	// 诸位[i] 为第 i 位所生之进位，亦即进入第 i+1 位之进位。
	诸位 []*线
}

// 末 最高位所生之进位，即无符号溢出之进位。
func (c *进位链) 末() *线 {
	if len(c.诸位) == 0 {
		return nil
	}
	return c.诸位[len(c.诸位)-1]
}

// 置加爻器 n 位行波进位加法器。
//
// 甲、乙、和 各 n 根，众[0] 为最低位。入位 可为 nil，则视作阴。
// 回以进位链。
func (n *网表) 置加爻器(甲, 乙 []*线, 入位 *线, 和 []*线) *进位链 {
	k := len(甲)
	if len(乙) != k || len(和) != k {
		panic("置加爻器：甲、乙、和 三者之数须相若")
	}
	if k == 0 {
		panic("置加爻器：位数不可为零")
	}
	if 入位 == nil {
		入位 = n.恒阴()
	}
	链 := &进位链{诸位: make([]*线, k)}
	进 := 入位
	for i := 0; i < k; i++ {
		出位 := n.私线()
		n.置全加器(甲[i], 乙[i], 进, 和[i], 出位)
		进 = 出位
		链.诸位[i] = 出位
	}
	return 链
}

// 置增爻器 加一之器。以半加器链承进位，比用全加器省半。
func (n *网表) 置增爻器(众 []*线, 出 []*线) {
	k := len(众)
	if len(出) != k {
		panic("置增爻器：出入之数须相若")
	}
	if k == 0 {
		panic("置增爻器：位数不可为零")
	}
	进 := n.恒阳()
	for i := 0; i < k; i++ {
		次 := n.私线()
		n.置半加器(众[i], 进, 出[i], 次)
		进 = 次
	}
}

// 置求补器 求补：逐位阳阴互易而后加一。
//
// 此即二之补数。负数不别立符号位，正因其可如是而生：
// 取某数之补，则原数与其补相加恰溢出而归零，加减之道遂合为一。
func (n *网表) 置求补器(众 []*线, 出 []*线) {
	k := len(众)
	if len(出) != k {
		panic("置求补器：出入之数须相若")
	}
	反 := n.私列(k)
	for i, w := range 众 {
		n.置非门(w, 反[i])
	}
	n.置增爻器(反, 出)
}

// 置多择门 n 位选择的多路器：以 择 之值（择[0] 为最低位）自 众 中选一而 out。
//
// 众 须有 2^n 根。内以二择一的择门搭成平衡二叉树，凡 n 层，
// 故延迟随位数对数而增，非如串联之随数而增。
func (n *网表) 置多择门(择 []*线, 众 []*线, 出 *线) {
	k := len(择)
	if len(众) != 1<<k {
		panic("置多择门：众之数须为 2 之择位数次方")
	}
	当前 := 众
	for 层 := 0; 层 < k; 层++ {
		次层 := make([]*线, len(当前)/2)
		for i := range 次层 {
			次层[i] = n.私线()
			n.置择门(择[层], 当前[2*i], 当前[2*i+1], 次层[i])
		}
		当前 = 次层
	}
	n.置继门(当前[0], 出)
}

