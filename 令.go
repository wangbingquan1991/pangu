// ==================================================================
// 令 · 六十四卦指令集
//
// 门既成，数既成，时序既成——机器能记、能算、能寻址，然犹不识「指令」
// 为何物。它只知自藏中取出一字，而不知那一字是数、是址、还是令。
//
// 令者，机器与人所立之约：以六位为一卦，一卦当一操，六十四卦便是六十四操。
// 操作码取卦之**先天值**，故八进制之下 码 = 0o（上卦）（下卦），
// 于是**上卦定其类，下卦定其操**。此非比喻，而是电路：乾类（0o70–0o77）
// 之下卦三位，可直连算爻器之择线，不费一择门——盖下卦正是 M1 所定之八操。
//
// 三型之制（皆二十四位，操作码居高六位）：
//
//	甲型  [6b 码][3b rd][3b rs1][3b rs2][9b 偏移]     算爻八操之器版、四条条件跃
//	乙型  [6b 码][3b rd][3b rs1][12b 立即数]          算爻八操之数版、载字/存字/载高
//	丙型  [6b 码][18b 地址]                           跃、停机、叩
//
// 位序一遵 门.go 之约：位 0 为最低。卦之先天值一遵 卦序.go 之约：
// 先天值 =（上卦 << 3）| 下卦，上卦居高三位。
//
// 六十四卦之位，M3 实定十七条，M5 又于坤上之留位立特权之令二（降、回），
// 今凡十九条。余者留待后之里程碑：坤上 0o05–0o07、巽上留 M6（虚境）、
// 离上留 M7。
// ==================================================================

// 字之度 指令诸域之位宽。
const (
	字位 = 24 // 字长，亦一令之长
	码位 = 6  // 操作码：一卦，六十四操
	器位 = 3  // 卦器之号：一经卦，八器
	数位 = 12 // 乙型立即数：四爻
	偏位 = 9  // 甲型偏移：三爻
	址位 = 18 // 丙型地址：六卦，可寻址 262144 字
)

// 诸掩 各域之掩码。
const (
	字掩 = (1 << 字位) - 1
	码掩 = (1 << 码位) - 1
	器掩 = (1 << 器位) - 1
	数掩 = (1 << 数位) - 1
	偏掩 = (1 << 偏位) - 1
	址掩 = (1 << 址位) - 1
)

// 类 操作码之上卦，定其大类。值即上卦之先天值。
const (
	类内务 = 0 // 坤 ☷ 停机、叩、载高
	类存取 = 2 // 坎 ☵ 载字、存字
	类转移 = 4 // 震 ☳ 跃、等跃、异跃、逊跃、胜跃
	类数  = 6 // 兑 ☱ 算爻八操之立即数版
	类器  = 7 // 乾 ☰ 算爻八操之寄存器版
)

// 令码 已定之操作码。皆先天值，八进制下即 0o（上卦）（下卦）。
//
// 卦符卦名不于此注出——那该由 别卦符 / 别卦名 依 卦序.go 算得，
// 手抄必错（典/07 有前车：作者自己的显示脚本便在此摔过一跤）。
const (
	停机 = 0o00 // 坤·坤  全零即停机，未写之藏跑飞至此亦止
	叩  = 0o01 // 坤·艮  系统调用。M3 中亦停机，乾器之值即叩号；M5 行陷阱后不复为停机
	载高 = 0o02 // 坤·坎  rd ← 立即数 << 12
	降化 = 0o03 // 坤·巽  降入化态（特权）。特权 ← 化态，计 ← 丙型之址
	回  = 0o04 // 坤·震  自爻变返（特权）。特权 ← 化态，计 ← 存计

	载字 = 0o20 // 坎·坤  rd ← 藏[rs1 + 符号扩(立即数)]
	存字 = 0o21 // 坎·艮  藏[rs1 + 符号扩(立即数)] ← rd（乙型之 rd 域于此反作源器）

	跃  = 0o40 // 震·坤  计 ← 丙型之十八位地址（绝对）
	等跃 = 0o41 // 震·艮  rs1 == rs2 则 计 ← 计 + 偏
	异跃 = 0o42 // 震·坎  rs1 != rs2 则跃
	逊跃 = 0o43 // 震·巽  有符号 rs1 <  rs2 则跃
	胜跃 = 0o44 // 震·震  有符号 rs1 >= rs2 则跃（**含等于**，详见 典/01）
)

// 特权之令 唯 枢态 可行，化态 行之则爻变（越权）。
//
// 二者之别在**去处**：回 者自爻变而返，计 ← 存计（来处）；
// 降化 者指定其往，计 ← 址（去处）。枢 启机之后，以 降化 入化之始。
//
// 名与卦之关系，此处恰有一正一反，并存之以为戒：
//
//	回 之卦为 ䷗ 复（复者，返也）——名与卦合，是巧；
//	降化 之卦为 ䷭ 升（升者，上也）——名与卦反，是常。
//
// 常者，何也？**卦者，号也，非义也。** 码取先天值，先天值只是序号，
// 义在名中，不在卦中。若执卦义以推令义，则 存字（䷦ 蹇）、载高（䷆ 师）
// 皆无所取。M3 之所以取先天值而舍文王序，正在于此：序号是机器要的，
// 义是人给的，二者不必相谋。
var 特权之令 = map[int]bool{降化: true, 回: true}

// 器操 算爻八操之寄存器版操作码。下卦即操，可直连算爻器之择线。
func 器操(操 算爻之操) int { return 0o70 | int(操) }

// 数操 算爻八操之立即数版操作码。下卦亦操。
func 数操(操 算爻之操) int { return 0o60 | int(操) }

// ------------------------------------------------------------------
// 诸域之取
// ------------------------------------------------------------------

// 取码 取操作码（位 23..18）。
func 取码(令 int) int { return (令 >> (字位 - 码位)) & 码掩 }

// 取rd 取目的器之号（位 17..15）。
func 取rd(令 int) int { return (令 >> 15) & 器掩 }

// 取rs1 取甲源器之号（位 14..12）。
func 取rs1(令 int) int { return (令 >> 12) & 器掩 }

// 取rs2 取乙源器之号（位 11..9）。乙型中此域为立即数之高三位。
func 取rs2(令 int) int { return (令 >> 9) & 器掩 }

// 取偏 取甲型之九位偏移（位 8..0），符号扩展后即跳转之相对量。
func 取偏(令 int) int { return 令 & 偏掩 }

// 取立即数 取乙型之十二位立即数域（位 11..0）。
func 取立即数(令 int) int { return 令 & 数掩 }

// 取址 取丙型之十八位地址域（位 17..0）。
func 取址(令 int) int { return 令 & 址掩 }

// 分类 取一**操作码**（六位，0..63）之上卦，即其类。
// 分操 取一操作码之下卦。凡算爻之类，此即其操。
//
// 名前缀之别，便是戒：取* 一族收二十四位之**令**，分* 一族收六位之**码**。
// 二者不可混——混则码入 取码 再右移十八位，一律得零，
// 于是六十四卦尽落坤下，错而无声。此病作者犯过，故立此二名以别之。
func 分类(码 int) int { return (码 & 码掩) >> 器位 }
func 分操(码 int) int { return 码 & 器掩 }

// ------------------------------------------------------------------
// 三型之编
// ------------------------------------------------------------------

// 编甲 编一甲型之令。
func 编甲(码, rd, rs1, rs2, 偏 int) int {
	return ((码 & 码掩) << (字位 - 码位)) |
		((rd & 器掩) << 15) | ((rs1 & 器掩) << 12) | ((rs2 & 器掩) << 9) |
		(偏 & 偏掩)
}

// 编乙 编一乙型之令。
func 编乙(码, rd, rs1, 数 int) int {
	return ((码 & 码掩) << (字位 - 码位)) |
		((rd & 器掩) << 15) | ((rs1 & 器掩) << 12) | (数 & 数掩)
}

// 编丙 编一丙型之令。
func 编丙(码, 址 int) int {
	return ((码 & 码掩) << (字位 - 码位)) | (址 & 址掩)
}

// 令型 指令之三型，外加未定。
type 令型 int

// 三型与未定。
const (
	甲型 令型 = iota
	乙型
	丙型
	未定型 // 码未定，机器遇之无所措
)

// 名 型之名。
func (f 令型) 名() string {
	switch f {
	case 甲型:
		return "甲"
	case 乙型:
		return "乙"
	case 丙型:
		return "丙"
	}
	return "未定"
}

// 取型 由操作码定其型。未定之码回以 未定型。
//
// 型由码定，而非由类定：同一类中亦有异型者，
// 如震上之 跃 为丙型（绝对地址），等跃 以下则为甲型（须两源器相比）。
func 取型(码 int) 令型 {
	switch 分类(码) {
	case 类内务:
		switch 分操(码) {
		case 0, 1, 3, 4:
			return 丙型 // 停机、叩、降化、回
		case 2:
			return 乙型 // 载高
		}
	case 类存取:
		switch 分操(码) {
		case 0, 1:
			return 乙型 // 载字、存字
		}
	case 类转移:
		switch 分操(码) {
		case 0:
			return 丙型 // 跃
		case 1, 2, 3, 4:
			return 甲型 // 等跃、异跃、逊跃、胜跃
		}
	case 类数:
		return 乙型
	case 类器:
		return 甲型
	}
	return 未定型
}

// ------------------------------------------------------------------
// 扩展之约
// ------------------------------------------------------------------

// 用符号 此码之立即数域是否作符号扩展。
//
// 存取之偏移恒为符号（地址可为负向）；加、减、较 三操为符号；
// 交、并、殊 三操零扩展（同 RISC-V 之 andi/ori/xori）；升、降 不用此域。
//
// 太极.go 中有一根同名之线「用符」，即此函在电路中的化身；
// Test用符与电路相合 专验二者不悖。
func 用符号(码 int) bool {
	switch 分类(码) {
	case 类存取:
		return true
	case 类数:
		switch 分操(码) {
		case int(加), int(减), int(较):
			return true
		}
	}
	return false
}

// 符号扩 把 位 位之数按符号扩展至 字位 位，回其**有符号**之二之补值。
//
// 回值在 -2^（位-1）.. 2^（位-1）-1 之间，可为负。故不可再 与 字掩——
// 「与 字掩」者，是把负数抹成大字正数之术，正与此函之意相反。
// 欲得线上之无符号位样者，用 截字（补之(v)）。
func 符号扩(数, 位 int) int {
	if 位 <= 0 || 位 > 字位 {
		panic(越界("符号扩之位", 位, 1, 字位))
	}
	数 &= (1 << 位) - 1
	符位 := 1 << (位 - 1)
	if (数 & 符位) != 0 {
		数 = 数 - (符位 << 1)
	}
	return 数
}

// 截字 截一数为字位之无符号位样（0 .. 字掩）。凡加减越界者，皆须经此。
//
// 一字有两副面孔：线上之**位样**（无符号，截字 出之）与人读之**补值**
// （有符号，补之 出之）。二者是同一批爻，非两个数。
func 截字(v int) int { return v & 字掩 }

// 补之 以一 24 位之位样作二之补，回其有符号之值（-2^23 .. 2^23-1）。
func 补之(v int) int {
	v &= 字掩
	if (v & (1 << (字位 - 1))) != 0 {
		return v - (1 << 字位)
	}
	return v
}

// 扩立即数 依扩展之约，把一令之十二位立即数域扩展为二十四位之操作数。
//
// 此即 用符号 之施行：符号者经 符号扩，零扩者径取其域，皆截于字位。
// 周期.go（L2）用之；太极.go（L1）则以 用符 一线与十二个与门行同一事。
// 二者一在数中、一在门中，其约则一——Test太极与周期对拍 专验其不悖。
func 扩立即数(令 int) int {
	数 := 取立即数(令)
	if 用符号(取码(令)) {
		return 截字(符号扩(数, 数位))
	}
	return 数
}

// 截址 截一数为 址位（十八）位，即计爻器之宽。
func 截址(v int) int { return v & 址掩 }

// ------------------------------------------------------------------
// 显象
// ------------------------------------------------------------------

// 字之卦 以八卦表一 24 位之字，自高至低，左为高。
//
// 二十四位恰为八经卦——此即 典/01 所言「每一个 24 位字，自左至右
// 恰好是八个卦」。八进制在爻机中之所以不是记法而是结构事实，于此可见。
func 字之卦(v int) string {
	var b strings.Builder
	for i := 字位/器位 - 1; i >= 0; i-- {
		b.WriteString(八卦符((v >> (i * 器位)) & 器掩))
	}
	return b.String()
}

// 字之八进 以八位八进制表一 24 位之字。
func 字之八进(v int) string { return fmt.Sprintf("%08o", v&字掩) }

// 令名 取一操作码之助记名。未定之码回以「—」。
func 令名(码 int) string {
	switch 码 {
	case 停机:
		return "停机"
	case 叩:
		return "叩"
	case 载高:
		return "载高"
	case 降化:
		return "降化"
	case 回:
		return "回"
	case 载字:
		return "载字"
	case 存字:
		return "存字"
	case 跃:
		return "跃"
	case 等跃:
		return "等跃"
	case 异跃:
		return "异跃"
	case 逊跃:
		return "逊跃"
	case 胜跃:
		return "胜跃"
	}
	switch 分类(码) {
	case 类数:
		return 算爻之操(分操(码)).操名() + "数"
	case 类器:
		return 算爻之操(分操(码)).操名()
	}
	return "—"
}

// 令之辞 反汇编一令为一行之辞，如：
//
//	䷬ 萃  加数 艮, 坤, 10
//
// 未定之码则出「—」与其八进制之码。
func 令之辞(令 int) string {
	令 &= 字掩
	码 := 取码(令)
	头 := 别卦符(码) + " " + 别卦名(码)
	switch 取型(码) {
	case 甲型:
		return fmt.Sprintf("%s %s %s, %s, %s, %d", 头, 令名(码),
			卦名(取rd(令)), 卦名(取rs1(令)), 卦名(取rs2(令)), 符号扩(取偏(令), 偏位))
	case 乙型:
		数 := 取立即数(令)
		if 用符号(码) {
			数 = 符号扩(数, 数位)
		}
		return fmt.Sprintf("%s %s %s, %s, %d", 头, 令名(码),
			卦名(取rd(令)), 卦名(取rs1(令)), 数)
	case 丙型:
		return fmt.Sprintf("%s %s %d", 头, 令名(码), 取址(令))
	}
	return fmt.Sprintf("%s — 0o%02o", 头, 码)
}
