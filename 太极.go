// 计值 计爻器之现值。
func (t *太极) 计值() int { return t.网.读数(t.计.出) }

// 令值 令器之现值。
func (t *太极) 令值() int { return t.网.读数(t.令) }

// 器值 第 i 器之现值。
func (t *太极) 器值(i int) int {
	if i < 0 || i >= 8 {
		panic(越界("太极.器值", i, 0, 7))
	}
	return t.网.读数(t.堆.诸器[i])
}

// 诸器值 八器之现值，以卦号为序。
func (t *太极) 诸器值() [8]int {
	var 诸 [8]int
	for i := range 诸 {
		诸[i] = t.器值(i)
	}
	return 诸
}

// 藏值 藏中第 j 字之现值。
func (t *太极) 藏值(j int) int {
	if j < 0 || j >= t.藏.字 {
		panic(越界("太极.藏值", j, 0, t.藏.字-1))
	}
	return t.网.读数(t.藏.诸字[j])
}

// 诸字值 藏中诸字之现值。
func (t *太极) 诸字值() []int {
	诸 := make([]int, t.藏.字)
	for j := range 诸 {
		诸[j] = t.藏值(j)
	}
	return 诸
}

// 相值 相位之现值。
func (t *太极) 相值() 爻 { return t.网.读(t.相) }

// 相名 相位之名，供诊断。
func (t *太极) 相名() string {
	if t.相值() == 阳 {
		return "执行"
	}
	return "取指"
}

// 止否 机器已止否。
func (t *太极) 止否() bool { return t.网.读(t.止) == 阳 }

// 门数 全机之门数。
func (t *太极) 门数() int { return t.网.门数() }

// ------------------------------------------------------------------
// 御器
// ------------------------------------------------------------------

// 复位 清诸器归阴。此必在装载之**前**——总复 连藏一同清阴，
// 先装载后复位则前功尽弃（本轮第四险）。
func (t *太极) 复位() error {
	n := t.网
	n.驱动(t.预, 阴)
	n.驱动(t.预写, 阴)
	n.置数(t.预址, 0)
	n.置数(t.预入, 0)
	if err := n.调定(0); err != nil {
		return err
	}
	return t.辰.复位()
}

// 装载 以预装载之口，把诸字写入藏。
//
// 一遵第八戒：先置 预址、预入、预写，待调定已安，而后拍辰。
// 装载期间 相 被 ¬预 封住，计 亦不增，故装载之后相仍在取指相。
func (t *太极) 装载(诸字 []int) error {
	n := t.网
	if len(诸字) > t.藏.字 {
		return fmt.Errorf("装载：%d 字溢于藏之 %d 字", len(诸字), t.藏.字)
	}
	n.驱动(t.预, 阳)
	n.驱动(t.预写, 阴)
	n.置数(t.预址, 0)
	n.置数(t.预入, 0)
	if err := n.调定(0); err != nil {
		return err
	}
	for j, v := range 诸字 {
		n.置数(t.预址, j)
		n.置数(t.预入, v&字掩)
		n.驱动(t.预写, 阳)
		if err := n.调定(0); err != nil {
			return err
		}
		if err := t.辰.拍(); err != nil {
			return err
		}
	}
	n.驱动(t.预写, 阴)
	n.驱动(t.预, 阴)
	n.置数(t.预址, 0)
	n.置数(t.预入, 0)
	return n.调定(0)
}

// 重置并装载 复位而后装载，并载程序之常序。
func (t *太极) 重置并装载(诸字 []int) error {
	if err := t.复位(); err != nil {
		return err
	}
	return t.装载(诸字)
}

// 步 拍辰一记，即半条指令。
func (t *太极) 步() error { return t.辰.拍() }

// 跑 拍辰直至 止 为阳，或至 上限 之数。
//
// 回以所拍之数。若 上限 用尽而机器未止，则回以「跑而未止」之谬。
func (t *太极) 跑(上限 int) (int, error) {
	for i := 0; i < 上限; i++ {
		if t.止否() {
			return i, nil
		}
		if err := t.辰.拍(); err != nil {
			return i, err
		}
	}
	if t.止否() {
		return 上限, nil
	}
	return 上限, fmt.Errorf("跑：%d 拍之内机器未止（计 %d，令 0o%s）",
		上限, t.计值(), 字之八进(t.令值()))
}

// 迹 一记机器现况之辞，供对拍与诊断。
func (t *太极) 迹() string {
	诸器 := t.诸器值()
	return fmt.Sprintf("拍%-6d 相%s 计%02d 令 0o%s │ 坤%08o 艮%08o 坎%08o 巽%08o 震%08o 离%08o 兑%08o 乾%08o",
		t.辰.拍数, t.相名(), t.计值(), 字之八进(t.令值()),
		诸器[0], 诸器[1], 诸器[2], 诸器[3], 诸器[4], 诸器[5], 诸器[6], 诸器[7])
}
