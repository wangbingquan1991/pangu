package 盘古

import "fmt"

// ==================================================================
// 太极 · 中央处理器
//
// 门成、数成、时序成、令成——四者皆备，然各是一堆散件：
// 算爻器只会算，卦器堆只会记，藏只会存取，计爻器只会数数。
// 把它们按一定的**数据通路**连起来，再立一个**控制单元**
// 按时发号施令者，是谓太极。
//
// 太极之要在「两拍一令」——一令须两拍方能行完：
//
//	取指相（相 为阴）  藏址 ← 计       令器 ← 藏[计]      计 ← 计 + 1
//	执行相（相 为阳）  算、存取、跃，各依其码
//
// 之所以不能一拍一令，是因为藏之读是**纯组合**的：改址即变，不待拍辰
// （典/01「同拍写入、随时读出」）。若一拍之内既要取指又要执行，
// 则取指所得之字尚未入令器，藏址已被执行改为他值，取指遂读错。
// 分两相则取指与执行各占一拍，两不相犯。
//
// 两拍之代价是：执行某令之时，计 已指其下一令。故甲型之偏移是
// 相对**下一令**的，此即 RISC 之通例，非本系统之怪癖。
//
// ====================== 本轮之四险 ======================
//
// 一、**停机须同时封住令器。** 只封计是不够的：下一拍相翻回取指相，
//     令器之存允复阳，停机之下一字又被锁入，机器遂继续跑下去。
//     故令器、计 皆须受 ¬止 管辖，且 止 必须是**粘滞**的寄存器
//     （见其二）。此为本轮最险的一处。
//
// 二、**复位之后令器为全零，而全零正是停机之码。** 若 止 是组合信号
//     （止 = 码 == 停机），则上电即自锁，机器永不能启动。
//     故 止 用寄存器，且只在**执行相**置位——复位时相为阴（取指相），
//     止 遂为阴，机器得以取第一条令。
//
// 三、**算爻之择不可直连令之下卦。** 存取类（坎上）也要用算爻器算地址，
//     而它必须强制为 加（0）。若径以 令[20..18] 为择，则 存字（0o21，
//     下卦为艮即减）会把地址算成 rs1 − 立即数。故 择 = 与(是算爻, 令[20..18])，
//     另以 是比跃 强制为 殊 或 较。
//
// 四、**装载期间须封住相爻器。** 预装载是「外力直接写藏」，与两相之机
//     本不相干。若相在装载时翻了一记，装载之后便从执行相起跑，遂错。
//     故 相之存允 = ¬预 ∧ ¬止。又，**复位必须在装载之前**——
//     总复 会连藏一同清阴，先装载后复位则前功尽弃。
// ==================================================================

// 太极 一部以卦器堆、算爻器、藏、计爻器合成的中央处理器。
//
// 诸字段皆**线之引用**，非值。欲取其值，须经 计值、令值、器值、藏值 诸法，
// 或直接 网.读数(...)。
type 太极 struct {
	网 *网表
	辰 *辰
	址 int // 藏之地址位数，藏之字数为 1 << 址

	// 诸状态之器
	计 *计爻器 // 程序计数器，址位 位
	令 []*线 // 令器，字位 位
	相 *线   // 相位：阴为取指，阳为执行
	止 *线   // 停机之志，粘滞
	堆 *卦器堆 // 八器
	藏 *藏   // 存储器

	// 数据通路上可观的诸线
	果  []*线 // 算爻器之果
	志  *算爻志 // 算爻器之志
	写回 []*线 // 将写入卦器堆之数
	藏址 []*线 // 藏之地址
	藏入 []*线 // 将写入藏之数
	扩数 []*线 // 立即数扩展之后
	高数 []*线 // 载高 之数，即 立即数 << 12

	// 预装载之口。四者皆无驱者，由外力拨之。
	预  *线
	预写 *线
	预址 []*线
	预入 []*线

	// 译码之出，留以观（译码两级：上卦定类，下卦定操）
	上译 []*线
	下译 []*线
}

// 三 自一列线中截取三根（切片），作一卦之择，供 置译门 之属。
func 三(众 []*线, 起 int) []*线 { return 众[起 : 起+器位] }

// 三卦 自一列线中截取三根（定长），供 置卦器堆、置算爻器 之属。
func 三卦(众 []*线, 起 int) [3]*线 { return [3]*线{众[起], 众[起+1], 众[起+2]} }

// 建太极 造一部太极，藏之地址位数为 址。
//
// 与 建周期机 相对：彼造 L2（纯整数，无门），此造 L1（门级，三万余门）。
// 二者之名相对、之用相对，而其**果须全同**——对拍之所验者，即此。
func 建太极(址 int) *太极 {
	return 建网表(fmt.Sprintf("太极%d", 址)).置太极(址)
}

// 置太极 造一部中央处理器。址 为藏之地址位数，须在 1..8 之间。
//
// 计爻器恒为 址位（18）位，与丙型之地址域同宽；藏之地址只取其低 址 位。
// 故 L1 之藏虽小（至多 256 字），计 之语义与将来之真机全同——
// 此乃对拍之所以可行。
func (n *网表) 置太极(址 int) *太极 {
	if 址 <= 0 || 址 > 8 {
		panic(fmt.Sprintf("置太极：藏之地址位数 %d 须在 1..8 之间", 址))
	}
	t := &太极{网: n, 址: 址}
	c := 建辰(n, n.置辰线())
	t.辰 = c
	辰线 := c.线

	// --------------------------------------------------------------
	// 一、预装载之口。四者皆无驱，待外力拨之。
	// --------------------------------------------------------------
	t.预 = n.引线("预")
	t.预写 = n.引线("预写")
	t.预址 = n.列线("预址", 址)
	t.预入 = n.列线("预入", 字位)
	反预 := n.反相(t.预)

	// --------------------------------------------------------------
	// 二、计爻器。其 入、载、增 三者皆 Gate 之出，此刻只立其线，
	//     俟诸谓词既备而后驱之。
	// --------------------------------------------------------------
	计入 := n.列线("计入", 址位)
	计载 := n.引线("计载")
	计增 := n.引线("计增")
	t.计 = n.置计爻器(址位, 计入, 计载, 计增, 辰线)

	// --------------------------------------------------------------
	// 三、令器、相、止 三者，此刻亦只立其线。
	//
	// 令器之入是 藏之出，而 藏 又须 果 而 果 又须 令器——
	// 三者首尾相衔。破解之法：先立其线（列线 只造线，不造门），
	// 俟通路既成，最后方以 置存爻器 闭合其环。
	// 环之所以可闭而不成组合回路，是因为环上必有锁爻器（计、令器、
	// 相、堆、藏皆是），而锁爻器之从级在辰阴之时守而不纳。
	// --------------------------------------------------------------
	t.令 = n.列线("令", 字位)
	t.相 = n.引线("相")
	t.止 = n.引线("止")
	反相 := n.反相(t.相)
	反止 := n.反相(t.止)

	// --------------------------------------------------------------
	// 四、译码。两级 3→8，共百二门；若径用 6→64 则七百七十四门。
	//
	// 上卦众[0] 为最低位，故取 令[21..23]；下卦取 令[18..20]。
	// --------------------------------------------------------------
	t.上译 = n.列线("上译", 8)
	t.下译 = n.列线("下译", 8)
	n.置译门(三(t.令, 字位-器位), t.上译) // 令[21..23]，定其类
	n.置译门(三(t.令, 字位-码位), t.下译) // 令[18..20]，定其操

	// 诸谓词。每一条皆一个二入与门，故不另注其门数。
	是 := func(上, 下 int) *线 {
		w := n.私线()
		n.置与门(t.上译[上], t.下译[下], w)
		return w
	}
	存取 := t.上译[类存取]
	类数 := t.上译[类数]
	类器 := t.上译[类器]

	是停机 := 是(类内务, 0) // 0o00 坤·坤
	是叩 := 是(类内务, 1)  // 0o01 坤·艮
	是载高 := 是(类内务, 2) // 0o02 坤·坎
	是载字 := 是(类存取, 0) // 0o20 坎·坤
	是存字 := 是(类存取, 1) // 0o21 坎·艮
	是丙跃 := 是(类转移, 0) // 0o40 震·坤
	是等跃 := 是(类转移, 1) // 0o41 震·艮
	是异跃 := 是(类转移, 2) // 0o42 震·坎
	是逊跃 := 是(类转移, 3) // 0o43 震·巽
	是胜跃 := 是(类转移, 4) // 0o44 震·震

	或 := func(甲, 乙 *线) *线 {
		w := n.私线()
		n.置或门(甲, 乙, w)
		return w
	}
	与 := func(甲, 乙 *线) *线 {
		w := n.私线()
		n.置与门(甲, 乙, w)
		return w
	}

	是算爻 := 或(类数, 类器)
	是较跃 := 或(是逊跃, 是胜跃)         // 用 较 之二跃
	是比跃 := 或(或(是等跃, 是异跃), 是较跃) // 四条条件跃之总
	是写回 := 或(或(是算爻, 是载高), 是载字)
	是数 := 或(存取, 类数) // 乙 取立即数而非 乙源器
	是止 := 或(是停机, 是叩)

	// --------------------------------------------------------------
	// 五、立即数之扩展与 载高 之数。
	//
	// 扩数[i] = 令[i]（i < 数位）；其上诸位 = 令[数位-1] 与 用符。
	// 用符 者，存取恒符号，加、减、较 符号，余者零扩——一遵 令.go 之 用符号。
	//
	// 高数 不耗一门：低十二位接地，高十二位径引 令[0..11]，
	// 此即「立即数 << 12」在硅上的本来面目——它只是一束错位的线。
	// --------------------------------------------------------------
	是符操 := n.私线()
	n.置全或门([]*线{t.下译[int(加)], t.下译[int(减)], t.下译[int(较)]}, 是符操)
	用符 := 或(存取, 与(类数, 是符操))

	// 高数 不耗一门：低十二位接地，高十二位径引 令[0..11]，
	// 此即「立即数 << 12」在硅上的本来面目——它只是一束错位的线。
	t.扩数 = make([]*线, 字位)
	t.高数 = make([]*线, 字位)
	低零 := n.阴列(数位)
	for i := 0; i < 数位; i++ {
		t.扩数[i] = t.令[i]
		t.高数[i] = 低零[i]
		t.高数[i+数位] = t.令[i]
	}
	for i := 数位; i < 字位; i++ {
		w := n.私线()
		n.置与门(t.令[数位-1], 用符, w)
		t.扩数[i] = w
	}

	// --------------------------------------------------------------
	// 六、卦器堆。
	//
	// 读甲 恒为 rs1（令[14..12]）。读乙 平时为 rs2（令[11..9]），
	// 唯 存字 反作 rd（令[17..15]）——盖 乙型 之 rd 域于 存字 之中
	// 不作目的而作源。此一处反常，ISA 之代价也。
	//
	// 写口之号 恒为 rd（令[17..15]）。
	// --------------------------------------------------------------
	读甲 := 三卦(t.令, 12)
	读乙 := [3]*线{}
	for b := 0; b < 器位; b++ {
		w := n.引线(fmt.Sprintf("读乙%d", b))
		n.置择门(是存字, t.令[9+b], t.令[15+b], w)
		读乙[b] = w
	}
	堆号 := 三卦(t.令, 15)

	t.写回 = n.列线("写回", 字位)
	堆存允 := n.引线("堆存允")
	t.堆 = n.置卦器堆(字位, t.写回, 堆号, 堆存允, 辰线, 读甲, 读乙)

	// 坤恒为零：rd 域全阴则全或为阴，写入被吞。八个择门之价，
	// 比在堆内译码（五十余门）省得多——且堆本身仍旧通用，不知此事。
	非零rd := n.私线()
	n.置全或门([]*线{t.令[15], t.令[16], t.令[17]}, 非零rd)
	n.置与门(与(t.相, 是写回), 非零rd, 堆存允)

	// --------------------------------------------------------------
	// 七、算爻器。
	//
	// 甲 恒为 甲源器（堆之甲口），乙 于 是数 之时取 扩数，否则取 乙源器。
	//
	// 择 之三爻最要小心（本轮第三险）：
	//
	//	择[0] = 或（与（是算爻，令[18]），是较跃）
	//	择[1] = 或（与（是算爻，令[19]），是较跃）
	//	择[2] = 或（与（是算爻，令[20]），是比跃）
	//
	// 验之：类存取 → 是算爻 阴、是比跃 阴 → 000 = 加 ✓
	//       等跃、异跃 → 是较跃 阴、是比跃 阳 → 100 = 殊 ✓（异或为零即相等）
	//       逊跃、胜跃 → 是较跃 阳            → 111 = 较 ✓
	//       算爻之类   → 是比跃 阴            → 下卦 ✓
	// --------------------------------------------------------------
	乙元 := n.列线("乙元", 字位)
	for i := 0; i < 字位; i++ {
		n.置择门(是数, t.堆.出乙[i], t.扩数[i], 乙元[i])
	}
	择 := [3]*线{}
	for b := 0; b < 器位; b++ {
		择[b] = n.引线(fmt.Sprintf("择%d", b))
	}
	n.置或门(与(是算爻, t.令[字位-码位+0]), 是较跃, 择[0])
	n.置或门(与(是算爻, t.令[字位-码位+1]), 是较跃, 择[1])
	n.置或门(与(是算爻, t.令[字位-码位+2]), 是比跃, 择[2])

	t.果 = n.列线("果", 字位)
	t.志 = n.置算爻器(t.堆.出甲, 乙元, 择, t.果)

	// --------------------------------------------------------------
	// 八、藏。
	//
	// 藏址 = 预 ? 预址 :（相 ? 果 : 计）
	// 藏入 = 预 ? 预入 : 堆之乙口
	// 藏之存允 = 预 ? 预写 :（相 与 是存字）
	// --------------------------------------------------------------
	t.藏址 = n.列线("藏址", 址)
	for i := 0; i < 址; i++ {
		常址 := n.私线()
		n.置择门(t.相, t.计.出[i], t.果[i], 常址)
		n.置择门(t.预, 常址, t.预址[i], t.藏址[i])
	}
	t.藏入 = n.列线("藏入", 字位)
	for i := 0; i < 字位; i++ {
		n.置择门(t.预, t.堆.出乙[i], t.预入[i], t.藏入[i])
	}
	常写 := 与(t.相, 是存字)
	藏存允 := n.引线("藏存允")
	n.置择门(t.预, 常写, t.预写, 藏存允)
	t.藏 = n.置藏(字位, 址, t.藏址, t.藏入, 藏存允, 辰线)

	// --------------------------------------------------------------
	// 九、写回之择。
	//
	//	写回 = 载高 ? 高数 :（载字 ? 藏之出 : 果）
	//
	// 存字 不写回——它所写者在藏，不在器。
	// --------------------------------------------------------------
	for i := 0; i < 字位; i++ {
		层 := n.私线()
		n.置择门(是载字, t.果[i], t.藏.出[i], 层)
		n.置择门(是载高, 层, t.高数[i], t.写回[i])
	}

	// --------------------------------------------------------------
	// 十、跃与计。
	//
	// 四条条件跃皆以算爻器之 志.零 判之，然取直取反，各各不同：
	//
	//	等跃  择 殊（异或）  志.零 = ¬或有(rs1^rs2) = 相等       取直
	//	异跃  择 殊          ¬志.零 = 不等                    取反
	//	逊跃  择 较          果 = rs1<rs2 ? 1 : 0；¬志.零 = 小于  取反
	//	胜跃  择 较          志.零 = ¬(rs1<rs2) = 不小于        取直
	//
	// 「胜」名曰胜，义为「不小于」——此是被电路逼出来的（典/01 已志）。
	//
	// 跃之目标：丙型之 跃 取绝对地址（不费一门），四条条件跃取
	// 计 + 符号扩（偏），故须另一具 址位 位之加法器。
	// 之所以不令算爻器兼算跃之目标（省去一加法器），是因为那样
	// 就得给算爻器的 甲 口再添一重 字位 位之择门（百九十二门），
	// 比另立一具十八位加法器（百六十二门）更贵。
	// --------------------------------------------------------------
	取反 := 或(是异跃, 是逊跃)
	跃志 := n.私线()
	n.置择门(取反, t.志.零, n.反相(t.志.零), 跃志)
	跃之决 := 或(是丙跃, 与(是比跃, 跃志))

	偏扩 := make([]*线, 址位)
	for i := 0; i < 偏位; i++ {
		偏扩[i] = t.令[i]
	}
	for i := 偏位; i < 址位; i++ {
		偏扩[i] = t.令[偏位-1] // 符号之位，径引之，不费一门
	}
	计偏和 := n.列线("计偏和", 址位)
	n.置加爻器(t.计.出, 偏扩, n.恒阴(), 计偏和)
	for i := 0; i < 址位; i++ {
		n.置择门(是丙跃, 计偏和[i], t.令[i], 计入[i])
	}
	n.置与门(t.相, 跃之决, 计载)

	// 取指之允 = ¬相 ∧ ¬预 ∧ ¬止。计之增 与 令器之存允 同用此一根——
	// 二者所求本是同一件事「此拍该取指否」，若各造一与门，则他日改其一
	// 而忘其二，机器遂半身不遂。
	取指允 := n.引线("取指允")
	n.置全与门([]*线{反相, 反预, 反止}, 取指允)
	n.置全与门([]*线{取指允}, 计增)

	// --------------------------------------------------------------
	// 十一、闭合其环：立 令器、相、止 三器。
	//
	// 令器之存允 = ¬相 ∧ ¬预 ∧ ¬止。三缺一不可：
	// 缺 ¬相 则执行相亦锁令（令器会被藏之出改写）；
	// 缺 ¬预 则装载之时乱锁；
	// 缺 ¬止 则停机之后，下一拍相翻回取指相，停机之下一字复被锁入，
	// 机器遂跑下去——此即本轮第一险。
	//
	// 止志之存允 = 相 ∧ 是止。必带 相：复位之后令器全零而全零正是停机，
	// 若止是组合信号则上电即自锁。加一 相 则复位时（相为阴）止不得置，
	// 机器遂能取第一条令——此即本轮第二险。
	// --------------------------------------------------------------
	令存允 := n.引线("令存允")
	n.置全与门([]*线{取指允}, 令存允)
	n.置存爻器(t.藏.出, 令存允, 辰线, t.令)

	相存允 := n.引线("相存允")
	n.置与门(反预, 反止, 相存允)
	n.置存爻器([]*线{反相}, 相存允, 辰线, []*线{t.相})

	止存允 := n.引线("止存允")
	n.置与门(t.相, 是止, 止存允)
	n.置存爻器([]*线{n.恒阳()}, 止存允, 辰线, []*线{t.止})

	return t
}

