package 盘古

import (
	"fmt"
	"strings"
)

// 象者，爻聚而成形。两爻为四象，三爻为八卦，六爻为别卦。
//
// ============================ 位序之约 ============================
//
// 本系统同时存在两套位序，二者互为镜像，不可混用：
//
//	一、数值之位序：入[0] 为最低位，权重 2^0。凡运算、地址、立即数皆用此序。
//	二、卦象之位序：初爻（最下爻）为最高位，自下而上书写。此即邵雍先天之序，
//	    亦与 Unicode 卦符的排列方向一致。
//
// 因此：三爻所成之数 v，其对应之卦在 Unicode 中的序位为 7-v。
// 值 7（阳阳阳）为乾 ☰，值 0（阴阴阴）为坤 ☷。
//
// 两套位序的转换一律经由本文件中的函数完成，其余各处不得自行换算。
// ==================================================================

const (
	// 四象基 U+268C ⚌ 太阳，其后依次 少阴 少阳 太阴。
	四象基 = 0x268C
	// 八卦基 U+2630 ☰ 乾，其后依次 兑 离 震 巽 坎 艮 坤（先天序）。
	八卦基 = 0x2630
)

// 八卦名表 依 Unicode 序位排列，即先天八卦序：乾一、兑二、离三、震四、巽五、坎六、艮七、坤八。
var 八卦名表 = [8]string{"乾", "兑", "离", "震", "巽", "坎", "艮", "坤"}

// 四象符 值取 0..3，其二进制自高至低对应初爻至上爻。
//
//	3 = 阳阳 ⚌ 太阳    2 = 阳阴 ⚍ 少阴
//	1 = 阴阳 ⚎ 少阳    0 = 阴阴 ⚏ 太阴
func 四象符(值 int) string {
	if 值 < 0 || 值 > 3 {
		panic(越界("四象符", 值, 0, 3))
	}
	return string(rune(四象基 + 3 - 值))
}

// 八卦符 值取 0..7，其二进制自高至低对应初爻、二爻、三爻。
func 八卦符(值 int) string {
	if 值 < 0 || 值 > 7 {
		panic(越界("八卦符", 值, 0, 7))
	}
	return string(rune(八卦基 + 7 - 值))
}

// 卦名 取八卦之汉字名。值之位序同 八卦符。
func 卦名(值 int) string {
	if 值 < 0 || 值 > 7 {
		panic(越界("卦名", 值, 0, 7))
	}
	return 八卦名表[7-值]
}

// 六爻符 以「上卦在下卦之上」的常法表一别卦，如 ☰☰ 为乾、☷☰ 为地天泰。
//
// 众[0] 为初爻，众[5] 为上爻。
//
// 按卦象位序，下卦以初爻为高位，上卦以四爻为高位。
func 六爻符(众 [6]爻) string {
	下 := 众[0].数()<<2 | 众[1].数()<<1 | 众[2].数()
	上 := 众[3].数()<<2 | 众[4].数()<<1 | 众[5].数()
	return 八卦符(上) + 八卦符(下)
}

// 串爻 将一列爻连写成 ⚊⚋ 之形，自初爻起。
func 串爻(众 []爻) string {
	var b strings.Builder
	for _, y := range 众 {
		b.WriteString(y.符())
	}
	return b.String()
}

// 排爻 将值排成一列爻，自高至低，用于显象（卦象位序）。
//
// 欲还原为数值，须先 倒爻 再 并爻，因二者位序相反。
func 排爻(值 int, 位 int) []爻 {
	众 := make([]爻, 位)
	for i := 0; i < 位; i++ {
		众[i] = 由数(值 >> (位 - 1 - i) & 1)
	}
	return 众
}

// 并爻 将一列爻并为整数，众[0] 为最低位（数值位序）。
func 并爻(众 []爻) int {
	v := 0
	for i, y := range 众 {
		v |= y.数() << i
	}
	return v
}

// 倒爻 将一列爻首尾颠倒，用于卦象位序与数值位序之间的转换。
func 倒爻(众 []爻) []爻 {
	倒 := make([]爻, len(众))
	for i, y := range 众 {
		倒[len(众)-1-i] = y
	}
	return 倒
}

// 越界 造一例统一的越界报错之辞。
func 越界(处 string, 值, 低, 高 int) string {
	return fmt.Sprintf("%s：值 %d 越出 %d..%d", 处, 值, 低, 高)
}
