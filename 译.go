// 令之译 反汇编一令为**可回译**之规范式。
//
// 与 令之辞 之别：令之辞 是给人看的（带卦符头、卦名、读来明白）；
// 令之译 是给机器读回的（唯助记与诸元），且其**可回译**——
//
//	汇一（令之译（令））恒等于 令
//
// 此式是译卦器之命脉。它若不成立，则人读到的与机器执行的是两件事，
// 反汇编便成了谎言——错，且错得悄无声息。故 往返 一验穷举而为之。
//
// 三型之式：
//
//	甲型　助记 rd, rs1, rs2, 偏       偏以有符号书之（−256..255）
//	乙型　助记 rd, rs1, 数            数依 用符号 之约，符号者可为负
//	丙型　助记 址                     十八位之址，恒书之
//
// 丙型之址**恒书**，纵 停机 之址无义亦书。何也？
//
// 一、**省址是糖，正体当全**。人写「停机」，机器当出「停机 0」——
//
//	正如人写「加 震, 坎, 巽」，机器出「加 震, 坎, 巽, 0」。
//	若 停机 独免，则 省址 之糖与之对应的正体之间便断了一层，
//	而演示（丁）分明写着「停机 ≡ 停机 0」，令之译 却出「停机」——
//	**同一件事，两副面孔；两副面孔之中，必有一副是假的。**
//
// 二、**甲型已先如此**。等跃 不用 rd，而规范式仍书 rd（作 坤）。
//
//	不用之域尚且书之，无义之址反而不书，是自相矛盾。
//
// 三、例外之单是债。昔日此处写着「码 != 停机 && 码 != 叩」——
//
//	一张手抄的操作码名单，伏在格式化函数之中。
//	他日增一丙型之令而忘改此处，其反汇编便不可回译，
//	而**往返之验未必察之**（若该令之址恰常为零）。此债不立。
//
// 故：规范式者，**一律全写**；省者，糖之事，非规范之事。
func 令之译(令 int) string {
	令 &= 字掩
	码 := 取码(令)
	名 := 令名(码)
	switch 取型(码) {
	case 甲型:
		return fmt.Sprintf("%s %s, %s, %s, %d", 名,
			卦名(取rd(令)), 卦名(取rs1(令)), 卦名(取rs2(令)), 符号扩(取偏(令), 偏位))
	case 乙型:
		数 := 取立即数(令)
		if 用符号(码) {
			数 = 符号扩(数, 数位)
		}
		return fmt.Sprintf("%s %s, %s, %d", 名,
			卦名(取rd(令)), 卦名(取rs1(令)), 数)
	case 丙型:
		return fmt.Sprintf("%s %d", 名, 取址(令))
	}
	return fmt.Sprintf("未定 0o%02o", 码)
}

// 反汇 一列机器码反汇编为一列规范之译辞。
func 反汇(诸令 []int) []string {
	诸 := make([]string, len(诸令))
	for i, 令 := range 诸令 {
		诸[i] = 令之译(令)
	}
	return 诸
}

// 反汇之文 一列机器码反汇编为一段源码，一字一行，可径付 汇。
//
// 之所以委诸 反汇 而不自起一循环：**决定「规范式长什么样」的地方只该有一处**。
// 若此处自起一循环、另写一遍 令之译，则他日改了规范式，一处改一处未改，
// 反汇编便有了两副面孔——而两副面孔之中，必有一副是假的。
//
// 此病作者犯过（变异十一存活：反汇 误用 令之辞而诸案不察），故志之。
func 反汇之文(诸令 []int) string {
	诸 := 反汇(诸令)
	if len(诸) == 0 {
		return ""
	}
	return strings.Join(诸, "\n") + "\n"
}
