// 译令 译一令之行。址 为此令之址——甲型之相对偏须以之折算。
func 译令(l 译行, 址 int, 标签 map[string]int) (int, []译过) {
	码, 有 := 助记码表[l.助记]
	if !有 && utf8.RuneCountInString(l.助记) == 1 {
		// 卦符直书者：䷬ 便是 加数，☷ 便是 停机。
		// 卦符本就是操作码，故以卦符为助记，不是糖，是归其本。
		r, _ := utf8.DecodeRuneInString(l.助记)
		if v, 是卦 := 译卦符(r); 是卦 {
			码, 有 = v, true
		}
	}
	if !有 {
		return 0, 造过(l.行, l.原文, "未知之助记符「%s」；卦符亦可为助记，如 ䷬ 即 加数", l.助记)
	}
	switch 取型(码) {
	case 甲型:
		return 译甲(l, 码, 址, 标签)
	case 乙型:
		return 译乙(l, 码, 址, 标签)
	case 丙型:
		return 译丙(l, 码, 址, 标签)
	}
	return 0, 造过(l.行, l.原文, "「%s」（0o%02o）之码未定，机器遇之无所措", l.助记, 码)
}

// 译甲 译一甲型之令：[6b 码][3b rd][3b rs1][3b rs2][9b 偏]。
//
// 甲型有两类，其元之序不同，故不可一律解之：
//
//	算爻之类（乾上）　助记 rd, rs1, rs2 [, 偏]     偏不用，缺省为零
//	转移之类（震上）　助记 rs1, rs2, 目标          三元者，rd 恒坤
//	               　助记 rd, rs1, rs2, 偏        四元者，反汇编之规范式用此
//
// 三元之跃是给人写的糖；四元之跃是反汇编写的正体。二者并存，
// 故人读到的与机器执行的仍是同一条令（往返之验专验此）。
func 译甲(l 译行, 码, 址 int, 标签 map[string]int) (int, []译过) {
	是跃 := 分类(码) == 类转移
	n := len(l.诸元)
	var 众 []译过
	var rd, rs1, rs2, 偏 int
	switch {
	case 是跃 && n == 3:
		rs1, 众 = 译器(l, l.诸元[0], 众)
		rs2, 众 = 译器(l, l.诸元[1], 众)
		偏, 众 = 译偏(l, l.诸元[2], 址, 标签, 众)
	case n == 3 || n == 4:
		rd, 众 = 译器(l, l.诸元[0], 众)
		rs1, 众 = 译器(l, l.诸元[1], 众)
		rs2, 众 = 译器(l, l.诸元[2], 众)
		if n == 4 {
			偏, 众 = 译偏(l, l.诸元[3], 址, 标签, 众)
		}
	default:
		return 0, append(众, 造过(l.行, l.原文,
			"甲型之令须三或四元，此有 %d 元", n)...)
	}
	return 编甲(码, rd, rs1, rs2, 偏), 众
}

// 译乙 译一乙型之令：[6b 码][3b rd][3b rs1][12b 数]。
//
// 三式并存，其果则一：
//
//	正式　助记 rd, rs1, 数           反汇编用此（三元，域域俱到）
//	括号　助记 rd, [rs1 ± 数]        存取之令读来更顺，如「载字 震, [艮 + 4]」
//	省rs1　载高 rd, 数               载高 不用 rs1，故可省之
//
// 括号之式唯存取（载字、存字）用得着，然此处不为之设限——
// 凡乙型皆可书，存取读之最顺，他令书之亦无害。
//
// 三元之式**不可省**：反汇编出的正是它，省了则往返之路断。
// 其余二式是给人写的糖，译出来与三元之式同一条令。
func 译乙(l 译行, 码, 址 int, 标签 map[string]int) (int, []译过) {
	var 众 []译过
	var rd, rs1, 数 int
	if len(l.诸元) == 2 && strings.HasPrefix(l.诸元[1], "[") {
		rd, 众 = 译器(l, l.诸元[0], 众)
		基, 偏, err := 析括(l.诸元[1], 标签)
		if err != nil {
			众 = append(众, 译过{行: l.行, 原文: l.原文, 辞: err.Error()})
		}
		偏, 众 = 校界(l, 用符号(码), 数位, "偏移", 偏, 众)
		return 编乙(码, rd, 基, 偏), 众
	}
	// 载高 不用 rs1：其 rs1 之域在电路中悬着，写什么都一样。
	// 与其教人每回都写一个 坤，不如容他省去。
	if 码 == 载高 && len(l.诸元) == 2 {
		rd, 众 = 译器(l, l.诸元[0], 众)
		数, 众 = 译元数(l, 码, l.诸元[1], 标签, 众)
		return 编乙(码, rd, 0, 数), 众
	}
	if len(l.诸元) != 3 {
		return 0, 造过(l.行, l.原文,
			"乙型之令须三元（rd, rs1, 数）或括号式（rd, [rs1 ± 数]），此有 %d 元", len(l.诸元))
	}
	rd, 众 = 译器(l, l.诸元[0], 众)
	rs1, 众 = 译器(l, l.诸元[1], 众)
	数, 众 = 译元数(l, 码, l.诸元[2], 标签, 众)
	return 编乙(码, rd, rs1, 数), 众
}

// 析括 析「[基 ± 偏]」为（基之器号，偏）。
func 析括(文 string, 标签 map[string]int) (基, 偏 int, err error) {
	if !strings.HasPrefix(文, "[") || !strings.HasSuffix(文, "]") {
		return 0, 0, fmt.Errorf("「%s」非括号之式；当作 [基 ± 偏]", 文)
	}
	内 := strings.ReplaceAll(文[len("["):len(文)-len("]")], " ", "")
	if 内 == "" {
		return 0, 0, fmt.Errorf("括号内空，当作 [基 ± 偏]")
	}
	// 自第二符起寻 + 或 -，使偏自带之负号不与分符相混。
	for i, r := range 内 {
		if i == 0 || (r != '+' && r != '-') {
			continue
		}
		号, 有 := 器号表[内[:i]]
		if !有 {
			return 0, 0, fmt.Errorf("「%s」非卦器之名", 内[:i])
		}
		v, err := 译数(内[i:], 标签)
		if err != nil {
			return 0, 0, err
		}
		return 号, v, nil
	}
	号, 有 := 器号表[内]
	if !有 {
		return 0, 0, fmt.Errorf("「%s」非卦器之名；括号内当作 [基 ± 偏]", 内)
	}
	return 号, 0, nil
}

// 译丙 译一丙型之令：[6b 码][18b 址]。
//
// 停机 与 叩 之址为零者，可径书 停机／叩，不必拖一个零。
// 反汇编亦然（见 令之译），故往返仍是同一条令。
func 译丙(l 译行, 码, 址 int, 标签 map[string]int) (int, []译过) {
	if len(l.诸元) == 0 {
		if 码 != 停机 && 码 != 叩 {
			return 0, 造过(l.行, l.原文, "「%s」须一址", 令名(码))
		}
		return 编丙(码, 0), nil
	}
	if len(l.诸元) != 1 {
		return 0, 造过(l.行, l.原文, "丙型之令至多一元，此有 %d 元", len(l.诸元))
	}
	v, err := 译数(l.诸元[0], 标签)
	if err != nil {
		return 0, []译过{{行: l.行, 原文: l.原文, 辞: err.Error()}}
	}
	var 众 []译过
	v, 众 = 校界(l, false, 址位, "地址", v, 众)
	return 编丙(码, v), 众
}

