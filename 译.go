// 汇 译一段源码为机器码。两遍而成：一遍记址，二遍编码。
//
// 两遍之故：标签可前引（跳向后面尚未译到的地方），
// 故必先尽记诸标签之址，方能折算相对之偏。一遍者做不到。
func 汇(源 string) *译果 {
	r := &译果{标签: map[string]int{}}
	诸行 := 分行(源)

	// 一遍：记址。
	址 := 0
	for _, l := range 诸行 {
		for _, 名 := range l.标签 {
			if _, 有 := r.标签[名]; 有 {
				r.过 = append(r.过, 造过(l.行, l.原文, "标签「%s」重出；一处之址不可有二名", 名)...)
				continue
			}
			if _, err := 译数(名, nil); err == nil {
				r.过 = append(r.过, 造过(l.行, l.原文,
					"「%s」是数，不可为标签之名；数名混则寻址无据", 名)...)
				continue
			}
			r.标签[名] = 址
		}
		switch l.助记 {
		case "":
		case 伪处:
			if len(l.诸元) != 1 {
				r.过 = append(r.过, 造过(l.行, l.原文, "处 须一元（址），此有 %d 元", len(l.诸元))...)
				continue
			}
			v, err := 译数(l.诸元[0], nil) // 处 之址须是常数，不得引标签
			if err != nil {
				r.过 = append(r.过, 译过{行: l.行, 原文: l.原文, 辞: err.Error()})
				continue
			}
			if v < 0 || v > 址掩 {
				r.过 = append(r.过, 造过(l.行, l.原文, "处 %d 越出 0..%d", v, 址掩)...)
				continue
			}
			址 = v
		case 伪字:
			if len(l.诸元) == 0 {
				址++
				continue
			}
			址 += len(l.诸元)
		default:
			址++
		}
	}
	if len(r.过) > 0 {
		return r
	}

	// 二遍：编码。
	址 = 0
	for _, l := range 诸行 {
		switch l.助记 {
		case "":
		case 伪处:
			v, _ := 译数(l.诸元[0], nil)
			址 = v
		case 伪字:
			for _, 元 := range l.诸元 {
				v, err := 译数(元, r.标签)
				if err != nil {
					r.过 = append(r.过, 译过{行: l.行, 原文: l.原文, 辞: err.Error()})
					v = 0
				}
				r.置(址, 截字(v))
				址++
			}
			if len(l.诸元) == 0 {
				r.置(址, 0)
				址++
			}
		default:
			令, 众 := 译令(l, 址, r.标签)
			r.过 = append(r.过, 众...)
			r.置(址, 令)
			址++
		}
	}
	return r
}

// 汇一 译一行为之机器码。用于往返之验，不涉标签与伪令。
//
// 之所以另出此函而非复用 汇：往返之验须跑数百万次，
// 汇 之两遍、补零、造 译果，于此皆是白费。
func 汇一(辞 string) (int, error) {
	诸 := 分行(辞)
	if len(诸) == 0 {
		return 0, fmt.Errorf("无有可译之辞")
	}
	if len(诸) > 1 {
		return 0, fmt.Errorf("汇一 只译一行，此有 %d 行", len(诸))
	}
	l := 诸[0]
	if len(l.标签) != 0 {
		return 0, fmt.Errorf("汇一 不纳标签")
	}
	if l.助记 == "" {
		return 0, fmt.Errorf("无有助记符")
	}
	令, 众 := 译令(l, 0, nil)
	if len(众) > 0 {
		return 0, fmt.Errorf("%s", 众[0].辞)
	}
	return 令, nil
}

