// 助记码表 助记名 → 操作码。由 令名 反查而成，不手抄。
//
// 凡 取型 未定之码不入表，故表中之数即是本机**实有之令**数。
// 令增一，此表自长，无须人来记。
var 助记码表 = 造助记码表()

func 造助记码表() map[string]int {
	表 := make(map[string]int, 别卦数)
	for 码 := 0; 码 < 别卦数; 码++ {
		if 取型(码) == 未定型 {
			continue
		}
		表[令名(码)] = 码
	}
	return 表
}

// 器号表 卦名与卦符 → 卦器之号（0..7）。亦由 卦名/八卦符 反查而成。
//
// 故卦器可书 乾、兑、离、震、巽、坎、艮、坤，亦可书 ☰☱☲☳☴☵☶☷。
var 器号表 = 造器号表()

func 造器号表() map[string]int {
	表 := make(map[string]int, 16)
	for v := 0; v < 8; v++ {
		表[卦名(v)] = v
		表[八卦符(v)] = v
	}
	return 表
}

