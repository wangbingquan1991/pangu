// ==================================================================
// 译 · 译卦器（汇编器与反汇编器）
//
// M3 之前，本机唯一的程序是 程.go 里那三段**手编**的机器码。
// 每一条都要人自己去算「操作码左移十八位，或上 rd 左移十五位……」，
// 一条算错，机器照跑不误，只是跑去了别处——错，且错得悄无声息。
//
// 译卦器所成者，是让人写「加数 艮, 坤, 10」，而由机器去算那些移位。
//
// 名字里的「卦」字不是装饰。助记符可以写汉字，也可以**直接写卦符**：
// ䷬ 便是 加数，☰ 便是 乾器，䷀ 便是数六十三。
// 卦符在源码里不是注释，是字——因为操作码本来就是一个别卦。
//
// 三件要紧事：
//
//	一、**双向之约**。令名 由码出名，助记码表 由名出码，
//	    二者皆自 取型/分类 推出，不由人手抄。故增一令，两侧同时长出来，
//	    不会一侧记得、一侧忘了。
//	二、**往返之验**。反汇编之规范式（令之译）必须能被 汇 原样读回：
//	    汇（反汇（令））恒等于 令。此式若不成立，则人读到的与机器执行的
//	    是两件事，反汇编就成了谎言。故 往返 一验穷举而为之（见 译_test.go）。
//	三、**过而不止**。译卦遇错不立停，尽其所能多报几处，
//	    每过皆带行号与原文。一行之错，不该教人改一处再跑一遍。
//
// 伪令二：处（定址）、字（置一字之数据）。
//
// 标签之别，最易忘：甲型之偏是**相对量**，书标签则译卦器折算
// 目标 −（本令址 + 1）；乙型之数与丙型之址是**绝对址**。
// 忘此别，则跳偏一个字——错，且错得悄无声息。
// ==================================================================

// 伪令 汇编之伪令，非机器之令。
const (
	伪处 = "处" // 处 址：定其后之码置于何址
	伪字 = "字" // 字 数…：径置一字之数据，不作令解
)

// 注之符 注释之起符。自此符至行末，皆为注。
const 注之符 = '；'

// 签之符 标签之尾符。全角为正；亦纳半角，以省输入法切换之劳。
const 签之符 = "：:"

// 元之符 诸元之分符。全角为正；亦纳半角。
const 元之符 = "，,"

// 引之符 字符字面之引号。引号之内，注符、签符、元符**皆失其力**。
const 引之符 = '\''

// 巡符 于 文 中寻 诸符 之一之首次出现，回其字节之位；无则 −1。
//
// # 引号之内不寻
//
// 注之符「；」、签之符「：」、元之符「，」三者皆是全角标点，
// 而**全角标点本身即是汉字**。人写 `字 '，'` 是要置一个逗字，
// 不是要把那一行切成两元。若径以分符切之，便切成「字 '」与「'」，
// 两边皆不可译——而机器报的过是「「'」非数，亦非卦符、非标签」，
// 报的是症状，不是病根；人看了只当自己写错了，不知是机器容不下这个字。
//
// # 此难中文所独有
//
// 英文之 `,` `:` `;` 不是词，故其分词器无须这一问；
// 而中文之分符，**字与符同体**。凡分符而又是字者，皆须让位于引号——
// 此是「词法先于句法」之常道，于中文则尤不可省。
//
// 省之，则一整类汉字永不可作字面量。而那一类恰恰是最常用的标点。
func 巡符(文 string, 诸符 string) int {
	在引 := false
	for i, r := range 文 {
		if r == 引之符 {
			在引 = !在引
			continue
		}
		if !在引 && strings.ContainsRune(诸符, r) {
			return i
		}
	}
	return -1
}

// 分元 分一段为诸元，以 元之符 为界。引号之内不分，其详见 巡符。
//
// 空元弃之（如末了多一个逗号），以从旧例。
func 分元(文 string) []string {
	var 诸 []string
	在引 := false
	起 := 0
	for i, r := range 文 {
		switch {
		case r == 引之符:
			在引 = !在引
		case !在引 && strings.ContainsRune(元之符, r):
			if 元 := strings.TrimSpace(文[起:i]); 元 != "" {
				诸 = append(诸, 元)
			}
			起 = i + utf8.RuneLen(r)
		}
	}
	if 元 := strings.TrimSpace(文[起:]); 元 != "" {
		诸 = append(诸, 元)
	}
	return 诸
}

