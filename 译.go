// 译数 译一数之原文。
//
//	十进　123、-5
//	十六　0x1F、-0x10
//	八进　0o17
//	别卦　䷀ 之类，取其先天值（0..63）
//	经卦　☰ 之类，取其先天值（0..7）
//	字符　'道' 之类，取其码位（U+9053 = 36947）
//	标签　在 标签 表中者，回该标签之址
//
// 字符之所以可当数：一字二十四位，恰是一个汉字之码位。
// 这不是巧立名目，是 典/01 所定之字长所致。
func 译数(文 string, 标签 map[string]int) (int, error) {
	if 文 == "" {
		return 0, fmt.Errorf("数之文为空")
	}
	号 := 1
	s := 文
	// 字符字面：'道'。先于剥号——字符之前不该有正负。
	if n := utf8.RuneCountInString(文); n >= 2 &&
		strings.HasPrefix(文, "'") && strings.HasSuffix(文, "'") {
		内 := 文[len("'") : len(文)-len("'")]
		if utf8.RuneCountInString(内) != 1 {
			return 0, fmt.Errorf("「%s」非一字之字符", 文)
		}
		r, _ := utf8.DecodeRuneInString(内)
		return int(r), nil
	}
	if strings.HasPrefix(s, "+") {
		s = s[1:]
	} else if strings.HasPrefix(s, "-") {
		号, s = -1, s[1:]
	}
	// 标签。**须在剥号之后**——否则「[艮 + 数区]」之「+数区」认不得「数区」，
	// 而人写「+数区」正是要引那个标签。此病作者犯过，故志之。
	if v, 有 := 标签[s]; 有 {
		return 号 * v, nil
	}
	// 卦符：单符者方为之，故「䷀」是数而「䷀䷀」不是。
	if utf8.RuneCountInString(s) == 1 {
		r, _ := utf8.DecodeRuneInString(s)
		if v, 有 := 译卦符(r); 有 {
			return 号 * v, nil
		}
	}
	var v int64
	var err error
	switch {
	case strings.HasPrefix(s, "0x"), strings.HasPrefix(s, "0X"):
		v, err = strconv.ParseInt(s[2:], 16, 32)
	case strings.HasPrefix(s, "0o"), strings.HasPrefix(s, "0O"):
		v, err = strconv.ParseInt(s[2:], 8, 32)
	default:
		v, err = strconv.ParseInt(s, 10, 32)
	}
	if err != nil {
		return 0, fmt.Errorf("「%s」非数，亦非卦符、非标签", 文)
	}
	return 号 * int(v), nil
}

// 译卦符 译一卦符为其先天值。非卦符则回否。
//
// 经卦 U+2630..U+2637（☰…☷），别卦 U+4DC0..U+4DFF（䷀…䷿）。
// 别卦之符是**文王序**，须经 文王先天 归化——此一转最易忘，
// 忘则「䷀ 是六十三」而「䷁ 是零」，恰与卦器之号相反。
func 译卦符(r rune) (int, bool) {
	switch {
	case r >= 八卦基 && r <= 八卦基+7:
		return 7 - int(r-八卦基), true
	case r >= 别卦基 && r <= 别卦基+rune(别卦数)-1:
		return 文王先天(int(r-别卦基) + 1), true
	}
	return 0, false
}

// 译器 译一卦器之名为号（0..7）。不合则记一过而回零。
func 译器(l 译行, 文 string, 众 []译过) (int, []译过) {
	v, 有 := 器号表[文]
	if !有 {
		众 = append(众, 造过(l.行, l.原文,
			"「%s」非卦器之名。八器为 坤 艮 坎 巽 震 离 兑 乾，亦可书 ☷ ☶ ☵ ☴ ☳ ☲ ☱ ☰", 文)...)
		return 0, 众
	}
	return v, 众
}

// 译偏 译甲型之偏移。
//
// **书数则为偏之值，书标签则为目标之址**（译卦器折之以 目标 −（址 + 1））。
// 此别不可省：跳回三字，人写「环」便知是环，不该教人去数那三字。
func 译偏(l 译行, 文 string, 址 int, 标签 map[string]int, 众 []译过) (int, []译过) {
	if 标, 有 := 标签[文]; 有 {
		return 校界(l, true, 偏位, "偏移", 标-(址+1), 众)
	}
	v, err := 译数(文, 标签)
	if err != nil {
		return 0, append(众, 译过{行: l.行, 原文: l.原文, 辞: err.Error()})
	}
	return 校界(l, true, 偏位, "偏移", v, 众)
}

// 译元数 译乙型之立即数，并依 用符号 之约校其界。
func 译元数(l 译行, 码 int, 文 string, 标签 map[string]int, 众 []译过) (int, []译过) {
	v, err := 译数(文, 标签)
	if err != nil {
		return 0, append(众, 译过{行: l.行, 原文: l.原文, 辞: err.Error()})
	}
	return 校界(l, 用符号(码), 数位, "立即数", v, 众)
}

// 校界 校一数是否容得进 位 位。
//
// 符 为真则作有符号解（界 −2^(位−1) .. 2^(位−1)−1），否则作无符号解
// （界 0 .. 2^位−1）。此正合 用符号 之约：符号扩者符，零扩者不符。
//
// 越界者记一过而回零。**不代为截断**——截断是沉默的，
// 而沉默的错是最难找的错。
func 校界(l 译行, 符 bool, 位 int, 名 string, 值 int, 众 []译过) (int, []译过) {
	低, 高 := 0, (1<<uint(位))-1
	if 符 {
		低 = -(1 << uint(位-1))
		高 = (1 << uint(位-1)) - 1
	}
	if 值 < 低 || 值 > 高 {
		众 = append(众, 造过(l.行, l.原文,
			"%s %d 越出 %d..%d；%d 位容它不下", 名, 值, 低, 高, 位)...)
		return 0, 众
	}
	return 值, 众
}

