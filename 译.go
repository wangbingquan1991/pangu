// 译行 一有义之行：已去注释，已分出标签、助记、诸元。
type 译行 struct {
	行  int      // 源码之行号，自 1 起
	原文 string   // 去注去空白之后
	标签 []string // 此行所立之标签（可有可无，可多）
	助记 string   // 助记符或伪令；空则此行唯标签
	诸元 []string // 诸操作数之原文
}

// 去注 截去一行之注。引号之内不见注符，其详见 巡符。
func 去注(s string) string {
	if i := 巡符(s, string(注之符)); i >= 0 {
		return s[:i]
	}
	return s
}

// 分行 分一段源码为诸行。空行与纯注之行略去。
func 分行(源 string) []译行 {
	var 诸 []译行
	for 号, 原 := range strings.Split(源, "\n") {
		文 := strings.TrimSpace(去注(原))
		if 文 == "" {
			continue
		}
		l := 译行{行: 号 + 1, 原文: 文}
		// 剥标签：可连剥数个，如「甲：乙：加 震, 坎, 巽」。
		for {
			名, 余, 有 := 分签(文)
			if !有 {
				break
			}
			l.标签 = append(l.标签, 名)
			文 = 余
		}
		if 文 != "" {
			野 := strings.Fields(文)
			l.助记 = 野[0]
			if len(野) > 1 {
				l.诸元 = 分元(strings.Join(野[1:], " "))
			}
		}
		诸 = append(诸, l)
	}
	return 诸
}

// 分签 自 文 之首剥去一个「名：」，回其余。引号之内不见签符，其详见 巡符。
//
// 名 中不得有空白，且不得为空——否则那冒号不是标签之尾。
// 如「载字 震, [艮]」中无冒号，不为标签；「环：加 震, 坎, 巽」则剥出「环」。
func 分签(文 string) (名, 余 string, 有 bool) {
	位 := 巡符(文, 签之符)
	if 位 < 0 {
		return "", 文, false
	}
	名 = 文[:位]
	if 名 == "" || strings.ContainsFunc(名, 是空白) {
		return "", 文, false
	}
	_, 大 := utf8.DecodeRuneInString(文[位:])
	return 名, strings.TrimSpace(文[位+大:]), true
}

// 是空白 此符是否为空白。除 ASCII 之空白外，亦纳全角之空格（U+3000）。
func 是空白(r rune) bool {
	return r == ' ' || r == '\t' || r == '\v' || r == '\r' || r == '\n' || r == '　'
}

