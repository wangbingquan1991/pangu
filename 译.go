// 译过 译卦所遇之一处不合。
type 译过 struct {
	行  int    // 源码之行号，自 1 起
	位  int    // 行内之位，以符计，自 1 起；0 为「不指某处」
	辞  string // 何过
	原文 string // 该行去注后之原文
}

// 呈 一过之辞，用以示人。
func (e 译过) 呈() string {
	if e.位 > 0 {
		return fmt.Sprintf("第 %d 行第 %d 符　%s\n　　│ %s", e.行, e.位, e.辞, e.原文)
	}
	return fmt.Sprintf("第 %d 行　%s\n　　│ %s", e.行, e.辞, e.原文)
}

// 造过 造一处译过。
func 造过(行 int, 原文, 式 string, 众 ...any) []译过 {
	return []译过{{行: 行, 原文: 原文, 辞: fmt.Sprintf(式, 众...)}}
}

// 译果 译卦之果。
type 译果 struct {
	诸字 []int          // 所成之全象，自址 0 起；未写之处为零
	标签 map[string]int // 标签之名 → 其址
	过  []译过           // 诸过；空则译成
}

// 成 译卦成否。
func (r *译果) 成() bool { return len(r.过) == 0 }

// 过之辞 诸过连为一辞，用以示人。
func (r *译果) 过之辞() string {
	var b strings.Builder
	for i, e := range r.过 {
		if i > 0 {
			b.WriteString("\n")
		}
		b.WriteString(e.呈())
	}
	return b.String()
}

// 置 于 址 处置一字，不足则补零。
func (r *译果) 置(址, 值 int) {
	for len(r.诸字) <= 址 {
		r.诸字 = append(r.诸字, 0)
	}
	r.诸字[址] = 值 & 字掩
}

