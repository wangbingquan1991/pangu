// Test锁爻器 验门控锁存器：启阳则透明，启阴则守。
func Test锁爻器(t *testing.T) {
	n := 建网表("锁爻之验")
	入 := n.引线("入")
	启 := n.引线("启")
	出 := n.引线("出")
	n.置锁爻器(入, 启, 出, nil)
	定(t, n)

	// 一、透明：启为阳，出 随 入。
	n.驱动(启, 阳)
	定(t, n)
	for _, 欲 := range []爻{阳, 阴, 阳, 阳, 阴} {
		n.驱动(入, 欲)
		定(t, n)
		if 得 := n.读(出); 得 != 欲 {
			t.Errorf("启为阳时出当随入：入 %v，出 %v", 欲, 得)
		}
	}

	// 二、守：启转阴，此际之值被锁住，此后 入 再变，出 不动。
	n.驱动(入, 阳)
	定(t, n)
	所守 := n.读(出)
	n.驱动(启, 阴)
	定(t, n)
	for _, 欲 := range []爻{阴, 阳, 阴, 阴} {
		n.驱动(入, 欲)
		定(t, n)
		if 得 := n.读(出); 得 != 所守 {
			t.Errorf("启为阴时出当守 %v：入 改为 %v 后出成 %v", 所守, 欲, 得)
		}
	}

	// 三、启复为阳，透明如初。
	n.驱动(启, 阳)
	定(t, n)
	n.驱动(入, 阴)
	定(t, n)
	if 得 := n.读(出); 得 != 阴 {
		t.Errorf("启复为阳当复透明：入 阴，出 %v", 得)
	}

	验纯粹(t, n)
}

// Test边锁爻器 验主从触发器：出 唯在辰之上升沿而变。
//
// 此验要紧之处在第三节——辰 已为阳（有效沿已过）而 入 偷变，
// 出 不当随之而变。若变，说明主从未能隔断，此器实为透明之锁存器，
// 用它搭起来的机器会在一拍之内穿帮。
func Test边锁爻器(t *testing.T) {
	n := 建网表("边锁之验")
	入 := n.引线("入")
	辰线 := n.置辰线()
	出 := n.引线("出")
	n.置边锁爻器(入, 辰线, 出)
	c := 建辰(n, 辰线)
	定(t, n)

	if c.现() != 阴 {
		t.Fatalf("辰之初值当为阴，实为 %v", c.现())
	}

	// 一、先以一拍定初值：入 为阴则出为阴。
	n.驱动(入, 阴)
	定(t, n)
	拍(t, c)
	if 得 := n.读(出); 得 != 阴 {
		t.Fatalf("初拍之后出当为阴，实为 %v", 得)
	}

	// 二、沿前之值，于沿后之出见之。
	for _, 欲 := range []爻{阳, 阴, 阳, 阳} {
		n.驱动(入, 欲)
		定(t, n)
		拍(t, c)
		if 得 := n.读(出); 得 != 欲 {
			t.Errorf("上升沿当纳沿前之入：入 %v，出 %v", 欲, 得)
		}
	}

	// 三、辰 为阳（沿已过）而 入 偷变，出 不当变。
	// 此时辰为阳，主已守，从虽透明，所纳者仍是主之所存。
	if c.现() != 阳 {
		t.Fatalf("拍过之后辰当为阳，实为 %v", c.现())
	}
	所守 := n.读(出)
	n.驱动(入, 所守.反())
	定(t, n)
	if 得 := n.读(出); 得 != 所守 {
		t.Errorf("辰为阳时入虽变，出当守 %v，实为 %v", 所守, 得)
	}

	// 四、辰 为阴（沿未来）而 入 变，出 亦不当变。
	// 此时主正透明而纳 入，然从守，故出不动——此正主从之分工。
	if err := c.伏(); err != nil {
		t.Fatalf("辰伏未安：%v", err)
	}
	n.驱动(入, 所守.反())
	定(t, n)
	if 得 := n.读(出); 得 != 所守 {
		t.Errorf("辰为阴时入虽变，出当守 %v，实为 %v", 所守, 得)
	}

	// 五、再拍一记，此际所偷变之值方才现于出。
	拍(t, c)
	if 得 := n.读(出); 得 == 所守 {
		t.Errorf("再拍之后出当变为 %v，实仍为 %v", 所守.反(), 得)
	}

	验纯粹(t, n)
}

// Test存爻器 验 n 位寄存器：存允 制其纳否，总复 使之归阴。
func Test存爻器(t *testing.T) {
	const 位 = 12
	n := 建网表("存爻之验")
	入 := n.列线("入", 位)
	出 := n.列线("出", 位)
	存允 := n.引线("存允")
	辰线 := n.置辰线()
	n.置存爻器(入, 存允, 辰线, 出)
	c := 建辰(n, 辰线)
	定(t, n)

	// 一、总复：一拍之下诸位归阴。
	// 不先复位则初态不定——锁爻器之初态乃两出皆阴的非法之态，
	// 收敛到哪一态全凭求值之序，与真实电路的上电不定一般无二。
	if err := c.复位(); err != nil {
		t.Fatalf("复位未安：%v", err)
	}
	if 得 := n.读数(出); 得 != 0 {
		t.Fatalf("复位之后出当为零，实为 %#x", 得)
	}

	掩 := 1<<位 - 1

	// 二、存允 为阳则纳。
	for _, 欲 := range []int{0xA5, 0x000, 0xFFF, 0x123, 0x800} {
		欲 &= 掩
		n.置数(入, 欲)
		n.驱动(存允, 阳)
		定(t, n)
		拍(t, c)
		if 得 := n.读数(出); 得 != 欲 {
			t.Errorf("存允为阳当纳 %#x，实为 %#x", 欲, 得)
		}
	}

	// 三、存允 为阴则守。
	所守 := n.读数(出)
	for _, 扰 := range []int{0x000, 0xFFF, 0x555} {
		n.置数(入, 扰)
		n.驱动(存允, 阴)
		定(t, n)
		拍(t, c)
		if 得 := n.读数(出); 得 != 所守 {
			t.Errorf("存允为阴当守 %#x：入 扰以 %#x，出成 %#x", 所守, 扰, 得)
		}
	}

	// 四、总复 再临，复归于阴。
	if err := c.复位(); err != nil {
		t.Fatalf("复位未安：%v", err)
	}
	if 得 := n.读数(出); 得 != 0 {
		t.Errorf("复位之后出当为零，实为 %#x", 得)
	}

	验纯粹(t, n)
}

// Test卦器堆 验八器之堆：以卦号择器而写，两口同时而读。
//
// 八器各写一位相异之数（值_i = 1 << (3i)），
// 则任一器读错、任一地址译错，皆无处遁形。
func Test卦器堆(t *testing.T) {
	const 位 = 24
	n := 建网表("卦器之验")
	入 := n.列线("入", 位)
	号 := [3]*线{n.引线("号0"), n.引线("号1"), n.引线("号2")}
	读甲 := [3]*线{n.引线("甲0"), n.引线("甲1"), n.引线("甲2")}
	读乙 := [3]*线{n.引线("乙0"), n.引线("乙1"), n.引线("乙2")}
	存允 := n.引线("存允")
	辰线 := n.置辰线()
	r := n.置卦器堆(位, 入, 号, 存允, 辰线, 读甲, 读乙)
	c := 建辰(n, 辰线)
	定(t, n)

	if err := c.复位(); err != nil {
		t.Fatalf("复位未安：%v", err)
	}

	// 一、八器各纳一数，其数只占与本器相应之三位。
	诸值 := [8]int{}
	for i := 0; i < 8; i++ {
		诸值[i] = 1 << (3 * i)
		n.置数(入, 诸值[i])
		n.置数(号[:], i)
		n.驱动(存允, 阳)
		定(t, n)
		拍(t, c)
	}

	// 二、逐器读回。两口各择一器，同时相较。
	for i := 0; i < 8; i++ {
		n.置数(读甲[:], i)
		n.置数(读乙[:], 7-i)
		定(t, n)
		if 得 := n.读数(r.出甲); 得 != 诸值[i] {
			t.Errorf("甲口读第 %d 器（%s）当得 %#x，实为 %#x", i, r.器名(i), 诸值[i], 得)
		}
		if 得 := n.读数(r.出乙); 得 != 诸值[7-i] {
			t.Errorf("乙口读第 %d 器（%s）当得 %#x，实为 %#x", 7-i, r.器名(7-i), 诸值[7-i], 得)
		}
	}

	// 三、两口同择一器，所得当同。
	n.置数(读甲[:], 3)
	n.置数(读乙[:], 3)
	定(t, n)
	if 甲, 乙 := n.读数(r.出甲), n.读数(r.出乙); 甲 != 乙 {
		t.Errorf("两口同读第 3 器（坎），所得当同：甲 %#x，乙 %#x", 甲, 乙)
	}

	// 四、改写一器，其余七器不当受影响。
	const 新值 = 0x5AA5A5
	n.置数(入, 新值)
	n.置数(号[:], 5)
	n.驱动(存允, 阳)
	定(t, n)
	拍(t, c)
	n.驱动(存允, 阴)
	定(t, n)
	for i := 0; i < 8; i++ {
		欲 := 诸值[i]
		if i == 5 {
			欲 = 新值
		}
		n.置数(读甲[:], i)
		定(t, n)
		if 得 := n.读数(r.出甲); 得 != 欲 {
			t.Errorf("只写第 5 器（巽）后，第 %d 器（%s）当为 %#x，实为 %#x", i, r.器名(i), 欲, 得)
		}
	}

	// 五、存允 为阴则虽拍而不纳。
	所守 := n.读数(r.出甲) // 此时甲口犹择第 7 器
	n.置数(入, 0xFFFFFF)
	n.置数(号[:], 7)
	定(t, n)
	拍(t, c)
	if 得 := n.读数(r.出甲); 得 != 所守 {
		t.Errorf("存允为阴，第 7 器（坤）当守 %#x，实为 %#x", 所守, 得)
	}

	t.Logf("卦器堆之规模：门 %d，线 %d", n.门数(), n.线数())
	验纯粹(t, n)
}

// Test藏 验存储器：同步而写，随时而读。
func Test藏(t *testing.T) {
	const 位, 址 = 8, 3
	n := 建网表("藏之验")
	址线 := n.列线("址", 址)
	入 := n.列线("入", 位)
	存允 := n.引线("存允")
	辰线 := n.置辰线()
	m := n.置藏(位, 址, 址线, 入, 存允, 辰线)
	c := 建辰(n, 辰线)
	定(t, n)

	if err := c.复位(); err != nil {
		t.Fatalf("复位未安：%v", err)
	}
	if 得 := n.读数(m.出); 得 != 0 {
		t.Fatalf("复位之后读出当为零，实为 %#x", 得)
	}

	// 一、逐字写入。字 j 纳 (j*37+11)，八位之内互不相同。
	诸值 := make([]int, m.字)
	for j := 0; j < m.字; j++ {
		诸值[j] = (j*37 + 11) & 0xFF
		n.置数(址线, j)
		n.置数(入, 诸值[j])
		n.驱动(存允, 阳)
		定(t, n)
		拍(t, c)
	}
	n.驱动(存允, 阴)
	定(t, n)

	// 二、逐字读回。读是组合的，改址即变，不待拍辰。
	for j := 0; j < m.字; j++ {
		n.置数(址线, j)
		定(t, n)
		if 得 := n.读数(m.出); 得 != 诸值[j] {
			t.Errorf("址 %d 当读出 %#x，实为 %#x", j, 诸值[j], 得)
		}
	}

	// 三、存允 为阴，虽改 入 与 址 而拍辰，诸字不当变。
	n.置数(入, 0xFF)
	for j := 0; j < m.字; j++ {
		n.置数(址线, j)
		定(t, n)
		拍(t, c)
	}
	for j := 0; j < m.字; j++ {
		n.置数(址线, j)
		定(t, n)
		if 得 := n.读数(m.出); 得 != 诸值[j] {
			t.Errorf("存允为阴，址 %d 当仍为 %#x，实为 %#x", j, 诸值[j], 得)
		}
	}

	// 四、只改一字，余者不当受影响。
	const 址改, 新值 = 6, 0xC3
	n.置数(址线, 址改)
	n.置数(入, 新值)
	n.驱动(存允, 阳)
	定(t, n)
	拍(t, c)
	n.驱动(存允, 阴)
	定(t, n)
	for j := 0; j < m.字; j++ {
		欲 := 诸值[j]
		if j == 址改 {
			欲 = 新值
		}
		n.置数(址线, j)
		定(t, n)
		if 得 := n.读数(m.出); 得 != 欲 {
			t.Errorf("只改址 %d 之后，址 %d 当为 %#x，实为 %#x", 址改, j, 欲, 得)
		}
	}

	t.Logf("藏之规模：%d 字 × %d 位，门 %d，线 %d", m.字, m.位, n.门数(), n.线数())
	验纯粹(t, n)
}

// Test计爻器 验程序计数器：可增、可载、可守。
func Test计爻器(t *testing.T) {
	const 位 = 8
	n := 建网表("计爻之验")
	入 := n.列线("入", 位)
	载 := n.引线("载")
	增 := n.引线("增")
	辰线 := n.置辰线()
	p := n.置计爻器(位, 入, 载, 增, 辰线)
	c := 建辰(n, 辰线)
	定(t, n)

	if err := c.复位(); err != nil {
		t.Fatalf("复位未安：%v", err)
	}
	if 得 := n.读数(p.出); 得 != 0 {
		t.Fatalf("复位之后计当为零，实为 %#x", 得)
	}

	// 一、载为阴、增为阳：每拍加一。
	n.驱动(载, 阴)
	n.驱动(增, 阳)
	定(t, n)
	for 欲 := 1; 欲 <= 5; 欲++ {
		拍(t, c)
		if 得 := n.读数(p.出); 得 != 欲 {
			t.Errorf("增五次：第 %d 拍后计当为 %d，实为 %d", 欲, 欲, 得)
		}
	}

	// 二、增回绕：八位之计，255 加一当归零。
	n.置数(入, 0)
	n.驱动(载, 阳)
	定(t, n)
	拍(t, c)
	n.置数(入, 255) // 载 255，再以增溢出，验其回绕
	定(t, n)
	拍(t, c)
	if 得 := n.读数(p.出); 得 != 255 {
		t.Fatalf("载入 255 后计当为 255，实为 %d", 得)
	}
	n.驱动(载, 阴)
	n.驱动(增, 阳)
	定(t, n)
	拍(t, c)
	if 得 := n.读数(p.出); 得 != 0 {
		t.Errorf("255 增一当回绕为零，实为 %d", 得)
	}

	// 三、载为阳：纳 入 所指之值（此即跳转）。
	for _, 欲 := range []int{0x2A, 0x00, 0xFF, 0x81} {
		n.置数(入, 欲)
		n.驱动(载, 阳)
		n.驱动(增, 阴)
		定(t, n)
		拍(t, c)
		if 得 := n.读数(p.出); 得 != 欲 {
			t.Errorf("载为阳当纳 %#x，实为 %#x", 欲, 得)
		}
	}

	// 四、二者皆阴：守而不动。
	所守 := n.读数(p.出)
	n.驱动(载, 阴)
	n.驱动(增, 阴)
	定(t, n)
	for i := 0; i < 4; i++ {
		拍(t, c)
		if 得 := n.读数(p.出); 得 != 所守 {
			t.Errorf("载增皆阴，计当守 %#x，第 %d 拍后成 %#x", 所守, i+1, 得)
		}
	}

	验纯粹(t, n)
}

// Test机之雏形 以 计爻器 驱 藏，作一具最简的取指之机。
//
// 计 之出即为 藏 之址，二者以继门相连，中间不假他物。
// 藏 中预置一列数，计 自增而逐条取出。
//
// 此非指令，尚无译卦之能（那是 M3 的事）。
// 然「依址取数、逐条而下」这条筋一旦通了，
// 冯·诺依曼机的骨架便立起来了——余下的不过是往里填东西。
func Test机之雏形(t *testing.T) {
	const 位, 址 = 8, 3
	n := 建网表("雏机之验")
	入 := n.列线("入", 位)
	存允 := n.引线("存允")
	载 := n.引线("载")
	增 := n.引线("增")
	辰线 := n.置辰线()

	// 一、计 先立，其出即为址。跳转之口无用处，接地（恒阴）即可，
	// 如此 载 为阳时便是「归于初址」——正合复位之意。
	p := n.置计爻器(址, n.阴列(址), 载, 增, 辰线)
	址线 := make([]*线, 址)
	for i := range 址线 {
		址线[i] = n.引线(fmt.Sprintf("址%d", i))
		n.置继门(p.出[i], 址线[i])
	}
	m := n.置藏(位, 址, 址线, 入, 存允, 辰线)
	c := 建辰(n, 辰线)
	定(t, n)

	if err := c.复位(); err != nil {
		t.Fatalf("复位未安：%v", err)
	}

	// 二、预置。存允 与 增 同时为阳：每一拍，藏 以 计 之现值写入，
	// 计 于同一沿加一。故第 j 拍写入第 j 字。
	诸值 := make([]int, m.字)
	n.驱动(存允, 阳)
	n.驱动(载, 阴)
	n.驱动(增, 阳)
	for j := 0; j < m.字; j++ {
		诸值[j] = (j*29 + 3) & 0xFF
		n.置数(入, 诸值[j])
		定(t, n)
		拍(t, c)
	}
	// 八拍之后，三位之计回绕归零。
	if 得 := n.读数(p.出); 得 != 0 {
		t.Fatalf("八拍之后计当回绕为零，实为 %d", 得)
	}

	// 三、取指。存允 转阴，增 仍为阳：每拍计加一，藏 随时而出。
	n.驱动(存允, 阴)
	定(t, n)
	for j := 0; j < m.字; j++ {
		if 得 := n.读数(m.出); 得 != 诸值[j] {
			t.Errorf("计 指第 %d 字，当取出 %#x，实为 %#x", j, 诸值[j], 得)
		}
		拍(t, c)
	}

	// 四、自败之验：若诸值恰成顺序（0,1,2,3…），
	// 则纵使址线根本没接上、藏 只是在自增，也能蒙混过关。
	// 故此处断言诸值不成等差一，以确保此验真的在验寻址。
	if 诸值[1]-诸值[0] == 1 && 诸值[2]-诸值[1] == 1 {
		t.Fatalf("测试自败：诸值近乎等差一（%v），纵寻址有错亦不能察", 诸值[:3])
	}

	t.Logf("雏机之规模：门 %d，线 %d", n.门数(), n.线数())
	验纯粹(t, n)
}
