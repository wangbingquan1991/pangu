// ==================================================================
// 时序之验
//
// 组合电路之验，穷举其真值表即可。
// 时序电路则不然：同一个入，在不同的辰之下，出可以不同——
// 它记得自己刚才是什么。故时序之验，验的是**沿**：
// 值该变的那一拍变了吗？不该变的那些时候，守住没有？
//
// 本文件诸验皆守「时序之约」（见 时序.go 文首）：
// 先置入、置存允，调定已安，然后拍辰；拍过之后，方可更其入。
// ==================================================================

// 定 调定并查错。
func 定(t *testing.T, n *网表) {
	t.Helper()
	if err := n.调定(0); err != nil {
		t.Fatalf("调定未安：%v", err)
	}
}

// 拍 拍一记辰并查错。
func 拍(t *testing.T, c *辰) {
	t.Helper()
	if err := c.拍(); err != nil {
		t.Fatalf("拍辰未安：%v", err)
	}
}

