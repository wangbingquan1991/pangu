func (m *周期机) 器值(i int) int {
	if i < 0 || i >= 8 {
		panic(越界("周期机.器值", i, 0, 7))
	}
	return m.诸器[i]
}

// 诸器值 八器之现值。
func (m *周期机) 诸器值() [8]int { return m.诸器 }

// 藏值 藏中第 j 字之现值。
func (m *周期机) 藏值(j int) int {
	if j < 0 || j >= m.字数 {
		panic(越界("周期机.藏值", j, 0, m.字数-1))
	}
	return m.诸字[j]
}

// 诸字值 藏中诸字之现值。
func (m *周期机) 诸字值() []int { return m.诸字 }

// 址值 藏址之线之现值（常址择门之出）。M5 之枢赖之，详见字段之注。
func (m *周期机) 址值() int { return m.址 }

// 写藏 径写一藏字。L2 本无此口（装载 只自零起写），
// 而枢须把内核装于高址，故开一口。
//
// 名之辨：装载 是「装一段程序于零址」，写藏 是「写一址」。
// 内核在 0o777000，用户程在 0，二者不在一处，故须此口。
func (m *周期机) 写藏(址, 值 int) error {
	if 址 < 0 || 址 >= m.字数 {
		return fmt.Errorf("写藏：址 0o%06o 越出 0..0o%06o", 址, m.字数-1)
	}
	m.诸字[址] = 值 & 字掩
	return nil
}

// 相值 相位之现值。
func (m *周期机) 相值() 爻 {
	if m.相 == 1 {
		return 阳
	}
	return 阴
}

// 相名 相位之名。
func (m *周期机) 相名() string {
	if m.相 == 1 {
		return "执行"
	}
	return "取指"
}

// 止否 机器已止否。
func (m *周期机) 止否() bool { return m.止 }

// 迹 一记机器现况之辞。
func (m *周期机) 迹() string {
	诸 := m.诸器
	return fmt.Sprintf("拍%-6d 相%s 计%02d 令 0o%s │ 坤%08o 艮%08o 坎%08o 巽%08o 震%08o 离%08o 兑%08o 乾%08o",
		m.拍数, m.相名(), m.计, 字之八进(m.令),
		诸[0], 诸[1], 诸[2], 诸[3], 诸[4], 诸[5], 诸[6], 诸[7])
}

// ------------------------------------------------------------------
// 机态 · 对拍之凭
// ------------------------------------------------------------------

// 机态 一机在某拍之全态。L1 与 L2 各能出之，故可比。
type 机态 struct {
	计  int
	令  int
	相  int // 0 取指，1 执行
	止  bool
	诸器 [8]int
	诸字 []int
}

// 态 取 L1 之全态。
func (t *太极) 态() 机态 {
	相 := 0
	if t.相值() == 阳 {
		相 = 1
	}
	return 机态{
		计:  t.计值(),
		令:  t.令值(),
		相:  相,
		止:  t.止否(),
		诸器: t.诸器值(),
		诸字: t.诸字值(),
	}
}

// 态 取 L2 之全态。
func (m *周期机) 态() 机态 {
	return 机态{
		计:  m.计,
		令:  m.令,
		相:  m.相,
		止:  m.止,
		诸器: m.诸器,
		诸字: m.诸字,
	}
}

// 较 与此态相较，回其不合之处之辞；全合则回空。
func (a 机态) 较(b 机态) string {
	if a.计 != b.计 {
		return fmt.Sprintf("计 %d ≠ %d", a.计, b.计)
	}
	if a.令 != b.令 {
		return fmt.Sprintf("令 0o%s ≠ 0o%s", 字之八进(a.令), 字之八进(b.令))
	}
	if a.相 != b.相 {
		相名 := []string{"取指", "执行"}
		return fmt.Sprintf("相 %s ≠ %s", 相名[a.相], 相名[b.相])
	}
	if a.止 != b.止 {
		return fmt.Sprintf("止 %v ≠ %v", a.止, b.止)
	}
	if a.诸器 != b.诸器 {
		return fmt.Sprintf("诸器 %v ≠ %v", a.诸器, b.诸器)
	}
	if len(a.诸字) != len(b.诸字) {
		return fmt.Sprintf("藏之字数 %d ≠ %d", len(a.诸字), len(b.诸字))
	}
	for j := range a.诸字 {
		if a.诸字[j] != b.诸字[j] {
			return fmt.Sprintf("藏[%d] 0o%s ≠ 0o%s", j, 字之八进(a.诸字[j]), 字之八进(b.诸字[j]))
		}
	}
	return ""
}
