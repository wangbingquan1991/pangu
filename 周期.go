package 盘古

import "fmt"

// ==================================================================
// 周期 · L2 周期级模拟器
//
// 太极（L1）是**门级**的：三万余门，一拍须逐门重算至定，约四毫秒。
// 它可信——因为它是从与非门一层层搭起来的，其中没有一句「假设」；
// 但它太慢，跑不了大程序，也跑不了穷举。
//
// 周期（L2）是**周期级**的：不算门，只算整数。一拍即一次整数运算，
// 快万倍。它不可信——因为它所写的每一条式子都是一句「假设」，
// 假设数据通路是那样连的、假设时序是那样走的。假设错了，它照样跑得欢。
//
// 故二者不可偏废，而当**对拍**：同一段机器码，两机逐拍并行，
// 每拍之后比其全态（计、令、相、止、八器、诸字），一处不合即止。
// L2 之可信，不由它自己证明，而由 L1 一拍一拍地替它证明。
// 此之谓「以慢御快」——慢者是尺，快者是布。
//
// ====================== 同时之变 ======================
//
// L2 最要紧的一条纪律：**诸新值皆自旧态算出，算毕而后同时纳之**。
//
// L1 之中，诸寄存器之入是组合电路，出是锁爻器；一拍之下，
// 所有锁爻器在同一沿上同时翻开，所纳者是**沿前**的那一批值。
// 故 计 之自增与 令器 之锁入互不相见，甲器之写入不看乙器之新值。
//
// 若在 L2 中随算随写（先写 计，再用新 计 去取指），则所得者是
// 一串行赋值之果，而非一拍同时之果——错，且错得悄无声息。
// 故本文件之 步 分两段：先自旧态算出诸新，再一并纳之。
//
// ====================== 对拍之疆 ======================
//
// 对拍虽严，其疆有界。凡在疆外者，L2 之可信**无人担保**，
// 读者用之，当自知之。其疆有三：
//
// 一、**藏之大小。** L1 之藏至多 256 字（置藏 以 址 ≤ 8 为限），
//     故 址 9..18 是 L2 独有之域，对拍不能至。此域之中，
//     L2 只由「与 L1 同构」一语担保，而同构者，人所断言，非机器所证。
//
// 二、**存取之符号扩展，在 址 ≤ 12 时不可观测。** 藏址 = 果 & 址掩，
//     而符号扩与零扩之差恰是 2^12 = 4096；址 ≤ 12 时 4096 ≡ 0 (mod 2^址)，
//     二者遂无别。**故 用符号 之于存取，对拍验不到。**
//     它之所以仍在，是因为语义当如此（偏移本当有正负），
//     且他日 址 大过十二，它便有用——今之无用，非其罪。
//
// 三、**叩 之实。** M3 之 叩 只置 止，不做别事；系统调用之实
//     留待 M5 之 枢。故「叩 之后如何」一段，对拍只验其「止」，
//     不验其「叩」。
//
// 凡此三者，皆当志于 典/08，不可使后人以为「对拍既绿，则万事大吉」。
// ==================================================================

// 周期机 L2 周期级模拟器。所存者皆整数，非线。
//
// 其字段名与 太极 一一相合，故对拍之验可不问其为 L1 为 L2。
type 周期机 struct {
	字数 int           // 藏之字数
	址掩 int           // 藏之地址掩，即 字数 - 1
	计  int           // 程序计数器，址位 位
	令  int           // 令器，字位 位
	相  int           // 相位：0 取指，1 执行
	止  bool          // 停机之志，粘滞
	址  int           // 藏址之线（见下）
	址变 func(int) int // 址总线之变换（界址之钩，见下）
	诸器 [8]int        // 八器
	诸字 []int         // 藏
	拍数 int           // 已拍之数
}

// 址 是**探针，不是状态**。
//
// 它记的是 常址 择门 之出——即「藏之地址口此刻接的是谁」：
// 取指相接 计，执行相接 果。L1 里这根线是真的（择门有输出），
// 只是它一头接着藏之地址口，无需存进锁爻器，故 太极 之中看不见它。
//
// M5 之所以要把这根线引出来：枢（L3）须在**存取发生之后**知道
// 「刚才那一笔碰的是哪个地址」，才好判它是否越了界、是否落在器区。
// 若不给这根线，枢 便只好自己照着 果 = 器[rs1] + 扩立即数(令)
// 再算一遍——那就是把一条语义抄成两份，而他日改了一处，另一处不报错。
//
// 故：**抽线，不抄式。** 线只有一根，抽出来共用；式若抄两份，必有一份朽。
// 此即 M4「凡手抄之单，必漏」之又一面。

// 址变 是**址总线上之一段**，不是一根探针。
//
// M6 之界址（基址＋限长）须在地址出口处变换其址。若让 L3 自己去算
// 「这一笔该落在哪一址」，它便须先算 果 ＝ 器[rs1] ＋ 扩(立即数)——
// 那是把 L2 的语义抄进 L3。故此处留一钩：空则直通（L1、L2 之旧途，
// 对拍之验不受其扰），不空则 L3 挂上它的 变换，**线上只有一份语义**。
//
// 真机之中，这一段是 CPU 与内存之间的一块电路（MMU）；
// 此处是一枚函数。形虽异，其所处则一：**在址离开CPU之后、抵达藏之前。**
//
// 又：钩是**可空**的，故 建周期机 不置之。Test太极与周期对拍 跑的是空钩，
// 故 L1 ↔ L2 之约不为 M6 所动——**新物不许动旧尺**。

// 建周期机 造一具 L2 模拟器。址 为藏之地址位数。
//
// L1 之藏至多 256 字（置藏 以 址 ≤ 8 为限），L2 无此限——
// 故 L2 可跑 L1 跑不动的大程序，而其所跑之小段则可与 L1 对拍。
func 建周期机(址 int) *周期机 {
	if 址 <= 0 || 址 > 址位 {
		panic(fmt.Sprintf("建周期机：址 %d 须在 1..%d 之间", 址, 址位))
	}
	return &周期机{
		字数: 1 << 址,
		址掩: (1 << 址) - 1,
		诸字: make([]int, 1<<址),
	}
}

// ------------------------------------------------------------------
// 算 · L2 之算爻器
// ------------------------------------------------------------------

// 算 以整数算出 甲 操 乙 之果。
//
// 其式与 太极_test.go 之 参照操 形同，然**其职不同**，不可因形同而并之：
//
//	参照操 是尺——验 L1 之电路算得对不对，故须自二之补之第一义写出；
//	算     是器——L2 之实现，故须照着**电路之所为**写。
//
// 二者今日形同，只说明 L1 之电路与二之补之理相合；他日若电路改了
// （比如 降 改成算术右移），则 算 当随之而改，参照操 不改，
// 二式遂分。分之之日，正是对拍立功之时。
//
// 又：算 之可信不由其自身证明，亦不由 参照操 证明（形同故），
// 而由**对拍**证明——同一段码，L1 逐门跑，L2 逐拍跑，一处不合即止。
func 算(甲, 乙 int, 操 算爻之操) int {
	甲 &= 字掩
	乙 &= 字掩
	switch 操 {
	case 加:
		return 截字(甲 + 乙)
	case 减:
		return 截字(甲 - 乙)
	case 交:
		return 甲 & 乙
	case 并:
		return 甲 | 乙
	case 殊:
		return 甲 ^ 乙
	case 升:
		return 截字(甲 << 1)
	case 降:
		return 甲 >> 1
	case 较:
		if 补之(甲) < 补之(乙) {
			return 1
		}
		return 0
	}
	panic(越界("算之操", int(操), 0, 7))
}

// 算爻择 一令所择之算爻之操。
//
// 此即 L1 中 择 三爻之数中化身（太极.go 第三险）：
//
//	算爻之类（乾上、兑上）  择 = 下卦
//	等跃、异跃             择 = 殊（异或为零即相等）
//	逊跃、胜跃             择 = 较（甲小於乙则出一）
//	其余（存取、绝对跃等）   择 = 加
//
// 存取之所以必须强制为 加，是因为它借算爻器算地址：
// 存字 之下卦是艮（即减），若不强制，地址便成了 rs1 − 立即数。
func 算爻择(令 int) 算爻之操 {
	码 := 取码(令)
	switch 分类(码) {
	case 类数, 类器:
		return 算爻之操(分操(码))
	}
	switch 码 {
	case 等跃, 异跃:
		return 殊
	case 逊跃, 胜跃:
		return 较
	}
	return 加
}

