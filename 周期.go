// 步 拍辰一记。
//
// 分两段：先自**旧态**算出诸新值，再一并纳之。此为同时之变，
// 不可随算随写——详见本文件首之「同时之变」。
func (m *周期机) 步() {
	旧计, 旧令, 旧相 := m.计, m.令, m.相
	旧器, 旧止 := m.诸器, m.止
	旧字 := m.诸字

	码 := 取码(旧令)
	类 := 分类(码)

	// 一、译码之谓词。
	是停机 := 码 == 停机
	是叩 := 码 == 叩
	是载高 := 码 == 载高
	是载字 := 码 == 载字
	是存字 := 码 == 存字
	是丙跃 := 码 == 跃
	是等跃 := 码 == 等跃
	是异跃 := 码 == 异跃
	是逊跃 := 码 == 逊跃
	是胜跃 := 码 == 胜跃
	是类数 := 类 == 类数
	是类器 := 类 == 类器
	是存取 := 类 == 类存取
	是算爻 := 是类数 || 是类器
	是比跃 := 是等跃 || 是异跃 || 是逊跃 || 是胜跃
	是写回 := 是算爻 || 是载高 || 是载字
	是数 := 是存取 || 是类数
	是止 := 是停机 || 是叩

	// 二、读口。
	//
	// 读甲 恒为 rs1；读乙 平时为 rs2，唯 存字 反作 rd——
	// 盖 乙型 之 rd 域于 存字 之中不作目的而作源。
	rs1, rs2, rd := 取rs1(旧令), 取rs2(旧令), 取rd(旧令)
	出甲 := 旧器[rs1]
	出乙 := 旧器[rs2]
	if 是存字 {
		出乙 = 旧器[rd]
	}

	// 三、算爻。
	元 := 出乙
	if 是数 {
		元 = 扩立即数(旧令)
	}
	果 := 算(出甲, 元, 算爻择(旧令))
	志零 := 果 == 0

	// 四、藏。
	//
	// 藏址 = 相 ? 果 : 计（L1 之 常址 择门）。其读是组合的，
	// 故 载字 之写回值 与 存字 之写入址 皆用**旧**藏而算。
	//
	// 新址 是常址择门之出，一并将其引出（见 址 字段之注），
	// 供 L3 之保护与器区之用——抽线，不抄式。
	新址 := 旧计 & m.址掩
	if 旧相 == 1 {
		新址 = 果 & m.址掩
	}
	// 址变：界址之钩。空则直通，不空则变换之——见 址变 字段之注。
	// 取指与执行皆经此，故**化之取指亦在其界之内**，无一途可绕。
	if m.址变 != nil {
		新址 = m.址变(新址) & m.址掩
	}
	//
	// 此处之 !旧止 是**冗余**的：止 既置，令器与相皆冻，令恒为 停机 或 叩，
	// 而 是存字 须上卦为坎，与之互斥，故写入永不发生。L1 之 藏存允
	// （= 预 ? 预写 : 相 ∧ 是存字）亦无 ¬止 一项，二者正相合。
	// 留此冗余，是存一条「停机之后不许再写」之志，非补电路之缺。
	新字 := 旧字
	if 旧相 == 1 && 是存字 && !旧止 {
		新字 = m.抄字()
		新字[新址] = 出乙
	}
	读字 := 旧字[新址]

	// 五、写回。
	写回 := 果
	if 是载字 {
		写回 = 读字
	}
	if 是载高 {
		写回 = (取立即数(旧令) << 数位) & 字掩
	}
	新器 := 旧器
	// rd == 0 即「坤恒为零」：写入被吞（L1 之 非零rd，八个择门之价）。
	// !旧止 亦冗余，其理同其四——读者对观 L1 之 堆存允 时，
	// 勿为多出的这一项去寻一根本不存在的线。
	if 旧相 == 1 && 是写回 && rd != 0 && !旧止 {
		新器 = 旧器
		新器[rd] = 写回
	}

	// 六、跃。
	//
	// 志零 之取直取反，四跃各各不同：等跃、胜跃 取直，异跃、逊跃 取反。
	// 「胜」名曰胜，义为「不小于」——典/01 已志。
	跃志 := 志零
	if 是异跃 || 是逊跃 {
		跃志 = !志零
	}
	跃之决 := 是丙跃 || (是比跃 && 跃志)

	// 七、计。
	//
	// 取指相恒增一，执行相则唯跃乃载。跃之目标：丙型取绝对地址，
	// 四条条件跃取 计 + 符号扩（偏）——偏 是相对**下一令**的，
	// 盖执行之时 计 已自增。
	新计 := 旧计
	switch {
	case 旧相 == 1 && 跃之决 && !旧止:
		if 是丙跃 {
			新计 = 取址(旧令)
		} else {
			新计 = 截址(旧计 + 符号扩(取偏(旧令), 偏位))
		}
	case 旧相 == 0 && !旧止:
		新计 = 截址(旧计 + 1)
	}

	// 八、令器、相、止。
	新令 := 旧令
	if 旧相 == 0 && !旧止 {
		新令 = 读字
	}
	新相 := 旧相
	if !旧止 {
		新相 = 1 - 旧相
	}
	新止 := 旧止 || (旧相 == 1 && 是止)

	// 九、同时纳之。
	m.计, m.令, m.相, m.止, m.址 = 新计, 新令, 新相, 新止, 新址
	m.诸器, m.诸字 = 新器, 新字
	m.拍数++
}

// 抄字 抄一份藏，供写入之用。写则抄，不写则不抄——
// 对拍之时，一程千拍，若每拍皆抄则费。
func (m *周期机) 抄字() []int {
	新 := make([]int, len(m.诸字))
	copy(新, m.诸字)
	return 新
}

