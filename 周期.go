// 复位 清诸器归阴。
func (m *周期机) 复位() {
	m.计, m.令, m.相, m.止, m.址 = 0, 0, 0, false, 0
	m.诸器 = [8]int{}
	for j := range m.诸字 {
		m.诸字[j] = 0
	}
	m.拍数 = 0
}

// 装载 把诸字写入藏。L2 之中无「预装载之口」——
// 盖预装载是 L1 为了把程序塞进门级之藏而设的权宜，
// L2 既不算门，便无须此口，径写其数组可也。
func (m *周期机) 装载(诸字 []int) error {
	if len(诸字) > m.字数 {
		return fmt.Errorf("装载：%d 字溢于藏之 %d 字", len(诸字), m.字数)
	}
	for j, v := range 诸字 {
		m.诸字[j] = v & 字掩
	}
	return nil
}

// 重置并装载 复位而后装载。
func (m *周期机) 重置并装载(诸字 []int) error {
	m.复位()
	return m.装载(诸字)
}

// 跑 拍辰直至 止 为真，或至 上限 之数。
func (m *周期机) 跑(上限 int) (int, error) {
	for i := 0; i < 上限; i++ {
		if m.止 {
			return i, nil
		}
		m.步()
	}
	if m.止 {
		return 上限, nil
	}
	return 上限, fmt.Errorf("跑：%d 拍之内机器未止（计 %d，令 0o%s）",
		上限, m.计, 字之八进(m.令))
}

