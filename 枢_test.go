// 建验机 以 化源 为用户程，配 启 与 真枢，造一具已装之枢机。
func 建验机(t *testing.T, 化源 string) *枢机 {
	t.Helper()
	k, err := 建化之机(化源)
	if err != nil {
		t.Fatalf("建化之机：%v\n源：\n%s", err, 化源)
	}
	return k
}

// 建枢态机 造一具枢机，装入 源 与**枢**，而**不降入化态**——供诸「枢态」之验。
//
// 建枢机 上电即在枢态（启 之 降化 须自枢态降），故径装径跑便是枢态。
//
// 藏之址取 址位（十八）而非小藏：器区在 0o777700，非十八位之藏够不着它。
//
// # 何以要装 枢（M6 之前不必）
//
// M5 之时，枢态 之 叩 与 变 皆轰，轰 在 入枢 之刹那便发——
// 故 叩之表 与 变之表 虽全是零（零即 停机），也轮不到它跑。
// M6 栈既立，枢态 亦可叩、亦可陷，那两张表**遂真要跳进去了**。
// 不装枢则跳进去撞一条 停机，机止而无声——
// 此之谓「所验者非所跑者」：**验的是一段空白，不是枢。**
//
// 化数 传一：建枢态机 只有上电那一化。
func 建枢态机(t *testing.T, 源 string) *枢机 {
	t.Helper()
	k := 建枢机(址位)
	if err := k.装(源 + "\n" + 枢之源码(1)); err != nil {
		t.Fatalf("装：%v\n源：\n%s", err, 源)
	}
	return k
}

// 跑必止 跑之，不至则败。回其拍数。
func 跑必止(t *testing.T, k *枢机, 上限 int) int {
	t.Helper()
	拍, err := k.跑(上限)
	if err != nil {
		t.Fatalf("%v\n志：\n%s", err, strings.Join(k.志(), "\n"))
	}
	return 拍
}

// 步至陷 逐拍步进，直至「曾入化态而后复升枢态」——即**入枢之刹那**。
//
// 回真则机器正当入枢后、变之处理器未行之瞬，供诸「撤其效」之验查其态。
//
// 何以须「曾入化态」：机之上电之特权本就是枢态，
// 故单看「特权 == 枢态」在上电之瞬便已成立，一拍未跑便回真。
// **一个只在起点就成立的判据，等于没有判据**——
// 此与变异测试之「自检」同理，量具须先证明它分得出两样东西。
//
// # 此判据之界：它捕的是「入枢」，不是「爻变」
//
// 叩 亦入枢。故一段先 叩 而后方陷之程，此函止于 叩，**非止于陷**——
// （在 Test告则不压栈 上撞见：二化之程的 叩「出」在第八条令之前，
// 故 片 ＝ 8 时第一陷不是 告 而是 叩，而 因 仍是上电之默认值。）
// 欲专捕一变者，用 步至其变。**量具之界不写明，便是下一个人的坑。**
func 步至陷(t *testing.T, k *枢机, 上限 int) bool {
	t.Helper()
	曾化 := false
	for i := 0; i < 上限; i++ {
		if k.机.止否() {
			return false
		}
		if k.特权 == 化态 {
			曾化 = true
		} else if 曾化 {
			return true
		}
		k.步()
	}
	t.Fatalf("步至陷：%d 拍之内未曾入枢（今 特权 %s，计 0o%06o）",
		上限, k.特权.名(), k.机.计)
	return false
}

// 步至其变 逐拍步进，直至 因 恰是 欲 之刹那——**专捕一变，不捕 叩**。
//
// 何以须此函：步至陷 捕的是「入枢」，而 叩 亦入枢，故它会止于 叩。
// 欲验 告 之栈，须等的是「因 ＝ 告」，不是「特权 ＝ 枢态」。
// 二名之差，正是 叩 与 变 之差。
func 步至其变(t *testing.T, k *枢机, 欲 变因, 上限 int) bool {
	t.Helper()
	for i := 0; i < 上限; i++ {
		if k.机.止否() {
			return false
		}
		if k.特权 == 枢态 && k.因 == 欲 {
			return true
		}
		k.步()
	}
	t.Fatalf("步至其变：%d 拍之内未曾陷于「%s」（今 因 %s，特权 %s，计 0o%06o）",
		上限, 欲.名(), k.因.名(), k.特权.名(), k.机.计)
	return false
}

