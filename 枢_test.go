// Test枢机之复位 复位 当归其上电之态：特权在枢，串口一空。
func Test枢机之复位(t *testing.T) {
	k := 建开天机(t)
	跑必止(t, k, 10000)
	if len(k.串口.出) == 0 {
		t.Fatal("跑过之后当有出")
	}
	k.复位()
	if k.特权 != 枢态 {
		t.Errorf("复位 之后特权当是枢态，今是 %s", k.特权.名())
	}
	if len(k.串口.出) != 0 || len(k.串口.入) != 0 {
		t.Errorf("复位 之后串口当空，今出 %d 入 %d", len(k.串口.出), len(k.串口.入))
	}
	if k.轰否 || k.轰由 != "" {
		t.Errorf("复位 之后不当仍志其轰：%s", k.轰由)
	}
	if k.机.计 != 0 || k.机.拍数 != 0 {
		t.Errorf("复位 之后 计/拍 当归零，今 0o%06o / %d", k.机.计, k.机.拍数)
	}
	if k.机.止否() {
		t.Error("复位 之后不当仍止")
	}
}

