// ------------------------------------------------------------------

// Test开天之验 **M5 之验收**：用户态执行「叩」，内核接管并打出汉字。
//
// 典/04 所定 M5 之的，此一验即其兑现：
//
//	启 之 降化 入化态 → 化 以 叩 求枢言之 → 枢 自 叩之表 跃入 叩言
//	→ 逐字出于器区 → 回 返化态 → 叩息 而止。
//	全程 化 未触枢之域一步，未行一令特权之令。
func Test开天之验(t *testing.T) {
	k := 建开天机(t)
	拍 := 跑必止(t, k, 10000)

	// 一、出之文 当正是 化之言
	if got := k.出之文(); got != 化之言 {
		t.Errorf("出之文 = %q，欲 %q", got, 化之言)
	}

	// 二、不轰、不陷
	if k.轰否 {
		t.Errorf("不当轰：%s", k.轰由)
	}
	for _, 记 := range k.记 {
		if strings.HasPrefix(记.辞, "变 ") {
			t.Errorf("用户程竟陷：%s", 记.辞)
		}
	}

	// 三、出之诸字 当逐字是 化之言 之码位
	欲之诸 := []rune(化之言)
	if len(k.串口.出) != len(欲之诸) {
		t.Fatalf("出 %d 字，欲 %d 字", len(k.串口.出), len(欲之诸))
	}
	for i, r := range 欲之诸 {
		if k.串口.出[i] != int(r) {
			t.Errorf("第 %d 字：出 0o%08o（%q），欲 U+%04X（%q）",
				i, k.串口.出[i], 字之文(k.串口.出[i]), r, r)
		}
	}

	// 四、志 之形：降化 → 叩言 → 出 × 字数 → 回 → 叩息
	诸志 := k.志()
	欲之形 := []string{"降化", "叩 " + fmt.Sprint(叩号("言"))}
	for range 欲之诸 {
		欲之形 = append(欲之形, "出 ")
	}
	欲之形 = append(欲之形, "回 ", "叩 "+fmt.Sprint(叩号("息")))
	if len(诸志) != len(欲之形) {
		t.Errorf("志 %d 条，欲 %d 条：\n%s", len(诸志), len(欲之形), strings.Join(诸志, "\n"))
	} else {
		for i, 欲 := range 欲之形 {
			if !strings.Contains(诸志[i], 欲) {
				t.Errorf("志第 %d 条 当含「%s」，今是：%s", i, 欲, 诸志[i])
			}
		}
	}

	// 五、止时当在枢中（息 之服务例程是枢之码）
	if k.特权 != 枢态 {
		t.Errorf("止时之特权当是枢态，今是 %s", k.特权.名())
	}
	t.Logf("开天：%d 拍，出「%s」", 拍, k.出之文())
	for _, 行 := range 诸志 {
		t.Logf("  %s", 行)
	}
}

