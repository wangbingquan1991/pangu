// 建验机 以 化源 为用户程，配 启 与 真枢，造一具已装之枢机。
func 建验机(t *testing.T, 化源 string) *枢机 {
	t.Helper()
	k, err := 建化之机(化源)
	if err != nil {
		t.Fatalf("建化之机：%v\n源：\n%s", err, 化源)
	}
	return k
}

// 建枢态机 造一具枢机，装入 源，而**不降入化态**——供诸「枢态」之验。
//
// 建枢机 上电即在枢态（启 之 降化 须自枢态降），故径装径跑便是枢态。
//
// 藏之址取 址位（十八）而非小藏：器区在 0o777770，非十八位之藏够不着它。
func 建枢态机(t *testing.T, 源 string) *枢机 {
	t.Helper()
	k := 建枢机(址位)
	if err := k.装(源); err != nil {
		t.Fatalf("装：%v\n源：\n%s", err, 源)
	}
	return k
}

// 跑必止 跑之，不至则败。回其拍数。
func 跑必止(t *testing.T, k *枢机, 上限 int) int {
	t.Helper()
	拍, err := k.跑(上限)
	if err != nil {
		t.Fatalf("%v\n志：\n%s", err, strings.Join(k.志(), "\n"))
	}
	return 拍
}

// 步至陷 逐拍步进，直至「曾入化态而后复升枢态」——即**陷之刹那**。
//
// 回真则机器正当陷后、变之处理器未行之瞬，供诸「撤其效」之验查其态。
//
// 何以须「曾入化态」：机之上电之特权本就是枢态，
// 故单看「特权 == 枢态」在上电之瞬便已成立，一拍未跑便回真。
// **一个只在起点就成立的判据，等于没有判据**——
// 此与变异测试之「自检」同理，量具须先证明它分得出两样东西。
func 步至陷(t *testing.T, k *枢机, 上限 int) bool {
	t.Helper()
	曾化 := false
	for i := 0; i < 上限; i++ {
		if k.机.止否() {
			return false
		}
		if k.特权 == 化态 {
			曾化 = true
		} else if 曾化 {
			return true
		}
		k.步()
	}
	t.Fatalf("步至陷：%d 拍之内未曾陷（今 特权 %s，计 0o%06o）",
		上限, k.特权.名(), k.机.计)
	return false
}

// 息之辞 用户程之收尾二令：置 乾 ← 息号，叩。
//
// 叩号 由名反查，不书 3——书 3 便是手抄一份「号 → 名」，
