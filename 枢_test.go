// 枢_test.go 枢（L3）之验。
//
// ------------------------------------------------------------------
// 此一验之所守
//
// L1 之可信由门数之穷举证，L2 之可信由与 L1 逐拍对拍。
// L3 之上再无 L4 可对其拍——**故 L3 之可信，须自为之证**，其法有二：
//
//	一、**抽线之验**：L3 不抄 L2 一式，故 L2 之诸验即 L3 之诸验。
//	   Test枢与周期对拍 专守此条：同一段码，L2 与 L3 逐拍处处相合。
//	   此验若绿，则 L3 「未曾动过指令语义」；若红，则 L3 抄了或改了。
//
//	二、**新线之验**：特权、爻变、器区 三者是 L3 所独有，L2 中无线可抽。
//	   此三者之验，皆以「化态 犯禁 → 必陷」之形写之，
//	   而其可信之疆界，由 具/变异枢.sh 量之——
//	   **对拍全绿，不等于处处验到；验之疆界，须以变异测试量之。**（典/08）
//
// ------------------------------------------------------------------
// 一条纪律：不另立一份枢
//
// 诸验若要试一段用户程，最省事的写法是「再写一个小内核」。
// 不可。那份枢必与真枢相远，而远得无声——它不报错，
// 只是验的是另一个内核。故诸验一律呼 建化之机，
// 换的只是 化之程 里那一段用户程（见 枢程.go 之 化之签）。
//
// 此病在本项目中已发四次：器号表、助记码表、变异脚本之 PAT、
// 以及此处若不设防便会有的「测试之枢」。治法一律是**不抄**。
// ==================================================================

