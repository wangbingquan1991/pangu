//
// 壳 只书其名而不书其号，号 由 叩号() 反查 叩之簿 而得。
// 此验守的是那反查之路：**名若不在簿中，叩号 便炸**——
// 宁可炸于编译之时，不可默默叩错了门。
// 而 叩名 之往返，则守「号 → 名」与「名 → 号」是同一条路。
func Test壳之令在簿(t *testing.T) {
	见 := map[string]bool{}
	for _, 令 := range 壳之令 {
		诸 := []rune(令.字)
		if len(诸) != 1 {
			t.Errorf("令「%s」当只一字，今 %d 字", 令.字, len(诸))
		}
		if 见[令.字] {
			t.Errorf("令「%s」重出；派令之时前者永中，而后者遂**永不可达**", 令.字)
		}
		见[令.字] = true
		if 令.叩 == "" {
			continue
		}
		号 := 叩号(令.叩)
		if 叩名(号) != 令.叩 {
			t.Errorf("叩号(%s) ＝ %d，而 叩名(%d) ＝ %s；往返不合", 令.叩, 号, 号, 叩名(号))
		}
	}
	if len(见) != 壳之令数 {
		t.Errorf("壳之令 %d 条，去其重只 %d 种", 壳之令数, len(见))
	}
}

// Test壳之区不侵其码 壳 之数据区当真落在 壳之区，且其长短与诸常量相合。
//
// 壳之源码 用**签**定位数据（「壳名数」之类），而 壳诸址 一组常量是另一套说法。
// 二者说的是同一片藏，若不相合，则任一方朽了都无人知晓。
// 此验便是那「两处皆真，而一验守其相合」之术：
// **与其令其一处不存，不如令其相合成为一条断言。**
// 此验以 化之程 装之（启 ＋ 化 ＋ 枢），不用裸的 壳之源码——
// **裸码之 壳之始 在零，真径之 壳之始 在 0o100**；
// 量一物而当在它真的所在之处量之，否则所量者是另一物。
func Test壳之区不侵其码(t *testing.T) {
	果 := 汇(化之程(壳之源码()))
	if !果.成() {
		t.Fatalf("壳 之码竟译不过：\n%s", 果.过之辞())
	}
	if 得 := 果.标签["壳之始"]; 得 != 化之址 {
		t.Errorf("壳之始 在 0o%06o，当在 化之址 0o%06o", 得, 化之址)
	}
	// 码 不可侵 数区：**壳码之末 即码之末字之次一址**
	末 := 果.标签["壳码之末"]
	if 末 > 壳之区 {
		t.Errorf("壳 之码自 0o%06o 编至 0o%06o（%d 字），侵了数据区 0o%06o",
			化之址, 末, 末-化之址, 壳之区)
	}
	if 得 := 果.标签["壳行"]; 得 != 壳之区 {
		t.Errorf("壳 之数据区 起于 0o%06o，当在 壳之区 0o%06o", 得, 壳之区)
	}
	// 诸签之址当与诸常量一一相合
	for _, c := range []struct {
		签 string
		址 int
	}{
		{"壳行", 壳行址}, {"壳行数", 壳行数址}, {"壳令", 壳令址},
		{"壳名", 壳名址}, {"壳名数", 壳名数址}, {"壳文", 壳文址},
		{"壳文数", 壳文数址}, {"壳目", 壳目址}, {"壳号", 壳号址},
		{"壳数", 壳数址}, {"壳元", 壳元址}, {"壳元乙", 壳元乙址},
		{"壳空", 壳空址}, {"壳末", 壳末址}, {"壳提", 壳提址},
		{"壳终", 壳终址}, {"壳成", 壳成址}, {"壳否", 壳否址},
		{"壳无", 壳无址},
	} {
		if 得, 有 := 果.标签[c.签]; !有 {
			t.Errorf("壳 之码中无签「%s」", c.签)
		} else if 得 != c.址 {
			t.Errorf("签「%s」在 0o%06o，而常量 说是 0o%06o", c.签, 得, c.址)
		}
	}
	t.Logf("壳：码 0o%06o..0o%06o（%d 字），数区 0o%06o..0o%06o（%d 字），余 %d 字",
		化之址, 末-1, 末-化之址, 壳之区, 壳之区+壳区之度-1, 壳区之度, 壳之区-末)
}

// 壳之入 以一稿为串口之入：字即码位，行以 U+000A 分。
//
// 稿 是 Go 之串，入 是二十四位之字列——二者之转只此一处，
// 若别处又抄一份，改一处便错，且不报错。
func 壳之入(稿 string) []int {
	诸 := make([]int, 0, len(稿))
	for _, r := range 稿 {
		诸 = append(诸, int(r))
	}
	return 诸
}

// 建壳机 造一具装了 壳 之枢机，并以其稿为串口之入。
func 建壳机(t *testing.T, 稿 string) *枢机 {
	t.Helper()
	k := 建验机(t, 壳之源码())
	k.串口.入 = 壳之入(稿)
	return k
}

