// Test枢之域之图 诸域之界不自相犯。
//
// 此验看似只是查几个常量，实则是**枢之全部地址契约**。
// 器区 与 枢文基 若相叠，机器不报错，只是把内核的码当作串口去写——
// 一个越界的址不会报错，它只是把字写到别处去。
func Test枢之域之图(t *testing.T) {
	// 叩之表 不犯 变之表
	if 叩之表基+叩号数 > 变之表基 {
		t.Errorf("叩之表 0o%06o 之 %d 槽溢入 变之表 0o%06o",
			叩之表基, 叩号数, 变之表基)
	}
	// 变之表 不犯 枢之正文
	if 变之表基+变之数 > 枢文基 {
		t.Errorf("变之表 溢入 枢文基")
	}
	// 枢之正文 不犯 器区
	if 枢文基 >= 器基 {
		t.Fatalf("枢文基 0o%06o 不先于 器基 0o%06o", 枢文基, 器基)
	}
	// 器区 正当藏之极：器基 + 器之数 恰是 址掩 + 1，不多一字，不少一字。
	//
	// 此非「小于」而是「等于」：器区踞藏之末，其后更无一址。
	// 若他日 器之数 增一而 器基 不移，此式立红——
	// 而它若只是「小于」，便会静默地把 器基 之上那一字吃掉。
	if 器基+器之数 != 址掩+1 {
		t.Errorf("器区 0o%06o..0o%06o 未终于藏之极 0o%06o（差 %d 字）",
			器基, 器基+器之数-1, 址掩, 址掩+1-(器基+器之数))
	}
	// 变之数 与 变之因之众 是同一件事之两面
	if 变之数 != len(变之因之众) {
		t.Errorf("变之数 %d 与 变之因之众 %d 不合", 变之数, len(变之因之众))
	}
	// 叩号数 与 叩之簿 亦然
	if 叩号数 != len(叩之簿) {
		t.Errorf("叩号数 %d 与 叩之簿 %d 不合", 叩号数, len(叩之簿))
	}
	// 是枢之域 之界：枢基 之下不入，枢基 之上皆入（器区 亦在其中）
	if 是枢之域(枢基 - 1) {
		t.Errorf("枢基 之前一址 0o%06o 不当在枢之域", 枢基-1)
	}
	for _, 址 := range []int{枢基, 变之表基, 枢文基, 器基, 器基 + 器之数 - 1, 址掩} {
		if !是枢之域(址) {
			t.Errorf("0o%06o 当在枢之域", 址)
		}
	}
	// 是器区 之界：八口，不多不少
	for _, 址 := range []int{器基 - 1, 器基 + 器之数} {
		if 是器区(址) {
			t.Errorf("0o%06o 不当在器区", 址)
		}
	}
	for i := 0; i < 器之数; i++ {
		if !是器区(器基 + i) {
			t.Errorf("器区第 %d 口 0o%06o 当在器区", i, 器基+i)
		}
	}
	// 器区 是 枢之域 之末段，故化态亦不得触
	for i := 0; i < 器之数; i++ {
		if !是枢之域(器基 + i) {
			t.Errorf("器区第 %d 口不当在枢之域之外", i)
		}
	}
	t.Logf("藏之图：化 0..0o%06o │ 叩之表 0o%06o×%d │ 变之表 0o%06o×%d │ 枢文 0o%06o │ 器区 0o%06o×%d",
		化之极-1, 叩之表基, 叩号数, 变之表基, 变之数, 枢文基, 器基, 器之数)
}

// ------------------------------------------------------------------
// 二、叩之簿
// ------------------------------------------------------------------

// Test叩之簿 叩之簿 之往返、无重、与越界之答。
//
// 「无重」之验不可省：若两号同名，叩号 只返其先者，
// 而那后一个号遂**永不可求**——它不报错，只是静静地没有。
func Test叩之簿(t *testing.T) {
	已见 := make(map[string]int, 叩号数)
	有之数 := 0
	for 号, 名 := range 叩之簿 {
		if 名 == "" {
			continue
		}
		有之数++
		if 先, 重 := 已见[名]; 重 {
			t.Errorf("叩之簿：名「%s」重出于号 %d 与 %d；叩号 只返 %d，故 %d 永不可求",
				名, 先, 号, 先, 号)
			continue
		}
		已见[名] = 号
		if got := 叩号(名); got != 号 {
			t.Errorf("叩号(%q) = %d，欲 %d", 名, got, 号)
		}
		if got := 叩名(号); got != 名 {
			t.Errorf("叩名(%d) = %q，欲 %q", 号, got, 名)
		}
	}
	if 有之数 == 0 {
		t.Fatal("叩之簿 一号未备，则 叩 无事可做")
	}
	// 未备之号 与 越界之号
	未备 := 0
	for 号 := 0; 号 < 叩号数; 号++ {
		if 叩之簿[号] == "" {
			未备++
			if got := 叩名(号); got != "未备" {
				t.Errorf("叩名(未备之号 %d) = %q，欲「未备」", 号, got)
			}
		}
	}
	for _, 号 := range []int{-1, 叩号数, 叩号数 + 100} {
		if got := 叩名(号); got != "" {
			t.Errorf("叩名(越界之号 %d) = %q，欲空", 号, got)
		}
	}
	// 叩号 遇无名者当炸，不当默默给一个「大概对」的号
	func() {
		defer func() {
			if recover() == nil {
				t.Error("叩号(「无此之名」) 不当回，当 panic")
			}
		}()
		_ = 叩号("无此之名")
	}()
	t.Logf("叩之簿：已备 %d 号，未备 %d 号", 有之数, 未备)
}

