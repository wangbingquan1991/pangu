// 十二、M6：化与序
// ------------------------------------------------------------------
//
// 典/04 所定 M6 之的：**两个「化」交替运行，各自的内存互不干扰**。
// 此节即其兑现，而验法之要在一处——
//
//	# 诸化之 计 与 和 故意用同一个虚址
//
//	化之累加源 中，甲之 和 与 乙之 和 在**同一个虚址** 化和址 上。
//	若两化各用一址，则「互不干扰」便是理所当然，验不出什么；
//	同址而异物，才是界址之屏。故此处**故意同址，专为一验**。
//
//	# 而 和 累加的是其字，不是恒加一
//
//	恒加一则 和 恒等于 计，纵屏破亦只错在数上，验不到「其字」。
//	和 ← 和 ＋ 其字，则 和 是此化之**指纹**：
//	甲（U+7532 ＝ 30002）三回当 90006，乙（U+4E59 ＝ 20057）五回当 100285。
//	屏若破，两化争写一址，和 遂成 190291——甲不是，乙也不是。

