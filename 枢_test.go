// Test枢态之变则压栈 枢态 之变不轰，压栈而已——M6 撤了 M5 那一途 轰。
//
// 变之栈 既立，枢态 之陷遂有处可记，回 亦知其所归。
// **今之 轰 只余一途：变之栈溢**（见 Test轰则即止）。
//
// 验三事：不轰、压了一层、而 兑 之志得过 序 而存
// （变之处理器 以 兑 志其因，序 不坏 兑——此是新立的约，不可不验）。
func Test枢态之变则压栈(t *testing.T) {
	未定 := 取未定之码(t)
	k := 建枢态机(t, fmt.Sprintf("处 0\n\t字 %d\n\t停机 0\n", 未定<<(字位-码位)))
	跑必止(t, k, 200)
	if k.轰否 {
		t.Fatalf("枢态之变 不当轰：%s", k.轰由)
	}
	if k.因 != 越令之变 {
		t.Errorf("因当是越令，今是 %s", k.因.名())
	}
	if got := k.栈深(); got != 1 {
		t.Errorf("枢态 之陷当压一层，今深 %d", got)
	}
	// 栈之所以深一而未弹：变之处理器 息其化而后入 序，
	// 序 遍寻无可行者遂 止 于 序穷——**未及 回**。
	// 此非疏漏，是「一化既死，机无所事」之正途。
	if got, 欲 := k.机.诸器[兑器], int(越令之变)+1; got != 欲 {
		t.Errorf("变之处理器 当志 兑 = %d，今是 %d（序 坏了 兑 否？）", 欲, got)
	}
	if k.化[k.当].状 != 化毕 {
		t.Errorf("化之过者当毕，今其状是「%s」", k.化[k.当].状.名())
	}
}

// Test轰则即止 轰 之一瞬，机便止——**非待后令而止**。
//
// # 此验何来：一桩真事
//
// 变异十三（轰 不置其止）**存活**。其时之验有二：
//
//	Test枢态行叩则轰　　码是「叩 0 ⏎ 停机 0」
//	Test枢态之变则轰　　码是「字 未定之码」，而下一字是零，零即「停机 0」
//
// 两处之 轰 后面**都恰是一条停机**。机遂止了——
// 然那是 停机 止的，不是 轰 止的。轰否 犹真，跑必止 犹过，
// 而 轰 之「止」一字未验。
//
// 此之谓**瞎处**：所验者（轰否，一志）与被坏者（止，一效）不是同一物，
// 而坏掉的那个效，恰好由别的东西补上了。
// 一个验法验不到的东西，跑一万遍也是验不到——它不报错，只是一遍遍地绿。
//
// # 何以不修旧验而另立一验
//
// 旧验验的是「轰否 与 轰由」，那两件事它验得很好，不当改。
// 缺的是第三件事：**止**。故另立一验，令 轰 之后**别无停机可撞**——
// 其后唯有一条死循环。机若止，必是 轰 止的；机若不止，跑 必报「未止」。
// 令那处再无物可补，则瞎处自明。
//
// # M6 之新境：栈溢非今之枢所能自致，故预填之
//
// M6 立了变之栈，轰 之诸途遂去其三，**只余一途：变之栈溢**。
// 而栈之深浅，由 枢 自枢态而叩之嵌套定之——
// 今之枢**无一处自枢态而叩者**（诸叩之服务例程皆终于 回 或 序），
// 故栈最深只及一层（枢态之陷），八层之溢，跑今之码是跑不出来的。
//
// 此非「轰 无用」，而是**轰 是机器为他日备的一手**：
// M7 外设之断既至，一断未毕而一断又来，栈之深遂不可先知。
// 故此处**预填其栈至于其极**，而后令 枢态 再陷一次——
// 所验者仍是 轰 之实：机当即便止，且止后一步也不当再拍。
// 预填者非伪造其境，而是**把 M7 所将致之境，提前取来一用**。
//
// 又：「栈最深只及一层」非我臆断——观 Test枢态之变则压栈 自明：
// 它压了一层，而机随即止于 序穷，未及 回，故那一层终身未弹。
func Test轰则即止(t *testing.T) {
	未定 := 取未定之码(t)
	k := 建枢态机(t, fmt.Sprintf(
		"处 0\n\t字 %d\n\t跃 0\t\t\t；其后别无停机，唯有一环\n",
		未定<<(字位-码位)))
	块 := k.化[k.当]
	for i := 0; i < 变栈之极; i++ {
		块.栈 = append(块.栈, 变记{返址: 0, 权: 枢态, 因: 越令之变})
	}
	拍, err := k.跑(200)
	if err != nil {
		t.Fatalf("轰 当即便止，今 %d 拍而未止：%v\n志：\n%s",
			拍, err, strings.Join(k.志(), "\n"))
	}
	if !k.轰否 {
		t.Fatal("当轰而未轰")
	}
	if !strings.Contains(k.轰由, "栈溢") {
		t.Errorf("轰之由当言其「栈溢」，今是：%s", k.轰由)
	}
	// 既轰，则那一层**不许压进去**——无处可记，记了便是丢。
	if got := k.栈深(); got != 变栈之极 {
		t.Errorf("既轰，栈不当动：当仍是 %d 层，今是 %d 层", 变栈之极, got)
	}
	// 轰 之后一拍也不当再拍：步 见 止 即返。
	k.步()
	if got := k.拍(); got != 拍 {
		t.Errorf("既轰，步 当无所为；今自 %d 拍进至 %d 拍", 拍, got)
	}
}

