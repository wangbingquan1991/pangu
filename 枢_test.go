// Test籍之越址则负 用户之址越出**现化之界限**者，写、读 皆返 −1。
//
// # 屏是枢守的，不是 变换 守的
//
// 枢态之下，址是**物址**——不变换、不校验。
// 故 化 递一个越界的虚址进来，枢 若不自加 界基 而自检其界，
// 便替它读到了邻化之域（甚或读出枢之码去）。
// **变换 只管化态之手；枢 替 化 跑的那一段，须由枢自己守。**
//
// 何以要验「恰在界内」这一半：只验「越之则负」，
// 则一个**把界缩了一半**之错也绿——与 Test籍名过其极则负 同理。
func Test籍之越址则负(t *testing.T) {
	界 := 化之极 // 建验机 之上电之化：界基 为零，界限 为 化之极
	for _, 案 := range []struct {
		名  string
		址  int
		字数 int
		欲负 bool
	}{
		{"界外", 界, 1, true},
		{"界外之远", 界 + 1, 1, true},
		{"界内之末", 界 - 2, 1, false},
		// **「余 < 字数」一检，非此案验不到**：
		// 址 ＝ 界 − 1 未越其界，故「址 ≥ 界限」不举；
		// 而 余 ＝ 1 < 字数 2，独此一检举之。
		// 若无此案，则 籍之检址 之末一检**永不可达**，
		// 而删了它诸验犹绿——量具够不着的地方，须另立一具。
		{"界内而字数越其末", 界 - 1, 2, true},
		// **「址 < 0」一检，非此案验不到**：
		// 界 是**有符号**之比（较 从符号，见 令.go），故 址 ＝ −1 者，
		// 「址 ≥ 界限」不举（−1 < 0o776000），「余 < 字数」亦不举
		// （余 ＝ 界限 ＋ 1，大得很）。三检之中，独此一检举之。
		{"负址", -1, 1, true},
	} {
		欲字数 := 案.字数
		k := 籍之机(t,
			建一次(籍名址, 验名数, 籍号址)+
				叩籍("写", "", 置数(离器, 案.址), 元址(坎器, 案.字数))+存兑于(籍记(0))+
				载于器(兑器, 籍号址)+
				叩籍("读", "", 置数(离器, 案.址), 元址(坎器, 案.字数))+存兑于(籍记(1)))
		跑必止(t, k, 200000)
		if k.轰否 {
			t.Fatalf("%s：不当轰：%s", 案.名, k.轰由)
		}
		for i := 0; i < 2; i++ {
			got := k.机.藏值(籍记(i))
			if 案.欲负 && !是负(got) {
				t.Errorf("%s：第 %d 叩 当返 −1，今是 %d", 案.名, i, got)
			}
			if !案.欲负 && got != 欲字数 {
				t.Errorf("%s：第 %d 叩 当返 %d，今是 0o%06o（%d）", 案.名, i, 欲字数, got, got)
			}
		}
	}
}

