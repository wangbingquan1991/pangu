//
// 此是 M7 之验收：
// **能创建、读写、列举文件，而文件名是汉字。**
// 全程无一 Go 之代码参与——建、写、读、列、删 皆是壳之码叩出来的，
// 壳 自己亦是一「化」，所凭唯 叩 而已。
func Test壳之全程(t *testing.T) {
	k := 建壳机(t,
		"建 盘古\n"+
			"写 盘古 开天\n"+
			"读 盘古\n"+
			"列\n"+
			"删 盘古\n"+
			"读 盘古\n"+
			"止\n")
	拍 := 跑必止(t, k, 500000)
	if k.轰否 {
		t.Fatalf("不当轰：%s", k.轰由)
	}
	// 〉 是提示符，每行一出；成／否／无 是报；⏎ 是换行
	欲 := "〉成⏎" + "〉成⏎" + "〉开天⏎" + "〉盘古⏎" + "〉成⏎" + "〉无⏎" + "〉"
	if got := k.出之文(); got != 欲 {
		t.Errorf("壳 之所出：\n%q\n欲：\n%q", got, 欲)
	}
	t.Logf("壳 跑 %d 拍而出 %d 字：%s", 拍, len(k.串口.出), k.出之文())
}

// Test壳之空名则否 「建」而无其名、「读」而无其名，皆当报「否」。
//
// 空名 之所以要另立一验：Test壳之全程 里**没有一行是空名的**，
// 而 壳 之中「名字数 ＝ 0 → 否」这一支，遂无人走过。
// **量具够不着的地方，须另立一具。**
func Test壳之空名则否(t *testing.T) {
	k := 建壳机(t, "建\n读\n删\n写\n止\n")
	跑必止(t, k, 500000)
	if k.轰否 {
		t.Fatalf("不当轰：%s", k.轰由)
	}
	欲 := "〉否⏎" + "〉否⏎" + "〉否⏎" + "〉否⏎" + "〉"
	if got := k.出之文(); got != 欲 {
		t.Errorf("空名诸令 之所出 = %q，欲 %q", got, 欲)
	}
}

// Test壳之未识之令则否 令字不在六令之中者，报「否」而不轰、不死。
//
// **壳 不当因一行之无稽而死。** 真壳遇不识之令，报一声错便是；
// 若径轰了，则「错一行」与「机坏」遂不可分。
func Test壳之未识之令则否(t *testing.T) {
	k := 建壳机(t, "龘 盘古\n列\n止\n")
	跑必止(t, k, 500000)
	if k.轰否 {
		t.Fatalf("不识之令 不当轰：%s", k.轰由)
	}
	// 「列」于空籍，一名亦无，故只余其提示符
	欲 := "〉否⏎" + "〉" + "〉"
	if got := k.出之文(); got != 欲 {
		t.Errorf("不识之令 之所出 = %q，欲 %q", got, 欲)
	}
}

// Test壳入尽则自息 串口之入既尽，壳 当自息，不当环而待之。
//
// 何以要验：**入 之返值是零**（无字则阴），而零亦是一个字。
// 壳 若以零为「字」而不为「尽」，则稿尽之后遂永环于 入——
// 机器不报错，只是再也跑不完。
func Test壳入尽则自息(t *testing.T) {
	k := 建壳机(t, "建 盘古\n") // 无「止」，稿尽而自息
	跑必止(t, k, 500000)
	if k.轰否 {
		t.Fatalf("不当轰：%s", k.轰由)
	}
	if got, 欲 := k.出之文(), "〉成⏎〉"; got != 欲 {
		t.Errorf("稿尽 之所出 = %q，欲 %q", got, 欲)
	}
	if !k.机.止否() {
		t.Error("稿尽 之后机当已止")
	}
}

// Test壳之籍满则否 建至籍满，再建则「否」。
//
// 壳 之「否」其下有三因（重名、籍满、名不当），而壳只报一个「否」——
// **机器只需分得出有无，人还须问一句为何**；那一句在 志 里，不在 出 里。
// 此验只守 壳 不至于籍满而崩。
func Test壳之籍满则否(t *testing.T) {
	var b strings.Builder
	for i := 0; i < 节数; i++ {
		fmt.Fprintf(&b, "建 %c\n", []rune(壳八名)[i])
	}
	b.WriteString("建 壬\n列\n止\n")
	k := 建壳机(t, b.String())
	跑必止(t, k, 500000)
	if k.轰否 {
		t.Fatalf("籍满 不当轰：%s", k.轰由)
	}
	欲 := strings.Repeat("〉成⏎", 节数) + "〉否⏎" + "〉"
	for _, r := range 壳八名 {
		欲 += string(r) + "⏎"
	}
	欲 += "〉"
	if got := k.出之文(); got != 欲 {
		t.Errorf("籍满 之所出 = %q\n欲 = %q", got, 欲)
	}
}

// 壳八名 籍满之验所用之八名。**字数由 节数 算，不由手书。**
const 壳八名 = "甲乙丙丁戊己庚辛"

// ------------------------------------------------------------------
// 诸字之辞 出「字 'x'」之诸行，供 处 与 字 之验。
func 诸字之辞(文 string) string {
	var b strings.Builder
	for _, r := range 文 {
		fmt.Fprintf(&b, "\t字 '%c'\n", r)
	}
	return b.String()
}
