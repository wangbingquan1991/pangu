// 诸字之辞 出「字 'x'」之诸行，供 处 与 字 之验。
func 诸字之辞(文 string) string {
	var b strings.Builder
	for _, r := range 文 {
		fmt.Fprintf(&b, "\t字 '%c'\n", r)
	}
	return b.String()
}
