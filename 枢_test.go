// 比机 比 L2 与 L3 之全态。
func 比机(t *testing.T, 名 string, 拍 int, m *周期机, k *枢机) {
	t.Helper()
	if k.机.计 != m.计 || k.机.令 != m.令 || int(k.机.相) != int(m.相) ||
		k.机.址 != m.址 || k.机.拍数 != m.拍数 {
		t.Errorf("%s：第 %d 拍 计/令/相/址/拍 不合\n  L2 %s\n  L3 %s",
			名, 拍, m.迹(), k.迹())
	}
	if k.机.诸器 != m.诸器 {
		t.Errorf("%s：第 %d 拍 诸器 不合\n  L2 %v\n  L3 %v",
			名, 拍, m.诸器, k.机.诸器)
	}
	if len(k.机.诸字) != len(m.诸字) {
		t.Fatalf("%s：第 %d 拍 藏之长短不合：L2 %d，L3 %d",
			名, 拍, len(m.诸字), len(k.机.诸字))
	}
	for j := range m.诸字 {
		if k.机.诸字[j] != m.诸字[j] {
			t.Errorf("%s：第 %d 拍 藏[0o%06o] 不合：L2 0o%08o，L3 0o%08o",
				名, 拍, j, m.诸字[j], k.机.诸字[j])
			return
		}
	}
}

// Test枢与周期对拍 **此是 L3 之根本之验。**
//
// L3 之上再无第四层可对其拍，故其可信须自为之证。
// 证法不在「L3 自己说自己对」，而在**证明 L3 什么也没做**：
// 同一段用户程，L2 与 L3 逐拍、逐器、逐字处处相合，
// 则 L3 于指令语义未曾插手——它加的那三件事（特权、爻变、器区）
// 在这段程里一件也没触到，故理当无迹。
//
// 若 L3 抄了一式、或改了一式，此验立红。
// 而其**疆界**（这段程究竟验到了什么）由 具/变异枢.sh 量之。
func Test枢与周期对拍(t *testing.T) {
	诸案 := []struct {
		名 string
		源 string
	}{
		{"斐波那契", 斐波那契之译},
		{"存取与载高", 存取之译},
		{"处与字", 数据之译},
		{"累加二十", 累加之译(20)},
		{"累加百", 累加之译(100)},
	}
	const 址 = 8 // 小藏（二百五十六字），逐字比之方不费时
	for _, 案 := range 诸案 {
		果 := 汇(案.源)
		if !果.成() {
			t.Fatalf("%s：译卦有过：%s", 案.名, 果.过之辞())
		}
		m := 建周期机(址)
		if err := m.装载(果.诸字); err != nil {
			t.Fatalf("%s：L2 装载：%v", 案.名, err)
		}
		k := 建枢机(址)
		if err := k.机.装载(果.诸字); err != nil {
			t.Fatalf("%s：L3 装载：%v", 案.名, err)
		}
		k.特权 = 化态 // 用户态：不触枢之域，不行特权之令
		拍 := 0
		for ; 拍 < 20000; 拍++ {
			if m.止否() != k.机.止否() {
				t.Errorf("%s：第 %d 拍 止 不合：L2 %v，L3 %v",
					案.名, 拍, m.止否(), k.机.止否())
				break
			}
			if m.止否() {
				break
			}
			比机(t, 案.名, 拍, m, k)
			m.步()
			k.步()
		}
		比机(t, 案.名, 拍, m, k)
		if k.轰否 {
			t.Errorf("%s：L3 不当轰：%s", 案.名, k.轰由)
		}
		if k.特权 != 化态 {
			t.Errorf("%s：L3 之特权当恒是化态，今是 %s", 案.名, k.特权.名())
		}
		if len(k.记) != 0 {
			t.Errorf("%s：L3 于用户程不当有记，今有 %d 条", 案.名, len(k.记))
		}
		t.Logf("%s：%d 拍，L2 与 L3 处处相合", 案.名, 拍)
	}
}

