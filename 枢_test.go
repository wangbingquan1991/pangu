// Test字之文 一字作码位观，还其为符。
//
// 何以是码位而非 UTF-8 三字节，见 字之文 之注：
// 三字节只容 BMP，码位则不择（二十四位 ≥ 二十一位）。
func Test字之文(t *testing.T) {
	// 诸符之中，**BMP 以外者最要紧**：U+20000（𠀀，CJK 扩展 B）与 U+1F600。
	//
	// 三字节之 UTF-8 只到 U+FFFF，故这两字正是「码位之说」与
	// 「三字节之说」分道之处。若 字之文 只容 BMP，此二字便验不出——
	// 而它不报错，只是**把 U+20000 显示成一个码**。瞎处须另立一验。
	诸符 := []rune{'盘', '古', '开', '天', '！', '中', '文', '道', '䷀', '☰', 'A', '0', ' '}
	诸符 = append(诸符, 0x20000, 0x1F600) // 𠀀 与 😀：皆在 BMP 之外
	诸符 = append(诸符, []rune(化之言)...)
	for _, r := range 诸符 {
		if got := 字之文(int(r)); got != string(r) {
			t.Errorf("字之文(U+%04X) = %q，欲 %q", r, got, string(r))
		}
	}
	// 非字者：不可印、代理区、越界。皆当以码示之，不以乱码示人。
	诸非字 := []struct {
		字   int
		欲非符 bool
	}{
		{0, true},        // NUL，不可印
		{0o007, true},    // BEL
		{0o000012, true}, // 换行（是空白，不可印）
		{0xD800, true},   // 代理区之首
		{0xDFFF, true},   // 代理区之末
		{0x110000, true}, // Unicode.MaxRune + 1
		{字掩, true},       // 全阳
	}
	for _, 案 := range 诸非字 {
		got := 字之文(案.字)
		if 案.欲非符 && !strings.HasPrefix(got, "⟨0o") {
			t.Errorf("字之文(0o%08o) = %q，欲码形（此字不当作符）", 案.字, got)
		}
	}
	// 字之文 掩其字位：越出二十四位之数不当溢出成别个字
	if got, 欲 := 字之文(字掩+1+int('中')), 字之文(int('中')); got != 欲 {
		t.Errorf("字之文 未掩字位：%q ≠ %q", got, 欲)
	}
	t.Logf("字之文：%q → 「%s」", 化之言, 字之文(int([]rune(化之言)[0])))
}

