// Test籍之重名则负 同名不可再建。
//
// 建 之两步，其次序不可换：**先查重名，后寻空节**。
// 若先占了一个空节而后发现重名，则那一节已被污（名已录、志已置），
// 纵末了返了 −1，它也留在籍里——**一桩未成之事，不该留下痕迹**。
// 此验只守其返值；其「不留痕迹」之半，由 Test籍之删而复建 之复建守之
