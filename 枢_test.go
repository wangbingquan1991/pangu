// Test越化之变则止 转化 不就，是**枢之过**，非化之罪。
//
// 转化 是特权之令，唯枢能行之；号越出诸化、或其所指之化非行，
// 皆枢之算错，故止其机而志之，不罪其化。
//
// # 何以须另立一验（M4 之训：瞎处须另立一验）
//
// 序 是**先问而后转**——先以 化可之口 问其可行否，不可行者径过。
// 故 转化 之越化之变，序 走不到；今之枢亦无别处行 转化 者。
// 一条走不到的路，跑一万遍也是验不到——它不报错，只是一遍遍地绿。
// 故此处不假 序，径自枢态行之。
func Test越化之变则止(t *testing.T) {
	诸案 := []struct {
		名 string
		源 string
	}{
		{"号越出诸化", fmt.Sprintf("\t加数 %s, 坤, 99\n\t转化 坤, %s, 坤, 0\n\t停机 0\n",
			卦名(震器), 卦名(震器))},
		{"所指之化非行", fmt.Sprintf("\t化息 0\n\t加数 %s, 坤, 0\n\t转化 坤, %s, 坤, 0\n\t停机 0\n",
			卦名(震器), 卦名(震器))},
	}
	for _, 案 := range 诸案 {
		k := 建枢态机(t, 案.源)
		跑必止(t, k, 2000)
		if k.轰否 {
			t.Errorf("%s：不当轰：%s", 案.名, k.轰由)
		}
		if k.因 != 越化之变 {
			t.Errorf("%s：因 = %s，欲 越化", 案.名, k.因.名())
		}
		if !k.机.止否() {
			t.Errorf("%s：枢之过当止其机，今未止", 案.名)
		}
		// 变之处理器 以 兑 ← 因 ＋ 1 志其因，而 序 不坏 兑，
		// 故此志得过 停机 而存——诸验遂得于机止之后观 兑 而知其因。
		if 欲 := int(越化之变) + 1; k.机.诸器[兑器] != 欲 {
			t.Errorf("%s：兑 = %d，欲 %d（因 ＋ 1）", 案.名, k.机.诸器[兑器], 欲)
		}
		if k.栈深() != 1 {
			t.Errorf("%s：枢态之陷当压栈一层，今深 %d", 案.名, k.栈深())
		}
		t.Logf("%s：止而志之，兑 ＝ %d，栈深 %d", 案.名, k.机.诸器[兑器], k.栈深())
	}
}

// Test化选与化可之口 器区之 化选、化可 二口。
//
// 化可 之约：**不问则已，问则必有一答，答不出便答「不可」**。
// 号越界者答阴，不陷。若越界者陷，则 序 遂须先问「有几化」——
// 那便又要一口，而那一口之数终将与 Go 之 len(k.化) 成为两份（M4 之训）。
func Test化选与化可之口(t *testing.T) {
	k := 二化之机(t, 0)
	if got := k.化之数(); got != 2 {
		t.Fatalf("化之数 = %d，欲 2", got)
	}
	for 号 := 0; 号 < k.化之数(); 号++ {
		k.器写(器基+化选之口, 号)
		if got := k.器读(器基 + 化选之口); got != 号 {
			t.Errorf("化选 ← %d，读回 %d", 号, got)
		}
		if got := k.器读(器基 + 化可之口); got != 1 {
			t.Errorf("化 %d 未跑，状是行，化可 当 1，今 %d", 号, got)
		}
	}
	// 越界则阴，不陷、不轰
	for _, 号 := range []int{2, 99, -1} {
		k.器写(器基+化选之口, 号)
		if got := k.器读(器基 + 化可之口); got != 0 {
			t.Errorf("化选 ← %d（越界），化可 = %d，欲 0", 号, got)
		}
	}
	if k.轰否 {
		t.Errorf("化选 越界不当轰：%s", k.轰由)
	}

	// 化息 之后，化可 当转而答阴——**口之所见，是化之现况，非一份名单**
	k.化[0].状 = 化毕
	k.器写(器基+化选之口, 0)
	if got := k.器读(器基 + 化可之口); got != 0 {
		t.Errorf("化 0 既毕，化可 当 0，今 %d", got)
	}
}

// Test器区之化口 器区之 界基、界限、当化、告 四口（M6 所增）。
//
// # 界基 与 界限 何以立口
//
// 界址之欺：化 不当知自己在物理的哪一处。故 化 无从读此二口——
// 化态 读之，其址（器区）恒在其界之外，遂陷越权而撤其值。
// 口是**开给枢的**：序 要报「转去了哪一化」，越权之处理器要志「越的是谁的界」。
//
// # 告 何以立口
//
// 异步之断须先有其举，而后有其应。钟 是其一（时到自鸣），
// 此口是其二（枢 举之，告立至）。今无外设，故举者唯枢自己——
// 而口已立，他日外设来时不必改此枢。
func Test器区之化口(t *testing.T) {
	k := 二化之机(t, 0)

	// 一、界基、界限、当化：皆报**现化**，不随 化选 而移。
	//
	// 化选／化可 是「择而问之」，界基／界限／当化 是「视其现况」——
	// 二事各有一口，不相侵。序 若欲知他化之界，须先 转化 过去，
	// 此即「口不越俎」之约：一口只做一事，故一事错时只错一处。
	if got := k.器读(器基 + 当化之口); got != k.当 {
		t.Errorf("当化之口 = %d，欲 %d（现化之号）", got, k.当)
	}
	if got := k.器读(器基 + 界基之口); got != k.化[k.当].界基 {
		t.Errorf("界基之口 = 0o%06o，欲 0o%06o（现化之界基）", got, k.化[k.当].界基)
	}
	if got := k.器读(器基 + 界限之口); got != k.化[k.当].界限 {
		t.Errorf("界限之口 = %d，欲 %d（现化之界限）", got, k.化[k.当].界限)
	}
	他 := 1 - k.当
	k.器写(器基+化选之口, 他)
	if got := k.器读(器基 + 界基之口); got != k.化[k.当].界基 {
		t.Errorf("既择化 %d，界基之口 = 0o%06o，仍当是现化 %d 之 0o%06o——"+
			"界基 报的是现化，不是所择之化", 他, got, k.当, k.化[k.当].界基)
	}
	k.器写(器基+化选之口, k.当)

	// 二、告 之口：不举则阴，举则阳，销则复阴。
	// 举与至是一物之二面：口 之所见，即 告至 之所问。
	if got := k.器读(器基 + 告之口); got != 0 {
		t.Errorf("未举告而读 告之口 = %d，欲 0", got)
	}
	k.器写(器基+告之口, 1)
	if got := k.器读(器基 + 告之口); got != 1 {
		t.Errorf("既举告，告之口 = %d，欲 1", got)
	}
	if !k.告至() {
		t.Error("既举告，告至 当为真——举与至，一物之二面")
	}
	k.器写(器基+告之口, 0)
	if got := k.器读(器基 + 告之口); got != 0 {
		t.Errorf("既销告，告之口 = %d，欲 0", got)
	}
	if k.告至() {
		t.Error("既销告，告至 当为假")
	}

	// 三、举 → 至 → 陷 → 销，四节缺一则不成为断。
	//
	// 片 为零（钟不鸣），故此处之告**唯举告之一途**。
	// 陷 一发而销其告（**销其告者，陷也**），故全程当**恰告一次**：
	// 若不销，则化态每一取指皆陷，机遂空转而永不进——
	// 那也是「错而无声」之类，而此一断言正戳在它上头。
	k2 := 二化之机(t, 0)
	k2.器写(器基+告之口, 1) // 未入化而已举告
	跑必止(t, k2, 20000)
	if n := 计志(k2, "变 告"); n != 1 {
		t.Errorf("志 中「变 告」当有 1 条，今 %d 条——陷 当销其告，销则不复告", n)
	}
	// 夺其先而不夺其果：两化仍各跑满三回与五回
	if got := 出之集(k2); got["甲"] != 3 || got["乙"] != 5 {
		t.Errorf("举告 之出之集 %v，欲 甲 3、乙 5", got)
	}
	for i, 欲 := range []int{3 * int('甲'), 5 * int('乙')} {
		if got := 化之和(k2, i); got != 欲 {
			t.Errorf("举告 之化 %d 之和 = %d，欲 %d", i, got, 欲)
		}
	}
	if k2.轰否 {
		t.Errorf("举告 不当轰：%s", k2.轰由)
	}
	t.Logf("举告：出「%s」，告 %d 次", k2.出之文(), 计志(k2, "变 告"))
}

// Test转化则复其钟 新化得一整片，不承旧化之余。
//
// 钟.过 是「此化**已得**几令」。转化 若不复其零，则新化一上来便背着
// 旧化欠下的时辰——它头一片遂短了，短多少全看旧化是何时被夺的。
// 此错极静：机器照跑，字照出，只是**诸化之片遂不等长**，
// 而「片 之数名副其实」之约遂成虚言。
//
// # 何以径呼 行转化，而不假 序 以观之
//
// 序 走得到 转化，然钟鸣之时 过 恰等于 片——欲测「复零」，
// 须先造一个**不等于 片**的 过，而 序 之中造不出来。
// 强以 序 观之，则所验者是「片满之后 转化」，不是「转化 必复其零」。
// 故此处径自枢态呼之，先置 过 为一数，再看 转化 之后它是零否。
func Test转化则复其钟(t *testing.T) {
	k := 二化之机(t, 8)
	令, err := 汇一(fmt.Sprintf("转化 坤, %s, 坤, 0", 卦名(艮器)))
	if err != nil {
		t.Fatalf("汇一「转化」：%v", err)
	}
	k.特权 = 枢态      // 转化 是特权之令，唯枢能行之
	k.机.诸器[艮器] = 1 // 欲转之号
	k.钟.过 = 5      // 旧化之余，任取一非零之数
	k.行转化(令)
	if k.当 != 1 {
		t.Fatalf("转化 之后 当 = %d，欲 1（转化 不就，则当留其旧）", k.当)
	}
	if k.轰否 {
		t.Fatalf("转化 不当轰：%s", k.轰由)
	}
	if got := k.钟.过; got != 0 {
		t.Errorf("转化 之后 钟.过 = %d，欲 0——"+
			"新化当得一整片，不承旧化之余（旧化余 5）", got)
	}
	// 顺带一验：转化 亦复其器。新化之诸器当自其块而出，非仍是旧化之器。
	if got := k.机.诸器[艮器]; got != k.化[1].诸器[艮器] {
		t.Errorf("转化 之后 艮 = %d，欲 %d（化 1 之旧器）", got, k.化[1].诸器[艮器])
	}
}

// Test器口之簿 器区之口之单，与其**实**相符否。
//
// 器口之簿 是唯一真源：演示 之器区表、器口之数，皆由它出。
// 若另抄一份名单，则增一口而表不变——**凡手抄之单，必漏**（M4 之训），
// 而漏掉的东西不报错，只是不见了。故此处不抄，只**量其自陈者合不合于实**：
//
//	口号 皆在器区之内（是器区(器基 ＋ 口)）
//	口号 递增而无重复
//	器口之数 由簿数出，不由手书
//	簿外之口（器口之数 .. 器之数-1）是**未配之口**，读之得零
func Test器口之簿(t *testing.T) {
	if 器口之数() != len(器口之簿) {
		t.Fatalf("器口之数() = %d，与 器口之簿 之实长 %d 不符——此数当由簿数出",
			器口之数(), len(器口之簿))
	}
	前 := -1
	for _, 口 := range 器口之簿 {
		if 口.口 <= 前 {
			t.Errorf("器口之簿 之口号当递增而无重复：%d 之后是 %d（「%s」）", 前, 口.口, 口.名)
		}
		前 = 口.口
		if !是器区(器基 + 口.口) {
			t.Errorf("口「%s」之号 %d 越出器区（器基 0o%06o ＋ 器之数 0o%o）",
				口.名, 口.口, 器基, 器之数)
		}
		if 口.名 == "" {
			t.Errorf("口号 %d 无名", 口.口)
		}
		if 口.注 == "" {
			t.Errorf("口「%s」无注", 口.名)
		}
	}
	// 簿外之口：未配，读之得零。
	//
	// 器之数 是 0o100 而只配其十，余者留 M7 之外设。
	// 「口有而未配」与「口无」是两事：前者**已留其址**，后者须移 器基——
	// 而 器基 一移，枢文基 与其之间那段便日日不同（见 器基 之注）。
	k := 二化之机(t, 0)
	for 口 := 器口之数(); 口 < 器之数; 口++ {
		if got := k.器读(器基 + 口); got != 0 {
			t.Errorf("未配之口 %d 读之得 %d，欲 0", 口, got)
		}
	}
}

