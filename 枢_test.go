// Test降化之特权 枢态 行 降化，则降入化态而径往其址。
func Test降化之特权(t *testing.T) {
	k := 建枢态机(t, fmt.Sprintf("处 0\n\t降化 0o%06o\n\n处 0o%06o\n\t停机 0\n",
		化之址, 化之址))
	if k.特权 != 枢态 {
		t.Fatalf("上电之特权当是枢态，今是 %s", k.特权.名())
	}
	k.步() // 一、取指
	k.步() // 二、执行：降化
	if k.特权 != 化态 {
		t.Errorf("降化 之后特权当是化态，今是 %s", k.特权.名())
	}
	if k.机.计 != 化之址 {
		t.Errorf("降化 之后计当是 0o%06o，今是 0o%06o", 化之址, k.机.计)
	}
	if k.机.相 != 0 {
		t.Errorf("降化 之后相当归零（重新取指），今是 %d", k.机.相)
	}
	跑必止(t, k, 100)
	// 化态 行 停机 亦止——停机 非特权之令，化态可行。
	if !k.轰否 {
		return
	}
	t.Errorf("不当轰：%s", k.轰由)
}

// Test化态行特权之令则越权 降化 与 回 皆特权之令，化态行之则越权。
//
// 变之处理器 以 兑 志其「因 ＋ 1」，故末了 兑 当是 越权之变 + 1 = 1。
// 此一验顺带验了整条变之路：陷 → 变之表 → 变越权 → 停机。
func Test化态行特权之令则越权(t *testing.T) {
	for _, 令名之 := range []string{"降化", "回"} {
		k := 建验机(t, fmt.Sprintf("\t%s 0\n\t停机 0\n", 令名之))
		if !步至陷(t, k, 100) {
			t.Fatalf("%s：未曾陷", 令名之)
		}
		if k.因 != 越权之变 {
			t.Errorf("%s：因当是越权，今是 %s", 令名之, k.因.名())
		}
		if k.存计 != 化之址+1 {
			t.Errorf("%s：存计当是 0o%06o（次令之址），今是 0o%06o",
				令名之, 化之址+1, k.存计)
		}
		if k.机.计 != 变之表基+int(越权之变) {
			t.Errorf("%s：陷后之计当是 变之表 之第 %d 槽 0o%06o，今是 0o%06o",
				令名之, int(越权之变), 变之表基+int(越权之变), k.机.计)
		}
		跑必止(t, k, 100)
		if got, 欲 := k.机.诸器[兑器], int(越权之变)+1; got != 欲 {
			t.Errorf("%s：变之处理器 当志 兑 = 因+1 = %d，今是 %d", 令名之, 欲, got)
		}
	}
}

// ------------------------------------------------------------------
// 五、特权：越权之三途
// ------------------------------------------------------------------

// Test化态取指于枢之域则越权 化态 而 计 已入枢之域，取指之先便陷。
//
// 其要在**令器未泄**：枢之码不可因这一拍而落入令器，
// 纵随即陷之亦不可——真机之中此检在地址总线上，取指之先。
func Test化态取指于枢之域则越权(t *testing.T) {
	泄 := 0o123456
	k := 建验机(t, "\t跃 0o777000\n\t停机 0\n")
	if err := k.机.写藏(枢基, 泄); err != nil {
		t.Fatalf("写藏：%v", err)
	}
	if !步至陷(t, k, 100) {
		t.Fatal("未曾陷")
	}
	if k.因 != 越权之变 {
		t.Errorf("因当是越权，今是 %s", k.因.名())
	}
	// 此陷不耗一拍，故 存计 是那**未曾取成**之址，而非次令之址。
	if k.存计 != 枢基 {
		t.Errorf("存计当是未曾取成之址 0o%06o，今是 0o%06o", 枢基, k.存计)
	}
	// 令器当已清（陷 既改其计，则令器亦清，次拍重新取指），
	// 尤要者：**它不是那个枢之码**。陷得再快，泄了便是迟了。
	if k.机.令 == 泄 {
		t.Errorf("令器泄了枢之码 0o%08o", 泄)
	}
	if k.机.令 != 0 {
		t.Errorf("陷 之后令器当清，今是 0o%08o", k.机.令)
	}
	跑必止(t, k, 100)
}

// Test化态读枢之域则撤 化态 读枢之域 → 越权，且**读回之值须撤**。
//
// 「撤」是此验之的真：若不撤，则越权之读虽陷而其实已读——
// 器里那个数便是偷来的，而陷只罚了「伸手」这一事，未罚「得手」。
func Test化态读枢之域则撤(t *testing.T) {
	// 枢基 之址由 置数 生出，不由「枢基 >> 数位」——
	// 后者丢掉低十二位（枢基 = 0o777000，其低十二位非全零），
	// 遂得一个「看着像」而差了 4088 的址。**像而不对，是最难察的一种错。**
	旧值 := 0o777
	k := 建验机(t, 置数(艮器, 枢基)+
		fmt.Sprintf("\t加数 %s, 坤, %d\t；兑 ← %d（志之，以备验其未变）\n", 卦名(兑器), 旧值, 旧值)+
		fmt.Sprintf("\t载字 %s, [%s]\t；兑 ← 藏[枢基]，化态不当读得\n", 卦名(兑器), 卦名(艮器))+
		"\t停机 0\n")
	if err := k.机.写藏(枢基, 0o654321); err != nil {
		t.Fatalf("写藏：%v", err)
	}
	if !步至陷(t, k, 100) {
		t.Fatal("未曾陷")
	}
	if k.因 != 越权之变 {
		t.Errorf("因当是越权，今是 %s", k.因.名())
	}
	if got := k.机.诸器[兑器]; got != 旧值 {
		t.Errorf("越权之读未撤：兑 当仍是 %d，今是 %d（其值是偷来的）", 旧值, got)
	}
	if k.机.址值() != 枢基 {
		t.Errorf("址之探针当是 0o%06o，今是 0o%06o", 枢基, k.机.址值())
	}
	跑必止(t, k, 100)
}

