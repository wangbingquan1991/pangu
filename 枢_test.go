// Test枢之域之图 诸域之界不自相犯。
//
// 此验看似只是查几个常量，实则是**枢之全部地址契约**。
// 器区 与 枢文基 若相叠，机器不报错，只是把内核的码当作串口去写——
// 一个越界的址不会报错，它只是把字写到别处去。
func Test枢之域之图(t *testing.T) {
	// 叩之表 不犯 变之表
	if 叩之表基+叩号数 > 变之表基 {
		t.Errorf("叩之表 0o%06o 之 %d 槽溢入 变之表 0o%06o",
			叩之表基, 叩号数, 变之表基)
	}
	// 变之表 不犯 枢之正文
	if 变之表基+变之数 > 枢文基 {
		t.Errorf("变之表 溢入 枢文基")
	}
	// 枢之正文 不犯 器区
	if 枢文基 >= 器基 {
		t.Fatalf("枢文基 0o%06o 不先于 器基 0o%06o", 枢文基, 器基)
	}
	// 器区 正当藏之极：器基 + 器之数 恰是 址掩 + 1，不多一字，不少一字。
	//
	// 此非「小于」而是「等于」：器区踞藏之末，其后更无一址。
	// 若他日 器之数 增一而 器基 不移，此式立红——
	// 而它若只是「小于」，便会静默地把 器基 之上那一字吃掉。
	if 器基+器之数 != 址掩+1 {
		t.Errorf("器区 0o%06o..0o%06o 未终于藏之极 0o%06o（差 %d 字）",
			器基, 器基+器之数-1, 址掩, 址掩+1-(器基+器之数))
	}
	// 变之数 与 变之因之众 是同一件事之两面
	if 变之数 != len(变之因之众) {
		t.Errorf("变之数 %d 与 变之因之众 %d 不合", 变之数, len(变之因之众))
	}
	// 叩号数 与 叩之簿 亦然
	if 叩号数 != len(叩之簿) {
		t.Errorf("叩号数 %d 与 叩之簿 %d 不合", 叩号数, len(叩之簿))
	}
	// 是枢之域 之界：化之极 之下不入，化之极 之上皆入（籍区、器区 亦在其中）
	//
	// 其界是 化之极，不是 枢基——M7 既立 籍区 于 枢基 之下，
	// 二址遂分。守 枢基 者，是守了「枢之正文」而放了「籍」：
	// 那一放不报错，只是一化写得动别化之档（M5 之二戒）。
	if 是枢之域(化之极 - 1) {
		t.Errorf("化之极 之前一址 0o%06o 不当在枢之域", 化之极-1)
	}
	for _, 址 := range []int{籍基, 籍基 + 节表之量, 籍存, 枢基, 变之表基, 枢文基, 器基, 器基 + 器之数 - 1, 址掩} {
		if !是枢之域(址) {
			t.Errorf("0o%06o 当在枢之域", 址)
		}
	}
	// 是器区 之界：八口，不多不少
	for _, 址 := range []int{器基 - 1, 器基 + 器之数} {
		if 是器区(址) {
			t.Errorf("0o%06o 不当在器区", 址)
		}
	}
	for i := 0; i < 器之数; i++ {
		if !是器区(器基 + i) {
			t.Errorf("器区第 %d 口 0o%06o 当在器区", i, 器基+i)
		}
	}
	// 器区 是 枢之域 之末段，故化态亦不得触
	for i := 0; i < 器之数; i++ {
		if !是枢之域(器基 + i) {
			t.Errorf("器区第 %d 口不当在枢之域之外", i)
		}
	}
	t.Logf("藏之图：化 0..0o%06o │ 叩之表 0o%06o×%d │ 变之表 0o%06o×%d │ 枢文 0o%06o │ 器区 0o%06o×%d",
		化之极-1, 叩之表基, 叩号数, 变之表基, 变之数, 枢文基, 器基, 器之数)
}

// Test枢文不侵器基 枢之正文不得长过 枢文基 与 器基 之间那一段。
//
// 此界本该有人守，而向来无人守：枢之码 逐日而长，
// 长过了 器基 便把器区之第一口当了正文之末字——
// 写 器基 者遂写进了一条令，而那令**不在叩之表里，亦不在正文里**，
// 它是一段无人认领的码，静静地躺在器的位置上。
// 机器不报错，只是某个器忽然不听使唤。
//
// 此验不数它该有多长，只数它**实有多长**——
// 汇 一遍，量 果.诸字 之数，与 器区之余 相较。
// **量而不算，则码一长便红；算而不量，则长到何时方红，无人知道。**
func Test枢文不侵器基(t *testing.T) {
	for _, 化数 := range []int{1, 2, 8} {
		果 := 汇(枢之源码(化数))
		if !果.成() {
			t.Fatalf("化数 %d：枢之源码 竟译不过：\n%s", 化数, 果.过之辞())
		}
		// 果.诸字 是**稠密**的，自址 0 起（译.go 之 r.置），
		// 故 len 已是末址 ＋ 1；再添 叩之表基 者是数了两遍。
		末 := len(果.诸字)
		if 末 <= 叩之表基 {
			t.Fatalf("化数 %d：枢之码 只 %d 字，短于 叩之表基 0o%06o；"+
				"是 处 失落，抑或 汇 之 诸字 改了起法？", 化数, 末, 叩之表基)
		}
		if 末 > 器基 {
			t.Errorf("化数 %d：枢之码 自 0o%06o 编至 0o%06o（%d 字），侵了 器基 0o%06o；"+
				"器区之余 只 %d 字",
				化数, 叩之表基, 末, 末-叩之表基, 器基, 器区之余)
		}
		if 化数 == 2 {
			余地 := 器基 - 末
			t.Logf("枢之码 %d 字（叩之表 %d ＋ 变之表 %d ＋ 枢文 %d），余地 %d 字",
				len(果.诸字)-叩之表基, 叩号数, 变之数, 末-枢文基, 余地)
			// 余地 之界亦须有人守：M7 之 籍 已用去大半，
			// 余之不足二十字者，下一叩便装不下——**先红于此，胜于红于彼**。
			if 余地 < 20 {
				t.Errorf("枢文之余 只 %d 字，不足以再容一叩；"+
					"当拓 器基，或缩 叩之表（叩号数 %d）", 余地, 叩号数)
			}
		}
	}
}

