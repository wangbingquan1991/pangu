// Test枢态可行叩 枢态 亦可叩——M6 撤了 M5 那一途 轰。
//
// # 旧验何往
//
// M5 之时 枢态 行 叩 则轰：其时 存计 只有一个，化态 陷来记的是化之来处，
// 枢态 若再叩，那个来处便被覆了，回 将不知返于何所。故 M5 宁可止，不可错。
//
// M6 立了变之栈，彼权宜遂去——**债在何处欠下，便在何处还**。
// 枢态 之 叩 遂只是多压一层，回 则弹之而复归枢态。
//
// # 此验验什么
//
// 不独验「不轰」——不轰 是个静默的否定，机器什么也不做便也「不轰」了。
// 故验三事：**字出了**（叩 真的走了服务例程）、
// **特权仍是枢态**（回 弹的是枢态之记，不是一律降为化态）、
// **栈复空**（压了一层，弹了一层，不欠不余）。
