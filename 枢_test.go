// Test叩则记其来处 叩 以 存计 记次令之址，回 则返于斯。
//
// 「次令之址」而非「叩之址」：执行相之末 计 已自增，
// 故此刻之 计 恰是返址。若记了 叩 自己的址，回 便成死循环。
func Test叩则记其来处(t *testing.T) {
	//
	// 返址之欲值由**标签**查出，不数指令：置数 出的是二令而非一令，
	// 故「叩 在第几字」随 欲置之字 而变。手数之，则改一处而错一处，
	// 且错得无声——此即「凡手抄之单，必漏」之第五发。
	化源 := 置数(兑器, int('盘')) +
		求叩("出") + "出后：\n" +
		息之辞() + "息后：\n"
	k := 建验机(t, 化源)
	跑必止(t, k, 10000)
	果 := 汇(化之程(化源))
	if !果.成() {
		t.Fatalf("译卦有过：%s", 果.过之辞())
	}
	var 诸返 []string
	for _, 记 := range k.记 {
		if strings.HasPrefix(记.辞, "叩 ") {
			诸返 = append(诸返, 记.辞)
		}
	}
	// 来处之权亦志之：M6 之中 枢态 亦可叩（变之栈 既立，存计 不复可覆），
	// 故「自何权而叩」遂成一事，不得不志。此二叩皆自化态而发。
	欲之返 := []string{
		fmt.Sprintf("叩 %d「出」，返 0o%06o（%s）", 叩号("出"), 果.标签["出后"], 化态.名()),
		fmt.Sprintf("叩 %d「息」，返 0o%06o（%s）", 叩号("息"), 果.标签["息后"], 化态.名()),
	}
	if len(诸返) != len(欲之返) {
		t.Fatalf("叩 之记 %d 条，欲 %d 条：%v", len(诸返), len(欲之返), 诸返)
	}
	for i, 欲 := range 欲之返 {
		if 诸返[i] != 欲 {
			t.Errorf("第 %d 次之叩：\n 得 %q\n 欲 %q", i, 诸返[i], 欲)
		}
	}
}

