// Test化态取指于枢之域则越权 化态 而 计 已入枢之域，取指之先便陷。
//
// 其要在**令器未泄**：枢之码不可因这一拍而落入令器，
// 纵随即陷之亦不可——真机之中此检在地址总线上，取指之先。
func Test化态取指于枢之域则越权(t *testing.T) {
	泄 := 0o123456
	k := 建验机(t, "\t跃 0o777000\n\t停机 0\n")
	if err := k.机.写藏(枢基, 泄); err != nil {
		t.Fatalf("写藏：%v", err)
	}
	if !步至陷(t, k, 100) {
		t.Fatal("未曾陷")
	}
	if k.因 != 越权之变 {
		t.Errorf("因当是越权，今是 %s", k.因.名())
	}
	// 此陷不耗一拍，故 存计 是那**未曾取成**之址，而非次令之址。
	if k.存计() != 枢基 {
		t.Errorf("存计当是未曾取成之址 0o%06o，今是 0o%06o", 枢基, k.存计())
	}
	// 令器当已清（陷 既改其计，则令器亦清，次拍重新取指），
	// 尤要者：**它不是那个枢之码**。陷得再快，泄了便是迟了。
	if k.机.令 == 泄 {
		t.Errorf("令器泄了枢之码 0o%08o", 泄)
	}
	if k.机.令 != 0 {
		t.Errorf("陷 之后令器当清，今是 0o%08o", k.机.令)
	}
	跑必止(t, k, 100)
}

// Test化态读枢之域则撤 化态 读枢之域 → 越其界，且**读回之值须撤**。
//
// 「撤」是此验之的真：若不撤，则越权之读虽陷而其实已读——
// 器里那个数便是偷来的，而陷只罚了「伸手」这一事，未罚「得手」。
//
// # M6 之新话旧义
//
// M5 说的是「化态触枢之域」，M6 说的是「化态越其界」。
// 二说于此**同指一址**：上电之化 界基 为零、界限 为 化之极 ＝ 枢基，
// 故「读 枢基」正是「虚址 ≥ 界限」之第一址。名易而实未移，
// 故 M5 之诸验不必改一字而自通。
func Test化态读枢之域则撤(t *testing.T) {
	// 枢基 之址由 置数 生出，不由「枢基 >> 数位」——
	// 后者丢掉低十二位（枢基 = 0o777000，其低十二位非全零），
	// 遂得一个「看着像」而差了 4088 的址。**像而不对，是最难察的一种错。**
	旧值 := 0o777
	k := 建验机(t, 置数(艮器, 枢基)+
		fmt.Sprintf("\t加数 %s, 坤, %d\t；兑 ← %d（志之，以备验其未变）\n", 卦名(兑器), 旧值, 旧值)+
		fmt.Sprintf("\t载字 %s, [%s]\t；兑 ← 藏[枢基]，化态不当读得\n", 卦名(兑器), 卦名(艮器))+
		"\t停机 0\n")
	if err := k.机.写藏(枢基, 0o654321); err != nil {
		t.Fatalf("写藏：%v", err)
	}
	if !步至陷(t, k, 100) {
		t.Fatal("未曾陷")
	}
	if k.因 != 越权之变 {
		t.Errorf("因当是越权，今是 %s", k.因.名())
	}
	if got := k.机.诸器[兑器]; got != 旧值 {
		t.Errorf("越权之读未撤：兑 当仍是 %d，今是 %d（其值是偷来的）", 旧值, got)
	}
	// 址之探针：越界者，变换 已把它引去了 界基（虚址零之物理所在）。
	//
	// **此是「不泄枢密」之实**。那一笔读到的字纵是化自己的，也不留（撤其效）；
	// 而枢之码，一字也不曾过总线。若探针仍是 枢基，则线已通，屏已破——
	// 纵随即陷之、随即撤之，那通的一瞬已经发生过了。
	//
	// 撤者，撤其效，非撤其址：址是线的去处，改它不得，也无须改。
	if 欲 := k.化[k.当].界基; k.机.址值() != 欲 {
		t.Errorf("越界之址 当被 变换 引去 界基 0o%06o，今是 0o%06o——枢之码过线了",
			欲, k.机.址值())
	}
	// 而 虚址 仍当是 化 之所见：化 以为自己读的是 枢基，
	// 界址之欺，正在于此——**化之所见与物之所在，自今而后是两件事**。
	if k.虚址 != 枢基 {
		t.Errorf("虚址当仍是 化 之所见 0o%06o，今是 0o%06o", 枢基, k.虚址)
	}
	跑必止(t, k, 100)
}

// Test化态写枢之域则撤 化态 写枢之域 → 越权，且**写入之字须撤**。
//
// # 何以验「撤」要抄整片藏，而不只验一个址（此是 M6 新出之瞎处）
//
// M6 之 变换 把越界之写**引去了 界基**（虚址零之物理所在），
// 而不是 化 自以为在写的那个址。上电之化 界基 为零，
// 故「化态写 枢基」那一笔，实落在 藏[0]——启之第一条令上。
//
// 而 M5 所写的这条验，查的是 藏[枢基]。那一笔根本没落在那里，
// 故**纵一字不撤，此验也是绿的**：它绿了整整一个里程碑，
// 而 具/变异枢.sh 之「六：越权之写 不撤」遂活了下来。
//
// 一条恒真的断言，与没有断言同——**而它不报错，只是一直绿着**。
// 故此处不问「撤到了哪个址」，只问一句话：**这一拍之后，藏可有一字不同？**
// 抄整片藏而比之，则无论 变换 把那一笔引去何处，皆在网中。
func Test化态写枢之域则撤(t *testing.T) {
	旧字 := 0o111111
	k := 建验机(t, 置数(艮器, 枢基)+
		fmt.Sprintf("\t加数 %s, 坤, 0o%o\n", 卦名(兑器), 0o777)+
		fmt.Sprintf("\t存字 %s, [%s]\t；化态 写 枢基，不当写得\n", 卦名(兑器), 卦名(艮器))+
		"\t停机 0\n")
	if err := k.机.写藏(枢基, 旧字); err != nil {
		t.Fatalf("写藏：%v", err)
	}
	// 藏[枢基] 仍要预置，是为存一条志：越界之写**不是**落在这里的。
	// 若它竟落在这里，则 变换 已坏，而此验之整片比法亦当先红于彼处。
	旧藏 := 藏之抄(k)
	if !步至陷(t, k, 100) {
		t.Fatal("未曾陷")
	}
	if k.因 != 越权之变 {
		t.Errorf("因当是越权，今是 %s", k.因.名())
	}
	if 差 := 藏之第一差(k.机.诸字, 旧藏); 差 >= 0 {
		t.Errorf("越权之写未撤：藏[0o%06o] 当仍是 0o%08o，今是 0o%08o（界基 0o%06o）",
			差, 旧藏[差], k.机.诸字[差], k.化[k.当].界基)
	}
	跑必止(t, k, 100)
	if 差 := 藏之第一差(k.机.诸字, 旧藏); 差 >= 0 {
		t.Errorf("变之处理器跑过之后，藏[0o%06o] 亦当仍是 0o%08o，今是 0o%08o",
			差, 旧藏[差], k.机.诸字[差])
	}
}

// 藏之抄 抄一份藏，备比。
func 藏之抄(k *枢机) []int {
	诸 := make([]int, len(k.机.诸字))
	copy(诸, k.机.诸字)
	return 诸
}

// 藏之第一差 得 与 欲 之第一处不同之址；全同则回 −1。
//
// 何以回的是**址**而非「同否」：报错若只说「不合」，
// 则读者须自己去翻整片藏；说出址来，则一眼可见那一笔落在了哪里——
// 而「落在哪里」往往正是病之所在（见 Test化态写枢之域则撤 之注）。
func 藏之第一差(得, 欲 []int) int {
	if len(得) != len(欲) {
		return 0
	}
	for i := range 欲 {
		if 得[i] != 欲[i] {
			return i
		}
	}
	return -1
}

