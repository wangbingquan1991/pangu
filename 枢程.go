// 枢之表 叩之表 与 变之表。二者皆**码**，非数。
//
// 一槽便是一条 跃 令。故反汇编可见其全形，
// 而叩之一事遂与诸令同列——它不特权的什么，它只是被跳到。
func 枢之表(b *strings.Builder) {
	fmt.Fprintf(b, "； ---- 叩之表：六十四槽，一槽一条 跃 令 ----\n")
	fmt.Fprintf(b, "； 槽 %d 起，共 %d 槽；余 %d 字。\n", 叩之表基, 叩号数, 叩表之余)
	fmt.Fprintf(b, "处 0o%06o\n", 叩之表基)
	for i := 0; i < 叩号数; i++ {
		fmt.Fprintf(b, "跃 叩%s\n", 叩名(i))
	}
	b.WriteString("\n")

	fmt.Fprintf(b, "； ---- 变之表：五槽，一因一槽 ----\n")
	fmt.Fprintf(b, "处 0o%06o\n", 变之表基)
	for _, 因 := range 变之因之众 {
		fmt.Fprintf(b, "跃 变%s\n", 因.名())
	}
	b.WriteString("\n")
}

// 序之源码 序（调度器）之码。
//
// 序 之事只有一件：**自 当 之次，寻一个可行之化而转之**；
// 寻不见（诸化皆毕）则止其机。
//
// # 何以先问而后转
//
// 转化 不就则陷 越化，而 陷 自枢态来者须压栈——
// 那一层压的是**现化**之栈，而 序 不属于任何一化，
// 压上去便是替别人记了一笔账，回 之时必错（错而无声）。
// 故 序 **先问 化可之口，问得可行方转**。问而不转，则无陷，则无压。
// 此非绕道，是**不可陷者，便不可不先问**。
//
// # 何以 序本 另起一段
//
// 环 试的是「他化」（当 之外者）。若遍而他化皆不可行，
// 犹当回视 当 自己——**当 若犹行，是无他可让，当续跑**。
// 故环尽而至于 序本：问 当 之可行否，行则转其自己，不行则 序穷。
//
// 若径以 当 入环，则二化之时 当 恒先被择中，而轮转遂不成——
// **此错极静：两化皆在跑，只是一化独占了机。**
//
// # 兑 不与
//
// 变之处理器 以 兑 志其因（因 ＋ 1），而 序 在 化息 之后、停机 之前跑。
// 序 若坏 兑，其志遂失，而诸验（「兑 ＝ 因 ＋ 1」）亦随之瞎。
// 故 序 只用 艮坎巽震离 五器，恰在 叩之约 所许之内而 兑 不与。
func 序之源码(化数 int) string {
	var b strings.Builder
	b.WriteString("； ---- 序 · 调度之码 ----\n")
	b.WriteString("； 艮＝器基　震＝当　坎＝候选　巽＝化之数　离＝可否　（兑 不与）\n")
	b.WriteString("序之始：\n")
	b.WriteString(置器基())
	fmt.Fprintf(&b, "\t载字 %s, [%s + %d]\t；震 ← 当（现化之号）\n",
		卦名(暂乙), 卦名(暂甲), 当化之口)
	fmt.Fprintf(&b, "\t加数 %s, %s, 0\t\t；坎 ← 候选，起于 当\n", 卦名(暂丙), 卦名(暂乙))
	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；巽 ← 化之数 %d\n", 卦名(暂丁), 化数, 化数)
	b.WriteString("序环：\n")
	fmt.Fprintf(&b, "\t加数 %s, %s, 1\t\t；候选 ← 候选 ＋ 1\n", 卦名(暂丙), 卦名(暂丙))
	fmt.Fprintf(&b, "\t逊跃 坤, %s, %s, 序问\t；候选 犹在化内则径问\n", 卦名(暂丙), 卦名(暂丁))
	fmt.Fprintf(&b, "\t加数 %s, 坤, 0\t\t；否则绕回域首\n", 卦名(暂丙))
	b.WriteString("序问：\n")
	fmt.Fprintf(&b, "\t等跃 坤, %s, %s, 序本\t；绕了一圈而复归于 当 → 回视其本化\n",
		卦名(暂丙), 卦名(暂乙))
	fmt.Fprintf(&b, "\t存字 %s, [%s + %d]\t；择 化 候选\n", 卦名(暂丙), 卦名(暂甲), 化选之口)
	fmt.Fprintf(&b, "\t载字 %s, [%s + %d]\t；离 ← 其化可行否\n", 卦名(暂戊), 卦名(暂甲), 化可之口)
	fmt.Fprintf(&b, "\t等跃 坤, %s, 坤, 序环\t；不可行（离 ＝ 0）则试其次\n", 卦名(暂戊))
	fmt.Fprintf(&b, "\t转化 坤, %s, 坤, 0\t\t；可行则转之（诸器自块而复）\n", 卦名(暂丙))
	b.WriteString("\t回 0\t\t\t\t；回 → 其化（栈空则归于块之计）\n")
	b.WriteString("序本：\n")
	fmt.Fprintf(&b, "\t存字 %s, [%s + %d]\t；择 化 当\n", 卦名(暂乙), 卦名(暂甲), 化选之口)
	fmt.Fprintf(&b, "\t载字 %s, [%s + %d]\t；离 ← 本化可行否\n", 卦名(暂戊), 卦名(暂甲), 化可之口)
	fmt.Fprintf(&b, "\t等跃 坤, %s, 坤, 序穷\t；本化亦不可行 → 无可行者\n", 卦名(暂戊))
	fmt.Fprintf(&b, "\t转化 坤, %s, 坤, 0\t\t；可行则转其自己（新得一片）\n", 卦名(暂乙))
	b.WriteString("\t回 0\n")
	b.WriteString("序穷：\n")
	b.WriteString("\t停机 0\t\t\t\t；诸化皆毕，机无所事\n\n")
	return b.String()
}

// 枢之身 枢之正文。
func 枢之身(b *strings.Builder, 化数 int) {
	fmt.Fprintf(b, "； ---- 枢之正文：叩之服务与变之处理器 ----\n")
	fmt.Fprintf(b, "处 0o%06o\n\n", 枢文基)

	// 出
	fmt.Fprintf(b, "； 出：出一字。兑 ＝ 欲出之字（三字节，正合一汉字）\n")
	fmt.Fprintf(b, "叩出：\n")
	b.WriteString(置器基())
	fmt.Fprintf(b, "\t存字 %s, %s, 0\t；出之口 ← 兑\n", 卦名(兑器), 卦名(暂甲))
	b.WriteString("\t回 0\n\n")

	// 言
	fmt.Fprintf(b, "； 言：出一串。兑 ＝ 首址，离 ＝ 字数；返 兑 ＝ 0\n")
	fmt.Fprintf(b, "叩言：\n")
	fmt.Fprintf(b, "\t加数 %s, %s, 0\t；暂乙 ← 首址\n", 卦名(暂乙), 卦名(兑器))
	b.WriteString(置器基())
	b.WriteString("言环：\n")
	fmt.Fprintf(b, "\t等跃 坤, %s, 坤, 言末\t；字数尽则出环\n", 卦名(离器))
	fmt.Fprintf(b, "\t载字 %s, %s, 0\t；兑 ← 藏[暂乙]\n", 卦名(兑器), 卦名(暂乙))
	fmt.Fprintf(b, "\t存字 %s, %s, 0\t；出之口 ← 兑\n", 卦名(兑器), 卦名(暂甲))
	fmt.Fprintf(b, "\t加数 %s, %s, 1\t；暂乙 ← 暂乙 + 1\n", 卦名(暂乙), 卦名(暂乙))
	fmt.Fprintf(b, "\t减数 %s, %s, 1\t；离 ← 离 − 1\n", 卦名(离器), 卦名(离器))
	b.WriteString("\t跃 言环\n")
	b.WriteString("言末：\n")
	fmt.Fprintf(b, "\t加数 %s, 坤, 0\t；兑 ← 0，言已成\n", 卦名(兑器))
	b.WriteString("\t回 0\n\n")

	// 入
	fmt.Fprintf(b, "； 入：入一字。返 兑 ＝ 所入之字，无则零\n")
	fmt.Fprintf(b, "叩入：\n")
	b.WriteString(置器基())
	fmt.Fprintf(b, "\t载字 %s, %s, %d\t；兑 ← 入之口\n", 卦名(兑器), 卦名(暂甲), 入之口)
	b.WriteString("\t回 0\n\n")

	// 息
	//
	// M5 之 息 是 停机：彼时只有一化，化死即机死。
	// M6 之 息 是 化息 ＋ 序：**一化之死，不是一机之死**。
	// 现化毕矣，而他化犹行，则机不当止。
	fmt.Fprintf(b, "； 息：息其化。兑 ＝ 退出之码\n")
	fmt.Fprintf(b, "叩息：\n")
	b.WriteString("\t化息 0\t\t\t\t；现化之状 ← 毕\n")
	b.WriteString("\t跃 序之始\t\t\t；他化续行\n\n")

	// 未备
	fmt.Fprintf(b, "； 未备：号在六十四之内而其服务未立。返 兑 ＝ −1\n")
	fmt.Fprintf(b, "叩未备：\n")
	fmt.Fprintf(b, "\t减数 %s, 坤, 1\t；兑 ← 0 − 1\n", 卦名(兑器))
	b.WriteString("\t回 0\n\n")

	// 变之处理器：三途
	//
	//	化之过（越权、越令、越号）　其化当死，而他化不当陪葬。
	//		故 化息 而后 跃 序之始。**此是 M5 与 M6 之大别**：
	//		M5 之变皆致命，盖其时只有一化，化死即机死；
	//		M6 之中一化越了界，死的只是它自己。
	//	枢之过（越化）　转化 是特权之令，唯枢能行之；
	//		号越界或非行，皆枢之算错，**非化之罪**，故止其机而志之。
	//	非过（告）　钟鸣或举告，常事也，径入 序。
	//
	// 因 ＋ 1 而后志之于 兑，故 兑 ＝ 0 者是「无变」，非「越权」。
	// 序 不坏 兑，故此志得过 序 而存于 停机 之后——
	// 诸验遂得于机止之后观 兑 而知其因。
	b.WriteString("； ---- 变之处理器 ----\n")
	b.WriteString("； 变 之三途：化之过（死其化而他化续）、枢之过（止其机）、非过（告，入序）。\n")
	b.WriteString("； 以 兑 志其因（因 ＋ 1）；序 不坏 兑，故其志得存于 停机 之后。\n")
	for _, 因 := range 变之因之众 {
		fmt.Fprintf(b, "变%s：\n", 因.名())
		switch 因 {
		case 告之变:
			b.WriteString("\t跃 序之始\t\t\t；告至则让，非过\n")
		case 越化之变:
			fmt.Fprintf(b, "\t加数 %s, 坤, %d\t\t；兑 ← 因 ＋ 1\n", 卦名(兑器), int(因)+1)
			b.WriteString("\t停机 0\t\t\t\t；枢之过：止而志之，不罪其化\n")
		default:
			fmt.Fprintf(b, "\t加数 %s, 坤, %d\t\t；兑 ← 因 ＋ 1\n", 卦名(兑器), int(因)+1)
			b.WriteString("\t化息 0\t\t\t\t；化之过：死其化\n")
			b.WriteString("\t跃 序之始\t\t\t；而他化续行\n")
		}
	}
	b.WriteString("\n")

	// 序
	b.WriteString(序之源码(化数))
}

