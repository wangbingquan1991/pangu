// 壳之区 壳 之数据区之**虚址**。诸化同此，盖码皆自虚址零起（化之首）。
//
// 何以远在 0o1000 而不就近于码（0o100）：
// 一则其码之长未可预知，码长则侵数区；
// 二则**加数 之立即数止十二位**，凡以「坤 为基、签为偏」径取之址皆须在 2047 内。
// **近则相侵，远则越界；0o1000 者，两不相犯之处也。**
const 壳之区 = 0o1000

// 壳行之度 一行之极（字）。
const 壳行之度 = 0o40

// 壳之诸区 数据区之内划。**皆由 壳之区 与诸度算出，不手书。**
const (
	壳行址  = 壳之区
	壳行数址 = 壳行址 + 壳行之度 // 行 之字数
	壳令址  = 壳行数址 + 1   // 令字
	壳名址  = 壳令址 + 1    // 名（末以零终，与 节名 同度）
	壳名数址 = 壳名址 + 节名之度
	壳文址  = 壳名数址 + 1 // 文（写之自出，读之自入）
	壳文数址 = 壳文址 + 据之极 + 1
	壳目址  = 壳文数址 + 1 // 目（录名之区，与 节名 同度）
	壳号址  = 壳目址 + 节名之度
	壳数址  = 壳号址 + 1
	壳元址  = 壳数址 + 1  // 游标甲：行
	壳元乙址 = 壳元址 + 1  // 游标乙：区
	壳空址  = 壳元乙址 + 1 // 空格之码
	壳末址  = 壳空址 + 1  // 行终之码
	壳提址  = 壳末址 + 1  // 诸辞：提、终、成、否、无
	壳终址  = 壳提址 + 1
	壳成址  = 壳终址 + 1
	壳否址  = 壳成址 + 1
	壳无址  = 壳否址 + 1
	壳诸令址 = 壳无址 + 1
	壳区之度 = 壳诸令址 + 壳之令数 - 壳之区
)

// 壳之令数 六令。
const 壳之令数 = 6

// 壳之令 六令：壳 之字 → 所叩之名（空者非叩，如 列 与 止）。
//
// # 何以 叩 之号不另抄一份
//
// **凡手抄之单，必漏**（M4 之训，已发三次）。壳 若手书「建 是四号」，
// 则 叩之簿 一改而壳遂叩错了门——它不报错，只是叩到了别一叩上去。
// 故此处只书其名，号 由 叩号() 反查 叩之簿 而得；
// 而「此名果在簿中否」一事，由 Test壳之令在簿 守之。
//
// # 何以令止六
//
// 壳 是**码**，不是 Go。每增一令便增一段比字之码与一段施行之码，
// 而所增者是译卦器译出来的字，长一分则 汇 慢一分、跑 慢一分。
// **令不在多，在足以自证其为一壳。**
var 壳之令 = [壳之令数]struct {
	字 string
	叩 string
}{
	{"列", ""},  // 列：非一叩，是 目 之遍
	{"建", "建"}, //
	{"写", "写"}, // 写 先 求 而后 写——**号 是枢给的，不是壳算的**
	{"读", "读"}, //
	{"删", "删"}, //
	{"止", ""},  // 止：非一叩，是 息
}

// 壳之辞 壳 所言之诸符。
//
// # 换行何以是「⏎」而不是 U+000A
//
// 机器之字二十四位，容得下 U+000A；然 字之文 于不可印者皆作「⟨0o…⟩」，
// 出 一个 U+000A 便印出「⟨0o000012⟩」来——**能出而不能读，与不出同**。
// 故换行以 U+23CE「⏎」为之：它是可印之符，而其形便是回车之意。
// **非不敢用控制之符，是用了无人看得见。**
const (
	壳之提 = '〉' // 提示符
	壳之终 = '⏎' // 换行（U+23CE）
	壳之成 = '成'
	壳之否 = '否'
	壳之无 = '无'
	壳之空 = ' '
	壳之末 = 0x0A // 行终（所入之符）
)

