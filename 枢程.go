// 枢之源码 枢之码：叩之表、变之表、诸服务与诸处理器。
func 枢之源码() string {
	var b strings.Builder
	枢之表(&b)
	枢之身(&b)
	return b.String()
}

// 枢之表 叩之表 与 变之表。二者皆**码**，非数。
//
// 一槽便是一条 跃 令。故反汇编可见其全形，
// 而叩之一事遂与诸令同列——它不特权的什么，它只是被跳到。
func 枢之表(b *strings.Builder) {
	fmt.Fprintf(b, "； ---- 叩之表：六十四槽，一槽一条 跃 令 ----\n")
	fmt.Fprintf(b, "； 槽 %d 起，共 %d 槽；余 %d 字。\n", 叩之表基, 叩号数, 叩表之余)
	fmt.Fprintf(b, "处 0o%06o\n", 叩之表基)
	for i := 0; i < 叩号数; i++ {
		fmt.Fprintf(b, "跃 叩%s\n", 叩名(i))
	}
	b.WriteString("\n")

	fmt.Fprintf(b, "； ---- 变之表：三槽，一因一槽 ----\n")
	fmt.Fprintf(b, "处 0o%06o\n", 变之表基)
	for _, 因 := range 变之因之众 {
		fmt.Fprintf(b, "跃 变%s\n", 因.名())
	}
	b.WriteString("\n")
}

// 枢之身 枢之正文。
func 枢之身(b *strings.Builder) {
	fmt.Fprintf(b, "； ---- 枢之正文：叩之服务与变之处理器 ----\n")
	fmt.Fprintf(b, "处 0o%06o\n\n", 枢文基)

	// 出
	fmt.Fprintf(b, "； 出：出一字。兑 ＝ 欲出之字（三字节，正合一汉字）\n")
	fmt.Fprintf(b, "叩出：\n")
	b.WriteString(置器基())
	fmt.Fprintf(b, "\t存字 %s, %s, 0\t；出之口 ← 兑\n", 卦名(兑器), 卦名(暂甲))
	b.WriteString("\t回 0\n\n")

	// 言
	fmt.Fprintf(b, "； 言：出一串。兑 ＝ 首址，离 ＝ 字数；返 兑 ＝ 0\n")
	fmt.Fprintf(b, "叩言：\n")
	fmt.Fprintf(b, "\t加数 %s, %s, 0\t；暂乙 ← 首址\n", 卦名(暂乙), 卦名(兑器))
	b.WriteString(置器基())
	b.WriteString("言环：\n")
	fmt.Fprintf(b, "\t等跃 坤, %s, 坤, 言末\t；字数尽则出环\n", 卦名(离器))
	fmt.Fprintf(b, "\t载字 %s, %s, 0\t；兑 ← 藏[暂乙]\n", 卦名(兑器), 卦名(暂乙))
	fmt.Fprintf(b, "\t存字 %s, %s, 0\t；出之口 ← 兑\n", 卦名(兑器), 卦名(暂甲))
	fmt.Fprintf(b, "\t加数 %s, %s, 1\t；暂乙 ← 暂乙 + 1\n", 卦名(暂乙), 卦名(暂乙))
	fmt.Fprintf(b, "\t减数 %s, %s, 1\t；离 ← 离 − 1\n", 卦名(离器), 卦名(离器))
	b.WriteString("\t跃 言环\n")
	b.WriteString("言末：\n")
	fmt.Fprintf(b, "\t加数 %s, 坤, 0\t；兑 ← 0，言已成\n", 卦名(兑器))
	b.WriteString("\t回 0\n\n")

	// 入
	fmt.Fprintf(b, "； 入：入一字。返 兑 ＝ 所入之字，无则零\n")
	fmt.Fprintf(b, "叩入：\n")
	b.WriteString(置器基())
	fmt.Fprintf(b, "\t载字 %s, %s, %d\t；兑 ← 入之口\n", 卦名(兑器), 卦名(暂甲), 入之口)
	b.WriteString("\t回 0\n\n")

	// 息
	fmt.Fprintf(b, "； 息：停机。兑 ＝ 退出之码\n")
	fmt.Fprintf(b, "叩息：\n")
	b.WriteString("\t停机 0\n\n")

	// 未备
	fmt.Fprintf(b, "； 未备：号在六十四之内而其服务未立。返 兑 ＝ −1\n")
	fmt.Fprintf(b, "叩未备：\n")
	fmt.Fprintf(b, "\t减数 %s, 坤, 1\t；兑 ← 0 − 1\n", 卦名(兑器))
	b.WriteString("\t回 0\n\n")

	// 变之处理器
	b.WriteString("； ---- 变之处理器 ----\n")
	b.WriteString("； M5 之变皆致命：止其机，以 兑 志其因。\n")
	b.WriteString("； 因 ＋ 1 而后志之，故 兑 ＝ 0 者是「无变」，非「越权」。\n")
	b.WriteString("； 他日 M7 化（进程）既立，变 可有不致命者——\n")
	b.WriteString("； 彼时存计须成栈，而非一器（见 枢.go 之 轰）。\n")
	for _, 因 := range 变之因之众 {
		fmt.Fprintf(b, "变%s：\n", 因.名())
		fmt.Fprintf(b, "\t加数 %s, 坤, %d\t；兑 ← 因 ＋ 1\n", 卦名(兑器), int(因)+1)
		b.WriteString("\t停机 0\n")
	}
	b.WriteString("\n")
}

// ------------------------------------------------------------------
// 开天
// ------------------------------------------------------------------

// 化之程 以 化源 为用户程之正文，配 启 与 枢，成一段可装之源码。
//
// 用户程可换，启 与 枢 不可换。测试呼此函以试诸用户程，
// 而所跑之枢恒是真枢——见 化之签 之注。
func 化之程(化源 string) string {
	return 启之源码() + 化之签() + 化源 + 枢之源码()
}

// 开天之源码 启、化、枢 合成一段，付 汇 一次译之。
//
// 三者之所以要合成一段：**化之始 是用户程之签，而枢之启始须跃向它。**
// 分作两段则枢不知化之始在何所，只好手抄一址——
// 而手抄之址，改了便错，且不报错。
//
// 址之次序：0（启）→ 0o100（化之码）→ 0o200（化之数）→
// 0o777000（叩之表）→ 0o777100（变之表）→ 0o777200（枢之正文）。
// 低者是化，高者是枢；中间一大片未写之藏，是留给后之里程的。
func 开天之源码() string {
	return 化之程(化之源码())
}

// 建化之机 以 化源 为用户程，配 启 与 枢，造一具已装之枢机。
//
// 藏之址恒取 址位（十八）——枢基在 0o777000，非十八位之藏容它不下。
func 建化之机(化源 string) (*枢机, error) {
	k := 建枢机(址位)
	if err := k.装(化之程(化源)); err != nil {
		return nil, err
	}
	return k, nil
}

// 建开天之机 造一具已装好启、化、枢 之枢机，其用户程即 M5 之验收程。
func 建开天之机() (*枢机, error) {
	return 建化之机(化之源码())
}
