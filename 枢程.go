// ------------------------------------------------------------------
// 置器基
// ------------------------------------------------------------------

// 暂器 枢之暂用之器。
//
// 叩之约：叩 可坏 艮、坎、巽、震、离；兑 为元一兼返值，不可无故坏之；
// 坤 恒为零；乾 是叩号，服务例程不当动它（动了则 回 之后用户不知其号）。
// 故枢以 艮 为暂甲（器基之所在），以 震 为暂乙（言之游标）。
//
// 元之序（M7 立其三四）：兑 元一兼返值，离 元二，坎 元三，震 元四。
// 四元已足籍之用（名址、名字数、源址、字数），故不必更立「参数块」之制——
// 真机之参数在栈在块，本机之参数在器，**器只有八，用尽便须另谋**。
//
// 序 用器最多（器基、当、候选、化之数、可否，凡五），
// 而 兑 不与——**兑 是变之处理器志因之器，序 若坏之，其志遂失**。
// 五暂恰是 叩之约 所容许之全数（艮坎巽震离），故 序 不必破约而器已足。
const (
	暂甲 = 艮器 // 器基
	暂乙 = 震器 // 叩「言」之游标；序 之「当」
	暂丙 = 坎器 // 序 之「候选」
	暂丁 = 巽器 // 序 之「化之数」
	暂戊 = 离器 // 序 之「可否」
)

// 置数 出「器 ← 数」之二令：载高 置其高十二位，加数 补其差。
//
// 何不径用 加数 之一令：乙型之立即数是**十二位有符号**，界在 −2048..2047。
// 一个汉字之码位（如「盘」U+76D8 = 30424）便装它不下——
// 故凡欲置一大数者，皆须二分之。此非权宜，是令式之固然。
//
// 何以向上取整：向下取整之余必在 0..4095，而十二位有符号之上界是 2047，
// 故余过 2047 者装不下（器基 之余正是 4088）。
// 向上取整则差必在 −4096..−1，只须其不越 −2048。
//
// 装不下便 panic——**宁可炸，不可静默地算错一个数。**
// 一个算错的数不会报错，它只是把字写到别处去、或把别的字印出来。
//
// 二数皆由 数 算出，非手书——数 若移，此式自随。
func 置数(器, 数 int) string {
	高 := 数 >> 数位
	差 := 数 - (高 << 数位)
	if 差 > (1<<(数位-1))-1 {
		高++
		差 = 数 - (高 << 数位)
	}
	if 差 < -(1<<(数位-1)) || 差 > (1<<(数位-1))-1 {
		panic(fmt.Sprintf("置数：数 %d（0o%o）之差 %d 越出十二位有符号之界", 数, 数, 差))
	}
	return fmt.Sprintf("\t载高 %s, 坤, 0o%o\n\t加数 %s, %s, %d\n",
		卦名(器), 高, 卦名(器), 卦名(器), 差)
}

// 置器基 出「暂甲 ← 器基」之二令。其术见 置数。
func 置器基() string { return 置数(暂甲, 器基) }

// ------------------------------------------------------------------
// 启 · 上电之第一令
// ------------------------------------------------------------------

// 启之源码 处 0 之数令。
//
// 上电之特权在枢，计在零。若有钟，先置其片；末了一令总是 降化——
// 降入化态，径往 化始。此一令之后，枢不复出，唯待 叩 与 变 而返。
//
// 片 之缺省是零：**无钟之机不夺其化**，化 之让与不让，悉听其便。
// 故 M5 之径（片 ＝ 0）与旧日一拍不差，其诸验不必改一字。
//
// 化始 以**文**传入（或标签，或址），不传数——
// 单化之径传「化之始」（标签，与化同段），诸化之径传「0o000000」
// （化 在别一段里，无标签可引）。
// **文只一处，址便只有一处；若此处传数而 化之签 又书一处，二者必其一朽。**
func 启之源码(化始 string, 片 int) string {
	var b strings.Builder
	b.WriteString("； ============ 启 · 上电之数令 ============\n")
	b.WriteString("； 上电之特权在枢，计在零。\n")
	if 片 > 0 {
		fmt.Fprintf(&b, "； 先置其钟（片 %d 令），而后降入化态——钟者，夺权之由也。\n", 片)
	} else {
		b.WriteString("； 不置钟：片为零则不鸣，化 之让与不让，悉听其便。\n")
	}
	b.WriteString("处 0\n")
	if 片 > 0 {
		b.WriteString(置器基())
		fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；兑 ← 时间片之令数\n", 卦名(兑器), 片)
		fmt.Fprintf(&b, "\t存字 %s, [%s + %d]\t；钟之口 ← 兑（过亦归零）\n",
			卦名(兑器), 卦名(暂甲), 钟之口)
	}
	fmt.Fprintf(&b, "\t降化 %s\t\t；降入化态，往化之始\n\n", 化始)
	return b.String()
}

