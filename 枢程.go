	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\t；巽 ← 计\n", 卦名(巽器), 化计址)
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\t；离 ← 次（限）\n", 卦名(离器), 化次址)
	fmt.Fprintf(&b, "\t逊跃 坤, %s, %s, 累加环\t；计 犹未及其次则环\n", 卦名(巽器), 卦名(离器))
	// 息
	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；乾 ← 叩号 ＝ 息\n", 卦名(乾器), 叩号("息"))
	fmt.Fprintf(&b, "\t加数 %s, 坤, 0\t\t；兑 ← 退出之码\n", 卦名(兑器))
	b.WriteString("\t叩 0\n")
	// 数区
