// 化之极址 越界之验所用之虚址：出 化之域 之外，犹在十二位立即数之内。
//
// 何以二者皆须成立：出界则陷 越权，在立即数之内则陷的是**越权**而非 越令。
// 一验若陷错了因，它验的便不是它自以为验的那一件——而机器不报错。
const 化之极址 = 0o777

// 化之越取源 一化之程：出一字，然后**跃出其域**，遂于取指之际陷 越权。
//
// 与 化之越界源 之别：彼越的是**存取**之址（存字 越其界限），
// 此越的是**取指**之址（跃 而 计 出其界限）。
// 二者同是「越其界」，而**问法因时而异**（见 枢.go 之 是化之域 与 越界否）：
//
//	取指　变换 尚未行、虚址 尚未记，故以 是化之域(计) 问之
//	存取　变换 已行、虚址 已记，故以 越界否() 问之
//
// 而二者之界**同出一源**：皆是 化块之界限。若其一改由 化之极 出，
// 则 化之域 之大小遂成虚设——化 A 能取到化 B 的码上去，而机器一声不响。
//
// # 何以 越址 正当 化之域（＝ 界限）
//
// 其一，界限 是**界之本身**：虚址 [0, 界限) 在域内，界限 及其外皆在域外。
// 取 化之域，便是取「第一个出界之址」——恰在界外一线，不须更远。
// 若取一个界内之址，则 取指 本不越界，此验遂无所验。
//
// 其二，出界之址经 变换 **一概被引入 界基**（见 枢.go「越界者回 界基」），
// 故远近无别：虚址 0o100 与 0o777777 所取者，皆是化自己之域首。
// 化 0 之域首是 载字，一条无害之令，故 取指之检 若失守，
// 化 0 遂自取其首令而 计 日增，循环不已——**机器永不终止**，
// 跑必止 立发其难。此即此验杀「取指之检 改由 化之极 出」之状。
//
// 其三，此亦所以此验**验对了对象**：
// 若化之域首恰是一条**特权之令**（如 停机），则纵 取指之检 不检，
// 特权之检 也会把它拦下，而此验遂分不出「究竟是哪一检拦的」——
// 一验若验错了对象，它绿的时候什么也不说明（M4 之训）。
// 化之越取源 之首令是 载字，非特权之令，故唯有 取指之检 能拦之。
//
// 末了：此验与 化之越界源 之验，**界同而问法异**。同用一界（化块之界限），
// 而一问于存取之后、一问于取指之先——故须两验，缺一则其一之路无人走过。
func 化之越取源(字 rune, 越址 int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "； ---- 一化之程：出「%c」而后跃出其域 ----\n", 字)
	b.WriteString("处 0\n")
	b.WriteString("化之始：\n")
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\t；兑 ← 欲出之字「%c」\n", 卦名(兑器), 化字址, 字)
	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；乾 ← 叩号 ＝ 出\n", 卦名(乾器), 叩号("出"))
	b.WriteString("\t叩 0\t\t\t\t；求枢出之\n")
	fmt.Fprintf(&b, "\t跃 0o%03o\t\t\t\t；越其界：界限 0o%03o，此址正当其外\n", 越址, 化之域)
	fmt.Fprintf(&b, "\n处 0o%02o\n", 化计址)
	b.WriteString("\t字 0\t\t\t\t；计\n")
	b.WriteString("\t字 0\t\t\t\t；和\n")
	b.WriteString("\t字 0\t\t\t\t；次（零：纵跑进邻化之码，亦只累加一回）\n")
	fmt.Fprintf(&b, "\t字 %d\t\t\t\t；字：「%c」\n", int(字), 字)
	b.WriteString("\n")
	return b.String()
}

// 建序之机 以 诸源 为诸化之程，配 启 与 枢，造一具已装之枢机。
//
// 与 建化之机 之别：
//
//	建化之机　一化。其码与 启、枢 同装于一段，虚址即物址，无钟。
//	          （上电之化 界基 为零、界限 为 化之极，变换 恒等）
//	建序之机　诸化。其码各装于己域（界基 由号算出），虚址自 化之首 起，
//	          界限 为 化之域，片 由 启 置。
//
// 何以此处可以「启 与 化 分作两段」而 M5 不可：
// M5 之 启 须 跃 向 化之始，而 化之始 是一**标签**，故必同段；
// M6 之诸化各有一段，无标签可引，只得书其址——
// 而 化之首 是一常量（零），**址遂非手抄，而是算出来的**。
// 「分作两段则须手抄一址」之戒，于此为 化之首 所解。
func 建序之机(诸源 []string, 片 int) (*枢机, error) {
	if len(诸源) == 0 {
		return nil, fmt.Errorf("建序之机：无化可建")
	}
	k := 建枢机(址位)
	if err := k.装(启之源码(fmt.Sprintf("0o%06o", 化之首), 片) +
		枢之源码(len(诸源))); err != nil {
		return nil, err
	}
	k.化 = nil // 弃上电之化，代以诸化
	for _, 源 := range 诸源 {
		if _, err := k.增化(源, 化之域); err != nil {
			return nil, err
		}
	}
	return k, nil
}

// 建开天之机 造一具已装好启、化、枢 之枢机，其用户程即 M5 之验收程。
func 建开天之机() (*枢机, error) {
	return 建化之机(化之源码())
}
