	// 故欲存零者，须先以 兑 载之。**此坑不深，然跌进去一声不响。**
	fmt.Fprintf(b, "\t加数 %s, 坤, 0\t\t；兑 ← 0（不可径书「存字 坤」：那是空写）\n", 卦名(兑器))
