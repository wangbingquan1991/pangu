	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t；离 ← 字数（由 化之言 算出）\n", 卦名(离器), 化之字数)
	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t；乾 ← 叩号 ＝ 言\n", 卦名(乾器), 叩号("言"))
