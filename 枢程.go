// ==================================================================
// 枢程 · 枢（内核）与化（用户程）之源码
//
// ------------------------------------------------------------------
// 枢何以要用译卦器之语自陈
//
// 枢 是内核。内核若用 Go 写成，则 M5 所成者不过是个「会跑叩的模拟器」，
// 而非一台有内核的机器——叩 之服务例程是 Go 的函数，机器从头到尾没写过一行。
//
// 故枢**必须是码**：以译卦器之语写就，汇 之，装入高址，
// 由 L3 之陷阱跳进去，由它自己读写器区，再以 回 返回。
// Go 那一侧（枢.go）只做机器**本该由电路做**的三件事：特权、爻变、器区。
// 除此之外，一字节的内核逻辑也不在 Go 里。
//
// 如此，M5 之验收「用户态执行叩，内核接管并打出汉字」
// 才是真的：**那几个汉字，是码打出来的。**
//
// ------------------------------------------------------------------
// 不抄
//
// 本文件之中，凡数皆由常量算出，不由手书：
//
//	叩之表之六十四行　　由 叩之簿 生成
//	诸叩之号　　　　　　由 叩号（依名反查）得之
//	器基之二令　　　　　由 器基 算出（置器基）
//	化言之字数　　　　　由 化之言 算出
//	变之因之码　　　　　由 变因 之值算出
//
// 此非炫技。手抄之单必漏，而漏在**过滤器**上者不报错，只是不见了（M4 之训）。
// ==================================================================

// 化之址 用户程之始（M5 之单化之径）。
//
// 此径之下，化 之码与 启、枢 同装于一段，虚址即物址
// （上电之化 界基 为零、界限 为 化之极，变换 恒等）。
// M6 之诸化之径另有 化之首，二者不可混——见 建序之机 之注。
const 化之址 = 0o100

// 化之数区 用户数据之址（M5 之单化之径）。
const 化之数区 = 0o200

// 化之首 一化之**虚址**之始（M6 之诸化之径）。
//
// 何以是零而非 化之址（0o100）：诸化之域等大（化之域 六十四字），
// 若 化之始 在 0o100，则一域须容得 0o100 字以上，
// 而 界限 遂大于 化之域，邻化之域相犯矣。
//
// **码之首即域之首，界基 之外无他物**——
// 故诸化之码同形（皆自虚址零起），可以一字不改而装于任何 界基。
const 化之首 = 0

// 一化之数区之**虚址**。诸化同此。
//
// 甲之 和 与 乙之 和 在**同一个虚址**上，而落在两个物址——
// 此即界址之屏：**同址而异物**。
// 若两化各用一址，则「互不干扰」便是理所当然，也就验不出什么了。
const (
	化计址 = 0o40 // 已累加之次数
	化和址 = 0o41 // 累加之和
	化次址 = 0o42 // 欲累加之次数
	化字址 = 0o43 // 欲出之字
)

// 化之言 M5 之验收程所欲言之辞。
const 化之言 = "盘古开天！"

// 化之字数 化之言 之字数，**由 化之言 算出**。
//
// 「字之数」与「字之列」是同一件事之两面，若抄作两份，
// 改一处便错，且不报错——故字数由辞算出，列亦由辞生成。
var 化之字数 = len([]rune(化之言))

// ------------------------------------------------------------------
// 置器基
// ------------------------------------------------------------------

// 暂器 枢之暂用之器。
//
// 叩之约：叩 可坏 艮、坎、巽、震、离；兑 为元一兼返值，不可无故坏之；
// 坤 恒为零；乾 是叩号，服务例程不当动它（动了则 回 之后用户不知其号）。
// 故枢以 艮 为暂甲（器基之所在），以 震 为暂乙（言之游标）。
//
// 序 用器最多（器基、当、候选、化之数、可否，凡五），
// 而 兑 不与——**兑 是变之处理器志因之器，序 若坏之，其志遂失**。
// 五暂恰是 叩之约 所容许之全数（艮坎巽震离），故 序 不必破约而器已足。
const (
	暂甲 = 艮器 // 器基
	暂乙 = 震器 // 叩「言」之游标；序 之「当」
	暂丙 = 坎器 // 序 之「候选」
	暂丁 = 巽器 // 序 之「化之数」
	暂戊 = 离器 // 序 之「可否」
)

// 置数 出「器 ← 数」之二令：载高 置其高十二位，加数 补其差。
//
// 何不径用 加数 之一令：乙型之立即数是**十二位有符号**，界在 −2048..2047。
// 一个汉字之码位（如「盘」U+76D8 = 30424）便装它不下——
// 故凡欲置一大数者，皆须二分之。此非权宜，是令式之固然。
//
// 何以向上取整：向下取整之余必在 0..4095，而十二位有符号之上界是 2047，
// 故余过 2047 者装不下（器基 之余正是 4088）。
// 向上取整则差必在 −4096..−1，只须其不越 −2048。
//
// 装不下便 panic——**宁可炸，不可静默地算错一个数。**
// 一个算错的数不会报错，它只是把字写到别处去、或把别的字印出来。
//
// 二数皆由 数 算出，非手书——数 若移，此式自随。
func 置数(器, 数 int) string {
	高 := 数 >> 数位
	差 := 数 - (高 << 数位)
	if 差 > (1<<(数位-1))-1 {
		高++
		差 = 数 - (高 << 数位)
	}
	if 差 < -(1<<(数位-1)) || 差 > (1<<(数位-1))-1 {
		panic(fmt.Sprintf("置数：数 %d（0o%o）之差 %d 越出十二位有符号之界", 数, 数, 差))
	}
	return fmt.Sprintf("\t载高 %s, 坤, 0o%o\n\t加数 %s, %s, %d\n",
		卦名(器), 高, 卦名(器), 卦名(器), 差)
}

// 置器基 出「暂甲 ← 器基」之二令。其术见 置数。
func 置器基() string { return 置数(暂甲, 器基) }

// ------------------------------------------------------------------
// 启 · 上电之第一令
// ------------------------------------------------------------------

// 启之源码 处 0 之数令。
//
// 上电之特权在枢，计在零。若有钟，先置其片；末了一令总是 降化——
// 降入化态，径往 化始。此一令之后，枢不复出，唯待 叩 与 变 而返。
//
// 片 之缺省是零：**无钟之机不夺其化**，化 之让与不让，悉听其便。
// 故 M5 之径（片 ＝ 0）与旧日一拍不差，其诸验不必改一字。
//
// 化始 以**文**传入（或标签，或址），不传数——
// 单化之径传「化之始」（标签，与化同段），诸化之径传「0o000000」
// （化 在别一段里，无标签可引）。
// **文只一处，址便只有一处；若此处传数而 化之签 又书一处，二者必其一朽。**
func 启之源码(化始 string, 片 int) string {
	var b strings.Builder
	b.WriteString("； ============ 启 · 上电之数令 ============\n")
	b.WriteString("； 上电之特权在枢，计在零。\n")
	if 片 > 0 {
		fmt.Fprintf(&b, "； 先置其钟（片 %d 令），而后降入化态——钟者，夺权之由也。\n", 片)
	} else {
		b.WriteString("； 不置钟：片为零则不鸣，化 之让与不让，悉听其便。\n")
	}
	b.WriteString("处 0\n")
	if 片 > 0 {
		b.WriteString(置器基())
		fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；兑 ← 时间片之令数\n", 卦名(兑器), 片)
		fmt.Fprintf(&b, "\t存字 %s, [%s + %d]\t；钟之口 ← 兑（过亦归零）\n",
			卦名(兑器), 卦名(暂甲), 钟之口)
	}
	fmt.Fprintf(&b, "\t降化 %s\t\t；降入化态，往化之始\n\n", 化始)
	return b.String()
}

// ------------------------------------------------------------------
// 化 · 用户之程
// ------------------------------------------------------------------

// 化之签 用户程之始：处 化之址，标 化之始。
//
// 启 之 降化 所跃向者，即此签。故**签只可有一处，而签后之正文可换**——
// 化之程 遂得以「换一段用户程」而 启 与 枢 不动。
//
// 何以要如此：测试若要试一段用户程，最省事的写法是另写一份枢。
// 而另写一份枢，则**所验者非所跑者**——那份枢必与真枢相远，
// 且远得无声（它不报错，只是验的是另一个内核）。
// 此病在本项目中已发四次，皆以「不抄」治之，此处亦然。
func 化之签() string {
	return "； ============ 化 · 用户之程 ============\n" +
		"； 此程全在化态：触不到枢之域，触不到器区，行不得 降化 与 回。\n" +
		"； 所能者唯 叩 而已。**叩 之一字，便是它与世界之间唯一的门。**\n\n" +
		fmt.Sprintf("处 0o%06o\n", 化之址) + "化之始：\n"
}

