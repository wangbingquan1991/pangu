// 化之程 以 化源 为用户程之正文，配 启 与 枢，成一段可装之源码。
//
// 用户程可换，启 与 枢 不可换。测试呼此函以试诸用户程，
// 而所跑之枢恒是真枢——见 化之签 之注。
//
// 此是**单化之径**：化 与 启、枢 同装一段，虚址即物址，无钟（片 ＝ 0）。
// 诸化之径见 建序之机。
func 化之程(化源 string) string {
	return 启之源码("化之始", 0) + 化之签() + 化源 + 枢之源码(1)
}

// 开天之源码 启、化、枢 合成一段，付 汇 一次译之。
//
// 三者之所以要合成一段：**化之始 是用户程之签，而枢之启始须跃向它。**
// 分作两段则枢不知化之始在何所，只好手抄一址——
// 而手抄之址，改了便错，且不报错。
//
// 址之次序：0（启）→ 0o100（化之码）→ 0o200（化之数）→
// 0o777000（叩之表）→ 0o777100（变之表）→ 0o777200（枢之正文）。
// 低者是化，高者是枢；中间一大片未写之藏，是留给后之里程的。
func 开天之源码() string {
	return 化之程(化之源码())
}

// 建化之机 以 化源 为用户程，配 启 与 枢，造一具已装之枢机。
//
// 藏之址恒取 址位（十八）——枢基在 0o777000，非十八位之藏容它不下。
func 建化之机(化源 string) (*枢机, error) {
	k := 建枢机(址位)
	if err := k.装(化之程(化源)); err != nil {
		return nil, err
	}
	return k, nil
}

// 化之累加源 一化之程：累加 次 回，每累加一回则出 字 一个，然后自息。
//
// # 何以 计 与 和 皆在藏中，不在器里
//
// 叩之约：叩 可坏 艮、坎、巽、震、离。化态之器**过不得一次 叩**——
// 若以器记其数，则一叩而数亡。
//
// # 而藏正是此验所欲验者
//
// 诸化之码同形（皆自虚址零起），其 计 与 和 亦在**同一个虚址**
// （化计址、化和址）。然甲之 和 不犯乙之 和——
// 此即界址之屏：**同址而异物**。
// 若两化各用一址，则「互不干扰」便是理所当然，也就验不出什么了。
//
// 故此处**故意用同址**，专为一验。
//
// # 何以其字亦在藏中
//
// 乙型之立即数止十二位（−2048 .. 2047），而「甲」是 U+7532 ＝ 30002，
// 一条 加数 装它不下。故其字随数区同入藏，用时 载字 取之。
// 此非权宜——**凡二十四位之常量，皆当自藏取，不当自令取**。
func 化之累加源(字 rune, 次 int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "； ---- 一化之程：累加 %d 回，每回出「%c」一个 ----\n", 次, 字)
	b.WriteString("处 0\n")
	b.WriteString("化之始：\n")
	// 初：计 ← 0，和 ← 0
	fmt.Fprintf(&b, "\t加数 %s, 坤, 0\t\t；兑 ← 0\n", 卦名(兑器))
	fmt.Fprintf(&b, "\t存字 %s, [坤 + 0o%02o]\t；藏[计] ← 0\n", 卦名(兑器), 化计址)
	fmt.Fprintf(&b, "\t存字 %s, [坤 + 0o%02o]\t；藏[和] ← 0\n", 卦名(兑器), 化和址)
	b.WriteString("累加环：\n")
	// 出 字
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\t；兑 ← 欲出之字「%c」\n", 卦名(兑器), 化字址, 字)
	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；乾 ← 叩号 ＝ 出\n", 卦名(乾器), 叩号("出"))
	b.WriteString("\t叩 0\t\t\t\t；求枢出之（坏 艮坎巽震离，兑 为返值）\n")
	// 计 ← 计 ＋ 1
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\n", 卦名(兑器), 化计址)
	fmt.Fprintf(&b, "\t加数 %s, %s, 1\n", 卦名(兑器), 卦名(兑器))
	fmt.Fprintf(&b, "\t存字 %s, [坤 + 0o%02o]\t；藏[计] ← 计 ＋ 1\n", 卦名(兑器), 化计址)
	// 和 ← 和 ＋ 字
	//
	// 和 累加的是**其字**，非恒加一。故 和 是此化之指纹：
	// 甲（U+7532 ＝ 30002）三回，和 当 90006；乙（U+4E59 ＝ 20057）五回，和 当 100285。
	// 若屏破而两化同写一址，则 和 是二者之和 190291——甲不是，乙也不是。
	// 恒加一则 和 恒等于 计，纵屏破亦只错在数上，**验不到「其字」**。
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\n", 卦名(兑器), 化和址)
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\t；离 ← 其字\n", 卦名(离器), 化字址)
	fmt.Fprintf(&b, "\t加 %s, %s, %s\t\t；和 ← 和 ＋ 其字（甲型：器与器，非 加数）\n",
		卦名(兑器), 卦名(兑器), 卦名(离器))
	fmt.Fprintf(&b, "\t存字 %s, [坤 + 0o%02o]\t；藏[和] ← 和 ＋ 字\n", 卦名(兑器), 化和址)
	// 计 < 次 则环
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\t；巽 ← 计\n", 卦名(巽器), 化计址)
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\t；离 ← 次（限）\n", 卦名(离器), 化次址)
	fmt.Fprintf(&b, "\t逊跃 坤, %s, %s, 累加环\t；计 犹未及其次则环\n", 卦名(巽器), 卦名(离器))
	// 息
	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；乾 ← 叩号 ＝ 息\n", 卦名(乾器), 叩号("息"))
	fmt.Fprintf(&b, "\t加数 %s, 坤, 0\t\t；兑 ← 退出之码\n", 卦名(兑器))
	b.WriteString("\t叩 0\n")
	// 数区
	fmt.Fprintf(&b, "\n处 0o%02o\n", 化计址)
	fmt.Fprintf(&b, "\t字 0\t\t\t\t；计：已累加几回\n")
	fmt.Fprintf(&b, "\t字 0\t\t\t\t；和：累加之和\n")
	fmt.Fprintf(&b, "\t字 %d\t\t\t\t；次：欲累加几回\n", 次)
	fmt.Fprintf(&b, "\t字 %d\t\t\t\t；字：欲出之字「%c」\n", int(字), 字)
	b.WriteString("\n")
	return b.String()
}

// 化之越界源 一化之程：出一字，然后**越其界**，然后自息。
//
// 此是「一化越界，死的只是它自己」之验所欲之程（典/04 之 M6 之的）。
//
// 越界之址取 0o777：化之域 止 化之域（0o100）字，故 0o777 出界；
// 而 0o777 ＝ 511，犹在十二位立即数之内（−2048 .. 2047），一条 存字 装得下。
// 若取更大的址，则越界之令自身先越了令，所陷者遂是 越令 而非 越权——
// **验错了因，而机器不报错**。
func 化之越界源(字 rune) string {
	var b strings.Builder
	fmt.Fprintf(&b, "； ---- 一化之程：出「%c」而后越其界 ----\n", 字)
	b.WriteString("处 0\n")
	b.WriteString("化之始：\n")
	fmt.Fprintf(&b, "\t载字 %s, [坤 + 0o%02o]\t；兑 ← 欲出之字「%c」\n", 卦名(兑器), 化字址, 字)
	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；乾 ← 叩号 ＝ 出\n", 卦名(乾器), 叩号("出"))
	b.WriteString("\t叩 0\t\t\t\t；求枢出之\n")
	fmt.Fprintf(&b, "\t存字 %s, [坤 + 0o%03o]\t；越界：域止 0o%03o 字\n",
		卦名(兑器), 化之极址, 化之域)
	fmt.Fprintf(&b, "\t加数 %s, 坤, %d\t\t；乾 ← 叩号 ＝ 息（此令永不可达）\n",
		卦名(乾器), 叩号("息"))
	b.WriteString("\t叩 0\n")
	fmt.Fprintf(&b, "\n处 0o%02o\n", 化计址)
	fmt.Fprintf(&b, "\t字 0\t\t\t\t；计\n")
	fmt.Fprintf(&b, "\t字 0\t\t\t\t；和\n")
	fmt.Fprintf(&b, "\t字 0\t\t\t\t；次\n")
	fmt.Fprintf(&b, "\t字 %d\t\t\t\t；字：「%c」\n", int(字), 字)
	b.WriteString("\n")
	return b.String()
}

// 化之极址 越界之验所用之虚址：出 化之域 之外，犹在十二位立即数之内。
//
// 何以二者皆须成立：出界则陷 越权，在立即数之内则陷的是**越权**而非 越令。
// 一验若陷错了因，它验的便不是它自以为验的那一件——而机器不报错。
const 化之极址 = 0o777

// 建序之机 以 诸源 为诸化之程，配 启 与 枢，造一具已装之枢机。
//
// 与 建化之机 之别：
//
//	建化之机　一化。其码与 启、枢 同装于一段，虚址即物址，无钟。
//	          （上电之化 界基 为零、界限 为 化之极，变换 恒等）
//	建序之机　诸化。其码各装于己域（界基 由号算出），虚址自 化之首 起，
//	          界限 为 化之域，片 由 启 置。
//
// 何以此处可以「启 与 化 分作两段」而 M5 不可：
// M5 之 启 须 跃 向 化之始，而 化之始 是一**标签**，故必同段；
// M6 之诸化各有一段，无标签可引，只得书其址——
// 而 化之首 是一常量（零），**址遂非手抄，而是算出来的**。
// 「分作两段则须手抄一址」之戒，于此为 化之首 所解。
func 建序之机(诸源 []string, 片 int) (*枢机, error) {
	if len(诸源) == 0 {
		return nil, fmt.Errorf("建序之机：无化可建")
	}
	k := 建枢机(址位)
	if err := k.装(启之源码(fmt.Sprintf("0o%06o", 化之首), 片) +
		枢之源码(len(诸源))); err != nil {
		return nil, err
	}
	k.化 = nil // 弃上电之化，代以诸化
	for _, 源 := range 诸源 {
		if _, err := k.增化(源, 化之域); err != nil {
			return nil, err
		}
	}
	return k, nil
}

// 建开天之机 造一具已装好启、化、枢 之枢机，其用户程即 M5 之验收程。
func 建开天之机() (*枢机, error) {
	return 建化之机(化之源码())
}
