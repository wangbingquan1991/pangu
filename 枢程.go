	fmt.Fprintf(&b, "壳提：字 '%c'\t\t；提示符\n", 壳之提)
	fmt.Fprintf(&b, "壳终：字 '%c'\t\t；换行\n", 壳之终)
	fmt.Fprintf(&b, "壳成：字 '%c'\t\t；成\n", 壳之成)
	fmt.Fprintf(&b, "壳否：字 '%c'\t\t；否\n", 壳之否)
