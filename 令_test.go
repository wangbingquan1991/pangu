// 八进之值 由一卦符反推其值，为 八卦符 之逆。
// 供测试自造参照，庶几不以本机之失验本机之失。
func 八进之值(r rune) int { return 7 - int(r-八卦基) }

// 定令集 已定之码及其型，供诸验参照。
//
// 凡二十八条：内务五、存取二、转移五、算爻之数八、算爻之器八。
//
// 内务五者：停机、叩、载高，益以 M5 所立之 降化 与 回。
//
// 名之辨：降化 是令（降入化态），降 是算爻之操（右移）。
// 二者同处一包而名相近，昔者尝径名其令为 降，遂与八操之 降 撞名——
// 编译乃拒。撞名尚是幸事（编译拒之）；若撞的是**义**而非名，便无人拒了。
func 定令集() map[int]令型 {
	c := make(map[int]令型, 30)
	c[停机] = 丙型
	c[叩] = 丙型
	c[载高] = 乙型
	c[降化] = 丙型
	c[回] = 丙型
	c[转化] = 甲型
	c[化息] = 丙型
	c[载字] = 乙型
	c[存字] = 乙型
	c[跃] = 丙型
	c[等跃] = 甲型
	c[异跃] = 甲型
	c[逊跃] = 甲型
	c[胜跃] = 甲型
	for o := 0; o < 8; o++ {
		c[数操(算爻之操(o))] = 乙型
		c[器操(算爻之操(o))] = 甲型
	}
	return c
}

// Test编解之回 编而后解，须还原如初。诸域之边界皆须遍历。
func Test编解之回(t *testing.T) {
	const 上限 = 1 << 12

	// 一、甲型：码六十四、器各八、偏取边界与穷举二途。
	for 码 := 0; 码 < (1 << 码位); 码++ {
		for rd := 0; rd < 8; rd++ {
			for rs1 := 0; rs1 < 8; rs1++ {
				for rs2 := 0; rs2 < 8; rs2++ {
					for _, 偏 := range []int{0, 1, 255, 256, 偏掩} {
						令 := 编甲(码, rd, rs1, rs2, 偏)
						if 令 < 0 || 令 > 字掩 {
							t.Fatalf("编甲越出字位：码 %d 偏 %d 得 %d", 码, 偏, 令)
						}
						if 得 := 取码(令); 得 != 码 {
							t.Fatalf("取码：欲 %d 得 %d", 码, 得)
						}
						if 得 := 取rd(令); 得 != rd {
							t.Fatalf("取rd：欲 %d 得 %d", rd, 得)
						}
						if 得 := 取rs1(令); 得 != rs1 {
							t.Fatalf("取rs1：欲 %d 得 %d", rs1, 得)
						}
						if 得 := 取rs2(令); 得 != rs2 {
							t.Fatalf("取rs2：欲 %d 得 %d", rs2, 得)
						}
						if 得 := 取偏(令); 得 != (偏 & 偏掩) {
							t.Fatalf("取偏：欲 %d 得 %d", 偏&偏掩, 得)
						}
					}
				}
			}
		}
	}

	// 二、甲型之偏移穷举：九位之内一一皆须还原。
	for 偏 := 0; 偏 <= 偏掩; 偏++ {
		令 := 编甲(器操(加), 1, 2, 3, 偏)
		if 得 := 取偏(令); 得 != 偏 {
			t.Fatalf("取偏穷举：欲 %d 得 %d", 偏, 得)
		}
	}

	// 三、乙型：立即数十二位，取其边界。
	for 码 := 0; 码 < (1 << 码位); 码++ {
		for rd := 0; rd < 8; rd++ {
			for rs1 := 0; rs1 < 8; rs1++ {
				for _, 数 := range []int{0, 1, 2047, 2048, 数掩} {
					令 := 编乙(码, rd, rs1, 数)
					if 令 < 0 || 令 > 字掩 {
						t.Fatalf("编乙越出字位：码 %d 数 %d 得 %d", 码, 数, 令)
					}
					if 得 := 取码(令); 得 != 码 {
						t.Fatalf("乙取码：欲 %d 得 %d", 码, 得)
					}
					if 得 := 取rd(令); 得 != rd {
						t.Fatalf("乙取rd：欲 %d 得 %d", rd, 得)
					}
					if 得 := 取rs1(令); 得 != rs1 {
						t.Fatalf("乙取rs1：欲 %d 得 %d", rs1, 得)
					}
					if 得 := 取立即数(令); 得 != (数 & 数掩) {
						t.Fatalf("取立即数：欲 %d 得 %d", 数&数掩, 得)
					}
				}
			}
		}
	}

	// 四、丙型：地址十八位。
	for 码 := 0; 码 < (1 << 码位); 码++ {
		for _, 址 := range []int{0, 1, 131071, 131072, 址掩} {
			令 := 编丙(码, 址)
			if 令 < 0 || 令 > 字掩 {
				t.Fatalf("编丙越出字位：码 %d 址 %d 得 %d", 码, 址, 令)
			}
			if 得 := 取码(令); 得 != 码 {
				t.Fatalf("丙取码：欲 %d 得 %d", 码, 得)
			}
			if 得 := 取址(令); 得 != (址 & 址掩) {
				t.Fatalf("取址：欲 %d 得 %d", 址&址掩, 得)
			}
		}
	}
	if 上限 != 数掩+1 {
		t.Fatal("测试自败：上限与数掩不合")
	}
}

// Test型之判 六十四码之型，须与 定令集 相合；未定之码回 未定型。
func Test型之判(t *testing.T) {
	定 := 定令集()
	if len(定) != 30 {
		t.Fatalf("测试自败：已定之令当为三十条，实得 %d", len(定))
	}
	for 码 := 0; 码 < (1 << 码位); 码++ {
		欲, 已定 := 定[码]
		得 := 取型(码)
		if !已定 {
			if 得 != 未定型 {
				t.Errorf("码 0o%02o 未定，然判为 %s", 码, 得.名())
			}
			continue
		}
		if 得 != 欲 {
			t.Errorf("码 0o%02o：欲 %s 得 %s", 码, 欲.名(), 得.名())
		}
	}
	// 型之名须可辨。
	for _, c := range []struct {
		型 令型
		名 string
	}{{甲型, "甲"}, {乙型, "乙"}, {丙型, "丙"}, {未定型, "未定"}} {
		if 得 := c.型.名(); 得 != c.名 {
			t.Errorf("型之名：欲 %s 得 %s", c.名, 得)
		}
	}
}

// Test令名 助记之名须与操作相合。八操之两版尤其不可混。
func Test令名(t *testing.T) {
	欲表 := map[int]string{
		停机: "停机", 叩: "叩", 载高: "载高", 降化: "降化", 回: "回",
		转化: "转化", 化息: "化息",
		载字: "载字", 存字: "存字",
		跃: "跃", 等跃: "等跃", 异跃: "异跃", 逊跃: "逊跃", 胜跃: "胜跃",
	}
	for _, o := range []算爻之操{加, 减, 交, 并, 殊, 升, 降, 较} {
		欲表[器操(o)] = o.操名()
		欲表[数操(o)] = o.操名() + "数"
	}
	for 码, 欲 := range 欲表 {
		if 得 := 令名(码); 得 != 欲 {
			t.Errorf("令名（0o%02o）：欲 %s 得 %s", 码, 欲, 得)
		}
	}
	// 未定之码回「—」。
	for 码 := 0; 码 < (1 << 码位); 码++ {
		if _, 有 := 欲表[码]; 有 {
			continue
		}
		if 得 := 令名(码); 得 != "—" {
			t.Errorf("未定之码 0o%02o 竟有名「%s」", 码, 得)
		}
	}
	// 八操之名须与 算术.go 之常量同序。
	for i, 欲 := range []string{"加", "减", "交", "并", "殊", "升", "降", "较"} {
		if 得 := 算爻之操(i).操名(); 得 != 欲 {
			t.Errorf("第 %d 操之名：欲 %s 得 %s", i, 欲, 得)
		}
	}
}

// Test扩展 符号扩须把 位 位之数展为字位之补数，正负皆然。
func Test扩展(t *testing.T) {
	// 参照：以 Go 之原生整数自算，庶几不为同一处之错所掩。
	// 参照式。此式必自 Bit Twiddling 之第一义写出，不可抄 符号扩 之身——
	// 抄则同错同对，测试全绿而病在（此病作者犯过，故志之）。
	欲 := func(数, 位 int) int {
		数 &= (1 << 位) - 1
		if 数&(1<<(位-1)) != 0 {
			数 -= 1 << 位
		}
		return 数
	}
	for 位 := 1; 位 <= 字位; 位++ {
		for _, 数 := range []int{0, 1, (1 << (位 - 1)) - 1, 1 << (位 - 1), (1 << 位) - 1, 字掩} {
			得, 望 := 符号扩(数, 位), 欲(数, 位)
			if 得 != 望 {
				t.Errorf("符号扩(%d, %d)：欲 %d 得 %d", 数, 位, 望, 得)
			}
			// 往返之律：截回 位 宽再扩一次，值须不变。
			if 再 := 符号扩(截字(得), 位); 再 != 得 {
				t.Errorf("符号扩(%d, %d) = %d，截字后复扩得 %d", 数, 位, 得, 再)
			}
		}
	}
	// 数端之界。负一是 -1，不是 字掩——字掩 是它在**线上**的位样。
	if 得 := 符号扩(数掩, 数位); 得 != -1 {
		t.Errorf("负一：欲 -1 得 %d", 得)
	}
	if 得 := 截字(符号扩(数掩, 数位)); 得 != 字掩 {
		t.Errorf("负一之位样：欲 %d 得 %d", 字掩, 得)
	}
	if 得 := 补之(字掩); 得 != -1 {
		t.Errorf("补之（字掩）：欲 -1 得 %d", 得)
	}
	if 得 := 补之(1 << (字位 - 1)); 得 != -(1 << (字位 - 1)) {
		t.Errorf("补之（最小负数）：欲 %d 得 %d", -(1 << (字位 - 1)), 得)
	}
	if 得 := 符号扩(1, 数位); 得 != 1 {
		t.Errorf("正一：欲 1 得 %d", 得)
	}
	if 得 := 截字(字掩 + 1); 得 != 0 {
		t.Errorf("截字：欲 0 得 %d", 得)
	}
	// 越界须警。
	for _, 位 := range []int{0, -1, 字位 + 1} {
		func() {
			defer func() {
				if recover() == nil {
					t.Errorf("符号扩之位 %d 当警而未警", 位)
				}
			}()
			符号扩(0, 位)
		}()
	}
}

// Test用符号 扩展之约：存取恒符号，加/减/较为符号，交/并/殊零扩展。
func Test用符号(t *testing.T) {
	欲符号 := map[int]bool{
		载字: true, 存字: true,
		数操(加): true, 数操(减): true, 数操(较): true,
		数操(交): false, 数操(并): false, 数操(殊): false,
		数操(升): false, 数操(降): false,
		载高: false,
	}
	for 码, 欲 := range 欲符号 {
		if 得 := 用符号(码); 得 != 欲 {
			t.Errorf("用符号（0o%02o）：欲 %v 得 %v", 码, 欲, 得)
		}
	}
	// 符号扩展之三组，恰为八操之坤、艮、乾——即 加、减、较。
	符号之操 := []算爻之操{加, 减, 较}
	for _, o := range []算爻之操{加, 减, 交, 并, 殊, 升, 降, 较} {
		欲 := false
		for _, s := range 符号之操 {
			if o == s {
				欲 = true
			}
		}
		if 得 := 用符号(数操(o)); 得 != 欲 {
			t.Errorf("用符号（%s数）：欲 %v 得 %v", o.操名(), 欲, 得)
		}
	}
}

// Test字之卦 一 24 位之字恰为八经卦，须可正可逆。
func Test字之卦(t *testing.T) {
	for _, v := range []int{0, 1, 字掩, 0b101010101010101010101010, 0x4DC0, 1 << 23} {
		卦 := 字之卦(v)
		rs := []rune(卦)
		if len(rs) != 字位/器位 {
			t.Fatalf("字之卦(%d)：欲 %d 卦，实得 %d（%s）", v, 字位/器位, len(rs), 卦)
		}
		// 还原：自高至低，每卦三爻。
		得 := 0
		for _, r := range rs {
			得 = (得 << 器位) | 八进之值(r)
		}
		if 得 != (v & 字掩) {
			t.Errorf("字之卦(%d) = %s，还原得 %d", v, 卦, 得)
		}
	}
	// 八字之卦须与八位八进制相合。
	if 得, 欲 := 字之八进(0o12345670), "12345670"; 得 != 欲 {
		t.Errorf("字之八进：欲 %s 得 %s", 欲, 得)
	}
}

// Test令之辞 反汇编须含卦符、卦名、助记与诸操作数，一字不缺。
func Test令之辞(t *testing.T) {
	例 := []struct {
		令 int
		含 []string
	}{
		// 加数 艮, 坤, 10
		{编乙(数操(加), 1, 0, 10), []string{别卦符(数操(加)), 别卦名(数操(加)), "加数", "艮", "坤", "10"}},
		// 加 震, 坎, 巽, 0
		{编甲(器操(加), 4, 2, 3, 0), []string{别卦符(器操(加)), 别卦名(器操(加)), "加", "震", "坎", "巽"}},
		// 等跃 坤, 艮, 坤, +5
		{编甲(等跃, 0, 1, 0, 5), []string{别卦符(等跃), 别卦名(等跃), "等跃", "坤", "艮", "5"}},
		// 跃 3
		{编丙(跃, 3), []string{别卦符(跃), 别卦名(跃), "跃", "3"}},
		// 停机
		{编丙(停机, 0), []string{别卦符(停机), 别卦名(停机), "停机"}},
		// 负数之立即数须显为负。
		{编乙(数操(减), 1, 1, 数掩), []string{"减数", "艮", "艮", "-1"}},
	}
	for _, c := range 例 {
		辞 := 令之辞(c.令)
		for _, s := range c.含 {
			if !strings.Contains(辞, s) {
				t.Errorf("令之辞（0o%s）未含「%s」：%s", 字之八进(c.令), s, 辞)
			}
		}
	}
	// 未定之码须显其码而不冒称。
	辞 := 令之辞(编丙(0o17, 0))
	if !strings.Contains(辞, "—") || !strings.Contains(辞, "0o17") {
		t.Errorf("未定之码之辞不显其码：%s", 辞)
	}
}

// Test令之例 斐波那契之程序，反汇编须逐条可辨。
//
// 此非仅为验 令.go，亦为后之三验（太极、周期、对拍）立一段共用之机器码。
func Test令之例(t *testing.T) {
	诸令 := 斐波那契之令()
	if len(诸令) != 11 {
		t.Fatalf("斐波那契当为十一字，实得 %d", len(诸令))
	}
	欲名 := []string{"加数", "加数", "加数", "等跃", "加", "加", "加", "减数", "跃", "加", "停机"}
	for i, 令 := range 诸令 {
		if 得 := 令名(取码(令)); 得 != 欲名[i] {
			t.Errorf("第 %d 令：欲 %s 得 %s（%s）", i, 欲名[i], 得, 令之辞(令))
		}
	}
	// 逐条印出，供人检视。
	t.Logf("\n%s", 印令(诸令))
}
