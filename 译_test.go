// 验往返 验一令之往返：反汇编之规范式，须能被 汇一 原样读回。
func 验往返(t *testing.T, 令 int) {
	t.Helper()
	辞 := 令之译(令)
	得, err := 汇一(辞)
	if err != nil {
		t.Fatalf("令 0o%s（%s）反汇为「%s」，回译有误：%v", 字之八进(令), 字之卦(令), 辞, err)
	}
	if 得 != 令 {
		t.Fatalf("往返不合：\n　原令 0o%s　%s\n　其　辞 %s\n　回译得 0o%s　%s",
			字之八进(令), 字之卦(令), 辞, 字之八进(得), 字之卦(得))
	}
	// 幂等：反汇编之辞再反汇编，仍须是同一句。
	if 再 := 令之译(得); 再 != 辞 {
		t.Fatalf("反汇编不幂等：「%s」→「%s」", 辞, 再)
	}
}

// Test往返穷举 往返之验，穷举而为之。
//
// 全域凡六百八十七万余字（甲型三百一十四万、乙型二百八十八万、丙型七十八万），
// 一过须数十秒。故常日之验分作两段：
//
//	一、**结构化之扫**：每一型之每一域，皆扫其诸位（1<<k）、其界、
//	   其符之翻转，再乘诸码与诸器之全组合。凡错在域之位、域之界、
//	   域之符者，此扫必擒之。
//	二、**定种之抽样**：以固定之种随机抽二十万字，扫其漏网。
//
// 全域之验则须设环境变量「穷举」为非空方跑（./跑.sh test 不跑之），
// 改了 令之译 或 译令 之后自跑一遍，验毕录于 典/09。
//
// 之所以不径以抽样代之全域：抽样的信，是概率的信；
// 全域的信，是穷尽的信。二者不可同日而语，故二者皆留。
func Test往返穷举(t *testing.T) {
	计 := 0
	扫 := func(令 int) {
		验往返(t, 令)
		计++
	}

	// 一、结构化之扫。
	for _, 码 := range 有效之码 {
		switch 取型(码) {
		case 甲型:
			// 诸器之全组合（8×8×8），偏为零。
			for rd := 0; rd < 8; rd++ {
				for rs1 := 0; rs1 < 8; rs1++ {
					for rs2 := 0; rs2 < 8; rs2++ {
						扫(编甲(码, rd, rs1, rs2, 0))
					}
				}
			}
			// 偏之诸位与其界。偏是九位之有符号，界 −256..255。
			for _, 偏 := range 诸界(偏位, true) {
				for _, 器 := range [][3]int{{0, 0, 0}, {7, 0, 7}, {1, 2, 3}, {7, 7, 7}} {
					扫(编甲(码, 器[0], 器[1], 器[2], 偏&偏掩))
				}
			}
		case 乙型:
			// 诸器之全组合，数为零。
			for rd := 0; rd < 8; rd++ {
				for rs1 := 0; rs1 < 8; rs1++ {
					扫(编乙(码, rd, rs1, 0))
				}
			}
			// 数之诸位与其界。符号者 −2048..2047，零扩者 0..4095。
			for _, 数 := range 诸界(数位, 用符号(码)) {
				扫(编乙(码, 7, 3, 数&数掩))
				扫(编乙(码, 0, 0, 数&数掩))
			}
		case 丙型:
			// 址之诸位与其界。址是十八位之无符号，界 0..262143。
			for _, 址 := range 诸界(址位, false) {
				扫(编丙(码, 址&址掩))
			}
		}
	}
	t.Logf("结构化之扫 %d 字", 计)

	// 二、定种之抽样。种定则案定，故此验可复现。
	r := rand.New(rand.NewSource(20260901))
	for i := 0; i < 20_0000; i++ {
		码 := 有效之码[r.Intn(len(有效之码))]
		扫(造验字(码, r))
	}
	t.Logf("加抽样二十万，往返之验共 %d 字", 计)

	// 三、全域之穷举。须设「穷举」方跑。
	if os.Getenv("穷举") == "" {
		t.Logf("全域之穷举未跑（设环境变量「穷举」为非空则跑之，凡六百八十七万字）")
		return
	}
	for _, 码 := range 有效之码 {
		switch 取型(码) {
		case 甲型:
			for rd := 0; rd < 8; rd++ {
				for rs1 := 0; rs1 < 8; rs1++ {
					for rs2 := 0; rs2 < 8; rs2++ {
						for 偏 := 0; 偏 <= 偏掩; 偏++ {
							扫(编甲(码, rd, rs1, rs2, 偏))
						}
					}
				}
			}
		case 乙型:
			for rd := 0; rd < 8; rd++ {
				for rs1 := 0; rs1 < 8; rs1++ {
					for 数 := 0; 数 <= 数掩; 数++ {
						扫(编乙(码, rd, rs1, 数))
					}
				}
			}
		case 丙型:
			for 址 := 0; 址 <= 址掩; 址++ {
				扫(编丙(码, 址))
			}
		}
	}
	t.Logf("全域之穷举共 %d 字", 计)
}

// 诸界 一位域之诸要值：零、诸位（1<<k 与其负）、其满、其满减一、其界之两侧。
//
// 位 位之有符号者，符 为真。此诸值足以擒「域之位错、域之界错、域之符错」三类之病。
func 诸界(位 int, 符 bool) []int {
	诸 := []int{0, 1, -1, 2, -2}
	for k := 0; k < 位; k++ {
		诸 = append(诸, 1<<uint(k), -(1 << uint(k)), (1<<uint(k))-1, -((1 << uint(k)) - 1))
	}
	if 符 {
		低, 高 := -(1 << uint(位-1)), (1<<uint(位-1))-1
		诸 = append(诸, 低, 高, 低+1, 高-1, 低-1, 高+1)
	} else {
		满 := (1 << uint(位)) - 1
		诸 = append(诸, 满, 满-1, 满+1, 满>>1)
	}
	return 诸
}

// 造验字 随机造一有待往返之验之字。
func 造验字(码 int, r *rand.Rand) int {
	switch 取型(码) {
	case 甲型:
		return 编甲(码, r.Intn(8), r.Intn(8), r.Intn(8), r.Intn(偏掩+1))
	case 乙型:
		return 编乙(码, r.Intn(8), r.Intn(8), r.Intn(数掩+1))
	case 丙型:
		return 编丙(码, r.Intn(址掩+1))
	}
	panic(越界("造验字之码", 码, 0, 别卦数-1))
}

