// Test分行 验去注、剥签、分元。
func Test分行(t *testing.T) {
	// 原文 是去注后之整行（**含标签**）——报错之时，教人看得见整行，
	// 比只看见助记之后的那半句强。
	案 := []struct {
		源  string
		行数 int
		首  译行
	}{
		{"加 震, 坎, 巽", 1, 译行{行: 1, 原文: "加 震, 坎, 巽", 助记: "加", 诸元: []string{"震", "坎", "巽"}}},
		{"加 震, 坎, 巽 ；此是注", 1, 译行{行: 1, 原文: "加 震, 坎, 巽", 助记: "加", 诸元: []string{"震", "坎", "巽"}}},
		{"；纯注之行", 0, 译行{}},
		{"", 0, 译行{}},
		{"   ", 0, 译行{}},
		{"环：加 震, 震, 艮", 1, 译行{行: 1, 原文: "环：加 震, 震, 艮", 标签: []string{"环"}, 助记: "加", 诸元: []string{"震", "震", "艮"}}},
		{"载字 震, [艮 + 4]", 1, 译行{行: 1, 原文: "载字 震, [艮 + 4]", 助记: "载字", 诸元: []string{"震", "[艮 + 4]"}}},
		{"环：", 1, 译行{行: 1, 原文: "环：", 标签: []string{"环"}}},
	}
	for _, c := range 案 {
		诸 := 分行(c.源)
		if len(诸) != c.行数 {
			t.Errorf("分行(%q) 得 %d 行，欲 %d 行", c.源, len(诸), c.行数)
			continue
		}
		if c.行数 == 0 {
			continue
		}
		得 := 诸[0]
		if 得.行 != c.首.行 || 得.原文 != c.首.原文 || 得.助记 != c.首.助记 {
			t.Errorf("分行(%q) 得 %+v，欲 %+v", c.源, 得, c.首)
		}
		if strings.Join(得.标签, "|") != strings.Join(c.首.标签, "|") {
			t.Errorf("分行(%q) 之标签 得 %q，欲 %q", c.源, 得.标签, c.首.标签)
		}
		if strings.Join(得.诸元, "|") != strings.Join(c.首.诸元, "|") {
			t.Errorf("分行(%q) 之诸元 得 %q，欲 %q", c.源, 得.诸元, c.首.诸元)
		}
	}
	// 标签可连立数个，且半角之冒号亦纳。
	诸 := 分行("甲：乙：停机")
	if len(诸) != 1 {
		t.Fatalf("「甲：乙：停机」当得一行，得 %d 行", len(诸))
	}
	if strings.Join(诸[0].标签, "|") != "甲|乙" {
		t.Errorf("标签 得 %q，欲 [甲 乙]", 诸[0].标签)
	}
	if 诸[0].助记 != "停机" {
		t.Errorf("助记 得 %q，欲 停机", 诸[0].助记)
	}
	// 冒号之前有空白者，非标签。
	诸 = 分行("加 震：坎, 巽")
	if len(诸) != 1 || len(诸[0].标签) != 0 {
		t.Errorf("「加 震：坎, 巽」之冒号前有空白，不当为标签；得 %+v", 诸)
	}
	// 全角之逗号亦为分元之符。
	诸 = 分行("加数 艮，坤，10")
	if len(诸) != 1 || strings.Join(诸[0].诸元, "|") != "艮|坤|10" {
		t.Errorf("全角逗号未分元：%+v", 诸)
	}
}

// Test译数 验诸般数之写法。
func Test译数(t *testing.T) {
	标 := map[string]int{"环": 3, "数区": 16}
	案 := []struct {
		文 string
		欲 int
	}{
		{"0", 0}, {"123", 123}, {"-5", -5}, {"+7", 7},
		{"0x1F", 31}, {"-0x10", -16}, {"0XABC", 0xABC},
		{"0o17", 15}, {"-0o20", -16}, {"0O777", 0777},
		{"䷀", 63}, {"䷁", 0}, {"☰", 7}, {"☷", 0}, {"☵", 2},
		{"'中'", 0x4E2D}, {"'文'", 0x6587}, {"'道'", 0x9053},
		{"环", 3}, {"数区", 16},
	}
	for _, c := range 案 {
		得, err := 译数(c.文, 标)
		if err != nil {
			t.Errorf("译数(%q) 有误：%v", c.文, err)
			continue
		}
		if 得 != c.欲 {
			t.Errorf("译数(%q) = %d，欲 %d", c.文, 得, c.欲)
		}
	}
	// 不合者当有辞，不可默然回零。
	for _, 文 := range []string{"", "十二", "0xZZ", "环外", "''", "'中文'"} {
		if _, err := 译数(文, 标); err == nil {
			t.Errorf("译数(%q) 当有误而无", 文)
		}
	}
}

