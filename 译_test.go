// 译_test.go 译卦器之验。
//
// 译卦器之所验，最要紧的不是「能不能译」，而是**译出来的与反回来的
// 是不是同一条令**。反汇编若与汇编不合，则人读到的与机器执行的是两件事，
// 反汇编便成了谎言——而谎言比没有反汇编更坏，因为它教人信它。
//
// 故往返之验居首，且穷举而为之。
//
// 次者是**手编与译卦相合**：程.go 里那三段手编之码，是昔日亲手算出来的，
// 一字一位皆经三验（L1 独跑、L2 对拍、变异测试）。译卦器译出的若与之
// 逐字相同，则译卦器接过了那三验之信。这是最省事也最硬的一验。

// ------------------------------------------------------------------
// 一、名与码之双向之约
// ------------------------------------------------------------------

// 有效之码 本机实有之诸码。由 取型 定，不由手抄。
var 有效之码 = 造有效之码()

func 造有效之码() []int {
	var 诸 []int
	for 码 := 0; 码 < 别卦数; 码++ {
		if 取型(码) != 未定型 {
			诸 = append(诸, 码)
		}
	}
	return 诸
}

// Test译卦之表 助记码表 与 器号表 皆由反查而成，验其无缺无重无讹。
//
// 二表若有一处手抄，则改 令名 之时此表不随之而改，
// 于是「译得出而反不回」——往返之验未必抓得到（若两侧同抄同错）。
// 故先验表之本身是**推出来的**，不是写出来的。
func Test译卦之表(t *testing.T) {
	if 得, 欲 := len(助记码表), len(有效之码); 得 != 欲 {
		t.Errorf("助记码表 有 %d 条，欲 %d 条（实有之令数）", 得, 欲)
	}
	for _, 码 := range 有效之码 {
		名 := 令名(码)
		if 名 == "—" {
			t.Fatalf("码 0o%02o 已定其型，而 令名 回「—」；二者之约不合", 码)
		}
		得, 有 := 助记码表[名]
		if !有 {
			t.Fatalf("「%s」不在 助记码表 中", 名)
		}
		if 得 != 码 {
			t.Errorf("助记码表[「%s」] = 0o%02o，欲 0o%02o", 名, 得, 码)
		}
	}
	// 未定之码不可入表，否则「译得出而机器不识」。
	for 码 := 0; 码 < 别卦数; 码++ {
		if 取型(码) != 未定型 {
			continue
		}
		if 名 := 令名(码); 名 != "—" {
			t.Errorf("码 0o%02o 未定其型，而 令名 回「%s」", 码, 名)
		}
		if _, 有 := 助记码表[令名(码)]; 有 {
			t.Errorf("未定之码 0o%02o 竟在 助记码表 中", 码)
		}
	}
	// 器号表：卦名与卦符各八，皆须反查得原号。
	if 得, 欲 := len(器号表), 16; 得 != 欲 {
		t.Errorf("器号表 有 %d 条，欲 %d 条（八卦之名与符）", 得, 欲)
	}
	for v := 0; v < 8; v++ {
		if 得 := 器号表[卦名(v)]; 得 != v {
			t.Errorf("器号表[「%s」] = %d，欲 %d", 卦名(v), 得, v)
		}
		if 得 := 器号表[八卦符(v)]; 得 != v {
			t.Errorf("器号表[「%s」] = %d，欲 %d", 八卦符(v), 得, v)
		}
	}
	// 八卦之名互不相同——否则反查之表便有讹。
	见 := map[string]int{}
	for v := 0; v < 8; v++ {
		if 旧, 有 := 见[卦名(v)]; 有 {
			t.Errorf("卦名 %d 与 %d 同作「%s」", 旧, v, 卦名(v))
		}
		见[卦名(v)] = v
	}
	t.Logf("实有之令 %d 条：%s", len(有效之码), strings.Join(令名诸(), " "))
}

// 令名诸 诸令之名，依码之序。
func 令名诸() []string {
	诸 := make([]string, 0, len(有效之码))
	for _, 码 := range 有效之码 {
		诸 = append(诸, 令名(码))
	}
	return 诸
}

// Test译卦符 别卦之符是**文王序**，须经 文王先天 归化，与经卦之直序不同。
//
// 此一转最易忘。忘则 ䷀ 译作零（当是六十三）、䷁ 译作一（当是零），
// 恰与卦器之号相反，而卦器之号亦自 卦名 出——于是 ䷀ 与 坤 同号，
// 乱得极隐蔽。故专立一验，以 别卦符/八卦符 之逆验之。
func Test译卦符(t *testing.T) {
	for v := 0; v < 8; v++ {
		符 := 八卦符(v)
		r, _ := utf8.DecodeRuneInString(符)
		得, 有 := 译卦符(r)
		if !有 {
			t.Fatalf("八卦符「%s」竟不识", 符)
		}
		if 得 != v {
			t.Errorf("译卦符(「%s」) = %d，欲 %d", 符, 得, v)
		}
	}
	for v := 0; v < 别卦数; v++ {
		符 := 别卦符(v)
		r, _ := utf8.DecodeRuneInString(符)
		得, 有 := 译卦符(r)
		if !有 {
			t.Fatalf("别卦符「%s」竟不识", 符)
		}
		if 得 != v {
			t.Errorf("译卦符(「%s」) = %d，欲 %d", 符, 得, v)
		}
	}
	// 非卦符者不可误认。
	for _, r := range []rune{'中', '文', '道', 'a', '7', '。'} {
		if _, 有 := 译卦符(r); 有 {
			t.Errorf("「%c」非卦符，而 译卦符 认之", r)
		}
	}
}

