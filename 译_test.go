// 四、手编与译卦相合
// ------------------------------------------------------------------

// Test手编与译卦相合 译卦器译出之码，须与手编之码逐字相同。
//
// 此是译卦器最硬的一验。程.go 那三段手编之码，是昔日一字一位亲手算出来的，
// 已经过 L1 独跑、L2 逐拍对拍、十三变异之验——它的可信是被证明过的。
// 译卦器若与之逐字相同，则那份可信便传了过来，不必重新证明。
//
// 昔日之手工，遂成今日之尺。
func Test手编与译卦相合(t *testing.T) {
	案 := []struct {
		名 string
		源 string
		欲 []int
	}{
		{"斐波那契", 斐波那契之译, 斐波那契之令()},
		{"累加", 累加之译(1000), 累加之令(1000)},
		{"存取", 存取之译, 存取之令()},
	}
	for _, c := range 案 {
		果 := 汇(c.源)
		if !果.成() {
			t.Errorf("%s：译卦有过：\n%s", c.名, 果.过之辞())
			continue
		}
		if len(果.诸字) != len(c.欲) {
			t.Errorf("%s：译出 %d 字，欲 %d 字", c.名, len(果.诸字), len(c.欲))
		}
		for i := range c.欲 {
			if i >= len(果.诸字) {
				break
			}
			if 果.诸字[i] != c.欲[i] {
				t.Errorf("%s：第 %d 字 译得 0o%s（%s），手编 0o%s（%s）",
					c.名, i, 字之八进(果.诸字[i]), 令之辞(果.诸字[i]),
					字之八进(c.欲[i]), 令之辞(c.欲[i]))
			}
		}
	}
}

// Test译卦之跑 译出之码，跑在 L2 上，须与手编者同果。
//
// 逐字相同已是极硬之验，此验则再加一层：译出者**真能跑**，
// 且跑到同一个地方。二者之果皆 fib(10) = 55。
func Test译卦之跑(t *testing.T) {
	源 := 斐波那契之译
	果 := 汇(源)
	if !果.成() {
		t.Fatalf("译卦有过：\n%s", 果.过之辞())
	}
	m := 建周期机(5)
	m.装载(果.诸字)
	拍, err := m.跑(1000)
	if err != nil {
		t.Fatalf("译出之码跑之有误：%v", err)
	}
	if !m.止否() {
		t.Fatal("译出之码跑而不止")
	}
	if 得, 欲 := m.器值(5), 斐波那契之数(10); 得 != 欲 {
		t.Errorf("离 = %d，欲 %d = fib(10)", 得, 欲)
	}
	t.Logf("译出之码跑 %d 拍，离 = %d", 拍, m.器值(5))

	// 全文回译：译出之码反汇编成文，再译一遍，须得同一批字。
	文 := 反汇之文(果.诸字)
	再 := 汇(文)
	if !再.成() {
		t.Fatalf("回译之文再译，有过：\n%s", 再.过之辞())
	}
	for i := range 果.诸字 {
		if 再.诸字[i] != 果.诸字[i] {
			t.Errorf("回译再译，第 %d 字 得 0o%s，欲 0o%s",
				i, 字之八进(再.诸字[i]), 字之八进(果.诸字[i]))
		}
	}
}

