// ------------------------------------------------------------------

// Test译过 译卦之过须有行号、有原文、有辞，且一处之过不碍其余之报。
//
// 「过而不止」不是客套：一行之错，不该教人改一处再跑一遍。
// 故诸过当尽报，而非遇一即返。
func Test译过(t *testing.T) {
	案 := []struct {
		源 string
		要 []string
	}{
		{"行走 震, 坎, 巽\n", []string{"未知之助记符"}},
		{"加 震, 乾狗, 巽\n", []string{"非卦器之名"}},
		{"加数 艮, 坤, 9999\n", []string{"越出"}},
		{"并数 艮, 坤, -1\n", []string{"越出"}},
		{"异跃 艮, 坤, 999\n", []string{"越出"}},
		{"跃 999999\n", []string{"越出"}},
		{"跃\n", []string{"须一址"}},
		{"加 震, 坎\n", []string{"须三或四元"}},
		{"加数 艮, 坤\n", []string{"须三元"}},
		{"停机 1, 2\n", []string{"至多一元"}},
		{"载字 震, [乾狗]\n", []string{"非卦器之名"}},
		{"处 999999\n", []string{"越出"}},
		{"处\n", []string{"须一元"}},
		{"字 不知\n", []string{"非数"}},
		{"处 1, 2\n", []string{"须一元"}},
	}
	for _, c := range 案 {
		果 := 汇(c.源)
		if 果.成() {
			t.Errorf("「%s」当有过而无", c.源)
			continue
		}
		辞 := 果.过之辞()
		for _, 要 := range c.要 {
			if !strings.Contains(辞, 要) {
				t.Errorf("「%s」之过中当含「%s」，实得：\n%s", c.源, 要, 辞)
			}
		}
		if !strings.Contains(辞, "第 1 行") {
			t.Errorf("「%s」之过中当带行号，实得：\n%s", c.源, 辞)
		}
	}

	// 过而不止：三行皆错，当报三过，且行号各别。
	果 := 汇("行走 震\n加 震, 乾狗\n停机 1, 2\n")
	if 得, 欲 := len(果.过), 3; 得 != 欲 {
		t.Errorf("三行皆错，当报三过，实报 %d 过：\n%s", 得, 果.过之辞())
	} else {
		for i, 欲行 := range []int{1, 2, 3} {
			if 果.过[i].行 != 欲行 {
				t.Errorf("第 %d 过之行号 = %d，欲 %d", i, 果.过[i].行, 欲行)
			}
		}
	}
	// 过之辞中当带原文，教人看得见错在哪一行。
	if !strings.Contains(果.过之辞(), "行走 震") {
		t.Errorf("过之辞中当带原文，实得：\n%s", 果.过之辞())
	}

	// ---- 界之缝 ----
	//
	// 十二位之数，有符号者 −2048..2047，无符号者 0..4095。
	// 二者之**缝**在 2048..4095：此段只无符号者得入，有符号者当拒。
	// 若只验 0 与 9999 两头，则「有符号之界放宽一倍」这类错漏网而过——
	// 3000 会被静默编成 −1096，跑起来才错，错而无声。
	//
	// 此段为空，变异测试（变异七）始察之。故志诸案，以塞其缝。
	界案 := []struct {
		源  string
		当过 bool // 真：当报「越出」；假：当安然而成
	}{
		{"加数 艮, 坤, 2047\n", false},  // 有符号之正极
		{"加数 艮, 坤, 2048\n", true},   // 缝之首
		{"加数 艮, 坤, 3000\n", true},   // 缝之中
		{"加数 艮, 坤, 4095\n", true},   // 缝之尾
		{"加数 艮, 坤, 4096\n", true},   // 无符号亦越
		{"加数 艮, 坤, -2048\n", false}, // 有符号之负极
		{"加数 艮, 坤, -2049\n", true},
		{"并数 艮, 坤, 2047\n", false}, // 无符号：缝之前
		{"并数 艮, 坤, 2048\n", false}, // 无符号：缝之首，当纳
		{"并数 艮, 坤, 3000\n", false}, // 无符号：缝之中，当纳
		{"并数 艮, 坤, 4095\n", false}, // 无符号之正极
		{"并数 艮, 坤, 4096\n", true},  // 越
		{"并数 艮, 坤, -1\n", true},    // 无符号不受负数
	}
	for _, c := range 界案 {
		果 := 汇(c.源)
		if c.当过 {
			if 果.成() {
				t.Errorf("「%s」当报越界之过而竟成，得 0o%s", c.源, 字之八进(果.诸字[0]))
				continue
			}
			if !strings.Contains(果.过之辞(), "越出") {
				t.Errorf("「%s」当报「越出」，实得：\n%s", c.源, 果.过之辞())
			}
			continue
		}
		if !果.成() {
			t.Errorf("「%s」当成而竟有过：\n%s", c.源, 果.过之辞())
			continue
		}
		// 成，尚须编得对：回译回去，值当还是原值。
		if 译 := 令之译(果.诸字[0]); !strings.Contains(译, 元之目(c.源)) {
			t.Errorf("「%s」编成 0o%s，反译得「%s」，数不符", c.源, 字之八进(果.诸字[0]), 译)
		}
	}
}

// 元之目 取「助记 a, b, c\n」之末一元，供 界之缝 回验其数。
func 元之目(源 string) string {
	行 := strings.TrimSuffix(源, "\n")
	if i := strings.LastIndex(行, ","); i >= 0 {
		return strings.TrimSpace(行[i+1:])
	}
	诸 := strings.Fields(行)
	return 诸[len(诸)-1]
}

