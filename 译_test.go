// Test标签 前引、后引、重名、未定义、以数为名。
func Test标签(t *testing.T) {
	// 后引（跳向后面）：须折算为 目标 −（本令址 + 1）。
	果 := 汇("等跃 艮, 坤, 毕\n加 震, 坎, 巽\n毕：停机\n")
	if !果.成() {
		t.Fatalf("后引译之有过：\n%s", 果.过之辞())
	}
	if 得, 欲 := 果.标签["毕"], 2; 得 != 欲 {
		t.Fatalf("标签「毕」= %d，欲 %d", 得, 欲)
	}
	// 等跃 在址 0，执行之时 计 已为 1，故 偏 = 2 − 1 = 1。
	if 得, 欲 := 符号扩(取偏(果.诸字[0]), 偏位), 1; 得 != 欲 {
		t.Errorf("后引之偏 = %d，欲 %d", 得, 欲)
	}

	// 前引（跳回前面）：偏为负。
	果 = 汇("环：加 震, 震, 艮\n异跃 艮, 坤, 环\n停机\n")
	if !果.成() {
		t.Fatalf("前引译之有过：\n%s", 果.过之辞())
	}
	// 异跃 在址 1，执行之时 计 已为 2，故 偏 = 0 − 2 = −2。
	if 得, 欲 := 符号扩(取偏(果.诸字[1]), 偏位), -2; 得 != 欲 {
		t.Errorf("前引之偏 = %d，欲 %d", 得, 欲)
	}

	// 丙型之 跃 是绝对址，不作折算。
	果 = 汇("跃 毕\n加 震, 坎, 巽\n毕：停机\n")
	if !果.成() {
		t.Fatalf("跃 译之有过：\n%s", 果.过之辞())
	}
	if 得, 欲 := 取址(果.诸字[0]), 2; 得 != 欲 {
		t.Errorf("跃 之址 = %d，欲 %d（绝对址，不折算）", 得, 欲)
	}

	// 标签作乙型之立即数，是绝对址。
	果 = 汇("加数 艮, 坤, 数区\n停机\n处 16\n数区：字 1\n")
	if !果.成() {
		t.Fatalf("标签作立即数译之有过：\n%s", 果.过之辞())
	}
	if 得, 欲 := 符号扩(取立即数(果.诸字[0]), 数位), 16; 得 != 欲 {
		t.Errorf("艮 = %d，欲 %d（数区 之绝对址）", 得, 欲)
	}

	// 重名、未定义、以数为名：皆当有过，且过中须带其名。
	过案 := []struct {
		源 string
		要 string
	}{
		{"环：停机\n环：停机\n", "重出"},
		{"跃 无此\n", "非数"},
		{"异跃 艮, 坤, 无此\n", "非数"},
		{"12：停机\n", "是数"},
	}
	for _, c := range 过案 {
		果 := 汇(c.源)
		if 果.成() {
			t.Errorf("「%s」当有「%s」之过而无", c.源, c.要)
			continue
		}
		if !strings.Contains(果.过之辞(), c.要) {
			t.Errorf("「%s」之过中当含「%s」，实得：\n%s", c.源, c.要, 果.过之辞())
		}
	}
}

