// Test反汇 反汇 与 反汇之文 当同一副面孔。
//
// 反汇之文 若自起一循环、另写一遍 令之译，则「规范式长什么样」便有了两处决定之地。
// 变异十一（反汇 误用 令之辞）之所以存活，正因从未有案直呼 反汇——
// 反汇之文 另走一路，反汇 遂成无人之境。故此处径验 反汇，并验二者相合。
func Test反汇(t *testing.T) {
	诸令 := 斐波那契之令()
	诸 := 反汇(诸令)
	if len(诸) != len(诸令) {
		t.Fatalf("反汇 得 %d 条，欲 %d 条", len(诸), len(诸令))
	}
	for i, 令 := range 诸令 {
		if 诸[i] != 令之译(令) {
			t.Errorf("反汇[%d] = 「%s」，欲 令之译「%s」", i, 诸[i], 令之译(令))
		}
		// 反汇 所出当**句句可回译**——此即「给人看」与「给机器读」之分野。
		// 令之辞 带卦符头，好看而不可回译；反汇 若误用 令之辞，此处立毙。
		if 得, err := 汇一(诸[i]); err != nil || 得 != 令 {
			t.Errorf("反汇[%d]「%s」不可回译：得 0o%s（误 %v），欲 0o%s",
				i, 诸[i], 字之八进(得), err, 字之八进(令))
		}
	}
	// 反汇之文 当是 反汇 逐条以换行相接，不多不少。
	欲文 := strings.Join(诸, "\n") + "\n"
	if 得 := 反汇之文(诸令); 得 != 欲文 {
		t.Errorf("反汇之文 与 反汇 不同一副面孔：\n实得 %q\n欲得 %q", 得, 欲文)
	}
	// 空者当空，不生赘行。
	if 得 := 反汇之文(nil); 得 != "" {
		t.Errorf("反汇之文(nil) = %q，欲空", 得)
	}
	if 得 := 反汇(nil); len(得) != 0 {
		t.Errorf("反汇(nil) 得 %d 条，欲 0 条", len(得))
	}
	// 整段反汇编之文，当可径付 汇 而复得原码——此即**段之往返**。
	// 字之往返 已由 往返穷举 尽验，此处验的是「段」这一层：行、空、序皆无误。
	果 := 汇(反汇之文(诸令))
	if !果.成() {
		t.Fatalf("反汇之文 回译竟有过：\n%s", 果.过之辞())
	}
	for i, 令 := range 诸令 {
		if 果.诸字[i] != 令 {
			t.Errorf("段之往返第 %d 字：得 0o%s，欲 0o%s", i, 字之八进(果.诸字[i]), 字之八进(令))
		}
	}
}

// Test反汇之译 令之译 与 令之辞 之分：一为机器读回，一为人读。
//
// 令之辞 带卦符头与卦名，读来明白，然**不可回译**（卦符头不在助记之位，
// 卦名亦不当卦器解）；令之译 唯助记与诸元，可以回译。
// 二者之别，即「给人看」与「给机器读」之别——不可混，亦不可省其一。
func Test反汇之译(t *testing.T) {
	for _, 令 := range 斐波那契之令() {
		译 := 令之译(令)
		辞 := 令之辞(令)
		if 译 == 辞 {
			t.Errorf("令 0o%s：令之译 与 令之辞 不当相同（一给机器，一给人）：%s", 字之八进(令), 译)
		}
		if !strings.Contains(辞, 译) {
			t.Errorf("令 0o%s：令之辞「%s」当含 令之译「%s」之诸元", 字之八进(令), 辞, 译)
		}
		// 令之译 可回译，且回译仍是原令——此即往返，往返穷举 已尽验之，
		// 此处只验 令之译 之形确是 汇 所认得的形。
		if 得, err := 汇一(译); err != nil || 得 != 令 {
			t.Errorf("令之译「%s」回译得 0o%s（误 %v），欲 0o%s", 译, 字之八进(得), err, 字之八进(令))
		}
	}
	t.Logf("斐波那契之译辞：\n%s", 反汇之文(斐波那契之令()))
}
