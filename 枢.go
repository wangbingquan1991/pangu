// 器写 写一器区之口。
func (k *枢机) 器写(址, 值 int) {
	switch 址 - 器基 {
	case 出之口:
		k.串口.出 = append(k.串口.出, 值&字掩)
		k.记 = append(k.记, 枢记{拍: k.拍(),
			辞: fmt.Sprintf("出 0o%08o 「%s」", 值&字掩, 字之文(值))})
	case 钟之口:
		k.钟.片, k.钟.过 = 值, 0
		k.记 = append(k.记, 枢记{拍: k.拍(),
			辞: fmt.Sprintf("置钟：片 %d 令（零则不鸣）", k.钟.片)})
	case 告之口:
		k.钟.告待 = 值 != 0
		if k.钟.告待 {
			k.记 = append(k.记, 枢记{拍: k.拍(), 辞: "举告"})
		} else {
			k.记 = append(k.记, 枢记{拍: k.拍(), 辞: "销告"})
		}
	case 化选之口:
		k.择化 = 值
	case 志之口, 入之口, 界基之口, 界限之口, 当化之口, 化可之口:
		// 此六口皆只读。写之无物受之——
		// 真机亦然（写只读口，其写弃于总线），故此处亦不当报错。
	default:
		// 未配之口：写之无物受之。留此空支，以志「器区有口而未尽配」。
	}
}

// 器读 读一器区之口。
func (k *枢机) 器读(址 int) int {
	switch 址 - 器基 {
	case 志之口:
		return 1 // 恒可出
	case 入之口:
		if len(k.串口.入) == 0 {
			return 0 // 无则阴
		}
		字 := k.串口.入[0]
		k.串口.入 = k.串口.入[1:]
		k.记 = append(k.记, 枢记{拍: k.拍(),
			辞: fmt.Sprintf("入 0o%08o 「%s」", 字, 字之文(字))})
		return 字
	case 钟之口:
		return k.钟.过
	case 告之口:
		if k.钟.告待 {
			return 1
		}
		return 0
	case 界基之口:
		return k.化[k.当].界基
	case 界限之口:
		return k.化[k.当].界限
	case 当化之口:
		return k.当
	case 化选之口:
		return k.择化
	case 化可之口:
		// 越界则阴：**不问则已，问则必有一答，答不出便答「不可」**。
		// 若越界者陷，则 序 遂须先问「有几化」——那便又要一口，
		// 而那一口之数，终将与 Go 之 len(k.化) 成为两份（M4 之训）。
		if k.择化 < 0 || k.择化 >= len(k.化) {
			return 0
		}
		if k.化[k.择化].状.可行否() {
			return 1
		}
		return 0
	}
	return 0 // 出之口 只写不读；未配之口 读之得零
}

// 字之文 一 24 位之字，作**一字之码位**观，还其为符。
//
// # 何以是码位，不是 UTF-8 三字节
//
// 典/01 云「一字三字节，正合一汉字之 UTF-8」，其言不虚，然其言未尽：
//
//	UTF-8 三字节只容得 BMP 之内（十六位），U+FFFF 以外者一字节也放不下；
//	码位则不择——极于 U+10FFFF，需二十一位，而字有二十四位，绰有余。
//
// 故以**码位为正，三字节为其用之一端**：字里存码位，出时按 UTF-8 编码成字节流
// 付与串口（那是 出之流 的事，不是 字 的事）。此亦 M4 以来一贯之实践——
// 译.go 之 `字 '道'` 取 36947 而非三字节，演示与测皆以 `rune(v)` 观之。
//
// # 何者不以符示
//
// 字非字者（是条令、是个数、是个址），以码示之，不以乱码示人。
// 码位越界（> U+10FFFF）、落在代理区（U+D800–U+DFFF，本不成字）、
// 或不可印（控制符之属），皆以 `⟨0o…⟩` 示之。
func 字之文(字 int) string {
	字 &= 字掩
	r := rune(字)
	switch {
	case 字 > unicode.MaxRune:
	case 字 >= 0o160000 && 字 <= 0o167777: // 代理区 U+D800–U+DFFF
	case !unicode.IsPrint(r):
	default:
		return string(r)
	}
	return fmt.Sprintf("⟨0o%08o⟩", 字)
}

// 出之文 串口所出之全文。
func (k *枢机) 出之文() string {
	var b strings.Builder
	for _, 字 := range k.串口.出 {
		b.WriteString(字之文(字))
	}
	return b.String()
}

