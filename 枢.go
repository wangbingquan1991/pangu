type 串口 struct {
	出 []int // 已出之诸字，先后有序
	入 []int // 待入之诸字，先入者先出
}

// ------------------------------------------------------------------
// 枢机
// ------------------------------------------------------------------

// 枢记 枢之志中一记。
type 枢记 struct {
	拍 int
	辞 string
}

// 枢机 L3 枢机。藏其 L2 之机，外加 L2 所无之三事。
type 枢机 struct {
	机  *周期机
	特权 特权     // 现处之权
	存计 int    // 爻变或叩之来处；回 之所返
	因  变因     // 末次爻变之因
	串口 串口     // 器区之实
	记  []枢记   // 枢之志
	轰否 bool   // 曾轰否（枢态之变，无可救者）
	轰由 string // 轰之由
}

// 建枢机 造一具 L3 枢机。址 为藏之地址位数。
//
// **上电之特权是枢态，不是化态。** 此非随意：启机之第一令是 降化，
// 而 降化 是特权之令，化态行之便是越权。故必自枢态起，
// 降 而后入化——此与真机之 reset 入管态同理。
// 又 太极 之中锁爻器之初态不可恃（典/02 第八戒），
// 故此处之特权亦**显式**置于枢态，不倚赖零值。
func 建枢机(址 int) *枢机 {
	return &枢机{机: 建周期机(址), 特权: 枢态}
}

// 复位 归其初态。
func (k *枢机) 复位() {
	k.机.复位()
	k.特权, k.存计, k.因 = 枢态, 0, 越权之变
	k.串口 = 串口{}
	k.记, k.轰否, k.轰由 = nil, false, ""
}

// 拍 L2 已拍之数。
func (k *枢机) 拍() int { return k.机.拍数 }

// ------------------------------------------------------------------
// 装载
// ------------------------------------------------------------------

// 装 以译卦器译 源，装其诸字于藏。
//
// 译卦器所出之 诸字 自址 0 起，未写之处为零，故内核（在 0o777000）
// 与用户程（在 0o100）可在**同一段源码**里，一次装入。
// 二者之所以要同一段：化之始 是用户程之签，而枢之启始须跃向它；
// 分作两段则枢不知化之始在何所，只好手抄一址——而手抄之址，改了便错，且不报错。
func (k *枢机) 装(源 string) error {
	果 := 汇(源)
	if !果.成() {
		var 诸 []string
		for _, e := range 果.过 {
			诸 = append(诸, e.呈())
		}
		return fmt.Errorf("装：译卦有过 %d 处：\n  %s", len(果.过), strings.Join(诸, "\n  "))
	}
	return k.机.装载(果.诸字)
}

// ------------------------------------------------------------------
// 一拍
// ------------------------------------------------------------------

// 步 拍辰一记。
//
// 其序：**先检取指，后委 L2，末检执行。**
// 此序不可颠倒，且其故各各不同，分志于下。
func (k *枢机) 步() {
	m := k.机
	if m.止否() {
		return
	}
	旧相, 旧令 := m.相, m.令
	旧特权 := k.特权
	旧器, 旧字 := m.诸器, m.诸字

	// 一、取指之检：化态 而 计 已入枢之域。
	//
	// 此检须在 步 **之前**。若待 L2 把那条令取进令器再查，
	// 化态 便已见了枢之码——纵随即陷之，码亦泄矣。
	// 真机之中此检在地址总线上，取指之先；此处亦然。
	//
	// 又：此陷不耗一拍（未呼 m.步），盖其拍未曾成。
	if 旧相 == 0 && 旧特权 == 化态 && 是枢之域(m.计) {
		k.陷(越权之变, m.计,
			fmt.Sprintf("化态取指于枢之域 0o%06o", m.计))
		return
	}

	// 二、一拍之实，尽委 L2。L3 不重算一条令。
	m.步()

	// 三、执行相之后，方有 L3 之事。取指相无事。
	//
	// 之所以能这样放手：**叩、特权之令、未定之码，在 L2 中皆不改器、不改藏、不跃。**
	// 三者之中，叩 还多置了一个 止——那是 M3 的权宜（彼时 叩 尚无陷阱，
	// 只得停机），是**留给 M5 的一笔债**，由 行叩 在接管之刹那清掉。
	// 余者（降化、回、未定之码）连 止 也不置。
	//
	// 故 L3 于其后改其计与特权，无所可撤，亦无所可撞。
	// 此非巧合，是当初留位之时便想着今日。
	if 旧相 != 1 {
		return
	}
	码 := 取码(旧令)

	// （甲）未定之码 → 越令。
	if 取型(码) == 未定型 {
		k.陷(越令之变, m.计,
			fmt.Sprintf("未定之码 0o%02o（%s）", 码, 别卦符(码)))
		return
	}

	// （乙）特权之令：化态行之则越权，枢态行之则陟降。
	if 特权之令[码] {
		if 旧特权 == 化态 {
			k.陷(越权之变, m.计,
				fmt.Sprintf("化态行特权之令「%s」", 令名(码)))
			return
		}
		k.行特权(码, 旧令)
		return
	}

	// （丙）叩：化态之唯一门。
	if 码 == 叩 {
		k.行叩(旧特权)
		return
	}

	// （丁）存取：化态触枢之域则越权，触器区则委诸器件。
	if 分类(码) == 类存取 {
		k.检存取(旧令, 旧特权, 旧器, 旧字)
	}
}

// 行特权 行 降化 与 回。调用之前已验其在枢态。
func (k *枢机) 行特权(码, 令 int) {
	m := k.机
	switch 码 {
	case 降化:
		// 降化：指定其往。特权 ← 化态，计 ← 丙型之址。
		k.特权 = 化态
		m.计 = 截址(取址(令))
		m.相, m.令 = 0, 0
		k.记 = append(k.记, 枢记{拍: k.拍(),
			辞: fmt.Sprintf("降化 → 化态，往 0o%06o", m.计)})
	case 回:
		// 回：返其来处。特权 ← 化态，计 ← 存计。
		k.特权 = 化态
		m.计 = 截址(k.存计)
		m.相, m.令 = 0, 0
		k.记 = append(k.记, 枢记{拍: k.拍(),
			辞: fmt.Sprintf("回 → 化态，返 0o%06o", m.计)})
	}
}

// 行叩 行系统调用。
//
// 四部：还债 → 校权 → 校号 → 记来处而改其计与权。此即**陷阱**之全形。
//
// 「还债」何以前列，见其下之注——**债只还了一半，等于没还**。
func (k *枢机) 行叩(旧特权 特权) {
	m := k.机
	号 := m.诸器[乾器]
	名 := 叩名(号)

	// 一、还 M3 之债。**须在分岔之前还**——此是当年写错过一次之处。
	//
	// 债者：L2 之中 叩 与 停机 同置其 止（M3 之 叩 只停机，别无他事），
	// 而 M5 之 叩 当陷阱，不当停机。债在何处欠下，便在何处还——
	// 还在此处，不在 L2，盖 L2 若改，「叩 即停机」那条旧约便无处可考。
	//
	// 何以须在分岔之前：越号者亦是一条陷阱之路（陷 越号之变），
	// 若待「号在界内」才抹其 止，则越号之叩便带着 L2 那个 止 一起陷进去——
	// 陷虽成，机已止，变之处理器遂一字不得行。
	// 它不报错，只是那一支**静静地不去**。故：债要还，便还尽。
	//
	// 轰 之一支亦先抹而后由 轰 自置其 止，故无碍。
	m.止 = false

	// 二、校权。
	if 旧特权 == 枢态 {
		// 枢态 行 叩，其存计将覆——见 轰 之注。
		k.轰(fmt.Sprintf("枢态行 叩（号 %d「%s」）：存计 将覆，故不许", 号, 名))
		return
	}
	// 三、校号。
	if 号 < 0 || 号 >= 叩号数 {
		k.陷(越号之变, m.计,
			fmt.Sprintf("叩号 %d 越出 0..%d", 号, 叩号数-1))
		return
	}
	// 四、记其来处，改其计与权。
	//
	// 计 于执行相已自增，故此刻之 计 便是**次令之址**，正合返址之义。
	k.存计, k.特权 = m.计, 枢态
	m.计, m.相, m.令 = 叩之表基+号, 0, 0
	k.记 = append(k.记, 枢记{拍: k.拍(),
		辞: fmt.Sprintf("叩 %d「%s」，返 0o%06o", 号, 名, k.存计)})
}

// 检存取 存取既成之后，检其越权、分其器区。
//
// 旧器 与 旧字 是 步 **之前**之快照，备撤其效之用：
// 越权之存取不当留痕，故须原样撤去；器区之存不当入藏，故亦须撤。
func (k *枢机) 检存取(令 int, 旧特权 特权, 旧器 [8]int, 旧字 []int) {
	m := k.机
	址 := m.址值()
	是存 := 取码(令) == 存字

	// （甲）化态 触 枢之域（含器区）→ 越权。撤其效而后陷。
	if 旧特权 == 化态 && 是枢之域(址) {
		if 是存 {
			m.诸字 = 旧字 // 撤其写入
		} else {
			m.诸器 = 旧器 // 撤其读回
		}
		动 := "读"
		if 是存 {
			动 = "写"
		}
		k.陷(越权之变, m.计,
			fmt.Sprintf("化态%s枢之域 0o%06o", 动, 址))
		return
	}

	// （乙）器区 → 委诸器件，不入藏。
	if 是器区(址) {
		if 是存 {
			m.诸字 = 旧字
			k.器写(址, 旧器[取rd(令)])
		} else if rd := 取rd(令); rd != 坤器 {
			// rd 为坤则不写——「坤恒为零」之约强于此。
			// 故「自器区读入坤器」是一句无物受之的读，器件之出遂弃。
			m.诸器[rd] = k.器读(址)
		}
	}
}

// ------------------------------------------------------------------
// 爻变与轰
// ------------------------------------------------------------------

// 陷 陷于爻变。
//
// 三事：记其来处于 存计、升其特权于 枢态、改其计于 变之表 之对应槽。
// 变之表 一槽一条 跃 令，故 计 指向槽，而槽中之 跃 自往其处理器——
// 与 叩之表 同理：**表者，码也，非数也。**
func (k *枢机) 陷(因 变因, 存计 int, 由 string) {
	m := k.机
	if k.特权 == 枢态 {
		k.轰(fmt.Sprintf("%s（枢态之变，无可救）", 由))
		return
	}
	k.存计, k.因, k.特权 = 存计, 因, 枢态
	m.计, m.相, m.令 = 变之表基+int(因), 0, 0
	k.记 = append(k.记, 枢记{拍: k.拍(),
		辞: fmt.Sprintf("变 %s：%s；存计 0o%06o", 因.名(), 由, 存计)})
}

// 轰 枢态之变，无可救者，止其机。
//
// 其故：陷 之首事是「存计 ← 来处」，而 存计 **只有一个**。
// 化态 陷来，存计 记的是化之来处；枢态 若再陷，那个来处便被覆了——
// 回 将不知返于何所。此非设计之疏，而是「一个存计只记一处」之必然。
//
// 欲救之，须有变之栈：陷 之时先压栈，回 之时再弹栈。
// 那是 M7 化（进程）之事。M5 之枢只有一个用户程，故宁可止，不可错。
//
// 「轰」者，一声而止；非崩溃，是**知止**。
func (k *枢机) 轰(由 string) {
	k.机.止 = true
	k.轰否, k.轰由 = true, 由
	k.记 = append(k.记, 枢记{拍: k.拍(), 辞: "轰：" + 由})
}

