// 化状 一化之状。M6 只有二状：可行，或已毕。
//
// 何以不立「眠」（待一事而寤）：**M6 无一事可待**。
// 外设未至，无断可候，故 眠 无源——立之则成一枚永不可达之状，
// 而诸验亦无处验它，变异之器遂杀它不死（M4 之训：瞎处须另立一验，
// 而此处连「另立」都无从立起）。M7 外设既至，自当以 叩「候」生之。
type 化状 int

const (
	化行 化状 = iota // 可行：序 可择之
	化毕           // 已毕：转化 不就，序 不复择之
)

func (s 化状) 名() string {
	switch s {
	case 化行:
		return "行"
	case 化毕:
		return "毕"
	}
	return fmt.Sprintf("化状%d", int(s))
}

// 可行否 状 为 化行 否。**化可之口 之答，即此一式。**
//
// 状 之值与「可行否」不同：状 是名，可行否 是判。
// 他日 化眠 既立，「眠」亦归不可行，而此式不改——
// 此即**由因出果，不由果抄果**（M5 之戒）。
func (s 化状) 可行否() bool { return s == 化行 }

// 变记 变之栈中一记。
//
// 记其三事，非独记其址：
//
//	返址　回 之所往
//	权　　回 之后复居何权（枢态之陷套枢态之陷，故不可一律降为化态）
//	因　　志而已，备观象与验；回 不用它
type 变记 struct {
	返址 int
	权  特权
	因  变因
}

// 化块 一化之块（PCB）。
//
// # 器与计只有一处安身
//
// 化在跑时，它的器在卦器堆里，它的计在计爻器里；
// 化不跑时，它的器与计在块里。**二者不容同时有两份**——
// 化态 一陷，诸器与计即存于此；转化 一至，即自此复。
// 故「上下文」不是一份抄本，而是一处唯一的所在。
//
// # 计 与 栈 之别：一底一深
//
// 块之 计 是**栈底**：化态之陷不压栈，只把返址写进 计——
// 一化一底，不待压而自在。栈 则记**枢态之嵌套**：
// 枢态再陷（如 序 之中 转化 不就），方压一层。
// 回 之时：栈非空则弹，栈空则归于块之 计。
//
// 如此，化之初生（未尝陷者）栈为空，回 亦知其所归——
// **栈底在块，不假压栈而有。**
type 化块 struct {
	号  int
	状  化状
	界基 int    // 物址 ＝ 界基 ＋ 虚址
	界限 int    // 虚址须小于此
	诸器 [8]int // 化态之现况
	计  int    // 化态之返址（虚址），亦栈之底
	栈  []变记   // 枢态嵌套之陷
}

// 钟 器区之钟，时间片之所在。
//
// 片 为零则不鸣——**上电之机无钟，须枢自置其片**。
// 此非缺省之便，而是志一条实情：无钟之机不夺其化，
// 化 之让与不让，悉听其便（协作式）；钟既置，方是夺权式。
type 钟 struct {
	片  int  // 时间片之拍数；零则不鸣
	过  int  // 化态已过之拍
	告待 bool // 有告待理否
}

// 鸣否 钟当鸣否。
func (c 钟) 鸣否() bool { return c.片 > 0 && c.过 >= c.片 }

