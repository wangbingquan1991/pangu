// 器口之数 已配之口之数，**由 器口之簿 数出**，不由手书。
func 器口之数() int { return len(器口之簿) }

// 化选 与 化可 何以要分两口：一择一问，是「索引寄存器 ＋ 数据寄存器」之常法。
//
// 亦可并作一口（写以择、读以问），然则「读」之一事遂有二义，
// 而反汇编者见 载字 兑, [暂甲 + 化状之口] 而不知其所问者谁。
// **口之贵在于可解，不在于少。**

// 告 之来路有二，二者皆归于 告之口：
//
//	一、钟鸣　化态 之拍满 片，则举告。此是**异步之断**，机器自为之。
//	二、举告　枢 写阳于 告之口，则告立至。此是**软断**，备他日外设之用
//	        （M7 之串口入、磁盘之毕，皆当叩此门）。
//
// 二路共一志（告待），故 陷 之时一并销之——**销其告者，陷也，非处理器也**。
// 若待处理器自销，则处理器尚未销而 回 已出，告遂复鸣，环而不止。

// 变栈之极 变之栈之深之极。
//
// 栈在 Go 之一片里，不在 藏 中——因 藏 之枢域已被 叩之表、变之表、枢文 占满，
// 而栈之深浅不可先知。此与「特权在 Go 的 if 里」同是一病，M6 亦未能免，
// 故明志之，不使后人以为机器上真有此物。
//
// 深之极取八：陷之嵌套（化态 → 叩 → 变 → 变……）实难逾四层，
// 八层是留给 M7 外设之断的余量。溢则轰——**栈溢者，无可救**，
// 盖其时连「往哪里陷」都已无处可记。
const 变栈之极 = 8

// 是枢之域 址 不在化之域（含器区）之中否。
//
// 其界由 化之极 出，不由 枢基 出——**枢之域者，非化之域也**。
// 二名虽同指一址，然「非化之域」是因，「枢基」是果；
// 由因出果，则改其一而另一自随；由果抄果，则两处皆可独改而无声。
func 是枢之域(址 int) bool { return 址 >= 化之极 && 址 <= 址掩 }

// 是器区 址 在器区之中否。
func 是器区(址 int) bool { return 址 >= 器基 && 址 < 器基+器之数 }

// ------------------------------------------------------------------
// 界址
// ------------------------------------------------------------------

// 变换 化态之虚址 → 物址。枢态 则径用物址，不变不校。
//
// 界址之式取**基址＋限长**：物址 ＝ 界基 ＋ 虚址，而虚址须小于 界限。
// 其所得有二，而其一出乎意料：
//
//	一、屏　　　两化之 界基 不同，则一化写不到另一化之域里去——
//	        　　**此即 M6 验收之「各自的内存互不干扰」**。
//	二、重定位　两化可用**同一段码**（皆自虚址 0 起）而各安一处，
//	        　　码不必改一字。M4 遗留的那笔「重定位之表」的债，于此自消。
//
// 何以取界址而不取分页：分页（虚境）于本机虽极自然——页号六位恰一卦、
// 偏移十二位恰一立即数——然它须一次引入页表、址之变换、缺页之变、写页表之令
// 四样新物。而 M6 之难本在**上下文切换与调度**，不在内存保护。
// 把两件难事塞进一个里程碑，是让它们同时变难。分页留 M7——
// 那时 籍（文件系统）要 mmap、要共享，**有真实的用处驱动它**；
// 为分页而分页，是为一个尚未出现的需求付账。
//
// # 越界者回 界基，不回其虚址
//
// 越界则回 界基（即虚址零之物理所在）为物址，非为真的要去读它——
// 只为给 L2 一个**不泄枢密**的去处：那一笔读或写随即被 撤 掉（见 检存取）。
// 若径以虚址为物址，则化态便真能读到枢之码——纵撤其值，其线已通，
// 而线通之一瞬，便是屏破之一瞬。
func (k *枢机) 变换(址 int) int {
	k.虚址 = 址
	if k.特权 == 枢态 {
		return 址 & 址掩
	}
	块 := k.化[k.当]
	if 址 < 0 || 址 >= 块.界限 {
		return 块.界基 & 址掩
	}
	return (块.界基 + 址) & 址掩
}

// 越界否 方才那一笔存取越了现化之界否。
//
// 判据取 **虚址**，不取物址——**虚址 才是化之所见**。
// 化 以为自己在写 0 处，那便是虚址 0；至于它落在物理的哪一址，化 不当知。
func (k *枢机) 越界否(权 特权) bool {
	if 权 == 枢态 {
		return false
	}
	块 := k.化[k.当]
	return k.虚址 < 0 || k.虚址 >= 块.界限
}

// 是化之域 虚址 在**现化**之域之中否。域者 [0, 界限)。
//
// 取指之检用之：彼时 变换 尚未行、虚址 尚未记，故不得不以此问之。
// 存取之检则用 越界否——**同是问界，问法因时而异**，而其界则一：
// 皆自 化块之界限 出，不自 化之极 出。
func (k *枢机) 是化之域(址 int) bool {
	块 := k.化[k.当]
	return 址 >= 0 && 址 < 块.界限
}

// ------------------------------------------------------------------
// 特权
// ------------------------------------------------------------------

// 特权 机器现处之权。两态，一爻可表。
//
// M6 之化（进程）不改此二态之数——**权只有两级，与有几化无涉**。
// 化 之别在 化块 与 边界，不在权。
type 特权 int

const (
	化态 特权 = iota // 用户态。越其界则越权，行特权之令则越权，唯 叩 是门
	枢态           // 内核态。无所不可
)

func (p 特权) 名() string {
	switch p {
	case 化态:
		return "化态"
	case 枢态:
		return "枢态"
	}
	return fmt.Sprintf("特权%d", int(p))
}

