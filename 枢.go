// 叩之簿 叩号 → 其名。空者未备。
//
// **此是唯一之真源。** 叩之表 之六十四行由它生成，
// 诸号之常量由 叩号 反查而得。若他日别处手抄一份「号 → 名」，
// 那一份必朽——此病在本项目中已发三次（器号表、助记码表、变异脚本之 PAT），
// 故此处宁可绕一道反查，不肯再立一份。
var 叩之簿 = [叩号数]string{
	0: "出", // 出一字于串口。兑 = 欲出之字
	1: "言", // 出一串。兑 = 首址，离 = 字数；返 兑 = 0
	2: "入", // 入一字。返 兑 = 所入之字，无则零
	3: "息", // 停机。兑 = 退出之码

	// 籍（M7）。四者皆以**节号**为凭，不以 节址 为凭——
	// 节址 是枢之址，若落回化态之手，化 遂持一柄枢之门的钥匙。
	// 号 则不然：号 越界者，枢 一较便知（号 < 节数）。
	// **与其验其址，不如不与之址。**
	4: "建", // 建档。兑 = 名之首址，离 = 名字数；返 兑 = 节号，重名或籍满则 −1
	5: "求", // 求档。兑 = 名之首址，离 = 名字数；返 兑 = 节号，无则 −1
	6: "写", // 写档。兑 = 节号，离 = 源址，坎 = 字数；返 兑 = 实写之字数
	7: "读", // 读档。兑 = 节号，离 = 目址，坎 = 字数；返 兑 = 实读之字数
	8: "删", // 删档。兑 = 节号；返 兑 = 零，无此档则 −1
	9: "目", // 录其名。兑 = 节号，离 = 目址；返 兑 = 名字数，无此档则 −1
}

// 叩号 依名反查其号。名不在簿中则 panic——
// 宁可炸，不可默默取一个「大概对」的号。
func 叩号(名 string) int {
	for i, n := range 叩之簿 {
		if n == 名 {
			return i
		}
	}
	panic(fmt.Sprintf("叩号：簿中无「%s」", 名))
}

// 叩名 依号查其名。未备之号回「未备」，越界者回空。
func 叩名(号 int) string {
	if 号 < 0 || 号 >= 叩号数 {
		return ""
	}
	if 名 := 叩之簿[号]; 名 != "" {
		return 名
	}
	return "未备"
}

