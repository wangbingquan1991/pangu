// 跑 拍辰直至 止，或至 上限 之数。
func (k *枢机) 跑(上限 int) (int, error) {
	for i := 0; i < 上限; i++ {
		if k.机.止否() {
			return i, nil
		}
		k.步()
	}
	if k.机.止否() {
		return 上限, nil
	}
	return 上限, fmt.Errorf("跑：%d 拍之内机器未止（计 0o%06o，特权 %s，令 0o%08o）",
		上限, k.机.计, k.特权.名(), k.机.令)
}

// 迹 一记枢机现况之辞。
func (k *枢机) 迹() string {
	块 := k.化[k.当]
	return fmt.Sprintf("%s │ 特权 %s │ 化 %d/%d（界 0o%06o＋%d）│ 存计 0o%06o │ 栈 %d │ 出 %d 字",
		k.机.迹(), k.特权.名(), k.当, len(k.化), 块.界基, 块.界限,
		k.存计(), k.栈深(), len(k.串口.出))
}

// 告至 有告待理否。
//
// 二路归一：钟鸣，或有人举告（写阳于 告之口）。
func (k *枢机) 告至() bool { return k.钟.告待 || k.钟.鸣否() }

// 志 枢之志，一记一行。
func (k *枢机) 志() []string {
	诸 := make([]string, 0, len(k.记))
	for _, r := range k.记 {
		诸 = append(诸, fmt.Sprintf("%6d  %s", r.拍, r.辞))
	}
	return 诸
}
