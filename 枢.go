// ==================================================================
// 枢 · L3 指令级模拟器：特权、爻变、叩、器区
//
// ------------------------------------------------------------------
// 三层之别
//
//	太极（L1）门级　三万余门，一拍逐门重算至定，约四毫秒。可信而慢。
//	周期（L2）周期级　不算门，只算整数，快万倍。快而不可自信。
//	枢　　（L3）指令级　不算周期，只管**机器与程序之交界**。
//
// L3 之于 L2，犹 L2 之于 L1：不自证，而由下一层证之。然其证法不同——
//
//	L2 之可信，由 L1 **逐拍对拍**证明（典/08）；
//	L3 之上再无 L4 可对其拍，故其可信由两事证明：
//
// 一、**它不碰指令语义。** 一拍之实，尽委 周期机.步。
//    L3 只在 步 之前后加几件 L2 所无之事：特权、爻变、器区、界址、化。
//    此数者 L2 中本来没有线，故非「改」而是「加」；
//    凡 L2 中已有的线，L3 一律委之，不另抄一式——
//
//	藏址　L3 用 周期机.址值 这根探针，而不自算 果；
//	界址　L3 只把 址变 一钩挂在 L2 的**地址总线**上，不自做存取。
//
//    界址所以必须挂线而不许自做：存取之址是 果 ＝ 器[rs1] ＋ 扩(立即数)，
//    那是 L2 的语义。L3 若照抄一遍，便是把一条语义抄成两份，
//    而他日改了一处，另一处不报错（M4「凡手抄之单，必漏」之又一面）。
//    挂线则只有一份：**变换在线上，语义在 L2，判界在 L3。**
//
// 二、**它自己的新逻辑，由变异测试量之。** 见 具/变异枢.sh。
//
// ------------------------------------------------------------------
// 与真实机器之别
//
// 真机的特权与陷阱在**电路**里：一位状态寄存器、几根比较线、一张向量表。
// 此处的 特权 与 变 在 Go 的 if 里。**这是模拟，不是实现**——
// M5 不造电路，只造契约。契约既定，他日若要把枢刻进门里，
// 此文件便是它的规约，而 具/变异枢.sh 便是它的验收。
// ==================================================================

// ------------------------------------------------------------------
// 藏之图
// ------------------------------------------------------------------

const (
	// 籍基 籍（文件系统）之区之始。居 枢基 之下，而仍在 化之极 之上。
	//
	// 籍 之**数据**（节表）在藏中，而 籍 之**码**在枢文之中——与 序 同理：
	// **籍 亦是码，不是 Go。** 化态 欲触 籍，唯有 叩 之一途，
	// 故一化纵算错了址，也毁不到别化之档，更毁不到籍之本身。
	//
	// 何以居 枢基 之下而不与之并列：籍与枢同是化态所不可触者，
	// 而 化之极 只有一界。**枢之域者，诸「化所不可触」之域之并也**。
	籍基 = 0o776000

	// 籍之量 籍区之字数。0o1000（五百一十二字），上接 枢基。
	//
	// 节表 只用其 0o400（二百五十六字），余者留与后之里程
	// （目录之树、块之位图，皆当居此），亦留 籍存 之暂存。
	籍之量 = 0o1000

	// 节之度 一节（一档）之字数。0o40（三十二字）：
	// 名 0o10、长 1、志 1、据 0o26。
	//
	// 何以取 0o40：三十二是二之五次方，故 **节址 ＝ 籍基 ＋（号 << 5）**，
	// 五次移位即可，不须乘法。机器无乘器（M1 之八操亦无乘），
	// 凡能以移位代乘者，皆当以移位为之——此非取巧，是机器之固然。
	节之度 = 0o40

	// 节之移 由 节号 移位得 节址 之位数。节之度 ＝ 1 << 节之移。
	//
	// 此数**由 节之度 算出则不能**（Go 之常量无对数），故立此名而验之：
	// Test籍之度与移相合 专守「1 << 节之移 ＝ 节之度」。
	// **名可手书，验不可无**——手书之数若无处验，它便是下一个人的坑。
	节之移 = 5

	// 节数 籍 之所能容之节（档）数。0o10（八）。
	节数 = 0o10

	// 节表之量 节表之字数 ＝ 节数 × 节之度（0o400 ＝ 二百五十六字）。
	节表之量 = 节数 * 节之度

	// 枢基 枢之域之始。自此以上，化态一步不许入。
	//
	// 取 0o777000 而非他数之故：藏之址十八位，其上界是 0o777777；
	// 留 0o1000（五百一十二字）与枢，恰是藏之 1/512——
	// 一个「刚好够放一张表和几段处理器」之数，不是一个圆整好看之数。
	枢基 = 0o777000

	// 化之极 化之域之上界（不含）。化态 之所能触者，0 .. 化之极-1。
	//
	// 其界由 籍基 出，不由 枢基 出——**化之极 是枢之域之始，
	// 而枢之域今有籍与枢二部**。若仍书 枢基，则 籍区 遂成化态可触之地，
	// 而一化便写得动别化之档（M5 之二戒：由因出果，不由果抄果）。
	//
	// 此是**无化之时**（或未开界址之时）之界。一旦有化，化态之界便由
	// 化块之 界限 出，不由此处出——见 越界否。
	化之极 = 籍基

	// 化之域 一化之虚址之量（字）。诸化之域等大，相衔而不相犯。
	//
	// 取 0o100（六十四字）之故：一段小程（码＋数）装得下，
	// 而 化之极 之下可容 0o7770 个化——机器之小而化之多，两不相碍。
	化之域 = 0o100

	// 叩之表基 叩之分派表。六十四槽，一槽一条 跃 令。
	叩之表基 = 枢基
	叩号数  = 64

	// 变之表基 爻变之向量表。五槽，一因一槽。
	变之表基 = 枢基 + 0o100
	变之数  = 5

	// 枢文基 枢之正文。叩之服务与变之处理器皆在于此。
	//
	// **紧接 变之表，不留无谓之隙**：旧作 枢基 ＋ 0o200，
	// 而 变之表 只占五字，其间 0o73（五十九字）遂白弃。
	// M7 之 籍 须以码为之，枢文 骤长，那五十九字便是从隙里捡回来的。
	// 址由 变之表基 与 变之数 算出，则表若长，正文自随——
	// 不须有人记得去改 0o200 这个数。
	枢文基 = 变之表基 + 变之数

	// 器基 器区之始，居藏之末。非藏，故写之无所存。
	//
	// M6 之口增于十（化选、化可），而 器之数 遂自八拓至 0o100（六十四）。
	// 何以拓这么多而不只拓二：**口之数当留余**，犹 叩之表 之留六十四槽——
	// 若每次增一口便移一次 器基，则 器基 之址遂成一串手抄之数，
	// 而 枢文基 与其之间那一段（枢之正文之长短）便日日不同。
	// 今 器基 定于 0o777700，留 0o100 口与 M7 之外设，可坐而不移。
	//
	// 而 器基 ＋ 器之数 仍恰是 址掩 ＋ 1——器区 恒抵藏之极，不余一字。
	器基  = 0o777700
	器之数 = 0o100
)

// 叩表之余 叩之表 之后尚余几字。布局一改，此数自变——**算出来的，不是抄下来的。**
const 叩表之余 = 变之表基 - 叩之表基 - 叩号数

// 器区之余 器区 与 枢文基 之间尚余几字，即枢之正文之长短。
const 器区之余 = 器基 - 枢文基

// ------------------------------------------------------------------
// 籍之形
// ------------------------------------------------------------------

// 一节之内诸域之偏移（相对 节址）。
//
// 一档之形，凡四域：
//
//	名　0o10 字（八个汉字），末以零终，故**名之极是七字**
//	长　据之字数
//	志　零则未用，非零则在用
//	据　文件之正文，0o26（二十二）字
//
// 何以名以零终而不另记其长：**名之有尽，在其字中，不在其旁。**
// 若另记名长，则名有二处可改（字与长），改其一而另一朽；
// 以零终之，则比名之时比到两零而自止，长无用矣。
const (
	节名址 = 0    // 名：0o10 字，末以零终
	节长址 = 0o10 // 长：据之字数
	节志址 = 0o11 // 志：零则未用，非零则在用
	节据址 = 0o12 // 据：文件之正文
)

// 籍之度。
const (
	节名之度 = 0o10      // 名之字数（含末零）
	名之极  = 节名之度 - 1  // 名之字数之极（七字，须留一字以终之）
	据之极  = 节之度 - 节据址 // 据之字数之极（0o26 ＝ 二十二字）
)

// 籍存 核之暂名之所在：求名 之时，先以 界基 引用户之名入此，然后与诸节比。
//
// 何以要先移进来，不径与用户之藏比：**比名之环须二游标（节名、用户名）
// 与二暂存之字（各一字），凡四器；而八器之中，坤为零、乾为叩号，
// 止余六器，犹须留一器以记余下之节数。四加一得五，六器足矣——
// 然用户名之游标每历一节便须归其原处，而归处之址已无处可记。**
// 先移入籍存（其址是常数，随时可置），则归处不必记。
//
// 若他日 籍 有目录之树，此暂存当不止一处；今只一名，故只一区。
const 籍存 = 籍基 + 节表之量

// 籍存之度 籍存 之字数：名 0o10 字（含末零），余者留。
const 籍存之度 = 节名之度 + 1

// 器区之口。M6 用其十，余五十四留 M7 之外设。
//
// 「只可读」之口，写之无物受之——不陷，不报，如写于水。
// 此非疏于检，而是**器区本无「不可写」之义**：
// 出之口 写之即出一字，本就无物可存；若强为只读之口立一陷，
// 则枢 每写一口便须先知哪几口可写——那是把一张名单抄进枢里（见 M4 之训）。
const (
	出之口 = 0 // 串口之出：写之即出一字
	志之口 = 1 // 串口之志：读之非零则可出，恒为阳
	入之口 = 2 // 串口之入：读之得一字，无则阴

	钟之口 = 3 // 钟：写之置**时间片之令数**（零则不鸣，过亦归零）；读之得已过之令
	告之口 = 4 // 告：读之得「有告待理否」（阳则一）；写阳则举告，写阴则销之

	界基之口 = 5 // 界基：读之得**现化**之界基。只可读
	界限之口 = 6 // 界限：读之得**现化**之界限。只可读
	当化之口 = 7 // 当化：读之得现化之号。只可读

	化选之口 = 8 // 化选：写之择其化（号 越界亦收，不陷）；读之得所择者之号
	化可之口 = 9 // 化可：读之得**所择之化**可行否（阳则一）。越界则阴
)

// 器口 一口之名与注。
type 器口 struct {
	口 int
	名 string
	注 string
}

