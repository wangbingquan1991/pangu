// 爻变与轰
// ------------------------------------------------------------------

// 陷 陷于爻变。
//
// 三事：安顿其来处（入枢）、升其特权于 枢态、改其计于 变之表 之对应槽。
// 变之表 一槽一条 跃 令，故 计 指向槽，而槽中之 跃 自往其处理器——
// 与 叩之表 同理：**表者，码也，非数也。**
func (k *枢机) 陷(因 变因, 返址 int, 由 string) {
	if !k.入枢(返址, 变之表基+int(因), k.特权, 因, 由) {
		return
	}
	k.记 = append(k.记, 枢记{拍: k.拍(),
		辞: fmt.Sprintf("变 %s：%s；返 0o%06o", 因.名(), 由, 返址)})
}

// 入枢 自 旧特权 升入枢态，往 去向，并安顿其来处。回「已入否」。
//
// 来处之安顿，两途，其别在**化之现况有几份**：
//
//	自化态　诸器 与 计 存入化块——**块即是底**，一化一底，不待压栈。
//	        化态之陷只会有一次（陷后便是枢态），故一处足够。
//	自枢态　压一层于变之栈——嵌套之陷，回 时层层弹出。
//
// 何以化态不压栈：化态之陷，其来处便是**化之继绪**，
// 而化之继绪只该有一处（块之计）。若亦压栈，则化之来处遂有二份，
// 而 回 之时不知该从哪一份。故：**底在块，深在栈，二者不叠。**
//
// 栈溢则轰而不入：其时连「往哪里陷」都已无处可记，不若止之。
// **止而志其由，胜于陷而失其所。**
func (k *枢机) 入枢(返址, 去向 int, 旧特权 特权, 因 变因, 由 string) bool {
	m := k.机
	块 := k.化[k.当]
	if 旧特权 != 化态 {
		if len(块.栈) >= 变栈之极 {
			k.轰(fmt.Sprintf("%s（变之栈溢：深 %d，极 %d；来处 0o%06o 无处可记）",
				由, len(块.栈), 变栈之极, 返址))
			return false
		}
		块.栈 = append(块.栈, 变记{返址: 返址, 权: 旧特权, 因: k.因})
	} else {
		块.诸器, 块.计 = m.诸器, 返址
	}
	k.因, k.特权 = 因, 枢态
	m.计, m.相, m.令 = 去向, 0, 0
	return true
}

// 轰 无可救者，止其机。
//
// M5 之 轰 有一大宗：枢态之变。其时 存计 只有一个，
// 化态 陷来，存计 记的是化之来处；枢态 若再陷，那个来处便被覆了——
// 回 将不知返于何所。故 M5 宁可止，不可错。
//
// M6 立了变之栈，那一大宗遂去。**今之 轰 只余一途：变之栈溢。**
// 栈溢者，连「往哪里陷」都已无处可记——此是真无可救，
// 非「懒得救」。余者（化态之陷、枢态之陷、枢态行叩）皆可救。
//
// 「轰」者，一声而止；非崩溃，是**知止**。
func (k *枢机) 轰(由 string) {
	k.机.止 = true
	k.轰否, k.轰由 = true, 由
	k.记 = append(k.记, 枢记{拍: k.拍(), 辞: "轰：" + 由})
}

