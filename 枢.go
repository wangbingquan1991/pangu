// 枢机 L3 枢机。藏其 L2 之机，外加 L2 所无之数事。
//
// 当 之一字最要：**它是「现化之号」，一切化态之问皆由它起**。
// 界、器、计、栈，皆 k.化[k.当] 之物。故 转化 之实，只是改这一个数
// （并随之复其器），而屏自移、栈自换、计自转——
// **一处改，诸处随；若分地而记，则必有其一朽。**
type 枢机 struct {
	机  *周期机
	特权 特权     // 现处之权
	化  []*化块  // 化之表
	当  int    // 现化之号（化 之序）
	因  变因     // 末次爻变之因
	虚址 int    // 末次经 变换 之**虚址**（址总线之探针，见 越界否）
	择化 int    // 化选之口 所择之化（化可之口 之所问者）
	钟  钟      // 器区之钟
	串口 串口     // 器区之实
	记  []枢记   // 枢之志
	轰否 bool   // 曾轰否（无可救者）
	轰由 string // 轰之由
}

// 建枢机 造一具 L3 枢机。址 为藏之地址位数。
//
// **上电之特权是枢态，不是化态。** 此非随意：启机之第一令是 降化，
// 而 降化 是特权之令，化态行之便是越权。故必自枢态起，
// 降 而后入化——此与真机之 reset 入管态同理。
// 又 太极 之中锁爻器之初态不可恃（典/02 第八戒），
// 故此处之特权亦**显式**置于枢态，不倚赖零值。
//
// 上电亦有一化（号零），其 界基 为零、界限 为 化之极——
// **此即「无界址」之状**：变换恒等，与 M5 之机一拍不差。
// 故 M5 之诸验不必改一字而自通，此非侥幸，是当初留位之时便想着今日。
func 建枢机(址 int) *枢机 {
	k := &枢机{机: 建周期机(址), 特权: 枢态}
	k.机.址变 = k.变换
	k.化 = []*化块{{号: 0, 状: 化行, 界基: 0, 界限: 化之极}}
	return k
}

// 复位 归其初态。
//
// 诸化**留其在表**（其码在藏中，未被抹），而其状、器、计、栈皆归于初——
// 此与真机之 reset 不同（真机 reset 之后须重装载），
// 此处留之，为的是「复位之后再跑一遍」之便。
func (k *枢机) 复位() {
	k.机.复位()
	k.特权, k.当, k.因, k.虚址, k.择化 = 枢态, 0, 越权之变, 0, 0
	k.钟 = 钟{}
	k.串口 = 串口{}
	k.记, k.轰否, k.轰由 = nil, false, ""
	for _, 块 := range k.化 {
		块.状, 块.计, 块.栈 = 化行, 0, nil
		块.诸器 = [8]int{}
	}
	if k.机.址变 == nil {
		k.机.址变 = k.变换
	}
}

// 存计 **现当返之处**：变之栈 之顶；栈空则 化块 所记之计。
//
// M5 之 存计 是一器，M6 之 存计 是**一道算出来的数**——
// 名虽仍旧，其义则广：旧者只记得一处，故枢态再陷便覆；
// 新者是栈之顶，**覆不了**——陷则压，回则弹。
// 名不改者，欲使读旧文者知其是同一物之长大，而非另起一物。
func (k *枢机) 存计() int {
	块 := k.化[k.当]
	if n := len(块.栈); n > 0 {
		return 块.栈[n-1].返址
	}
	return 块.计
}

// 栈深 现化之变之栈之深。观象与验之用。
func (k *枢机) 栈深() int { return len(k.化[k.当].栈) }

// 拍 L2 已拍之数。
func (k *枢机) 拍() int { return k.机.拍数 }

// ------------------------------------------------------------------
// 装载
// ------------------------------------------------------------------

// 装 以译卦器译 源，装其诸字于藏。
//
// 译卦器所出之 诸字 自址 0 起，未写之处为零，故内核（在 0o777000）
// 与用户程（在 0o100）可在**同一段源码**里，一次装入。
// 二者之所以要同一段：化之始 是用户程之签，而枢之启始须跃向它；
// 分作两段则枢不知化之始在何所，只好手抄一址——而手抄之址，改了便错，且不报错。
func (k *枢机) 装(源 string) error {
	果 := 汇(源)
	if !果.成() {
		var 诸 []string
		for _, e := range 果.过 {
			诸 = append(诸, e.呈())
		}
		return fmt.Errorf("装：译卦有过 %d 处：\n  %s", len(果.过), strings.Join(诸, "\n  "))
	}
	return k.机.装载(果.诸字)
}

// 装化 译 源 而装其诸字于 界基 起之处。**自虚址零起，界基 即其物理之根。**
//
// 与 装 之别：装 自物址 0 起（启 与 枢 用之，彼二者恒在物理之低高两端），
// 装化 自 界基 起（诸化用之）。而译卦器所出之诸字恒自址 0 起，
// 故**同一段码可装于两处而一字不改**——此即界址之赐。
//
// M4 那笔「重定位之表」的债（译卦器之遗留），于此不须还而自消：
// 重定位者，改码中之址也；界址者，挪码之根也。
// **改码则码有二份（原本与改本），挪根则码恒一份。**
//
// 界限 之检：码若越其界，则**报错而止，不许静默地写到邻化之域里去**。
// 越界之写不报错，只是邻化之某一字忽然变了——
// 而那变了的字，看起来像邻化自己算错。
func (k *枢机) 装化(源 string, 界基, 界限 int) error {
	果 := 汇(源)
	if !果.成() {
		var 诸 []string
		for _, e := range 果.过 {
			诸 = append(诸, e.呈())
		}
		return fmt.Errorf("装化：译卦有过 %d 处：\n  %s", len(果.过), strings.Join(诸, "\n  "))
	}
	if len(果.诸字) > 界限 {
		return fmt.Errorf("装化：其码 %d 字越出界限 %d 字（界基 0o%06o）",
			len(果.诸字), 界限, 界基)
	}
	for j, v := range 果.诸字 {
		址 := 界基 + j
		if 址 > 址掩 {
			return fmt.Errorf("装化：界基 0o%06o ＋ %d 字越出藏之极 0o%06o", 界基, j, 址掩)
		}
		if 是枢之域(址) {
			return fmt.Errorf("装化：化之域（界基 0o%06o，%d 字）侵了枢之域（0o%06o 起）",
				界基, len(果.诸字), 化之极)
		}
		k.机.诸字[址] = v & 字掩
	}
	return nil
}

// 增化 增一化于表：译 源 而装之，并为之立块。回其号。
//
// 界基 由**号**算出，不由调用者给：化之域 等大相衔，
// 故 号 一定则其 界基 自定，二者不容各记一份。
// 若调用者手传 界基，则「第几化」与「在何址」遂成两事，而其一必朽。
func (k *枢机) 增化(源 string, 界限 int) (int, error) {
	号 := len(k.化)
	界基 := 化之域 * (号 + 1)
	if err := k.装化(源, 界基, 界限); err != nil {
		return 0, err
	}
	k.化 = append(k.化, &化块{号: 号, 状: 化行, 界基: 界基, 界限: 界限})
	return 号, nil
}

// 化之数 化之表里现有几化。
func (k *枢机) 化之数() int { return len(k.化) }

// ------------------------------------------------------------------
// 一拍
// ------------------------------------------------------------------

// 步 拍辰一记。
//
// 其序：**先检告，次检取指，后委 L2，末检执行。**
// 此序不可颠倒，且其故各各不同，分志于下。
func (k *枢机) 步() {
	m := k.机
	if m.止否() {
		return
	}
	旧相, 旧令 := m.相, m.令
	旧特权 := k.特权
	旧器, 旧字 := m.诸器, m.诸字

	// 〇、告之检：化态 而 告已至，则陷「告」。
	//
	// 何以居首：**中断不切一条令。** 真机之中，中断是在指令之间被采样的；
	// 此处亦然——只于 取指相（旧相 ＝ 0）问之，故一令之执行不被腰斩。
	//
	// 片 之单位是「令」，不是「拍」：一条令有取指、执行两拍，
	// 而 过 只在取指相累加，故 过 即是「此化已得几令」。
	// 化 之所得者，是**几条令的工夫**，不是几个门延迟的工夫——
	// 时间片之数若系于门之快慢，则同一段码在 L1 与 L2 上便要跑出两个结果。
	//
	// 又：此陷不耗一拍，与取指之越界同理。
	//
	// **先判后加**：过 是「此化已得几令」，非「将要取第几条」。
	// 若先加后判，则 过 在**尚未执行之令**的取指相上就已递增，
	// 于是 片 ＝ 8 者只得 7 令——少一条，且不报错。
	// 先判则 令 0 .. 令 片-1 皆得执行，第 片 条方被夺。
	// 其差止一条令，而**片 之数遂名不符实**；此即「错而无声」之类。
	if 旧相 == 0 && 旧特权 == 化态 {
		if k.告至() {
			片 := k.钟.片
			由 := fmt.Sprintf("钟鸣：化 %d 之片已尽（%d 令）", k.当, 片)
			if k.钟.告待 {
				由 = fmt.Sprintf("告至：化 %d 之外，有人举告", k.当)
			}
			k.钟.过, k.钟.告待 = 0, false // **销其告者，陷也**——见 告之口 之注
			k.陷(告之变, m.计, 由)
			return
		}
		if k.钟.片 > 0 {
			k.钟.过++
		}
	}

	// 一、取指之检：化态 而 计 已越其界。
	//
	// 此检须在 步 **之前**。若待 L2 把那条令取进令器再查，
	// 化态 便已见了界外之码——纵随即陷之，码亦泄矣。
	// 真机之中此检在地址总线上，取指之先；此处亦然。
	//
	// 又：此陷不耗一拍（未呼 m.步），盖其拍未曾成。
	if 旧相 == 0 && 旧特权 == 化态 && !k.是化之域(m.计) {
		k.陷(越权之变, m.计,
			fmt.Sprintf("化态取指越其界：计 0o%06o，界限 %d 字", m.计, k.化[k.当].界限))
		return
	}

	// 二、一拍之实，尽委 L2。L3 不重算一条令。
	m.步()

	// 三、执行相之后，方有 L3 之事。取指相无事。
	//
	// 之所以能这样放手：**叩、特权之令、未定之码，在 L2 中皆不改器、不改藏、不跃。**
	// 三者之中，叩 还多置了一个 止——那是 M3 的权宜（彼时 叩 尚无陷阱，
	// 只得停机），是**留给 M5 的一笔债**，由 行叩 在接管之刹那清掉。
	// 余者（降化、回、未定之码）连 止 也不置。
	//
	// 故 L3 于其后改其计与特权，无所可撤，亦无所可撞。
	// 此非巧合，是当初留位之时便想着今日。
	if 旧相 != 1 {
		return
	}
	码 := 取码(旧令)

	// （甲）未定之码 → 越令。
	if 取型(码) == 未定型 {
		k.陷(越令之变, m.计,
			fmt.Sprintf("未定之码 0o%02o（%s）", 码, 别卦符(码)))
		return
	}

	// （乙）特权之令：化态行之则越权，枢态行之则陟降。
	if 特权之令[码] {
		if 旧特权 == 化态 {
			k.陷(越权之变, m.计,
				fmt.Sprintf("化态行特权之令「%s」", 令名(码)))
			return
		}
		k.行特权(码, 旧令)
		return
	}

	// （丙）叩：化态之唯一门。
	if 码 == 叩 {
		k.行叩(旧特权)
		return
	}

	// （丁）存取：化态越其界则越权（撤其效），触器区则委诸器件。
	if 分类(码) == 类存取 {
		k.检存取(旧令, 旧特权, 旧器, 旧字)
	}
}

// 行特权 行 降化、回、转化、化息。调用之前已验其在枢态。
func (k *枢机) 行特权(码, 令 int) {
	m := k.机
	switch 码 {
	case 降化:
		// 降化：指定其往。特权 ← 化态，计 ← 丙型之址（虚址）。
		k.特权 = 化态
		m.计 = 截址(取址(令))
		m.相, m.令 = 0, 0
		k.记 = append(k.记, 枢记{拍: k.拍(),
			辞: fmt.Sprintf("降化 → 化态，往 0o%06o（虚）", m.计)})
	case 回:
		k.行回()
	case 转化:
		k.行转化(令)
	case 化息:
		k.行化息()
	}
}

// 行回 自爻变或叩而返。
//
// 两途，其别在**栈之有无**：
//
//	栈非空　弹其一记，复其址与其权。此是枢态之嵌套（序 之中 转化 不就，
//	        遂陷 越化，处理器再试而 回——回 的是 序，不是化）。
//	栈空　　归于 化块 之 计，特权 ← 化态。此是化态之陷与叩之常途；
//	        化之初生而未尝陷者亦由此入，**块之计 便是它的栈底**。
//
// 旧日（M5）之 回 一律降为化态，盖其时 存计 只有一个，枢态之陷无从记；
// 栈既立（M6），此权宜遂去——**债在何处欠下，便在何处还**。
func (k *枢机) 行回() {
	m := k.机
	块 := k.化[k.当]
	if n := len(块.栈); n > 0 {
		记 := 块.栈[n-1]
		块.栈 = 块.栈[:n-1]
		k.特权 = 记.权
		m.计 = 截址(记.返址)
		k.记 = append(k.记, 枢记{拍: k.拍(),
			辞: fmt.Sprintf("回 → %s，弹栈（余 %d 层），返 0o%06o",
				记.权.名(), len(块.栈), m.计)})
	} else {
		k.特权 = 化态
		m.计 = 截址(块.计)
		k.记 = append(k.记, 枢记{拍: k.拍(),
			辞: fmt.Sprintf("回 → 化态，栈空而归于底 0o%06o", m.计)})
	}
	m.相, m.令 = 0, 0
}

// 行转化 转其化。化号 取自 甲型之 rs1 域。
//
// 三事：择其可行、移其当、复其器。**不复其计**——
// 计 由随后的 回 自栈（或自块）取之，转化 不预。
// 此非疏漏：转化 不知来者是化态之陷还是枢态之套，
// 而「往哪里去」正是 回 的职分。二者各司其一，不相侵。
//
// 又：**转化 不存现化之器**——那已在 陷 之时存过了（化态之陷存诸器于块）。
// 若此处再存一次，存的便是枢（的暂器）之值，化之现况遂被覆。
// 此错极易犯，而其状极静：化 跑回来时，它的器已不是它的器了。
func (k *枢机) 行转化(令 int) {
	m := k.机
	号 := m.诸器[取rs1(令)]
	if 号 < 0 || 号 >= len(k.化) {
		k.陷(越化之变, m.计,
			fmt.Sprintf("转化之号 %d 越出 0..%d（今有 %d 化）", 号, len(k.化)-1, len(k.化)))
		return
	}
	的 := k.化[号]
	if 的.状 != 化行 {
		k.陷(越化之变, m.计,
			fmt.Sprintf("化 %d 之状是「%s」，非行，转化不就", 号, 的.状.名()))
		return
	}
	旧 := k.当
	k.当 = 号
	m.诸器 = 的.诸器
	k.钟.过 = 0 // 新化得一整片，不承旧化之余
	k.记 = append(k.记, 枢记{拍: k.拍(),
		辞: fmt.Sprintf("转化 %d → %d，界 0o%06o＋%d 字",
			旧, 号, 的.界基, 的.界限)})
}

// 行化息 息其现化：状 ← 毕。
//
// 化息 之后，现化仍是它（当 不改），然它已不可行——
// 序 之 转化 不就于它，遂择其次；遍寻无可行者，机止。
// **化息 不自己转走**：谁该接着跑，是 序 的事，不是 化息 的事。
func (k *枢机) 行化息() {
	块 := k.化[k.当]
	块.状 = 化毕
	k.记 = append(k.记, 枢记{拍: k.拍(),
		辞: fmt.Sprintf("化息：化 %d 毕，不复可行", 块.号)})
}

// 行叩 行系统调用。
//
// 三部：还债 → 校号 → 记来处而入枢。此即**陷阱**之全形。
//
// 旧有四部，其二是「校权」——枢态行叩则轰（因 存计 将覆）。
// M6 栈既立，存计 不复可覆，故其部撤，**枢态亦可叩**。
// 撤之而非留之：彼权宜之由已不复存在，留着便是说谎。
func (k *枢机) 行叩(旧特权 特权) {
	m := k.机
	号 := m.诸器[乾器]
	名 := 叩名(号)

	// 一、还 M3 之债。**须在分岔之前还**——此是当年写错过一次之处。
	//
	// 债者：L2 之中 叩 与 停机 同置其 止（M3 之 叩 只停机，别无他事），
	// 而 M5 之 叩 当陷阱，不当停机。债在何处欠下，便在何处还——
	// 还在此处，不在 L2，盖 L2 若改，「叩 即停机」那条旧约便无处可考。
	//
	// 何以须在分岔之前：越号者亦是一条陷阱之路（陷 越号之变），
	// 若待「号在界内」才抹其 止，则越号之叩便带着 L2 那个 止 一起陷进去——
	// 陷虽成，机已止，变之处理器遂一字不得行。
	// 它不报错，只是那一支**静静地不去**。故：债要还，便还尽。
	//
	// 轰 之一支亦先抹而后由 轰 自置其 止，故无碍。
	m.止 = false

	// 二、校号。
	if 号 < 0 || 号 >= 叩号数 {
		k.陷(越号之变, m.计,
			fmt.Sprintf("叩号 %d 越出 0..%d", 号, 叩号数-1))
		return
	}
	// 三、记其来处，入枢。
	//
	// 计 于执行相已自增，故此刻之 计 便是**次令之址**，正合返址之义。
	由 := fmt.Sprintf("叩 %d「%s」", 号, 名)
	if !k.入枢(m.计, 叩之表基+号, 旧特权, k.因, 由) {
		return
	}
	k.记 = append(k.记, 枢记{拍: k.拍(),
		辞: fmt.Sprintf("%s，返 0o%06o（%s）", 由, k.存计(), 旧特权.名())})
}

// 检存取 存取既成之后，检其越权、分其器区。
//
// 旧器 与 旧字 是 步 **之前**之快照，备撤其效之用：
// 越权之存取不当留痕，故须原样撤去；器区之存不当入藏，故亦须撤。
func (k *枢机) 检存取(令 int, 旧特权 特权, 旧器 [8]int, 旧字 []int) {
	m := k.机
	址 := m.址值() // **物址**：已经 变换 了的
	是存 := 取码(令) == 存字

	// （甲）化态 越其界（器区恒在界外）→ 越权。撤其效而后陷。
	//
	// 判据是 虚址，不是物址：化 之所见者，虚址也。
	// 越界者，变换 已把它引去了 界基（虚址零）处，故此处**尚可撤**，
	// 而那一笔读到的字，纵是化自己的，也不留——撤者，撤其效，非撤其址。
	if k.越界否(旧特权) {
		if 是存 {
			m.诸字 = 旧字 // 撤其写入
		} else {
			m.诸器 = 旧器 // 撤其读回
		}
		动 := "读"
		if 是存 {
			动 = "写"
		}
		k.陷(越权之变, m.计,
			fmt.Sprintf("化态%s越其界：虚址 0o%06o，界限 %d 字", 动, k.虚址, k.化[k.当].界限))
		return
	}

	// （乙）器区 → 委诸器件，不入藏。
	if 是器区(址) {
		if 是存 {
			m.诸字 = 旧字
			k.器写(址, 旧器[取rd(令)])
		} else if rd := 取rd(令); rd != 坤器 {
			// rd 为坤则不写——「坤恒为零」之约强于此。
			// 故「自器区读入坤器」是一句无物受之的读，器件之出遂弃。
			m.诸器[rd] = k.器读(址)
		}
	}
}

