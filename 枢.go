// ==================================================================
// 枢 · L3 指令级模拟器：特权、爻变、叩、器区
//
// ------------------------------------------------------------------
// 三层之别
//
//	太极（L1）门级　三万余门，一拍逐门重算至定，约四毫秒。可信而慢。
//	周期（L2）周期级　不算门，只算整数，快万倍。快而不可自信。
//	枢　　（L3）指令级　不算周期，只管**机器与程序之交界**。
//
// L3 之于 L2，犹 L2 之于 L1：不自证，而由下一层证之。然其证法不同——
//
//	L2 之可信，由 L1 **逐拍对拍**证明（典/08）；
//	L3 之上再无 L4 可对其拍，故其可信由两事证明：
//
// 一、**它不碰指令语义。** 一拍之实，尽委 周期机.步。
//    L3 只在 步 之前后加三件 L2 所无之事：特权、爻变、器区。
//    此三者 L2 中本来没有线，故非「改」而是「加」；
//    凡 L2 中已有的线，L3 一律委之，不另抄一式
//    （藏址便是一例：L3 用 周期机.址值 这根探针，而不自算 果）。
//
// 二、**它自己的新逻辑，由变异测试量之。** 见 具/变异枢.sh。
//
// ------------------------------------------------------------------
// 与真实机器之别
//
// 真机的特权与陷阱在**电路**里：一位状态寄存器、几根比较线、一张向量表。
// 此处的 特权 与 变 在 Go 的 if 里。**这是模拟，不是实现**——
// M5 不造电路，只造契约。契约既定，他日若要把枢刻进门里，
// 此文件便是它的规约，而 具/变异枢.sh 便是它的验收。
// ==================================================================

// ------------------------------------------------------------------
// 藏之图
// ------------------------------------------------------------------

const (
	// 枢基 枢之域之始。自此以上，化态一步不许入。
	//
	// 取 0o777000 而非他数之故：藏之址十八位，其上界是 0o777777；
	// 留 0o1000（五百一十二字）与枢，恰是藏之 1/512——
	// 一个「刚好够放一张表和几段处理器」之数，不是一个圆整好看之数。
	枢基 = 0o777000

	// 化之极 化之域之上界（不含）。化态 之所能触者，0 .. 化之极-1。
	化之极 = 枢基

	// 叩之表基 叩之分派表。六十四槽，一槽一条 跃 令。
	叩之表基 = 枢基
	叩号数  = 64

	// 变之表基 爻变之向量表。三槽，一因一槽。
	变之表基 = 枢基 + 0o100
	变之数  = 3

	// 枢文基 枢之正文。叩之服务与变之处理器皆在于此。
	枢文基 = 枢基 + 0o200

	// 器基 器区之始，居藏之极。八口，非藏。
	器基  = 0o777770
	器之数 = 8
)

// 叩表之余 叩之表 之后尚余几字。布局一改，此数自变——**算出来的，不是抄下来的。**
const 叩表之余 = 变之表基 - 叩之表基 - 叩号数

// 器区之余 器区 与 枢文基 之间尚余几字，即枢之正文之长短。
const 器区之余 = 器基 - 枢文基

// 器区之口。器区八口，M5 只用其三，余者留待后之里程碑。
const (
	出之口 = 0 // 串口之出：写之即出一字
	志之口 = 1 // 串口之志：读之非零则可出，恒为阳
	入之口 = 2 // 串口之入：读之得一字，无则阴
)

// 是枢之域 址 不在化之域（含器区）之中否。
//
// 其界由 化之极 出，不由 枢基 出——**枢之域者，非化之域也**。
// 二名虽同指一址，然「非化之域」是因，「枢基」是果；
// 由因出果，则改其一而另一自随；由果抄果，则两处皆可独改而无声。
func 是枢之域(址 int) bool { return 址 >= 化之极 && 址 <= 址掩 }

// 是器区 址 在器区之中否。
func 是器区(址 int) bool { return 址 >= 器基 && 址 < 器基+器之数 }

// ------------------------------------------------------------------
// 特权
// ------------------------------------------------------------------

// 特权 机器现处之权。两态，一爻可表。
type 特权 int

const (
	化态 特权 = iota // 用户态。触枢之域则越权，行特权之令则越权，唯 叩 是门
	枢态           // 内核态。无所不可
)

func (p 特权) 名() string {
	switch p {
	case 化态:
		return "化态"
	case 枢态:
		return "枢态"
	}
	return fmt.Sprintf("特权%d", int(p))
}

// ------------------------------------------------------------------
// 爻变
// ------------------------------------------------------------------

// 变因 爻变之因。三槽，与 变之表 之三槽一一相合。
type 变因 int

const (
	越权之变 变因 = iota // 化态触枢之域，或行特权之令
	越令之变           // 未定之码
	越号之变           // 叩号越出六十四
)

func (c 变因) 名() string {
	switch c {
	case 越权之变:
		return "越权"
	case 越令之变:
		return "越令"
	case 越号之变:
		return "越号"
	}
	return fmt.Sprintf("变因%d", int(c))
}

// 变之因之众 诸变之因，供遍历之用。
var 变之因之众 = []变因{越权之变, 越令之变, 越号之变}

// ------------------------------------------------------------------
// 叩之簿
// ------------------------------------------------------------------

// 叩之簿 叩号 → 其名。空者未备。
//
// **此是唯一之真源。** 叩之表 之六十四行由它生成，
// 诸号之常量由 叩号 反查而得。若他日别处手抄一份「号 → 名」，
// 那一份必朽——此病在本项目中已发三次（器号表、助记码表、变异脚本之 PAT），
// 故此处宁可绕一道反查，不肯再立一份。
var 叩之簿 = [叩号数]string{
	0: "出", // 出一字于串口。兑 = 欲出之字
	1: "言", // 出一串。兑 = 首址，离 = 字数；返 兑 = 0
	2: "入", // 入一字。返 兑 = 所入之字，无则零
	3: "息", // 停机。兑 = 退出之码
}

// 叩号 依名反查其号。名不在簿中则 panic——
// 宁可炸，不可默默取一个「大概对」的号。
func 叩号(名 string) int {
	for i, n := range 叩之簿 {
		if n == 名 {
			return i
		}
	}
	panic(fmt.Sprintf("叩号：簿中无「%s」", 名))
}

// 叩名 依号查其名。未备之号回「未备」，越界者回空。
func 叩名(号 int) string {
	if 号 < 0 || 号 >= 叩号数 {
		return ""
	}
	if 名 := 叩之簿[号]; 名 != "" {
		return 名
	}
	return "未备"
}

