// ==================================================================
// 周期之验
//
// L2 之验，其法与 L1 大异，故先辨之：
//
// L1 之验，是与一个**独立算出**的参照值相对。何也？L1 是电路，
// 电路中无一句假设，故唯一可错的只是「接错了一根线」，
// 而接错线这件事，只有拿一个不知情的第三方来比才查得出。
//
// L2 则不然——L2 全身都是假设：假设数据通路是那样连的，
// 假设时序是那样走的，假设 择 三爻是那样择的。
// 故 L2 若只与参照值对，那不过是拿它自己的假设再复述一遍，
// 参照值亦是同样的假设，二者同错同对，验之何益。
//
// 故 L2 之验，当与 L1 **逐拍对拍**：同一段机器码，两机并跑，
// 每拍之后比其全态（计、令、相、止、八器、诸字），一处不合即止。
//
// 此验之价值，不在「查出了几个错」，而在它所立的那个不等式：
//
//	可信(L2) ≤ 可信(L1)，而 可信(L1) 由门级之构造担保
//
// 换言之：**L2 之可信是借来的，不是自证的。借据即对拍。**
// 慢者是尺，快者是布——布之长短，须以尺量之，不可自夸。
// ==================================================================

// 对拍上限 一段码至多跑几拍。过此则视为跑飞。
const 对拍上限 = 2000

// 对拍案 一段待对拍之机器码，及其收敛之后之验法。
//
// 址 取能容下诸令之最小者——藏之门数居全机六成，藏小则跑得快。
type 对拍案 struct {
	名 string
	址 int
	令 []int
	验 func(t *testing.T, 太 *太极, 周 *周期机)
}

// 期慌 验 函 必慌，且回其所慌之物。不慌则验败。
func 期慌(t *testing.T, 何 string, 函 func()) {
	t.Helper()
	defer func() {
		if recover() == nil {
			t.Errorf("%s：当慌而不慌", 何)
		}
	}()
	函()
}

// 双验 以同一验法，两机各验一遍。
//
// 两机之「相合」已由 对拍 任之，此所验者是「其收敛之果确是所欲」。
// 二者所问不同，不可相代：两机可以一致地错，也可以错得不同而果同。
func 双验(t *testing.T, 太 *太极, 周 *周期机, 验 func(名 string, 藏值, 器值 func(int) int)) {
	t.Helper()
	验("太极", 太.藏值, 太.器值)
	验("周期机", 周.藏值, 周.器值)
}

// 验诸器 验两机之八器皆合于 欲。
func 验诸器(t *testing.T, 名 string, 太 *太极, 周 *周期机, 欲 [8]int) {
	t.Helper()
	if 得 := 太.诸器值(); 得 != 欲 {
		t.Errorf("%s：太极之诸器 得 %v，欲 %v", 名, 得, 欲)
	}
	if 得 := 周.诸器值(); 得 != 欲 {
		t.Errorf("%s：周期机之诸器 得 %v，欲 %v", 名, 得, 欲)
	}
}

// ------------------------------------------------------------------
// 对拍
// ------------------------------------------------------------------

// 对拍 以同一段机器码，令 太（L1）与 周（L2）逐拍并行，每拍之后比其全态。
//
// 其序：装载 → 比一记（装载之后两机即当相合）→ 逐拍 → 每拍比一记 → 收敛后行 案.验。
//
// 不合之时，须打出最近数拍两机之迹与全份反汇编——
// 只说「第几拍相左」是没用的，看不出是哪根线接错了。
func 对拍(t *testing.T, 太 *太极, 周 *周期机, 案 对拍案) int {
	t.Helper()
	if len(案.令) > 太.藏.字 {
		t.Fatalf("%s：诸令 %d 字溢于藏之 %d 字", 案.名, len(案.令), 太.藏.字)
	}
	if err := 太.重置并装载(案.令); err != nil {
		t.Fatalf("%s：太极重置并装载：%v", 案.名, err)
	}
	if err := 周.重置并装载(案.令); err != nil {
		t.Fatalf("%s：周期机重置并装载：%v", 案.名, err)
	}
	if 差 := 太.态().较(周.态()); 差 != "" {
		t.Fatalf("%s：装载之后两机即异：%s", 案.名, 差)
	}

	// 留最近数拍之迹。全留则太长，不留则不合之时无从下手。
	const 留 = 5
	诸迹 := make([]string, 0, 留)
	拍 := 0
	for ; 拍 < 对拍上限; 拍++ {
		if 太.止否() {
			break
		}
		if err := 太.步(); err != nil {
			t.Fatalf("%s：第 %d 拍 太极 不调：%v", 案.名, 拍+1, err)
		}
		周.步()

		诸迹 = append(诸迹, fmt.Sprintf("  第%3d拍 │ L1 %s\n         │ L2 %s",
			拍+1, 太.迹(), 周.迹()))
		if len(诸迹) > 留 {
			诸迹 = 诸迹[1:]
		}

		if 差 := 太.态().较(周.态()); 差 != "" {
			t.Fatalf("%s：第 %d 拍之后两机相左：%s\n最近 %d 拍：\n%s\n%s",
				案.名, 拍+1, 差, len(诸迹), strings.Join(诸迹, "\n"), 印令(案.令))
		}
	}
	if !太.止否() {
		t.Fatalf("%s：%d 拍之内两机皆未止\n%s", 案.名, 对拍上限, 印令(案.令))
	}
	if 案.验 != nil {
		案.验(t, 太, 周)
	}
	return 拍
}

