// Test周期之构 验 建周期机 之界、藏之容、复位之净、装载之溢。
func Test周期之构(t *testing.T) {
	期慌(t, "建周期机(0)", func() { 建周期机(0) })
	期慌(t, "建周期机(址位+1)", func() { 建周期机(址位 + 1) })

	m := 建周期机(5)
	if 得 := m.字数; 得 != 32 {
		t.Errorf("字数：得 %d，欲 32", 得)
	}
	if 得 := m.址掩; 得 != 31 {
		t.Errorf("址掩：得 %d，欲 31", 得)
	}
	if 得 := len(m.诸字); 得 != 32 {
		t.Errorf("藏之字数：得 %d，欲 32", 得)
	}

	// 复位之净：诸器、计、令、相、止 皆归阴，藏亦清。
	m.诸字[3] = 0xFFFFFF
	m.诸器[5] = 77
	m.计, m.令, m.相, m.止 = 9, 0xABCDEF, 1, true
	m.复位()
	if m.计 != 0 || m.令 != 0 || m.相 != 0 || m.止 || m.拍数 != 0 {
		t.Errorf("复位之后未能归阴：计 %d 令 0o%s 相 %d 止 %v 拍 %d",
			m.计, 字之八进(m.令), m.相, m.止, m.拍数)
	}
	空器 := [8]int{}
	if m.诸器 != 空器 {
		t.Errorf("复位之后八器未清：%v", m.诸器)
	}
	for j, v := range m.诸字 {
		if v != 0 {
			t.Fatalf("复位之后 藏[%d] = 0o%s，当为阴", j, 字之八进(v))
		}
	}

	// 装载之溢。
	if err := m.装载(make([]int, 33)); err == nil {
		t.Error("装载三十三字于三十二字之藏，当谬而不谬")
	}
	if err := m.装载(make([]int, 32)); err != nil {
		t.Errorf("装载三十二字于三十二字之藏：%v", err)
	}

	// 观象之界。
	期慌(t, "器值(-1)", func() { m.器值(-1) })
	期慌(t, "器值(8)", func() { m.器值(8) })
	期慌(t, "藏值(-1)", func() { m.藏值(-1) })
	期慌(t, "藏值(32)", func() { m.藏值(32) })
}

// Test周期斐波那契 L2 独跑斐波那契，验其果与其拍数。
//
// 此案亦见于 太极_test.go。彼所验者是「L1 算得对不对」，
// 此所验者是「L2 算得与 L1 一样否」——拍数亦须相同，
// 盖两拍一令，拍数不同即是时序不同，虽结果偶合亦不可信。
func Test周期斐波那契(t *testing.T) {
	诸令 := 斐波那契之令()
	m := 建周期机(4)
	if err := m.重置并装载(诸令); err != nil {
		t.Fatalf("重置并装载：%v", err)
	}
	拍, err := m.跑(对拍上限)
	if err != nil {
		t.Fatalf("%v\n%s", err, 印令(诸令))
	}
	if 得, 欲 := m.器值(5), 斐波那契之数(10); 得 != 欲 {
		t.Errorf("离（fib(10)）：得 %d，欲 %d\n%s", 得, 欲, 印令(诸令))
	}
	// 一百三十二拍之数，取自 L1 之实测；此数是契约，非巧合。
	if 拍 != 132 {
		t.Errorf("所拍之数：得 %d，欲 132", 拍)
	}
	t.Logf("斐波那契：%d 拍，离 = %d\n%s", 拍, m.器值(5), 印令(诸令))
}

// Test周期之速 L2 跑 L1 跑不动之程，以明「以慢御快」之利。
//
// 一匝千次，凡六千余拍。以 L1 之速（数毫秒一拍）计之，须数十秒；
// L2 则一瞬。此即 L2 之所以必须存在——不是为了省事，
// 是为了让「跑大程序」这件事在技术上有可能。
func Test周期之速(t *testing.T) {
	const N = 1000
	诸令 := 累加之令(N)
	m := 建周期机(4)
	if err := m.重置并装载(诸令); err != nil {
		t.Fatalf("重置并装载：%v", err)
	}
	起 := time.Now()
	拍, err := m.跑(100000)
	历时 := time.Since(起)
	if err != nil {
		t.Fatalf("%v\n%s", err, 印令(诸令))
	}
	if 得, 欲 := m.器值(4), N*(N+1)/2; 得 != 欲 {
		t.Errorf("震（1+..+%d）：得 %d，欲 %d", N, 得, 欲)
	}
	if 得 := m.器值(1); 得 != 0 {
		t.Errorf("艮：得 %d，欲 0", 得)
	}
	t.Logf("累加 %d 匝：%d 拍，震 = %d，历时 %v（每拍 %v）",
		N, 拍, m.器值(4), 历时, 历时/time.Duration(max(拍, 1)))
}

