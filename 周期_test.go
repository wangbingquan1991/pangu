// Test太极与周期对拍 M3 之验收。
//
// 典/04-开天之图 为 M3 所定者：「跑通一段手写的 24 位机器码
// （如计算斐波那契），L1 与 L2 结果一致」。此验是其下半——
// 上半在 太极_test.go 之 Test太极斐波那契。
//
// 案之选，以**变异测试**为绳：每案皆须能杀掉至少一个变异体。
// 凡变异而案不红者，非变异体与之等价，即案有盲——
// 二者皆须查明并志之，不可含混放过。
//
// 十二案各攻一隅：
//
//	斐波那契  循环、丙型绝对跃、乙型算爻、条件跃
//	存取      存字、载字、载高、并数
//	存取之偏  存取之正负偏移、存字 之 rd 反作源
//	八操      甲型八操，施于小正数
//	符号      甲型八操，施于负数（降 之逻辑/算术、截顶、溢出、借位）
//	负数      乙型八操之负数立即数（用符号：加减小较符号扩，交并殊零扩）
//	四跃      四条条件跃，中与不中各验
//	负偏      后向之跃，负偏移之符号扩展
