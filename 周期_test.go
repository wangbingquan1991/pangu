// 八操之令 八种算爻之操，各来一遍。十二字。
//
// 甲型之八操只用 器操（乾上，0o7x）；乙型之八操（数操，兑上 0o6x）
// 另见于 斐波那契 与 存取 二案（加、减、并）。
//
// 收敛之后：艮 = 240、坎 = 63、巽 = 177、震 = 303、离 = 0、兑 = 1、乾 = 48。
func 八操之令() []int {
	诸 := []int{}
	诸 = append(诸, 载常(1, 0x00F0)...) // 0  艮 = 240
	诸 = append(诸, 载常(2, 0x003F)...) // 1  坎 = 63
	诸 = append(诸,
		编甲(器操(升), 4, 1, 0, 0), // 2  震 = 艮 << 1 = 480
		编甲(器操(降), 3, 1, 0, 0), // 3  巽 = 艮 >> 1 = 120
		编甲(器操(较), 5, 1, 2, 0), // 4  离 = 艮 < 坎 ? 1 : 0 = 0
		编甲(器操(较), 6, 2, 1, 0), // 5  兑 = 坎 < 艮 ? 1 : 0 = 1
		编甲(器操(交), 7, 1, 2, 0), // 6  乾 = 艮 & 坎 = 0x30
		编甲(器操(并), 4, 1, 2, 0), // 7  震 = 艮 | 坎 = 0xFF
		编甲(器操(殊), 3, 1, 2, 0), // 8  巽 = 艮 ^ 坎 = 0xCF
		编甲(器操(加), 4, 1, 2, 0), // 9  震 = 艮 + 坎 = 303
		编甲(器操(减), 3, 1, 2, 0), // 10 巽 = 艮 - 坎 = 177
		编丙(停机, 0),             // 11 停机
	)
	return 诸
}

// 四跃之令 四条条件跃，中与不中各验一遍。十九字。
//
// 其法：每跃之后跟一句「震 += 1」，中则跃过此句，不中则落而行之。
// 故 震 之终值即「不中之数」。此案七跃，其中三者不当中，故 震 当为 3。
//
// 跃之偏是相对**下一令**的：跃在址 a，执行之时 计 已为 a+1，
// 故「+1」者，跃至 a+2，即跳过紧跟的那一句。两拍一令之代价也。
func 四跃之令() []int {
	return []int{
		编乙(数操(加), 1, 0, 5), // 0  艮 = 5
		编乙(数操(加), 2, 0, 5), // 1  坎 = 5
		编乙(数操(加), 3, 0, 3), // 2  巽 = 3
		编乙(数操(加), 4, 0, 0), // 3  震 = 0
		编甲(等跃, 0, 1, 2, 1), // 4  艮 == 坎（5==5）中
		编乙(数操(加), 4, 4, 1), // 5  （不中则行）
		编甲(异跃, 0, 1, 2, 1), // 6  艮 != 坎（5!=5）不中
		编乙(数操(加), 4, 4, 1), // 7  行 → 震 = 1
		编甲(异跃, 0, 1, 3, 1), // 8  艮 != 巽（5!=3）中
		编乙(数操(加), 4, 4, 1), // 9  （不中则行）
		编甲(逊跃, 0, 3, 1, 1), // 10 巽 <  艮（3<5） 中
		编乙(数操(加), 4, 4, 1), // 11 （不中则行）
		编甲(逊跃, 0, 1, 3, 1), // 12 艮 <  巽（5<3） 不中
		编乙(数操(加), 4, 4, 1), // 13 行 → 震 = 2
		编甲(胜跃, 0, 1, 2, 1), // 14 艮 >= 坎（5>=5）中
		编乙(数操(加), 4, 4, 1), // 15 （不中则行）
		编甲(胜跃, 0, 3, 1, 1), // 16 巽 >= 艮（3>=5）不中
		编乙(数操(加), 4, 4, 1), // 17 行 → 震 = 3
		编丙(停机, 0),          // 18 停机
	}
}

// 负偏之令 后向之跃，验负偏移之符号扩展。六字。
//
// 跃在址 4，执行之时 计 = 5，欲回址 2，故偏为 -3。
// 收敛之后：艮 = 0、震 = 3（循环三匝）。
func 负偏之令() []int {
	return []int{
		编乙(数操(加), 1, 0, 3),      // 0  艮 = 3
		编乙(数操(加), 4, 0, 0),      // 1  震 = 0
		编乙(数操(加), 4, 4, 1),      // 2  震 += 1
		编乙(数操(减), 1, 1, 1),      // 3  艮 -= 1
		编甲(异跃, 0, 1, 0, 偏码(-3)), // 4  艮 != 0 → 5-3 = 2
		编丙(停机, 0),               // 5  停机
	}
}

// 坤恒零之令 验「坤恒为零」。六字。
//
// 写入被吞，非读出为阴——故验者须观**旁人读坤**所得，
// 而非观坤之自身（坤之自身恒阴，验之无别）。
// 收敛之后：艮 = 7、坤 = 0、震 = 0、巽 = 0。
func 坤恒零之令() []int {
	return []int{
		编乙(数操(加), 1, 0, 7),    // 0  艮 = 7
		编甲(器操(加), 0, 1, 0, 0), // 1  坤 ← 艮 + 坤 = 7，被吞
		编甲(器操(加), 4, 0, 0, 0), // 2  震 = 坤 + 坤 = 0
		编乙(载高, 0, 0, 0xFFF),   // 3  坤 ← 0xFFF000，被吞
		编甲(器操(加), 3, 0, 0, 0), // 4  巽 = 坤 + 坤 = 0
		编丙(停机, 0),             // 5  停机
	}
}

// 叩之令 验 叩 之后机器即止，其下一令不复行。三字。
//
// 收敛之后：艮 = 42（而非 99）。
func 叩之令() []int {
	return []int{
		编乙(数操(加), 1, 0, 42), // 0  艮 = 42
		编丙(叩, 0),            // 1  叩
		编乙(数操(加), 1, 0, 99), // 2  不当行
	}
}

// 自改之令 自改之码：把一令写进藏，然后跃去行它。十字。
//
// 此案最毒——它所验者是「藏之写」与「取指」二事之先后：
// 若写者尚未落藏而取指已发，则跃去之后取到的仍是旧令，
// 两机皆不报错，只是算出个不同的数。故非对拍不能察。
//
// 收敛之后：离 = 7，艮 = 8，坎 = 藏[8] = 0xC28007（即「加数 离 坤 7」）。
func 自改之令() []int {
	欲写 := 编乙(数操(加), 5, 0, 7) // 加数 离, 坤, 7
	诸 := []int{}
	诸 = append(诸, 载常(1, 8)...)     // 0     艮 = 8
	诸 = append(诸, 载常(2, 欲写)...)    // 1..2  坎 = 欲写
	诸 = append(诸, 编乙(存字, 2, 1, 0)) // 3     藏[艮+0] ← 坎
	诸 = append(诸, 编丙(跃, 8))        // 4     跃 8
	for len(诸) < 8 {
		诸 = append(诸, 编丙(停机, 0)) // 5..7  填白，不可达
	}
	诸 = append(诸, 编丙(停机, 0)) // 8  将被改写者
	诸 = append(诸, 编丙(停机, 0)) // 9  停机
	return 诸
}

// 符号之令 八操施于**负数**之上。十三字。
//
// 此案专为补一处盲而设。八操之令 所施者皆小正数，而 降（逻辑右移）
// 与算术右移、升 之截顶、加减之溢出，皆须负数方能分辨——
// 正数之上，二者同果，验之如不验。
// 此盲是变异测试查出来的：以算术右移代 降，旧九案竟全绿。
//
// 收敛之后：艮 = 巽 = 0xFFFFFF、坎 = 震 = 1、离 = 1、兑 = 0、乾 = 2。
func 符号之令() []int {
	诸 := []int{}
	诸 = append(诸, 载常(1, 0xFFFFFF)...) // 0..1  艮 = -1
	诸 = append(诸, 载常(2, 1)...)        // 2     坎 = 1
	诸 = append(诸,
		编甲(器操(升), 4, 1, 0, 0), // 3  震 = 艮 << 1 = 0xFFFFFE（截顶）
		编甲(器操(降), 3, 1, 0, 0), // 4  巽 = 艮 >> 1 = 0x7FFFFF（逻辑！）
		编甲(器操(较), 5, 1, 2, 0), // 5  离 = (-1 <  1) = 1
		编甲(器操(较), 6, 2, 1, 0), // 6  兑 = ( 1 < -1) = 0
		编甲(器操(减), 7, 2, 1, 0), // 7  乾 = 1 - (-1) = 2
		编甲(器操(加), 4, 1, 2, 0), // 8  震 = -1 + 1 = 0（溢出回绕）
		编甲(器操(减), 3, 0, 2, 0), // 9  巽 = 0 - 1 = 0xFFFFFF（借位）
		编甲(器操(交), 4, 1, 2, 0), // 10 震 = -1 & 1 = 1
		编甲(器操(并), 3, 1, 2, 0), // 11 巽 = -1 | 1 = 0xFFFFFF
		编丙(停机, 0),             // 12 停机
	)
	return 诸
}

// 存取之偏 验存取之正负偏移。八字。
//
// 数据置于 藏[8] 与 藏[15]，程序占 0..7，两不相犯。
// 存字 之 rd 域不作目的而作源（ISA 之一处反常），最易写错，故验之。
//
// 收敛之后：藏[8] = 震 = 0xAB、藏[15] = 坎 = 巽 = 0xBC、艮 = 12。
func 存取之偏() []int {
	return []int{
		编乙(数操(加), 1, 0, 12),   // 0  艮 = 12（基址）
		编乙(数操(加), 2, 0, 0xAB), // 1  坎 = 0xAB
		编乙(存字, 2, 1, 偏码(-4)),  // 2  藏[12-4] ← 坎
		编乙(数操(加), 2, 2, 0x11), // 3  坎 = 0xBC
		编乙(存字, 2, 1, 3),       // 4  藏[12+3] ← 坎
		编乙(载字, 4, 1, 偏码(-4)),  // 5  震 ← 藏[8]
		编乙(载字, 3, 1, 3),       // 6  巽 ← 藏[15]
		编丙(停机, 0),             // 7  停机
	}
}

// 负数之令 验 用符号 之约：加、减、较 符号扩展，交、并、殊 零扩展。十字。
//
// 此案亦是变异测试逼出来的。旧案之中，乙型立即数非小正数即偏移，
// 而偏移走的是 取偏（甲型九位），不经 扩立即数——
// 故「立即数一律零扩展」这一变异，十一案竟全绿。
//
// 收敛之后：艮 = 7、坎 = 0xFFFFFF、巽 = 震 = 0xFFF、离 = 兑 = 0、乾 = 0xFFF000。
func 负数之令() []int {
	return []int{
		编乙(数操(加), 1, 0, 10),     // 0  艮 = 10
		编乙(数操(加), 1, 1, 偏码(-3)), // 1  艮 = 10 + (-3) = 7     （零扩则 4103）
		编乙(数操(加), 2, 0, 0),      // 2  坎 = 0
		编乙(数操(加), 2, 2, 偏码(-1)), // 3  坎 = 0 + (-1) = 0xFFFFFF （零扩则 4095）
		编乙(数操(较), 5, 1, 偏码(-8)), // 4  离 = (7 < -8) = 0      （零扩则 1）
		编乙(数操(较), 6, 2, 偏码(-8)), // 5  兑 = (-1 < -8) = 0
		编乙(数操(交), 4, 2, 偏码(-1)), // 6  震 = -1 & -1 = 0xFFF   （零扩，故 0xFFF 非 -1）
		编乙(数操(并), 3, 1, 偏码(-1)), // 7  巽 = 7 | -1 = 0xFFF
		编乙(数操(殊), 7, 2, 偏码(-1)), // 8  乾 = -1 ^ -1 = 0xFFF000（零扩，故非 0）
		编丙(停机, 0),               // 9  停机
	}
}

// 越址之令 验 计 之宽与 藏址 之截。六字。
//
// 计 恒为 址位（十八）位，藏址 则只取其低 址 位。
// 故跃至越出藏容之址（20 > 15）不算谬，只是回绕——此乃真机之事：
// 藏小者，址自回绕，机器不报错，只是跑到了别处。
// 验者须明知此事，不可把回绕当作越界，亦不可指望机器报错。
//
// 收敛之后：艮 = 5，计 = 22（而非 6）。
func 越址之令() []int {
	return []int{
		编丙(跃, 20),          // 0      跃 20 → 藏址 = 20 & 15 = 4
		编丙(停机, 0),          // 1..3   填白，不可达
		编丙(停机, 0),          // 2
		编丙(停机, 0),          // 3
		编乙(数操(加), 1, 0, 5), // 4      艮 = 5
		编丙(停机, 0),          // 5      停机
	}
}

// 累加之令 一匝 N 次之循环，累加 1..N。L1 跑不动，唯 L2 可。
//
// 收敛之后：震 = N(N+1)/2、艮 = 0。
func 累加之令(N int) []int {
	// N 须能容于 加数 之十二位有符号立即数（0..2047），
	// 否则 载常 出二字，址 4 之负偏 −3 便指错了地方。
	if N <= 0 || N > (数掩>>1) {
		panic(越界("累加之令之 N", N, 1, 数掩>>1))
	}
	return []int{
		编乙(数操(加), 1, 0, N),      // 0  艮 = N
		编乙(数操(加), 4, 0, 0),      // 1  震 = 0
		编甲(器操(加), 4, 4, 1, 0),   // 2  震 += 艮
		编乙(数操(减), 1, 1, 1),      // 3  艮 -= 1
		编甲(异跃, 0, 1, 0, 偏码(-3)), // 4  艮 != 0 → 5-3 = 2
		编丙(停机, 0),               // 5  停机
	}
}

