func Test爻之运算(t *testing.T) {
	if 阳.反() != 阴 || 阴.反() != 阳 {
		t.Errorf("反之义失：阳反为 %v，阴反为 %v", 阳.反(), 阴.反())
	}
	表 := []struct {
		甲, 乙         爻
		与, 或, 异或, 与非 爻
	}{
		{阴, 阴, 阴, 阴, 阴, 阳},
		{阴, 阳, 阴, 阳, 阳, 阳},
		{阳, 阴, 阴, 阳, 阳, 阳},
		{阳, 阳, 阳, 阳, 阴, 阴},
	}
	for _, r := range 表 {
		if 得 := r.甲.与(r.乙); 得 != r.与 {
			t.Errorf("%s 与 %s 得 %s，欲 %s", r.甲, r.乙, 得, r.与)
		}
		if 得 := r.甲.或(r.乙); 得 != r.或 {
			t.Errorf("%s 或 %s 得 %s，欲 %s", r.甲, r.乙, 得, r.或)
		}
		if 得 := r.甲.异或(r.乙); 得 != r.异或 {
			t.Errorf("%s 异或 %s 得 %s，欲 %s", r.甲, r.乙, 得, r.异或)
		}
		if 得 := r.甲.与非(r.乙); 得 != r.与非 {
			t.Errorf("%s 与非 %s 得 %s，欲 %s", r.甲, r.乙, 得, r.与非)
		}
	}
	if 阳.符() != "⚊" || 阴.符() != "⚋" {
		t.Errorf("爻符有误：阳 %q，阴 %q", 阳.符(), 阴.符())
	}
}

func Test象之符(t *testing.T) {
	// 八卦：值之二进制自高至低为初爻、二爻、三爻。
	名 := [8]string{"坤", "艮", "坎", "巽", "震", "离", "兑", "乾"}
	符 := [8]string{"☷", "☶", "☵", "☴", "☳", "☲", "☱", "☰"}
	for 值 := 0; 值 < 8; 值++ {
		if 得 := 卦名(值); 得 != 名[值] {
			t.Errorf("值 %d 之卦名得 %s，欲 %s", 值, 得, 名[值])
		}
		if 得 := 八卦符(值); 得 != 符[值] {
			t.Errorf("值 %d 之卦符得 %s，欲 %s", 值, 得, 符[值])
		}
	}
	// 四象：太阳 3、少阴 2、少阳 1、太阴 0。
	象符 := [4]string{"⚏", "⚎", "⚍", "⚌"}
	for 值 := 0; 值 < 4; 值++ {
		if 得 := 四象符(值); 得 != 象符[值] {
			t.Errorf("值 %d 之四象得 %s，欲 %s", 值, 得, 象符[值])
		}
	}
	// 六爻符：乾为 ☰☰，坤为 ☷☷。
	var 乾爻, 坤爻 [6]爻
	for i := range 乾爻 {
		乾爻[i] = 阳
		坤爻[i] = 阴
	}
	if 得 := 六爻符(乾爻); 得 != "☰☰" {
		t.Errorf("六爻全阳得 %s，欲 ☰☰", 得)
	}
	if 得 := 六爻符(坤爻); 得 != "☷☷" {
		t.Errorf("六爻全阴得 %s，欲 ☷☷", 得)
	}
	// 排爻自高至低，并爻以首为低，故须倒爻相接方能复原。
	for 值 := 0; 值 < 64; 值++ {
		众 := 排爻(值, 6)
		if 并爻(倒爻(众)) != 值 {
			t.Errorf("排爻倒爻并爻不复原：值 %d → %s → %d", 值, 串爻(众), 并爻(倒爻(众)))
		}
	}
}

