// ==================================================================
// 穷举 · 验门之法
//
// 门之真伪，非举例可明，必穷举而后定。
// 凡 k 根入线，遍历 2^k 种取値，逐一置入、调定、比对。
//
// 注：测试函数之名的 Test 前缀系 Go 工具链所强求（非此不认），
// 与 出口.go 中的 Run 同属「仅此若干处用非中文」之列。
// ==================================================================

// 穷举 遍历 入 之全部取值，与 期望 所给之出逐一比对。
func 穷举(t *testing.T, n *网表, 入 []*线, 出 []*线, 期望 func(众 []爻) []爻) {
	t.Helper()
	k := len(入)
	if k > 20 {
		t.Fatalf("入线 %d 根，穷举规模过大（2^%d）", k, k)
	}
	for 码 := 0; 码 < 1<<k; 码++ {
		众 := make([]爻, k)
		for b := 0; b < k; b++ {
			众[b] = 由数(码 >> b & 1)
			n.驱动(入[b], 众[b])
		}
		if err := n.调定(0); err != nil {
			t.Fatalf("码 %d 调定不成：%v", 码, err)
		}
		欲 := 期望(众)
		if len(欲) != len(出) {
			t.Fatalf("码 %d：期望出 %d 个，实有出线 %d 根", 码, len(欲), len(出))
		}
		for i, w := range 出 {
			if 得 := n.读(w); 得 != 欲[i] {
				t.Errorf("码 %0*b（入 %s）：出[%d] 得 %s，欲 %s",
					k, 码, 串爻(众), i, 得.符(), 欲[i].符())
			}
		}
	}
}

// 验纯粹 断言网表之中除 与非门 与 恒源 外别无他种逻辑门。
//
// 恒源 乃电源之轨，非门也，故容之。此验一破，便是有人偷用了未经派生之门。
func 验纯粹(t *testing.T, n *网表) {
	t.Helper()
	for i, g := range n.门表 {
		switch g.(type) {
		case *与非门, *恒源:
		default:
			t.Errorf("网表「%s」第 %d 门为 %T，非与非门亦非恒源：万门当出于一", n.名, i, g)
		}
	}
}

// 双门 造一网表，置两入线（甲、乙）与一出线（出）。
func 双门(名 string) (*网表, *线, *线, *线) {
	n := 建网表(名)
	return n, n.引线("甲"), n.引线("乙"), n.引线("出")
}

