func Test译门(t *testing.T) {
	for k := 1; k <= 4; k++ {
		n := 建网表("译")
		入 := n.列线("入", k)
		出 := n.列线("出", 1<<k)
		n.置译门(入, 出)
		穷举(t, n, 入, 出, func(众 []爻) []爻 {
			v := 并爻(众)
			欲 := make([]爻, len(出))
			for i := range 欲 {
				欲[i] = 作爻(i == v)
			}
			return 欲
		})
		验纯粹(t, n)
	}
}

// Test十六爻全与门 十六爻相与，穷举 2^16 = 65536 组。
// 此即 M0 之验收：与门于众爻之上依然成立。
func Test十六爻全与门(t *testing.T) {
	const 位 = 16
	n := 建网表("十六爻与")
	入 := n.列线("入", 位)
	出 := n.引线("出")
	n.置全与门(入, 出)
	穷举(t, n, 入, []*线{出}, func(众 []爻) []爻 {
		欲 := 阳
		for _, y := range 众 {
			欲 = 欲.与(y)
		}
		return []爻{欲}
	})
	验纯粹(t, n)
}

func Test全异或门之奇偶(t *testing.T) {
	const 位 = 8
	n := 建网表("八爻奇偶")
	入 := n.列线("入", 位)
	出 := n.引线("出")
	n.置全异或门(入, 出)
	穷举(t, n, 入, []*线{出}, func(众 []爻) []爻 {
		数 := 0
		for _, y := range 众 {
			数 += y.数()
		}
		return []爻{由数(数 % 2)}
	})
	验纯粹(t, n)
}

// Test振荡 三非首尾相衔成环，永不调定，调定当报振荡之错。
func Test振荡(t *testing.T) {
	n := 建网表("环振")
	a := n.引线("甲")
	b := n.引线("乙")
	c := n.引线("丙")
	n.置非门(a, b)
	n.置非门(b, c)
	n.置非门(c, a) // 奇数级反相成环，必然振荡

	err := n.调定(10000)
	if err == nil {
		t.Fatalf("环形振荡电路竟告调定，步数 %d", n.步数)
	}
	if !strings.Contains(err.Error(), "振荡") {
		t.Errorf("所报之错非振荡：%v", err)
	}
}

