package 盘古

// 卦序者，文王之序与先天之序的转换。
//
// ========================= 两套卦序 =========================
//
// 六十四卦在 Unicode 中（U+4DC0 起）依「文王卦序」排列——那是《易经》通行本
// 的读诵之序：乾一、坤二、屯三……既济六十三、未济六十四。其排列之理，古今
// 聚讼，迄今未有一个公认的数学解释（OEIS A102241 的注脚即持此说）。
//
// 机器所用者却是另一套：「先天之序」（邵雍传伏羲六十四卦次序）。此序中，
// 一卦之六爻自成一个六位二进制数——可计算、可运算、可寻址。
// 操作码、地址、立即数皆活在先天之序中；文王之序只用于「显象」，即把一串
// 比特译成人能认得的卦名与卦符。
//
// 两套序之间的转换，全赖 文王先天表 一张表。此表不可凭记忆手抄，
// 其来历、位约定与六重校验之法，尽录于 典/07-卦序映射表.md。
//
// ====================== 位约定（至要） ======================
//
// 别卦之先天值：值 = (上卦 << 3) | 下卦。上卦居高三位，下卦居低三位。
// 每一经卦自身之值沿用 象.go 既有之约：初爻为高位，值 7 为乾、0 为坤
// （即 Unicode 序位 = 7 − 值）。
//
// 于是六爻在位中的分布为：
//
//	位5 位4 位3 │ 位2 位1 位0
//	四爻 五爻 上爻 │ 初爻 二爻 三爻
//	──── 上卦 ────┼ ──── 下卦 ────
//
// 注意：外部文献（含 OEIS A102241）多以「上爻为高位」记先天值，与本约
// 相差一次三爻位反转（乾、坤、离、坎四卦自对称而不变，兑↔巽、震↔艮 互换）。
// 本系统一律用本约；凡引外部数值，须先归化，不得直接抄入。
// ==========================================================

const (
	// 别卦基 U+4DC0 ䷀，为文王卦序第一卦（乾）。U+4DC0–U+4DFF 共六十四字。
	别卦基 = 0x4DC0
	// 别卦数 六十四。
	别卦数 = 64
)

// 六十四卦名表 依文王卦序排列的卦名。
//
// 出处：朱熹《周易本义·卦名次序歌》——「乾坤屯蒙需讼師，比小畜兮履泰否……」，
// 凡六十四句，与通行本卦序一一相合。
var 六十四卦名表 = [别卦数]string{
	"乾", "坤", "屯", "蒙", "需", "讼", "师", "比",
	"小畜", "履", "泰", "否", "同人", "大有", "谦", "豫",
	"随", "蛊", "临", "观", "噬嗑", "贲", "剥", "复",
	"无妄", "大畜", "颐", "大过", "坎", "离", "咸", "恒",
	"遁", "大壮", "晋", "明夷", "家人", "睽", "蹇", "解",
	"损", "益", "夬", "姤", "萃", "升", "困", "井",
	"革", "鼎", "震", "艮", "渐", "归妹", "丰", "旅",
	"巽", "兑", "涣", "节", "中孚", "小过", "既济", "未济",
}

// 文王先天表 文王序位减去一（0..63）→ 先天值（0..63）。
//
// 数据为先天值，已依本位约定归化（上爻为高位者已作三爻位反转）。
// 未经归化的原始序列见 典/07-卦序映射表.md。
var 文王先天表 = [别卦数]int{
	63, 0, 20, 10, 23, 58, 2, 16, 31, 62, 7, 56, 61, 47, 1, 32,
	52, 11, 6, 24, 44, 13, 8, 4, 60, 15, 12, 51, 18, 45, 49, 35,
	57, 39, 40, 5, 29, 46, 17, 34, 14, 28, 55, 59, 48, 3, 50, 19,
	53, 43, 36, 9, 25, 38, 37, 41, 27, 54, 26, 22, 30, 33, 21, 42,
}

// 先天文王表 先天值（0..63）→ 文王序位（1..64）。由 文王先天表 反转而成。
//
// 以包级变量初始化而非 init()，只为免去又一个非中文标识符——
// Go 会依依赖关系自行排定初始化之序。
var 先天文王表 = 造先天文王表()

// 造先天文王表 反查表之构造函数。
func 造先天文王表() [别卦数]int {
	var 表 [别卦数]int
	for 序, 值 := range 文王先天表 {
		表[值] = 序 + 1
	}
	return 表
}

// ------------------------------------------------------------------

// 文王先天 由文王序位（1..64）取先天值（0..63）。
func 文王先天(序 int) int {
	if 序 < 1 || 序 > 别卦数 {
		panic(越界("文王先天", 序, 1, 别卦数))
	}
	return 文王先天表[序-1]
}

// 先天文王 由先天值（0..63）取文王序位（1..64）。
func 先天文王(值 int) int {
	if 值 < 0 || 值 >= 别卦数 {
		panic(越界("先天文王", 值, 0, 别卦数-1))
	}
	return 先天文王表[值]
}

// 上卦 取别卦之上卦（外卦）之值，0..7。
func 上卦(值 int) int {
	if 值 < 0 || 值 >= 别卦数 {
		panic(越界("上卦", 值, 0, 别卦数-1))
	}
	return 值 >> 3
}

// 下卦 取别卦之下卦（内卦）之值，0..7。
func 下卦(值 int) int {
	if 值 < 0 || 值 >= 别卦数 {
		panic(越界("下卦", 值, 0, 别卦数-1))
	}
	return 值 & 7
}

// ------------------------------------------------------------------

// 别卦符 由先天值取其在 U+4DC0 段中的卦符。
func 别卦符(值 int) string {
	return string(rune(别卦基 + 先天文王(值) - 1))
}

// 别卦名 由先天值取卦名汉字。
func 别卦名(值 int) string {
	return 六十四卦名表[先天文王(值)-1]
}

// 别卦象 以两经卦表一别卦，上卦在前。如 ☷☰ 为地天泰。
func 别卦象(值 int) string {
	return 八卦符(上卦(值)) + 八卦符(下卦(值))
}

// 别卦爻 以 ⚊⚋ 之串表六爻，自初爻起、至上爻止。
func 别卦爻(值 int) string {
	验卦值(值, "别卦爻")
	众 := []爻{
		由数((值 >> 2) & 1), // 初爻：下卦之高位
		由数((值 >> 1) & 1), // 二爻
		由数((值 >> 0) & 1), // 三爻
		由数((值 >> 5) & 1), // 四爻：上卦之高位
		由数((值 >> 4) & 1), // 五爻
		由数((值 >> 3) & 1), // 上爻
	}
	return 串爻(众)
}

// 卦之辞 综一卦之象、名、符为一辞，用于诊断与演示。
//
//	如：䷊ 泰 ☷☰ ⚊⚊⚊⚋⚋⚋
func 卦之辞(值 int) string {
	return 别卦符(值) + " " + 别卦名(值) + " " + 别卦象(值) + " " + 别卦爻(值)
}

// 文王卦符 依文王序位（1..64）取卦符。
func 文王卦符(序 int) string {
	if 序 < 1 || 序 > 别卦数 {
		panic(越界("文王卦符", 序, 1, 别卦数))
	}
	return string(rune(别卦基 + 序 - 1))
}

// ------------------------------------------------------------------

// 倒置 取一卦颠倒一百八十度之卦，易家谓之「综卦」。
//
// 六爻首尾相易：初爻与上爻换、二爻与五爻换、三爻与四爻换。
// 在本位约定下，这恰是六位之位反转。
func 倒置(值 int) int {
	验卦值(值, "倒置")
	倒 := 0
	for i := 0; i < 6; i++ {
		if 值&(1<<i) != 0 {
			倒 |= 1 << (5 - i)
		}
	}
	return 倒
}

// 错卦 取一卦逐爻阴阳互易之卦，易家谓之「错卦」（旁通）。
func 错卦(值 int) int {
	验卦值(值, "错卦")
	// 位运算之戒：^ 与 - 同级而左结合，括号断不可省。
	return 值 ^ (别卦数 - 1)
}

// 验卦值 查先天值是否在 0..63 之内，否则报以统一之辞。
func 验卦值(值 int, 处 string) {
	if 值 < 0 || 值 >= 别卦数 {
		panic(越界(处, 值, 0, 别卦数-1))
	}
}
