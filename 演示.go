// 演示门 造一座异或电路，穷举其真值表而印之。
//
// 此电路看似只有一门，实则内藏四个与非门——异或非原语，乃派生而来。
func 演示门() {
	n := 建网表("异或之演")
	甲 := n.引线("甲")
	乙 := n.引线("乙")
	出 := n.引线("出")
	n.置异或门(甲, 乙, 出)

	fmt.Print(n.述())
	fmt.Println()
	fmt.Println("  甲  乙  │  出  │ 四象  爻")
	fmt.Println("─────────┼─────┼──────────")
	for 码 := 0; 码 < 4; 码++ {
		a := 由数(码 >> 1 & 1)
		b := 由数(码 & 1)
		n.驱动(甲, a)
		n.驱动(乙, b)
		if err := n.调定(0); err != nil {
			panic(err)
		}
		o := n.读(出)
		值 := a.数()<<1 | b.数()
		fmt.Printf("  %s   %s  │  %s   │  %s   %s\n",
			a.符(), b.符(), o.符(), 四象符(值), 串爻(排爻(值, 2)))
	}
}

// 演示算爻 造一座二十四位算爻器，以八操演之。
//
// 八操各配一经卦，择者三爻，正合一卦之数——此即「以卦为操作码」之雏形。
func 演示算爻() {
	const 位 = 24
	n := 建网表("算爻之演")
	甲 := n.列线("甲", 位)
	乙 := n.列线("乙", 位)
	果 := n.列线("果", 位)
	择 := [3]*线{n.引线("择0"), n.引线("择1"), n.引线("择2")}
	志 := n.置算爻器(甲, 乙, 择, 果)

	fmt.Printf("二十四位算爻器既成：门 %d，线 %d\n", n.门数(), n.线数())
	fmt.Println()
	fmt.Println(" 操  卦 │        甲        乙 │      果（十六进制）  果（有符号）  进位 零 负 溢出")
	fmt.Println("───────┼────────────────────┼───────────────────────────────────────────────")

	例 := []struct {
		操    算爻之操
		甲, 乙 int
	}{
		{加, 1234567, 7654321},
		{减, 7654321, 1234567},
		{交, 0x0ABCDE, 0x0F0F0F},
		{并, 0x0ABCDE, 0x0F0F0F},
		{殊, 0x0ABCDE, 0x0F0F0F},
		{升, 0x000123, 0},
		{降, 0x0ABCDE, 0},
		{较, 0xFFFFFF, 1}, // 甲 为负一，乙 为一
	}

	// 括号一律不可省。Go 之中 & 与 << 同级而左结合，
	// 若写 v&1<<(位-1)，实则 (v&1)<<(位-1)，正数遂被误判为负。
	掩 := 1<<位 - 1
	符位 := 1 << (位 - 1)
	有符 := func(v int) int {
		v &= 掩
		if v&符位 != 0 {
			v -= 1 << 位
		}
		return v
	}

	for _, 例 := range 例 {
		置演示之数(n, 甲, 例.甲)
		置演示之数(n, 乙, 例.乙)
		for i := 0; i < 3; i++ {
			n.驱动(择[i], 由数(int(例.操)>>i&1))
		}
		if err := n.调定(0); err != nil {
			panic(err)
		}
		得 := 读演示之数(n, 果)
		fmt.Printf("  %s  %s │ %11d %8d │ %18s %14d    %s   %s  %s   %s\n",
			卦名(int(例.操)), 八卦符(int(例.操)),
			有符(例.甲), 有符(例.乙),
			十六进制(得), 有符(得),
			n.读(志.进位).符(), n.读(志.零).符(), n.读(志.负).符(), n.读(志.溢出).符())
	}
	fmt.Println()
	fmt.Println("（进位、零、负、溢出 四志：阳作 ⚊，阴作 ⚋）")
}

// 置演示之数 将一数置入一列线。
func 置演示之数(n *网表, 众 []*线, v int) {
	for i, w := range 众 {
		n.驱动(w, 由数(v>>i&1))
	}
}

// 读演示之数 自一列线读出其所成之数。
func 读演示之数(n *网表, 众 []*线) int {
	v := 0
	for i, w := range 众 {
		v |= n.读(w).数() << i
	}
	return v
}

// 十六进制 将一数写作十六进制之形，每四位一空格。
func 十六进制(v int) string {
	s := fmt.Sprintf("%06X", v)
	return s[:2] + " " + s[2:4] + " " + s[4:]
}

