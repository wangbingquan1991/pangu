// 演示锁爻 以一八位寄存器演「沿」之要义。
//
// 同一组入，在不同的辰与存允之下，出可以相同也可以不同——
// 这正是时序电路与组合电路的分野。表中第三步最要紧：
// 沿已过而入偷改，出不动者，主从隔断之效也。
func 演示锁爻() {
	const 位 = 8
	n := 建网表("锁爻之演")
	入 := n.列线("入", 位)
	出 := n.列线("出", 位)
	存允 := n.引线("存允")
	辰线 := n.置辰线()
	n.置存爻器(入, 存允, 辰线, 出)
	c := 建辰(n, 辰线)
	演示定(n)
	if err := c.复位(); err != nil {
		panic(err)
	}

	fmt.Println("\n【一】锁爻与辰：同一入，因辰与存允之异而结果不同")
	fmt.Printf("八位寄存器既成：门 %d，线 %d\n", n.门数(), n.线数())
	fmt.Println()
	fmt.Println(" 步 │ 辰 │ 存允 │ 入 │ 出 │ 何以")
	fmt.Println("────┼────┼─────┼────┼────┼──────────────────────────────")

	步表 := []struct {
		辰  爻
		存允 爻
		入  int
		说  string
	}{
		{阴, 阳, 0xA5, "存允已阳、入已置，然上升之沿未至，出不动"},
		{阳, 阳, 0xA5, "上升之沿至，纳 A5"},
		{阳, 阳, 0x3C, "沿已过，入虽偷改，出不动——主从隔断之效"},
		{阴, 阴, 0x3C, "存允转阴，辰伏以待"},
		{阳, 阴, 0x3C, "沿至而不纳：存允为阴，守其旧"},
		{阴, 阳, 0x3C, "存允复阳，辰复伏"},
		{阳, 阳, 0x3C, "沿至，纳 3C"},
	}
	for i, s := range 步表 {
		n.驱动(存允, s.存允)
		n.置数(入, s.入)
		演示定(n)
		n.驱动(辰线, s.辰)
		演示定(n)
		fmt.Printf("  %d │  %s │  %s  │ %02X │ %02X │ %s\n",
			i+1, s.辰.符(), s.存允.符(), s.入, n.读数(出), s.说)
	}
}

// 演示卦器 演八卦器堆：八器以八卦为名，三爻（一卦）择其一。
//
// 号 之三爻成卦，卦之所指即器之所在。写入以卦择，读出亦以卦择，
// 两口可同时而读——为将来算爻器的双入而备。
func 演示卦器() {
	const 位 = 24
	n := 建网表("卦器之演")
	入 := n.列线("入", 位)
	号 := [3]*线{n.引线("号0"), n.引线("号1"), n.引线("号2")}
	读甲 := [3]*线{n.引线("甲0"), n.引线("甲1"), n.引线("甲2")}
	读乙 := [3]*线{n.引线("乙0"), n.引线("乙1"), n.引线("乙2")}
	存允 := n.引线("存允")
	辰线 := n.置辰线()
	r := n.置卦器堆(位, 入, 号, 存允, 辰线, 读甲, 读乙)
	c := 建辰(n, 辰线)
	演示定(n)
	if err := c.复位(); err != nil {
		panic(err)
	}

	fmt.Println("\n【二】卦器堆：八器以八卦为名，三爻（一卦）择其一")
	fmt.Printf("八器各二十四位：门 %d，线 %d\n", n.门数(), n.线数())
	fmt.Println()
	fmt.Println(" 器 │ 卦 名 │     所纳     │   甲口所读   │ 同否")
	fmt.Println("────┼──────┼─────────────┼─────────────┼──────")

	// 八器各纳一数，其数只占与本器相应之三位。
	for i := 0; i < 8; i++ {
		n.置数(入, 1<<(3*i))
		n.置数(号[:], i)
		n.驱动(存允, 阳)
		演示定(n)
		演示拍(c)
	}
	n.驱动(存允, 阴)
	演示定(n)

	for i := 0; i < 8; i++ {
		n.置数(读甲[:], i)
		演示定(n)
		欲 := 1 << (3 * i)
		得 := n.读数(r.出甲)
		fmt.Printf("  %d │  %s  %s │  %s  │  %s  │  %s\n",
			i, 八卦符(i), 卦名(i), 十六进制(欲), 十六进制(得), 作爻(欲 == 得).符())
	}
}

// 演示取指 演一具最简的取指之机：计 自增，藏 逐条而出。
//
// 计 之出即为 藏 之址，中间不假他物。
// 此非指令——尚无译卦之能（那是 M3 的事）。
// 然「依址取数、逐条而下」这条筋一旦通了，
// 冯·诺依曼机的骨架便立起来了，余下的不过是往里填东西。
func 演示取指() {
	const 位, 址 = 8, 3
	n := 建网表("取指之演")
	入 := n.列线("入", 位)
	存允 := n.引线("存允")
	载 := n.引线("载")
	增 := n.引线("增")
	辰线 := n.置辰线()

	// 计 先立，其出即为址。跳转之口无用处，接地即可，
	// 如此 载 为阳时便是「归于初址」——正合复位之意。
	p := n.置计爻器(址, n.阴列(址), 载, 增, 辰线)
	址线 := make([]*线, 址)
	for i := range 址线 {
		址线[i] = n.引线(fmt.Sprintf("址%d", i))
		n.置继门(p.出[i], 址线[i])
	}
	m := n.置藏(位, 址, 址线, 入, 存允, 辰线)
	c := 建辰(n, 辰线)
	演示定(n)
	if err := c.复位(); err != nil {
		panic(err)
	}

	fmt.Printf("\n【三】取指之机：计 自增，藏 逐条而出\n")
	fmt.Printf("藏 %d 字 × %d 位，计 %d 位：门 %d，线 %d\n", m.字, m.位, p.位, n.门数(), n.线数())
	fmt.Println()
	fmt.Println(" 拍 │ 计（址） │ 所出 │ 十进制")
	fmt.Println("────┼─────────┼─────┼───────")

	// 预置：存允 与 增 同时为阳。每一拍，藏 以 计 之现值写入，计 于同一沿加一。
	诸值 := make([]int, m.字)
	n.驱动(存允, 阳)
	n.驱动(载, 阴)
	n.驱动(增, 阳)
	for j := 0; j < m.字; j++ {
		诸值[j] = (j*29 + 3) & 0xFF
		n.置数(入, 诸值[j])
		演示定(n)
		演示拍(c)
	}
	n.驱动(存允, 阴)
	演示定(n)

	for j := 0; j < m.字; j++ {
		得 := n.读数(m.出)
		fmt.Printf("  %d │     %d    │  %02X  │   %3d    %s\n",
			j, n.读数(p.出), 得, 得, 示异同(得, 诸值[j]))
		演示拍(c)
	}
	fmt.Println()
	fmt.Println("（诸值取 29j+3，非等差一——纵使址线未接上，所出亦不能蒙混成序）")
}

// 示异同 两数相同则空，不同则示警。
func 示异同(得, 欲 int) string {
	if 得 == 欲 {
		return ""
	}
	return fmt.Sprintf("← 谬！当为 %d", 欲)
}

// 演示译门 造一座三位译码器，以八卦显其八出。
//
// 三位即一卦：译门之出线逐一亮起，正如八卦依次而显。
func 演示译门() {
	n := 建网表("译门之演")
	入 := []*线{n.引线("位二"), n.引线("位一"), n.引线("位零")}
	出 := make([]*线, 8)
	for i := range 出 {
		出[i] = n.引线(fmt.Sprintf("出%d", i))
	}
	n.置译门(入, 出)

	fmt.Println()
	fmt.Print(n.述())
	fmt.Println()
	fmt.Println(" 入(位二位一位零) │ 独阳之出 │ 卦  名  爻象")
	fmt.Println("──────────────┼─────────┼─────────────")
	for 值 := 0; 值 < 8; 值++ {
		众 := 排爻(值, 3)
		n.驱动(入[0], 众[2]) // 入[0] 权重最低，取自爻象之末位
		n.驱动(入[1], 众[1])
		n.驱动(入[2], 众[0])
		if err := n.调定(0); err != nil {
			panic(err)
		}
		独 := -1
		阳数 := 0
		for i, w := range 出 {
			if n.读(w) == 阳 {
				独 = i
				阳数++
			}
		}
		fmt.Printf("      %s%s%s       │  出%d     │  %s  %s  %s\n",
			众[0].符(), 众[1].符(), 众[2].符(),
			独, 八卦符(值), 卦名(值), 串爻(众))
		if 阳数 != 1 {
			panic(fmt.Sprintf("译门之出应恰有一阳，值 %d 实得 %d", 值, 阳数))
		}
	}
}

// 演示太极 一部二十四位之中央处理器，跑一段手编之机器码。
//
// 此演所欲明者三事：
//
//	一、**令之成。** 一段手编之机器码，逐条可反汇编而读之。
//	   一令二十四位，正是八卦；左起第一卦定其类，第二卦定其操。
//	   此非比喻——那三位线，的的确确接在译门的入上。
//
//	二、**两拍一令。** 藏之读是组合的（址一变，字立出），
//	   故取指与执行不可同拍而毕：一拍取令，一拍行之。
//	   下表之中 相 在「取指」「执行」之间逐拍而翻，便是此理之迹。
//
//	三、**以慢御快。** 太极（L1）是门级的：藏十六字便二万三千门，
//	   三十二字则三万四千门，一拍须逐门重算至定，约二毫秒——
//	   它可信，因为它全身没有一句「假设」；
//	   周期（L2）纯整数，一门也无，一拍数十纳秒，快十万倍——
//	   它不可自信，因为它全身都是假设：
//	   假设数据通路是那样连的、假设时序是那样走的。
//	   故以 L1 逐拍量 L2，量毕方许 L2 独行。慢者是尺，快者是布。
func 演示太极() {
	const 址 = 4
	const 示拍 = 18 // 恰一匝：三令之立，与循环之首轮
	诸令 := 斐波那契之令()

	fmt.Println("\n【四】太极运化：一部二十四位之机，跑手编之机器码")

	// 反汇编之宽，取诸令中最长者——不预设一个将来会被撑破的定数。
	宽 := 0
	for _, 令 := range 诸令 {
		if w := 显宽(令之辞(令)); w > 宽 {
			宽 = w
		}
	}

	// ---- （甲）机器码 ----
	fmt.Println("\n（甲）手编之机器码：十一字，算 fib(10)")
	fmt.Println()
	fmt.Printf(" 址 │ 八卦（自高而低） │ %s\n", 填充("反汇编", 宽))
	fmt.Printf("────┼─────────────────┼%s\n", strings.Repeat("─", 宽+2))
	for i, 令 := range 诸令 {
		fmt.Printf(" %2d │ %s │ %s\n", i, 字之卦(令), 填充(令之辞(令), 宽))
	}
	fmt.Println()
	fmt.Println("  一令二十四位，正是八卦。左起第一卦（位廿三至廿一）定其类，")
	fmt.Println("  第二卦（位二十至十八）定其操——故 加数 作 ䷬ 萃（兑上坤下）：")
	fmt.Print("  兑为数类，坤为加操。此非附会，那六根线真接在译门之上。")

	// ---- （乙）L1 逐拍之迹 ----
	太 := 建太极(址)
	if err := 太.重置并装载(诸令); err != nil {
		panic(err)
	}
	fmt.Printf("\n\n（乙）太极（L1）逐拍之迹：两拍一令\n")
	fmt.Printf("门 %d，线 %d，藏 %d 字 × %d 位\n",
		太.门数(), 太.网.线数(), 太.藏.字, 太.藏.位)
	fmt.Println()
	fmt.Printf(" 拍 │ 相  │ 计 │ 令（八卦）│ %s │   艮   坎   巽   震   离\n",
		填充("反汇编", 宽))
	fmt.Printf("────┼─────┼────┼──────────┼%s┼────────────────────────\n",
		strings.Repeat("─", 宽+2))
	for p := 1; p <= 示拍; p++ {
		if err := 太.步(); err != nil {
			panic(err)
		}
		诸器 := 太.诸器值()
		fmt.Printf(" %2d │ %s │ %02d │ %s │ %s │ %4d %4d %4d %4d %4d\n",
			p, 太.相名(), 太.计值(), 字之卦(太.令值()),
			填充(令之辞(太.令值()), 宽),
			诸器[1], 诸器[2], 诸器[3], 诸器[4], 诸器[5])
	}
	fmt.Println("  ⋮")
	fmt.Println()
	fmt.Println("  相 之「取指」「执行」逐拍而翻，此即两拍一令。")
	fmt.Println("  凡十八拍，恰是三令之立（拍一至六）与循环之首轮（拍七至十八）。")

	// ---- （丙）L1 跑毕 ----
	fmt.Println("\n（丙）跑至停机（L1）")
	始 := time.Now()
	余拍, err := 太.跑(4000)
	历一 := time.Since(始)
	if err != nil {
		panic(err)
	}
	太拍 := 示拍 + 余拍
	欲 := 斐波那契之数(10)
	fmt.Printf("凡 %d 拍（前 %d 拍已示），离 = %d，fib(10) = %d %s\n",
		太拍, 示拍, 太.器值(5), 欲, 示异同(太.器值(5), 欲))
	fmt.Printf("历时 %v，每拍 %v\n", 历一, 历一/time.Duration(max(余拍, 1)))

	// ---- （丁）L2 同跑 ----
	fmt.Println("\n（丁）周期（L2）同跑：两机之果须全同")
	周 := 建周期机(址)
	if err := 周.重置并装载(诸令); err != nil {
		panic(err)
	}
	始 = time.Now()
	周拍, err := 周.跑(4000)
	历二 := time.Since(始)
	if err != nil {
		panic(err)
	}
	每拍一 := 历一 / time.Duration(max(余拍, 1))
	每拍二 := 历二 / time.Duration(max(周拍, 1))
	fmt.Println()
	fmt.Printf("  太极（L1）  门 %6d  %4d 拍  离 %5d  每拍 %10v\n",
		太.门数(), 太拍, 太.器值(5), 每拍一)
	fmt.Printf("  周期（L2）  门 %6d  %4d 拍  离 %5d  每拍 %10v\n",
		0, 周拍, 周.器值(5), 每拍二)
	if 太拍 != 周拍 || 太.器值(5) != 周.器值(5) {
		panic(fmt.Sprintf("两机之果相左：L1 %d 拍 离 %d，L2 %d 拍 离 %d",
			太拍, 太.器值(5), 周拍, 周.器值(5)))
	}
	fmt.Printf("\n  拍数与离皆同，速之差 %.0f 倍。\n",
		float64(每拍一)/float64(max(int(每拍二), 1)))
	fmt.Println("  然 L2 之可信不自证——乃 周期_test.go 十三案、")
	fmt.Println("  三百二十四拍、逐拍比对之所赐。布之长短，须以尺量。")

	// ---- （戊）L2 独行 ----
	const N = 1000
	fmt.Printf("\n（戊）L2 独行：累加 1..%d（L1 所不能）\n", N)
	诸令二 := 累加之令(N)
	m2 := 建周期机(址)
	if err := m2.重置并装载(诸令二); err != nil {
		panic(err)
	}
	始 = time.Now()
	p2, err := m2.跑(1 << 22)
	历三 := time.Since(始)
	if err != nil {
		panic(err)
	}
	和 := N * (N + 1) / 2
	fmt.Println()
	fmt.Printf("  %s\n", strings.ReplaceAll(strings.TrimRight(印令(诸令二), "\n"), "\n", "\n  "))
	fmt.Println()
	fmt.Printf("凡 %d 拍，震 = %d，1..%d 之和 = %d %s；历时 %v\n",
		p2, m2.器值(4), N, 和, 示异同(m2.器值(4), 和), 历三)
	fmt.Printf("同一段码若以 L1 跑之，按上实测之每拍 %v 计，须 %v。\n",
		每拍一, 每拍一*time.Duration(p2))
	fmt.Println()
	fmt.Println("  L1 慢，而它是尺；L2 快，而它是布。")
	fmt.Println("  无尺，布不知其长短；无布，尺量不尽天下。二者不可偏废。")
}

// 显宽 一字符串在等宽之下所占之列数。汉字与诸符号占两列，其余占一列。
func 显宽(s string) int {
	占 := 0
	for _, r := range s {
		if r > 0x2E80 {
			占 += 2
		} else {
			占++
		}
	}
	return 占
}

// 演示卦序 列六十四卦：文王之序、先天之值、二经卦之象、六爻之形。
//
// 左起三列是文王之序——人读的次序；右起是先天之值——机器算的次序。
// 二者之间的那张表，便是此番所补之物。
func 演示卦序() {
	fmt.Println("\n【五】六十四卦：文王之序与先天之序")
	fmt.Println()
	fmt.Println(" 序 │ 符  卦名   象    六爻（自初爻起）│先天 │ 序 │ 符  卦名   象    六爻（自初爻起）│先天")
	fmt.Println("────┼────────────────────────────────┼─────┼────┼────────────────────────────────┼─────")

	for 行 := 0; 行 < 32; 行++ {
		上 := 行 + 1
		下 := 行 + 33
		fmt.Println(" " + 一行之辞(上) + " │" + 一行之辞(下))
	}

	fmt.Println()
	fmt.Println("  左为文王之序（人读之序），右为其先天之值（机器算之序）。")
	fmt.Printf("  乾 ䷀ 居首，先天 %d；坤 ䷁ 次之，先天 %d。", 文王先天(1), 文王先天(2))
	fmt.Printf("既济 ䷾ 在 %d，未济 ䷿ 在 %d。\n", 先天文王(21), 先天文王(42))
	fmt.Println("  凡六十四卦，两序一一对应，是为一排列——此即操作码与卦符之间的那张表。")
}

// 一行之辞 取一卦之半行：序、符、名、象、爻、先天值。
func 一行之辞(序 int) string {
	值 := 文王先天(序)
	return fmt.Sprintf("%2d │ %s  %s  %s  %s│ %2d  ",
		序, 别卦符(值), 填充(别卦名(值), 8), 别卦象(值), 别卦爻(值), 值)
}

// 填充 以空格补足，使其在等宽之下对齐。
// 汉字与诸符号占两格宽，故按显示宽度而非字符数计——此即 显宽 之职。
func 填充(s string, 宽 int) string {
	return s + strings.Repeat(" ", 宽-显宽(s))
}
