	//
	// 器之数 是 0o100（六十四口），今只配其十，余者留 M7 之外设。
	// 若逐口而列，则六十二行「—」——**一张表若大半是空行，便无人看它**。
	// 故此处只列已配者，而「有几口已配」由 器口之簿 数出，不另书一数
	// （手抄之数必朽，且朽在数上者不报错，只是少列一口）。
	for _, p := range 器口之簿 {
		fmt.Printf("  %s │ %s │ %s\n",
			填充(fmt.Sprintf("0o%06o", 器基+p.口), 10), 填充(p.名, 4), p.注)
	}
	fmt.Printf("  %s │ ⋮\n", 填充(fmt.Sprintf("0o%06o", 器基+器口之数()), 10))
	fmt.Printf("  （余 %d 口未配，留 M7 之外设；读之得零，写之无物受之）\n",
		器之数-器口之数())
	fmt.Println()
	fmt.Println("  器区之所以为器区：写它**不入藏**。若写了也入藏，")
	fmt.Println("  则它便与寻常之址无异，唯多一重副作用而已。")
	fmt.Println()
	fmt.Println("  界基 与 界限 二口，是化之**所见**：化 以虚址为址，")
	fmt.Println("  而物址 ＝ 界基 ＋ 虚址，越 界限 者陷越权。化 不知己在物理之何所。")

	// ---- （丁）开天 ----
	k, err := 建开天之机()
	if err != nil {
		panic(fmt.Sprintf("演示枢：建开天之机：%v", err))
	}
	拍, err := k.跑(500)
	if err != nil {
		panic(fmt.Sprintf("演示枢：开天 未止：%v", err))
	}
	fmt.Println()
	fmt.Printf("（丁）开天：%d 拍，出「%s」\n", 拍, k.出之文())
	fmt.Println()
	fmt.Println("  拍 │ 枢之志")
	fmt.Println("  ───┼────────────────────────────────────")
	for _, s := range k.志() {
		fmt.Println("  " + s)
	}
	fmt.Println()
	fmt.Println("  化 只见得 叩 一令；执器区而书之者，是枢之码。")
	fmt.Println("  **那五个字，是码打出来的。**")

	// ---- （戊）越权之试 ----
	越源 := 置数(艮器, 枢基) +
		fmt.Sprintf("\t存字 %s, [%s]\t；化态 写枢之域\n", 卦名(兑器), 卦名(艮器)) +
		"\t停机 0\n"
	k2, err := 建化之机(越源)
	if err != nil {
		panic(fmt.Sprintf("演示枢：建越权之机：%v", err))
	}
	if _, err := k2.跑(200); err != nil {
		panic(fmt.Sprintf("演示枢：越权之试 未止：%v", err))
	}
	fmt.Println()
	fmt.Printf("（戊）越权之试：化态 写 0o%06o → 陷「%s」\n", 枢基, k2.因.名())
	fmt.Println()
