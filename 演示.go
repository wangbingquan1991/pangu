// 出之文之辞 自「出」之诸条拼出其文。
func 出之文之辞(诸 []string) string {
	var b strings.Builder
	for _, s := range 诸 {
		if i := strings.Index(s, "「"); i >= 0 {
			if j := strings.Index(s[i:], "」"); j > 0 {
				b.WriteString(s[i+len("「") : i+j])
			}
		}
	}
	return b.String()
}

