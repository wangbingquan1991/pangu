// 演示节名 自藏中读出第 号 节之名，译为汉字，并出其诸码位。
//
// 此是**从藏里读**，不从 叩目 问——叩目 亦是码，若以码验码，
// 则译错之处两处同错（M3 之训：以慢御快）。此处径取其字，
// 与 壳 之所出两相比照，二者同则可信。
func 演示节名(k *枢机, 号 int) (名 string, 码 string) {
	节址 := 籍基 + (号 << 节之移)
	var b strings.Builder
	var 诸 []string
	for i := 0; i < 节名之度; i++ {
		v := k.机.藏值(节址 + 节名址 + i)
		if v == 0 {
			break // 名以零终
		}
		b.WriteRune(rune(v))
		诸 = append(诸, fmt.Sprintf("U+%04X", v))
	}
	return b.String(), strings.Join(诸, " ")
}

